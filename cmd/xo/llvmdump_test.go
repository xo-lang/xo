package main

import (
	"bytes"
	"strings"
	"testing"
)

// TestLLVMDump checks `xo llvmdump` (decision 0166): the module, one
// definition with --func, positions relative to the working directory,
// --each, and a run the checker rejects.
func TestLLVMDump(t *testing.T) {
	dir := writeFiles(t, map[string]string{
		"prog/main.xo": "fn div(a: Int, b: Int) -> Int { a / b }\n\nfn main(os: Os) {\n  os.stdio.println(\"${div(7, 2)}\")\n}\n",
		"bad/main.xo":  "fn main(os: Os) {\n  let x: Int = \"no\"\n}\n",
	})
	t.Chdir(dir)
	run1 := func(args ...string) (string, int) {
		var out, errOut bytes.Buffer
		code := run(append([]string{"llvmdump"}, args...), &out, &errOut)
		return out.String() + errOut.String(), code
	}
	out, code := run1("prog")
	if code != 0 {
		t.Fatalf("exit %d: %s", code, out)
	}
	for _, want := range []string{
		"== ir\n; generated by xo build --backend=llvm",
		"define internal i64 @\"x.div\"(i64 %v0, i64 %v1) #1 {",
		"c\"prog/main.xo:1:33\\00\"",
		"define void @xo_entry() #1 {",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("the module lacks %q:\n%s", want, out)
		}
	}
	if strings.Contains(out, "target-cpu") {
		t.Errorf("the module has target attributes")
	}

	out, code = run1("--func=x.div", "prog")
	if code != 0 || !strings.HasPrefix(out, "== ir\ndefine internal i64 @\"x.div\"") || strings.Contains(out, "x.main") {
		t.Errorf("--func=x.div: exit %d:\n%s", code, out)
	}

	out, code = run1("--each", "prog", "bad")
	if code != 0 || !strings.Contains(out, "=== llvm prog\n== ir\n") || !strings.Contains(out, "=== llvm bad\n== rejected\n") {
		t.Errorf("--each: exit %d:\n%s", code, out)
	}
}
