package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestProtoGen runs `xo proto gen` (decision 0530): one file to standard output, several files
// into --out, a parse error with its position, and the usage errors.
func TestProtoGen(t *testing.T) {
	t.Parallel()
	dir := writeFiles(t, map[string]string{
		"a.proto":   "syntax = \"proto3\";\nmessage A { int32 x = 1; repeated string tags = 2; }\n",
		"b.proto":   "syntax = \"proto2\";\nmessage B { required int32 y = 1; optional string s = 2; }\n",
		"bad.proto": "message C {\n  int32 z = ;\n}\n",
	})
	a, b, bad := filepath.Join(dir, "a.proto"), filepath.Join(dir, "b.proto"), filepath.Join(dir, "bad.proto")

	r := xo(t, "proto", "gen", a).want(0)
	for _, want := range []string{"// Code generated by xo proto gen. DO NOT EDIT.", "struct A {", `x proto "1": Int32`, `tags proto "2": List[Str]`} {
		if !strings.Contains(r.out, want) {
			t.Fatalf("stdout lacks %q:\n%s", want, r.out)
		}
	}

	out := filepath.Join(dir, "gen")
	xo(t, "proto", "gen", "--out="+out, a, b).want(0)
	got, err := os.ReadFile(filepath.Join(out, "b.xo"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(got), `y proto "1": Int32`) || !strings.Contains(string(got), `s proto "2": Str?`) {
		t.Fatalf("b.xo:\n%s", got)
	}
	if _, err := os.Stat(filepath.Join(out, "a.xo")); err != nil {
		t.Fatal(err)
	}

	r = xo(t, "proto", "gen", bad).want(1)
	if !strings.Contains(r.err, "bad.proto:2:") {
		t.Fatalf("stderr lacks the position: %s", r.err)
	}
	xo(t, "proto", "gen", a, b).want(2)
	xo(t, "proto", "gen").want(2)
	xo(t, "proto").want(2)
}
