// TestProtoGen runs `xo proto gen` (decision 0530): one file to standard output, several files
// into --out, a parse error with its position, and the usage errors.
func TestProtoGen(t *testing.T) {
	t.Parallel()
	dir := writeFiles(t, map[string]string{
		"a.proto":   "syntax = \"proto3\";\nmessage A { int32 x = 1; repeated string tags = 2; }\n",
		"b.proto":   "syntax = \"proto2\";\nmessage B { required int32 y = 1; optional string s = 2; }\n",
		"bad.proto": "message C {\n  int32 z = ;\n}\n",
	})
	a, b, bad := filepath.Join(dir, "a.proto"), filepath.Join(dir, "b.proto"), filepath.Join(dir, "bad.proto")

	r := xo(t, "proto", "gen", a).want(0)
	for _, want := range []string{"// Code generated by xo proto gen. DO NOT EDIT.", "struct A {", `x proto "1": Int32`, `tags proto "2": List[Str]`} {
		if !strings.Contains(r.out, want) {
			t.Fatalf("stdout lacks %q:\n%s", want, r.out)
		}
	}

	out := filepath.Join(dir, "gen")
	xo(t, "proto", "gen", "--out="+out, a, b).want(0)
	got, err := os.ReadFile(filepath.Join(out, "b.xo"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(got), `y proto "1": Int32`) || !strings.Contains(string(got), `s proto "2": Str?`) {
		t.Fatalf("b.xo:\n%s", got)
	}
	if _, err := os.Stat(filepath.Join(out, "a.xo")); err != nil {
		t.Fatal(err)
	}

	r = xo(t, "proto", "gen", bad).want(1)
	if !strings.Contains(r.err, "bad.proto:2:") {
		t.Fatalf("stderr lacks the position: %s", r.err)
	}
	xo(t, "proto", "gen", a, b).want(2)
	xo(t, "proto", "gen").want(2)
	xo(t, "proto").want(2)
}

// TestProtoGenBuilds generates two files, one importing the other, into one directory with a main
// and runs it: the output compiles (it carried an unused `use std/protobuf`, XO0110, before
// 2026-11-16) and a message of the imported file resolves and round-trips.
func TestProtoGenBuilds(t *testing.T) {
	t.Parallel()
	dir := writeFiles(t, map[string]string{
		"p/a.proto": "syntax = \"proto3\";\npackage p.a;\nmessage A { int32 v = 1; }\nenum K { Z = 0; ONE = 1; }\nmessage H { K k = 1; }\n",
		"p/b.proto": "syntax = \"proto3\";\npackage p.b;\nimport \"p/a.proto\";\nmessage B { p.a.A a = 1; repeated p.a.A more = 2; p.a.H h = 3; }\n",
		"gen/main.xo": "use std/protobuf\n\nfn main(os: Os) {\n  let b = B{a: A{v: 7}, more: [A{v: 8}], h: H{k: K.One}}\n" +
			"  let back = protobuf.unmarshal[B](protobuf.marshal(b)).or_fault(\"unmarshal\")\n" +
			"  os.stdio.println(\"${back.a.v} ${back.more[0].v} ${back.h.k == K.One}\")\n}\n",
	})
	out := filepath.Join(dir, "gen")
	xo(t, "proto", "gen", "--out="+out, filepath.Join(dir, "p", "a.proto"), filepath.Join(dir, "p", "b.proto")).want(0)
	r := xo(t, "run", out).want(0)
	if r.out != "7 8 true\n" {
		t.Fatalf("got %q\n%s", r.out, r.err)
	}
	// alone, b.proto's import is not in the set
	xo(t, "proto", "gen", filepath.Join(dir, "p", "b.proto")).want(1)
}

// TestProtoGenWellKnownEnumsUnpacked builds what xo proto gen writes for a
// field typed by an enum of another file, a well-known type (std/protowkt's)
// and a proto2 repeated number (unpacked on the wire, as protoc writes it),
// and runs a round trip (decision 0683 item 4, task #109). gen_set refused
// the first two before.
func TestProtoGenWellKnownEnumsUnpacked(t *testing.T) {
	t.Parallel()
	dir := writeFiles(t, map[string]string{
		"p/a.proto": "syntax = \"proto3\";\npackage p.a;\nenum K { Z = 0; ONE = 1; }\n",
		"p/b.proto": "syntax = \"proto3\";\npackage p.b;\nimport \"p/a.proto\";\nimport \"google/protobuf/timestamp.proto\";\nmessage B { p.a.K k = 1; google.protobuf.Timestamp at = 2; }\n",
		"p/c.proto": "syntax = \"proto2\";\npackage p.c;\nmessage C { repeated int32 n = 1; }\n",
		"gen/main.xo": "use std/protobuf\nuse std/protowkt\n\nfn main(os: Os) {\n  let b = B{k: K.One, at: protowkt.Timestamp{seconds: 5, nanos: 6}}\n" +
			"  let back = protobuf.unmarshal[B](protobuf.marshal(b)).or_fault(\"unmarshal\")\n" +
			"  let at = back.at\n" +
			"  let c = protobuf.marshal(C{n: [1, 2]})\n" +
			"  os.stdio.println(\"${back.k == K.One} ${at.seconds} ${at.nanos} ${c.to_hex()}\")\n}\n",
	})
	out := filepath.Join(dir, "gen")
	xo(t, "proto", "gen", "--out="+out, filepath.Join(dir, "p", "a.proto"), filepath.Join(dir, "p", "b.proto"), filepath.Join(dir, "p", "c.proto")).want(0)
	r := xo(t, "run", out).want(0)
	// 0801 0802: field 1 once per element (protoc's proto2 form), not 0a020102 (packed)
	if r.out != "true 5 6 08010802\n" {
		t.Fatalf("got %q\n%s", r.out, r.err)
	}
}

// TestProtoGenServiceRuns generates the gRPC stubs of a service with the four kinds of rpc (decision 0706),
// registers typed handlers with the generated handle_ functions, and calls each through the generated client
// over HTTP/2: unary, server streaming, client streaming and bidirectional.
func TestProtoGenServiceRuns(t *testing.T) {
	t.Parallel()
	dir := writeFiles(t, map[string]string{
		"svc.proto":   "syntax = \"proto3\";\npackage demo;\n\nmessage Req { string name = 1; int32 n = 2; }\nmessage Resp { string text = 1; }\n\nservice Greeter {\n  rpc SayHello(Req) returns (Resp);\n  rpc Count(Req) returns (stream Resp);\n  rpc Join(stream Req) returns (Resp);\n  rpc Chat(stream Req) returns (stream Resp);\n}\n",
		"gen/main.xo": "// decision 0706: the stubs xo proto gen writes for svc.proto, served and called over HTTP/2.\nuse std/grpc\nuse std/http\n\nfn main(os: Os) {\n  var srv = grpc.server(os.clock)\n  handle_greeter_say_hello(srv, fn(_call, req) -> Resp ! grpc.Status { Ok(Resp{text: \"hello ${req.name}\"}) })\n  handle_greeter_count(srv, fn(_call, req, send) -> () ! grpc.Status {\n    for i in 0..Int(req.n) {\n      send.send(Resp{text: \"${req.name} ${i}\"})?\n    }\n    Ok(())\n  })\n  handle_greeter_join(srv, fn(_call, recv) -> Resp ! grpc.Status {\n    var parts: List[Str] = []\n    while let Some(r) = recv.next()? {\n      parts.push(r.name)\n    }\n    Ok(Resp{text: parts.join(\"+\")})\n  })\n  handle_greeter_chat(srv, fn(_call, recv, send) -> () ! grpc.Status {\n    while let Some(r) = recv.next()? {\n      send.send(Resp{text: \"echo ${r.name}\"})?\n    }\n    Ok(())\n  })\n  let l = os.net.listen(\"127.0.0.1:0\").or_fault(\"listen\")\n  let hs = http.server(l, srv.router()).with_protocols(#{http.Protocol.UnencryptedHttp2})\n  scope s {\n    s.spawn_background(fn() { hs.serve().ignore_err(\"the program ends the server\") })\n    let c = new_greeter_client(grpc.client(http.client(os.net, timeout: 30s), \"http://${hs.addr()}\"))\n    os.stdio.println(\"unary: ${c.say_hello(Req{name: \"xo\", n: 0}).or_fault(\"unary\").text}\")\n    let seen = Mutex[List[Str]].new([])\n    c.count(Req{name: \"c\", n: 3}, fn(r) -> Bool {\n      seen.with(fn(var l) { l.push(r.text) })\n      true\n    }).or_fault(\"count\")\n    os.stdio.println(\"server stream: ${seen.with_read(fn(l) { l })}\")\n    os.stdio.println(\"client stream: ${c.join([Req{name: \"a\", n: 0}, Req{name: \"b\", n: 0}]).or_fault(\"join\").text}\")\n    let got = c.chat(fn(st) -> List[Str] ! grpc.Status uses net.dial {\n      st.send(Req{name: \"x\", n: 0})?\n      st.send(Req{name: \"y\", n: 0})?\n      st.close_send()\n      var out: List[Str] = []\n      while let Some(r) = st.recv()? {\n        out.push(r.text)\n      }\n      Ok(out)\n    }).or_fault(\"chat\")\n    os.stdio.println(\"bidi: ${got}\")\n  }\n  os.stdio.println(\"done\")\n}\n",
	})
	out := filepath.Join(dir, "gen")
	xo(t, "proto", "gen", "--out="+out, filepath.Join(dir, "svc.proto")).want(0)
	r := xo(t, "run", out).want(0)
	want := "unary: hello xo\nserver stream: [\"c 0\", \"c 1\", \"c 2\"]\nclient stream: a+b\nbidi: [\"echo x\", \"echo y\"]\ndone\n"
	if r.out != want {
		t.Fatalf("got %q\nwant %q\n%s", r.out, want, r.err)
	}
}
