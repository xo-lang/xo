#!/usr/bin/env bash
# Vendor fiat-crypto's P-256 C code into third_party/fiat-crypto (decision 0134).
#
#   scripts/vendor-fiat-crypto.sh
#
# Downloads the generated 64 bit P-256 field and scalar files of
# fiat-c/src/ and the license files from github.com/mit-plv/fiat-crypto at
# the pinned commit, checks every file's SHA-256 against the pinned list
# below, and writes them with SHA256SUMS (which TestVendored checks the
# embedded copies against). Nothing else of the repository is taken.
#
# Update: set commit below, run with UPDATE=1 to print the new sums
# (review the diff of the C files: they must stay generated by the same
# command line and expose the same functions), paste them into the list,
# run again without UPDATE, then run `go test ./third_party/fiat-crypto
# ./internal/build -run 'TestVendored|TestTLSAccel|TestP256'` and the TLS
# tests (`go test ./internal/llvm -run 'TestTLSDiff'`), and update
# knowledgebase/infrastructure/toolchain.md ("TLS library").
set -euo pipefail

commit="f3ecb2cf1f771de34771e967193ee7f0ee0b0acf"
# SHA-256 and path in the fiat-crypto repository of every vendored file
pinned="
68cc5c4fa08de660a869a412618a30848f11d18051245013fe53fa4e313ec701 fiat-c/src/p256_64.c
eed8ad2adb15aa8e120ff8f7ded6c6297284724a612f6b284c5afba9bebfae83 fiat-c/src/p256_scalar_64.c
0034712d5e97a4f5b900a160a5c19d582b740d8e0638b4e44fd07e7b492dcd13 LICENSE-MIT
9eacbcb81be660840c714a560a9d65ba07913db98dd4baf969f78dd499fdd60f LICENSE-APACHE
0c1240e29b4a2c528bcc3ccc38a98b1dba5e3e6b465da910208935f082e2ced6 LICENSE-BSD-1
6c935d087a2992d0f092665400a2fa99c98db58d96fbe29368f8f48182bed9aa COPYRIGHT
ad74c036a6afaedc418fed65f171c877c2f74a4c70938a03930aa11c98a20508 AUTHORS
"

repo="$(cd "$(dirname "$0")/.." && pwd)"
dest="$repo/third_party/fiat-crypto"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
base="https://raw.githubusercontent.com/mit-plv/fiat-crypto/$commit"

fail=0
while read -r sum path; do
	[ -n "$path" ] || continue
	out="$tmp/$(basename "$path")"
	curl -fsSL -o "$out" "$base/$path"
	got="$(shasum -a 256 "$out" | cut -d' ' -f1)"
	if [ "${UPDATE:-}" = 1 ]; then
		echo "$got $path"
	elif [ "$got" != "$sum" ]; then
		echo "vendor-fiat-crypto: SHA-256 mismatch for $path: got $got, want $sum" >&2
		fail=1
	fi
done <<<"$pinned"
[ "${UPDATE:-}" = 1 ] && exit 0
[ "$fail" = 0 ] || exit 1

mkdir -p "$dest/src"
rm -f "$dest"/src/*.c
: >"$tmp/SHA256SUMS"
while read -r sum path; do
	[ -n "$path" ] || continue
	name="$(basename "$path")"
	case "$path" in
	fiat-c/src/*) rel="src/$name" ;;
	*) rel="$name" ;;
	esac
	cp "$tmp/$name" "$dest/$rel"
	echo "$sum  $rel" >>"$tmp/SHA256SUMS"
done <<<"$pinned"
cp "$tmp/SHA256SUMS" "$dest/SHA256SUMS"
echo "vendored fiat-crypto at $commit: $(ls "$dest/src" | tr '\n' ' ')"
