// scripts/gomath: Go's math package (pure Go, assembly removed) as std/rt code:
// every float64 product wrapped in float64(...), which forbids the
// compiler's fused multiply-add (Go spec, Arithmetic operators), and every
// package-level name prefixed with gm, in one file of package rt.
package main

import (
	"bytes"
	"go/ast"
	"go/format"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	dir := os.Args[1]
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, nil, 0)
	if err != nil {
		panic(err)
	}
	pkg := pkgs["pm"]
	var files []*ast.File
	var names []string
	for n := range pkg.Files {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		files = append(files, pkg.Files[n])
	}
	info := &types.Info{Types: map[ast.Expr]types.TypeAndValue{}, Uses: map[*ast.Ident]types.Object{}, Defs: map[*ast.Ident]types.Object{}}
	conf := types.Config{Importer: importer.Default()}
	tp, err := conf.Check("pm", fset, files, info)
	if err != nil {
		panic(err)
	}
	isPkg := func(o types.Object) bool { return o != nil && o.Parent() == tp.Scope() }
	f64 := types.Typ[types.Float64]
	var out bytes.Buffer
	out.WriteString("// Code generated by scratch gomath/rewrite from Go 1.26's math package\n// (pure Go, assembly removed); DO NOT EDIT. Decision 0287.\n\npackage rt\n\nimport (\n\t\"math/bits\"\n)\n\nvar _ = bits.Len64\n")
	for _, f := range files {
		ast.Inspect(f, func(n ast.Node) bool {
			if id, ok := n.(*ast.Ident); ok {
				if o := info.Uses[id]; isPkg(o) {
					id.Name = "gm" + id.Name
				} else if o := info.Defs[id]; isPkg(o) {
					id.Name = "gm" + id.Name
				}
			}
			return true
		})
		ast.Walk(wrapper{info, f64}, f)
		for _, d := range f.Decls {
			if g, ok := d.(*ast.GenDecl); ok && g.Tok == token.IMPORT {
				continue
			}
			var b bytes.Buffer
			format.Node(&b, fset, d)
			s := b.String()
			s = strings.ReplaceAll(s, "unsafe.Pointer", "UNSAFE")
			out.WriteString("\n" + s + "\n")
		}
	}
	src, err := format.Source(out.Bytes())
	if err != nil {
		os.WriteFile(filepath.Join(os.Args[2]), out.Bytes(), 0o644)
		panic(err)
	}
	os.WriteFile(os.Args[2], src, 0o644)
}

type wrapper struct {
	info *types.Info
	f64  types.Type
}

func (w wrapper) Visit(n ast.Node) ast.Visitor {
	// rewrite the children of n: a float64 product becomes float64(product)
	rewrite := func(e ast.Expr) ast.Expr {
		if b, ok := e.(*ast.BinaryExpr); ok && b.Op == token.MUL {
			if tv, ok := w.info.Types[b]; ok && tv.Value == nil && types.Identical(tv.Type, w.f64) {
				return &ast.CallExpr{Fun: ast.NewIdent("float64"), Args: []ast.Expr{b}}
			}
		}
		return e
	}
	switch x := n.(type) {
	case *ast.BinaryExpr:
		x.X, x.Y = rewrite(x.X), rewrite(x.Y)
	case *ast.ParenExpr:
		x.X = rewrite(x.X)
	case *ast.AssignStmt:
		for i := range x.Rhs {
			x.Rhs[i] = rewrite(x.Rhs[i])
		}
	case *ast.ReturnStmt:
		for i := range x.Results {
			x.Results[i] = rewrite(x.Results[i])
		}
	case *ast.CallExpr:
		if id, ok := x.Fun.(*ast.Ident); ok && id.Name == "float64" {
			return w
		}
		for i := range x.Args {
			x.Args[i] = rewrite(x.Args[i])
		}
	case *ast.ValueSpec:
		for i := range x.Values {
			x.Values[i] = rewrite(x.Values[i])
		}
	case *ast.UnaryExpr:
		x.X = rewrite(x.X)
	case *ast.CompositeLit:
		for i := range x.Elts {
			x.Elts[i] = rewrite(x.Elts[i])
		}
	case *ast.IndexExpr:
		x.Index = rewrite(x.Index)
	case *ast.IfStmt, *ast.ForStmt:
	}
	return w
}
