// Command brotlioracle prints the std/brotli corpus:
// github.com/andybalholm/brotli v1.2.2 (std/brotli's reference) encoding
// seeded random inputs at random qualities and windows, some flushed part
// way, and its Reader on those streams and on changed, cut and extended
// copies of them. scripts/stdcorpus runs it; it is its own module so the
// repository's go.mod has no third-party requirement.
package main

import (
	"bytes"
	"fmt"
	"io"
	"math/rand"
	"os"
	"strings"

	"github.com/andybalholm/brotli"
)

var words = []string{"the ", "of ", "and ", "to ", "in ", "is ", "that ", "for ", "<a href=\"", "\">", "</a>", "<p>", "</p>\n", "function ", "var ", " = ", ";\n", "{", "}", "return ", "http://", ".com/", "Hello", " World", "THE ", "été ", "日本語", "😀", "data", "json", "\"key\": ", "[1, 2, 3]", "\t", "  "}

func input(rg *rand.Rand) []byte {
	kind := rg.Intn(4)
	n := rg.Intn(4000)
	switch rg.Intn(10) {
	case 0:
		n = rg.Intn(4)
	case 1:
		// past Go's 32 KiB read pieces, and small windows many times over;
		// noise only to 5000 bytes, so the corpus stays small
		n = 20000 + rg.Intn(30000)
		if kind == 1 {
			n = 5000
		}
	}
	var b []byte
	for len(b) < n {
		switch kind {
		case 0:
			b = append(b, words[rg.Intn(len(words))]...)
		case 1:
			b = append(b, byte(rg.Intn(256)))
		case 2:
			// runs and repeats at varied distances
			if len(b) > 8 && rg.Intn(3) > 0 {
				d := 1 + rg.Intn(len(b))
				l := 2 + rg.Intn(40)
				for i := 0; i < l; i++ {
					b = append(b, b[len(b)-d])
				}
			} else {
				b = append(b, byte('a'+rg.Intn(6)))
			}
		default:
			if rg.Intn(4) == 0 {
				b = append(b, byte(rg.Intn(256)))
			} else {
				b = append(b, words[rg.Intn(8)]...)
			}
		}
	}
	return b[:n]
}

func encode(rg *rand.Rand, data []byte) ([]byte, string) {
	q := rg.Intn(12)
	w := 0
	if rg.Intn(2) == 0 {
		w = 10 + rg.Intn(15)
	}
	flushes := 0
	var buf bytes.Buffer
	wr := brotli.NewWriterOptions(&buf, brotli.WriterOptions{Quality: q, LGWin: w})
	rest := data
	for len(rest) > 0 {
		k := len(rest)
		if rg.Intn(4) == 0 {
			k = rg.Intn(len(rest) + 1)
		}
		wr.Write(rest[:k])
		rest = rest[k:]
		if len(rest) > 0 {
			wr.Flush()
			flushes++
		}
	}
	wr.Close()
	return buf.Bytes(), fmt.Sprintf("q%d w%d flushes %d", q, w, flushes)
}

func decode(s []byte) ([]byte, string) {
	out, err := io.ReadAll(brotli.NewReader(bytes.NewReader(s)))
	if err != nil {
		return nil, err.Error()
	}
	return out, ""
}

func fnv(b []byte) int64 {
	h := uint64(14695981039346656037)
	for _, c := range b {
		h ^= uint64(c)
		h *= 1099511628211
	}
	return int64(h)
}

func main() {
	rg := rand.New(rand.NewSource(66))
	var o strings.Builder
	o.WriteString("// Generated by scripts/stdcorpus from github.com/andybalholm/brotli v1.2.2 (NewWriterOptions with Flush, NewReader) on seeded\n// inputs, qualities and windows, and on changed, cut and extended streams.\n// Do not edit: regenerate with go run ./scripts/stdcorpus.\nuse std/brotli\n\n")
	o.WriteString("/// (how it was written, the stream, the input's length and FNV-1a 64)\nconst STREAMS: List[(Str, Str, Int, Int)] = [\n")
	var streams [][]byte
	for i := 0; i < 160; i++ {
		data := input(rg)
		s, how := encode(rg, data)
		if out, e := decode(s); e != "" || !bytes.Equal(out, data) {
			panic("andybalholm round trip: " + e)
		}
		streams = append(streams, s)
		fmt.Fprintf(&o, "  (%q, \"%x\", %d, %d),\n", how, s, len(data), fnv(data))
	}
	o.WriteString("]\n\n/// (the stream, what Go's Reader gives: the output's length and FNV-1a 64, or its error)\nconst DAMAGED: List[(Str, Int, Int, Str)] = [\n")
	for i := 0; i < 900; i++ {
		src := streams[rg.Intn(len(streams))]
		if len(src) > 3000 {
			src = streams[rg.Intn(40)]
		}
		s := append([]byte{}, src...)
		switch rg.Intn(5) {
		case 0:
			s = s[:rg.Intn(len(s)+1)]
		case 1:
			s = append(s, byte(rg.Intn(256)))
		default:
			for k := 0; k <= rg.Intn(3); k++ {
				if len(s) > 0 {
					s[rg.Intn(len(s))] ^= byte(1 << rg.Intn(8))
				}
			}
		}
		out, e := decode(s)
		fmt.Fprintf(&o, "  (\"%x\", %d, %d, %q),\n", s, len(out), fnv(out), e)
	}
	o.WriteString("]\n\n")
	o.WriteString(tests)
	os.Stdout.WriteString(o.String())
}

const tests = `fn unhex(s: Str) -> Bytes { Bytes.from_hex(s).or_fault("hex") }

fn fnv(b: Bytes) -> Int {
  var h = -3750763034362895579
  for c in b {
    h = (h ^ Int(c)).wrapping_mul(1099511628211)
  }
  h
}

fn outcome(data: Bytes) -> Str {
  match brotli.decode(data) {
    Ok(out) => "${out.len()} ${fnv(out)}"
    Err(e) => e.display()
  }
}

test "andybalholm's streams decode to their input" {
  var bad: List[Str] = []
  for (how, s, n, h) in STREAMS {
    let got = outcome(unhex(s))
    if got != "${n} ${h}" {
      bad.push("${how}: ${got} want ${n} ${h}")
    }
  }
  expect(bad) == []
}

test "damaged streams give Go's output or error" {
  var bad: List[Str] = []
  for (s, n, h, e) in DAMAGED {
    let want = if e == "" { "${n} ${h}" } else { e }
    let got = outcome(unhex(s))
    if got != want {
      bad.push("${s}: ${got} want ${want}")
    }
  }
  expect(bad[0..(if bad.len() < 8 { bad.len() } else { 8 })]) == []
}
`
