// pathAlphabet is the pieces random paths are made of: empty segments,
// dots, dot-dot, hidden files, extensions, doubled separators and a
// non-ASCII name.
var pathAlphabet = []string{"", "a", "b", "c", "dir", "file", "x.go", ".", "..", ".hidden", "a.b", "é"}

// pathRandom is a seeded random path of up to six pieces.
func pathRandom(r *rand.Rand) string {
	var b strings.Builder
	n := r.Intn(6)
	for i := 0; i < n; i++ {
		b.WriteString(pathAlphabet[r.Intn(len(pathAlphabet))])
		if r.Intn(3) > 0 {
			b.WriteString("/")
		}
	}
	switch r.Intn(8) {
	case 0:
		return "/" + b.String()
	case 1:
		return b.String() + "/"
	}
	return b.String()
}

// pathPatternAlphabet is the pieces random patterns are made of: stars,
// question marks, byte classes (valid and not), escapes, and literals.
var pathPatternAlphabet = []string{"*", "*", "?", "a", "b", "c", "/", "[a-c]", "[^a]", "[", "]", "-", `\*`, `\\`, "abc", "é", "."}

// pathRandomPattern is a seeded random pattern of up to six pieces.
func pathRandomPattern(r *rand.Rand) string {
	var b strings.Builder
	n := r.Intn(6)
	for i := 0; i < n; i++ {
		b.WriteString(pathPatternAlphabet[r.Intn(len(pathPatternAlphabet))])
	}
	return b.String()
}

func pathCorpus() string {
	r := rand.New(rand.NewSource(43))
	var o strings.Builder
	o.WriteString(header("Go's path package on the inputs of path/path_test.go (cleantests, splittests, jointests, exttests, basetests, dirtests, isAbsTests) and path/match_test.go (matchTests), and on seeded random paths, against path's clean, split, join, dir, base, ext, is_abs and is_match (Go's path tests are Copyright 2009 The Go Authors, BSD-style license)"))
	o.WriteString("\nuse std/path\n")

	// the inputs: the replaced corpus's, Go's table inputs, and seeded
	// randoms
	var inputs []string
	seen := map[string]bool{}
	add := func(s string) {
		s = textOf(s)
		if !seen[s] {
			seen[s] = true
			inputs = append(inputs, s)
		}
	}
	for _, s := range pathLegacyInputs {
		add(s)
	}
	for _, s := range goSplitPaths {
		add(s)
	}
	for _, s := range goIsAbsPaths {
		add(s)
	}
	for _, s := range []string{"", "/", "//", "///", ".", "./", "../", "a//b//c", "a/b/", "/a/./b/../c", "x/../../y"} {
		add(s)
	}
	for i := 0; i < 1200; i++ {
		add(pathRandom(r))
	}

	o.WriteString("\n/// (p, Go's Clean, Dir, Base and Ext)\nconst CONV_CASES: List[(Str, Str, Str, Str, Str)] = [\n")
	for _, s := range inputs {
		fmt.Fprintf(&o, "  (%s, %s, %s, %s, %s),\n", xq(s), xq(path.Clean(s)), xq(path.Dir(s)), xq(path.Base(s)), xq(path.Ext(s)))
	}
	o.WriteString("]\n")

	o.WriteString("\n/// (p, Go's Split: dir and file)\nconst SPLIT_CASES: List[(Str, Str, Str)] = [\n")
	for _, s := range inputs {
		d, f := path.Split(s)
		fmt.Fprintf(&o, "  (%s, %s, %s),\n", xq(s), xq(d), xq(f))
	}
	o.WriteString("]\n")

	o.WriteString("\n/// (a, b, Go's Join)\nconst JOIN_CASES: List[(Str, Str, Str)] = [\n")
	seenJoin := map[[2]string]bool{}
	join := func(a, b string) {
		a, b = textOf(a), textOf(b)
		if seenJoin[[2]string{a, b}] {
			return
		}
		seenJoin[[2]string{a, b}] = true
		fmt.Fprintf(&o, "  (%s, %s, %s),\n", xq(a), xq(b), xq(path.Join(a, b)))
	}
	for _, p := range pathLegacyJoins {
		join(p[0], p[1])
	}
	for _, p := range goJoinPairs {
		join(p[0], p[1])
	}
	for i := 0; i < 600; i++ {
		join(pathRandom(r), pathRandom(r))
	}
	o.WriteString("]\n")

	o.WriteString("\n/// (p, Go's IsAbs)\nconst IS_ABS_CASES: List[(Str, Str)] = [\n")
	for _, s := range inputs {
		w := "false"
		if path.IsAbs(s) {
			w = "true"
		}
		fmt.Fprintf(&o, "  (%s, %s),\n", xq(s), xq(w))
	}
	o.WriteString("]\n")

	o.WriteString("\n/// (pattern, name, Go's Match; \"err\" when it reports ErrBadPattern)\nconst MATCH_CASES: List[(Str, Str, Str)] = [\n")
	seenMatch := map[[2]string]bool{}
	match := func(pat, name string) {
		pat, name = textOf(pat), textOf(name)
		if seenMatch[[2]string{pat, name}] {
			return
		}
		seenMatch[[2]string{pat, name}] = true
		w := "false"
		ok, err := path.Match(pat, name)
		if err != nil {
			w = "err"
		} else if ok {
			w = "true"
		}
		fmt.Fprintf(&o, "  (%s, %s, %s),\n", xq(pat), xq(name), xq(w))
	}
	for _, c := range goMatchCases {
		match(c[0], c[1])
	}
	for i := 0; i < 1000; i++ {
		match(pathRandomPattern(r), pathRandom(r))
	}
	o.WriteString("]\n")

	o.WriteString(pathTests)
	return o.String()
}

