// Command tomloracle prints std/toml's encode_with corpus: fixed records
// encoded by github.com/pelletier/go-toml/v2 (MIT) under each Encoder
// setting, as Xo source (internal/stdtest/testdata/corpus/toml).
package main

import (
	"bytes"
	"fmt"
	"os"
	"strconv"
	"strings"

	toml "github.com/pelletier/go-toml/v2"
)

type Point struct {
	X int64 `toml:"x"`
	Y int64 `toml:"y"`
}

type Server struct {
	Name  string   `toml:"name"`
	Ports []int64  `toml:"ports"`
	Tags  []string `toml:"tags"`
}

type Inner struct {
	Deep  string  `toml:"deep"`
	Pts   []Point `toml:"pts"`
	Empty []int64 `toml:"empty"`
}

type Mid struct {
	Level int64     `toml:"level"`
	Grid  [][]int64 `toml:"grid"`
	Inner Inner     `toml:"inner"`
}

type Config struct {
	Title   string   `toml:"title"`
	Ratio   float64  `toml:"ratio"`
	On      bool     `toml:"on"`
	Origin  Point    `toml:"origin"`
	Mid     Mid      `toml:"mid"`
	Servers []Server `toml:"servers"`
	Last    []string `toml:"last"`
}

func sample() Config {
	return Config{
		Title:  "it's \"x\"",
		Ratio:  0.5,
		On:     true,
		Origin: Point{X: 1, Y: -2},
		Mid: Mid{
			Level: 3,
			Grid:  [][]int64{{1, 2}, {}, {3}},
			Inner: Inner{Deep: "d", Pts: []Point{{X: 4, Y: 5}, {X: 6, Y: 7}}, Empty: []int64{}},
		},
		Servers: []Server{{Name: "a", Ports: []int64{80, 443}, Tags: []string{}}, {Name: "b", Ports: []int64{}, Tags: []string{"t1", "t 2"}}},
		Last:    []string{"z"},
	}
}

func xoStr(s string) string {
	q := strconv.Quote(s)
	return strings.ReplaceAll(q, "$", "\\$")
}

func main() {
	var o strings.Builder
	o.WriteString("// Generated by scripts/stdcorpus (tomloracle) from github.com/pelletier/go-toml/v2 v2.4.3 (MIT): one record under each Encoder setting.\n")
	o.WriteString("// Do not edit: regenerate with go run ./scripts/stdcorpus toml.\n\n")
	o.WriteString(xoTypes)
	o.WriteString("/// (tables_inline, arrays_multiline, indent_tables, indent, go-toml's text)\n")
	o.WriteString("const ENCODE_CASES: List[(Bool, Bool, Bool, Str, Str)] = [\n")
	for _, sym := range []string{"  ", "\t"} {
		for m := 0; m < 8; m++ {
			inline, multi, ind := m&1 != 0, m&2 != 0, m&4 != 0
			if sym != "  " && !multi && !ind {
				continue
			}
			var b bytes.Buffer
			e := toml.NewEncoder(&b)
			e.SetTablesInline(inline)
			e.SetArraysMultiline(multi)
			e.SetIndentTables(ind)
			e.SetIndentSymbol(sym)
			if err := e.Encode(sample()); err != nil {
				fmt.Fprintln(os.Stderr, err)
				os.Exit(1)
			}
			fmt.Fprintf(&o, "  (%v, %v, %v, %s, %s),\n", inline, multi, ind, xoStr(sym), xoStr(b.String()))
		}
	}
	o.WriteString("]\n")
	o.WriteString(xoTest)
	fmt.Print(o.String())
}

// xoTypes are sample's types and value in Xo (the same fields, in order).
const xoTypes = `use std/toml

struct Point {
  x: Int
  y: Int
} derive Json

struct Server {
  name: Str
  ports: List[Int]
  tags: List[Str]
} derive Json

struct Inner {
  deep: Str
  pts: List[Point]
  empty: List[Int]
} derive Json

struct Mid {
  level: Int
  grid: List[List[Int]]
  inner: Inner
} derive Json

struct Config {
  title: Str
  ratio: Float
  on: Bool
  origin: Point
  mid: Mid
  servers: List[Server]
  last: List[Str]
} derive Json

fn sample() -> Config {
  Config{
    title: "it's \"x\"",
    ratio: 0.5,
    on: true,
    origin: Point{x: 1, y: -2},
    mid: Mid{level: 3, grid: [[1, 2], [], [3]], inner: Inner{deep: "d", pts: [Point{x: 4, y: 5}, Point{x: 6, y: 7}], empty: []}},
    servers: [Server{name: "a", ports: [80, 443], tags: []}, Server{name: "b", ports: [], tags: ["t1", "t 2"]}],
    last: ["z"],
  }
}

`

const xoTest = `
test "encode_with lays out a record as go-toml's Encoder does under each setting" {
  for (inline, multi, ind, sym, want) in ENCODE_CASES {
    let got = toml.encode_with(sample(), toml.EncodeOptions{tables_inline: inline, arrays_multiline: multi, indent_tables: ind, indent: sym}).or_fault("encode_with")
    expect(got) == want
    // every layout reads back as the same record
    expect(toml.decode[Config](got).or_fault("decode") == sample()) == true
  }
}

test "encode is encode_with's defaults" {
  expect(toml.encode(sample()).or_fault("encode")) == ENCODE_CASES[0].4
}
`
