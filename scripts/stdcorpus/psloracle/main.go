// Command psloracle prints the std/publicsuffix corpus: golang.org/x/net
// v0.60.0's publicsuffix PublicSuffix and EffectiveTLDPlusOne on hand
// picked domains (wildcards, exceptions, private suffixes, IP addresses,
// empty labels) and seeded random ones built from labels the list uses.
// scripts/stdcorpus runs it; it is its own module so the repository's
// go.mod has no third-party requirement.
package main

import (
	"fmt"
	"math/rand"
	"strings"

	"golang.org/x/net/publicsuffix"
)

func xq(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`)
	return `"` + r.Replace(s) + `"`
}

var fixed = []string{
	"", ".", "com", "example.com", "www.example.com", "a.b.c.example.com",
	"co.uk", "example.co.uk", "www.example.co.uk", "uk", "parliament.uk",
	"ck", "www.ck", "foo.ck", "a.foo.ck", "kawasaki.jp", "city.kawasaki.jp",
	"www.city.kawasaki.jp", "foo.kawasaki.jp", "a.foo.kawasaki.jp",
	"github.io", "user.github.io", "www.user.github.io", "blogspot.com",
	"foo.blogspot.com", "appspot.com", "x.appspot.com", "s3.amazonaws.com",
	"bucket.s3.amazonaws.com", "nosuchtld", "a.nosuchtld", "b.a.nosuchtld",
	"127.0.0.1", "::1", "2001:db8::1", "192.168.0.1", ".example.com",
	"example.com.", "a..example.com", "xn--fiqs8s", "foo.xn--fiqs8s",
	"xn--55qx5d.cn", "www.xn--55qx5d.cn", "compute.amazonaws.com",
	"ec2.compute.amazonaws.com", "a.b.compute.amazonaws.com", "gov.uk",
	"service.gov.uk", "x.service.gov.uk", "pvt.k12.ma.us", "a.pvt.k12.ma.us",
	"k12.ma.us", "ma.us", "us", "test.us", "b.c.d.e.f.g.h.example.net",
}

var labels = []string{
	"com", "net", "org", "uk", "co", "jp", "ck", "www", "foo", "bar", "example",
	"github", "io", "blogspot", "appspot", "amazonaws", "s3", "compute",
	"kawasaki", "city", "gov", "ac", "k12", "ma", "us", "de", "fr", "cn",
	"xn--55qx5d", "edu", "au", "nz", "br", "com.br", "a", "b", "zz", "test",
	"herokuapp", "cloudfront", "azurewebsites", "pages", "dev", "app",
	"tokyo", "osaka", "nom", "ne", "or", "go", "lg", "ad", "ed", "gr",
}

func main() {
	r := rand.New(rand.NewSource(617))
	ds := append([]string{}, fixed...)
	for i := 0; i < 3000; i++ {
		n := 1 + r.Intn(5)
		var parts []string
		for k := 0; k < n; k++ {
			parts = append(parts, labels[r.Intn(len(labels))])
		}
		ds = append(ds, strings.Join(parts, "."))
	}
	fmt.Print("// Generated by scripts/stdcorpus from golang.org/x/net v0.60.0's publicsuffix PublicSuffix and EffectiveTLDPlusOne on hand picked and seeded domains.\n// Do not edit: regenerate with go run ./scripts/stdcorpus.\n")
	fmt.Print("use std/publicsuffix\n\n/// (domain, public suffix, icann, eTLD+1 or the error's text after \"!\")\nconst CASES: List[(Str, Str, Bool, Str)] = [\n")
	for _, d := range ds {
		ps, icann := publicsuffix.PublicSuffix(d)
		e, err := publicsuffix.EffectiveTLDPlusOne(d)
		if err != nil {
			e = "!" + err.Error()
		}
		fmt.Printf("  (%s, %s, %v, %s),\n", xq(d), xq(ps), icann, xq(e))
	}
	fmt.Print(`]

test "public_suffix and effective_tld_plus_one answer as x/net's publicsuffix" {
  var bad: List[Str] = []
  for (d, ps, icann, e) in CASES {
    let (gps, gi) = publicsuffix.public_suffix(d)
    let ge = match publicsuffix.effective_tld_plus_one(d) {
      Ok(s) => s
      Err(x) => "!" + x.msg
    }
    if gps != ps || gi != icann || ge != e {
      bad.push("${d}: got (${gps}, ${gi}, ${ge}), want (${ps}, ${icann}, ${e})")
    }
  }
  expect(bad.join("\n")) == ""
}
`)
}
