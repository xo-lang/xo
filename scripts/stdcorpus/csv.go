// csvAlpha holds the fragments a random text or field is built from:
// separators, quotes, line ends, leading and inner spaces, escaped quotes,
// a backslash and non-ASCII text. U+0000, U+001E and U+001F are absent: the
// record encoding's separators.
var csvAlpha = []string{
	"a", "b", "z", "0", ",", "\"", "\"\"", "\r", "\n", "\r\n", " ", "  ", "\t",
	"é", "日", "☺", "\\", `\.`, "£", ";", "#", "€", "θ",
}

// csvRandomSoup is a random text of fragments: unbalanced quotes, bare quotes
// and line ends where Go's Reader reports an error.
func csvRandomSoup(r *rand.Rand) string {
	var b strings.Builder
	for i, n := 0, r.Intn(24); i < n; i++ {
		b.WriteString(csvAlpha[r.Intn(len(csvAlpha))])
	}
	return b.String()
}

// csvRandomField is a random field: fragments, sometimes after a leading
// space, sometimes empty.
func csvRandomField(r *rand.Rand) string {
	var b strings.Builder
	if r.Intn(6) == 0 {
		b.WriteString(" ")
	}
	for i, n := 0, r.Intn(4); i < n; i++ {
		b.WriteString(csvAlpha[r.Intn(len(csvAlpha))])
	}
	return b.String()
}

// csvRandomRows is nrows records of one to five random fields, so records of
// one empty field, of empty fields only, and fields with separators, quotes
// and line ends all occur.
func csvRandomRows(r *rand.Rand, nrows int) [][]string {
	rows := make([][]string, nrows)
	for i := range rows {
		rec := make([]string, 1+r.Intn(5))
		for j := range rec {
			rec[j] = csvRandomField(r)
		}
		rows[i] = rec
	}
	return rows
}

// csvRandomOpts is a random option set for a read case: four separators (one
// multi byte), comments, field counts, lazy quotes and trimming.
func csvRandomOpts(r *rand.Rand) (comma, comment rune, fields int, lazy, trim bool) {
	comma = []rune{',', ',', ';', '\t', '£'}[r.Intn(5)]
	comment = []rune{0, 0, 0, '#', '€'}[r.Intn(5)]
	fields = []int{-1, -1, -1, 0, 2, 3}[r.Intn(6)]
	return comma, comment, fields, r.Intn(4) == 0, r.Intn(4) == 0
}

// csvPlain refuses a text the record encoding cannot hold.
func csvPlain(s string) string {
	if strings.ContainsAny(s, "\x00\x1e\x1f") {
		fmt.Fprintf(os.Stderr, "stdcorpus: csv: %q holds U+0000, U+001E or U+001F, the record encoding's separators\n", s)
		os.Exit(1)
	}
	return s
}

// csvRecs is records as the corpus's texts read back: the record count,
// U+001F, and each record's field count, U+0000, its fields joined by
// U+0000, records joined by U+001E.
func csvRecs(recs [][]string) string {
	parts := make([]string, len(recs))
	for i, r := range recs {
		fields := make([]string, len(r))
		for j, f := range r {
			fields[j] = csvPlain(f)
		}
		parts[i] = fmt.Sprintf("%d\x00%s", len(r), strings.Join(fields, "\x00"))
	}
	return fmt.Sprintf("%d\x1f%s", len(parts), strings.Join(parts, "\x1e"))
}

// csvGoReadOf is Go's Reader.ReadAll on c: csvRecs of its records, or "err "
// and its error's text, as std/csv's CsvErr displays it.
func csvGoReadOf(c csvReadCase) string {
	r := csv.NewReader(strings.NewReader(csvPlain(c.text)))
	if c.comma != 0 {
		r.Comma = c.comma
	}
	r.Comment = c.comment
	r.FieldsPerRecord = c.fields
	r.LazyQuotes = c.lazy
	r.TrimLeadingSpace = c.trim
	recs, err := r.ReadAll()
	if err != nil {
		return "err " + err.Error()
	}
	return csvRecs(recs)
}

// csvFormatXo is csv.format's text as std/csv.xo documents it: Go's Writer,
// except that a record of one empty field is written as "", so it reads back
// as a record, where Go's Writer writes an empty line (which its Reader
// skips).
func csvFormatXo(rows [][]string, comma rune, crlf bool) string {
	var b strings.Builder
	w := csv.NewWriter(&b)
	if comma != 0 {
		w.Comma = comma
	}
	w.UseCRLF = crlf
	for _, r := range rows {
		if len(r) == 1 && r[0] == "" {
			w.Flush()
			b.WriteString(`""`)
			if crlf {
				b.WriteString("\r\n")
			} else {
				b.WriteString("\n")
			}
			continue
		}
		w.Write(r)
	}
	w.Flush()
	return b.String()
}

// csvTextOfRows is rows with each field read as std/rt reads a Str: an
// invalid byte is U+FFFD (decision 0259).
func csvTextOfRows(rows [][]string) [][]string {
	out := make([][]string, len(rows))
	for i, r := range rows {
		out[i] = make([]string, len(r))
		for j, f := range r {
			out[i][j] = textOf(f)
		}
	}
	return out
}

// xr is r as an Xo rune literal, ',' for a comma of 0 (Go's default).
func xr(r rune) string {
	switch r {
	case 0:
		return `'\x00'`
	case '\n':
		return `'\n'`
	case '\r':
		return `'\r'`
	case '\t':
		return `'\t'`
	case '\'':
		return `'\''`
	case '\\':
		return `'\\'`
	}
	if r < 0x20 || r == 0x7f {
		return fmt.Sprintf(`'\u{%x}'`, r)
	}
	return "'" + string(r) + "'"
}

// xsep is a read or write case's separator: ',' when the case leaves Go's
// Comma at its default.
func xsep(comma rune) string {
	if comma == 0 {
		return "','"
	}
	return xr(comma)
}

// xrows is rows as Xo's List[List[Str]] literal.
func xrows(rows [][]string) string {
	var b strings.Builder
	b.WriteString("[")
	for i, r := range rows {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString("[")
		for j, f := range r {
			if j > 0 {
				b.WriteString(", ")
			}
			b.WriteString(xq(f))
		}
		b.WriteString("]")
	}
	b.WriteString("]")
	return b.String()
}

// csvRoundTrip keeps a write case the round trip through csv.format and
// csv.parse keeps: without UseCRLF, whose Writer drops a carriage return,
// and without "\r\n" in a field, which a Reader folds to "\n".
func csvRoundTrip(c csvWriteCase) bool {
	if c.crlf {
		return false
	}
	for _, r := range c.rows {
		for _, f := range r {
			if strings.Contains(f, "\r\n") {
				return false
			}
		}
	}
	return true
}

func csvCorpus() string {
	var o strings.Builder
	o.WriteString(header("encoding/csv's Reader.ReadAll and Writer on Go's reader_test.go readTests and writer_test.go writeTests, on the inputs of the ad hoc differential test this corpus replaces, and on seeded random texts and records, against std/csv's parse and format (Go's encoding/csv tests are Copyright 2011 The Go Authors, BSD-style license)"))
	o.WriteString("use std/csv\n")

	// read cases: Go's tests, the module test's inputs, then randoms
	reads := csvGoRead()
	reads = append(reads, csvOldRead...)
	rd := rand.New(rand.NewSource(43))
	wr := rand.New(rand.NewSource(47))
	for i := 0; i < 1000; i++ {
		text := csvRandomSoup(rd)
		comma, comment, fields, lazy, trim := csvRandomOpts(rd)
		reads = append(reads, csvReadCase{text, comma, comment, fields, lazy, trim})
	}
	for i := 0; i < 1000; i++ {
		comma, comment, fields, lazy, trim := csvRandomOpts(rd)
		rows := csvRandomRows(wr, 1+rd.Intn(4))
		text := csvFormatXo(rows, comma, false)
		reads = append(reads, csvReadCase{text, comma, comment, fields, lazy, trim})
	}
	o.WriteString("\n/// (text, sep, comment, fields, lazy quotes, trim leading space, Go's records as their counts and fields, or its error)\nconst READ_CASES: List[(Str, Rune, Rune, Int, Bool, Bool, Str)] = [\n")
	for _, c := range reads {
		c.text = textOf(c.text)
		csvPlain(c.text)
		fmt.Fprintf(&o, "  (%s, %s, %s, %d, %v, %v, %s),\n", xq(c.text), xsep(c.comma), xr(c.comment), c.fields, c.lazy, c.trim, xq(csvGoReadOf(c)))
	}
	o.WriteString("]\n")

	// write cases: Go's tests, the module test's inputs, then randoms
	writes := csvGoWrite()
	writes = append(writes, csvOldWrite...)
	for i := 0; i < 1000; i++ {
		n := 1 + rd.Intn(4)
		comma := []rune{',', ',', ';', '\t', '£'}[rd.Intn(5)]
		writes = append(writes, csvWriteCase{csvRandomRows(wr, n), comma, rd.Intn(2) == 0})
	}
	o.WriteString("\n/// (rows, sep, crlf, csv.format's text: Go's Writer, but a record of one empty field is \"\")\nconst WRITE_CASES: List[(List[List[Str]], Rune, Bool, Str)] = [\n")
	for _, c := range writes {
		rows := csvTextOfRows(c.rows)
		fmt.Fprintf(&o, "  (%s, %s, %v, %s),\n", xrows(rows), xsep(c.comma), c.crlf, xq(csvFormatXo(rows, c.comma, c.crlf)))
	}
	o.WriteString("]\n")

	// round trip: format then parse is the same records
	o.WriteString("\n/// (rows, sep): csv.parse(csv.format(rows, sep: sep), sep: sep) is rows\nconst ROUND_TRIP: List[(List[List[Str]], Rune)] = [\n")
	n := 0
	for _, c := range writes {
		if !csvRoundTrip(c) {
			continue
		}
		fmt.Fprintf(&o, "  (%s, %s),\n", xrows(csvTextOfRows(c.rows)), xsep(c.comma))
		n++
	}
	o.WriteString("]\n")

	o.WriteString(csvTests)
	return o.String()
}

