// csvStrip removes Go's position markers from a reader_test.go input: §
// before the start of a field, ¶ before a record and ∑ at an error, which
// Go's testing code removes before parsing. Inputs are copied verbatim from
// Go's table, so they can be compared with it.
func csvStrip(s string) string {
	return strings.NewReplacer("§", "", "¶", "", "∑", "").Replace(s)
}

