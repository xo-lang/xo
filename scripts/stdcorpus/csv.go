package main

// The csv corpus: Go's encoding/csv Reader and Writer as the oracle for
// std/csv's parse and format (decision 0164, decision 0298), on Go's own
// reader_test.go and writer_test.go inputs, on the inputs of the ad hoc
// differential test the corpus replaces (std/native/csv_test.xo, whose
// generator was never in the repo), and on seeded random texts and records.
//
// The records of a text are encoded as the list count, U+001F, and each
// record as its field count, U+0000, its fields joined by U+0000, records
// joined by U+001E, so an empty list, an empty record and one empty field
// all differ. Texts and fields holding U+0000, U+001E or U+001F are
// refused here, since the encoding could not tell them apart.
//
// One divergence is recorded rather than removed: csv.format writes a
// record of one empty field as "", so it reads back as a record, where Go's
// Writer writes an empty line, which Go's Reader skips. std/csv.xo's
// documentation states it, and WRITE_CASES holds Xo's form for every such
// record (see csvFormatXo).

import (
	"encoding/csv"
	"fmt"
	"math/rand"
	"os"
	"strings"
)

// csvReadCase is one Reader input: text read with comma (0 for Go's default
// ','), comment, FieldsPerRecord as fields (-1 unset), LazyQuotes and
// TrimLeadingSpace.
type csvReadCase struct {
	text    string
	comma   rune
	comment rune
	fields  int
	lazy    bool
	trim    bool
}

// csvWriteCase is one Writer input: rows written with comma (0 for ',') and
// UseCRLF.
type csvWriteCase struct {
	rows  [][]string
	comma rune
	crlf  bool
}

