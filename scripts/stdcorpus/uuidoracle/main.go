// Command uuidoracle prints the std/uuid corpus: github.com/google/uuid
// v1.6.0 (std/uuid's reference, decision 0282) on its own forms and on
// seeded random texts and bytes. scripts/stdcorpus runs it; it is its own
// module so the repository's go.mod has no third-party requirement.
package main

import (
	"fmt"
	"math/rand"
	"os"
	"strconv"
	"strings"

	"github.com/google/uuid"
)

func xq(s string) string {
	q := strconv.Quote(s)
	return strings.ReplaceAll(q, "$", `\$`)
}

func main() {
	r := rand.New(rand.NewSource(14))
	var o strings.Builder
	o.WriteString("// Generated by scripts/stdcorpus from github.com/google/uuid v1.6.0's Parse, FromBytes, Version, and String on seeded random texts and bytes (" + os.Args[1] + ").\n// Do not edit: regenerate with go run ./scripts/stdcorpus.\n")
	o.WriteString("use std/uuid\n\n/// (text, google/uuid's result: ok STRING VERSION or err TEXT)\nconst PARSE: List[(Str, Str)] = [\n")
	hex := "0123456789abcdefABCDEF"
	for i := 0; i < 2000; i++ {
		var b strings.Builder
		for k := 0; k < 32; k++ {
			b.WriteByte(hex[r.Intn(len(hex))])
		}
		h := b.String()
		dashed := h[0:8] + "-" + h[8:12] + "-" + h[12:16] + "-" + h[16:20] + "-" + h[20:32]
		var s string
		switch r.Intn(8) {
		case 0:
			s = h
		case 1:
			s = "urn:uuid:" + dashed
		case 2:
			s = "{" + dashed + "}"
		case 3:
			s = []string{"", "x", "00000000-0000-0000-0000-000000000000", "urn:uuid:", "{}", dashed + " ", "URN:UUID:" + dashed, "{" + dashed, dashed + "}"}[r.Intn(9)]
		default:
			s = dashed
		}
		if r.Intn(5) == 0 && len(s) > 0 {
			bs := []byte(s)
			bs[r.Intn(len(bs))] = "-xg{}:Z9 "[r.Intn(9)]
			s = string(bs)
		}
		if r.Intn(10) == 0 && len(s) > 0 {
			s = s[:r.Intn(len(s))]
		}
		w := ""
		if u, err := uuid.Parse(s); err != nil {
			w = "err " + err.Error()
		} else {
			w = fmt.Sprintf("ok %s %d", u.String(), int(u.Version()))
		}
		fmt.Fprintf(&o, "  (%s, %s),\n", xq(s), xq(w))
	}
	o.WriteString("]\n\n/// (bytes in hex, google/uuid's FromBytes: ok STRING or err TEXT)\nconst FROM_BYTES: List[(Str, Str)] = [\n")
	for i := 0; i < 300; i++ {
		b := make([]byte, []int{16, 16, 16, 15, 17, 0}[r.Intn(6)])
		r.Read(b)
		w := ""
		if u, err := uuid.FromBytes(b); err != nil {
			w = "err " + err.Error()
		} else {
			w = "ok " + u.String()
		}
		fmt.Fprintf(&o, "  (%q, %s),\n", fmt.Sprintf("%x", b), xq(w))
	}
	o.WriteString(`]

fn first_bad[T](bad: List[T]) -> List[T] { bad[0..(if bad.len() < 20 { bad.len() } else { 20 })] }

test "parse gives google/uuid's UUID, version, and errors" {
  var bad: List[(Str, Str, Str)] = []
  for (s, want) in PARSE {
    let got = match uuid.parse(s) {
      Ok(u) => "ok ${u} ${u.version()}"
      Err(e) => "err ${e.msg}"
    }
    if got != want {
      bad.push((s, got, want))
    }
  }
  expect(first_bad(bad)) == []
}

test "from_bytes is google/uuid's FromBytes, and bytes gives them back" {
  var bad: List[(Str, Str, Str)] = []
  for (h, want) in FROM_BYTES {
    let b = Bytes.from_hex(h) ?? b""
    let got = match uuid.from_bytes(b) {
      Ok(u) => if u.bytes() == b { "ok ${u}" } else { "bytes differ" }
      Err(e) => "err ${e.msg}"
    }
    if got != want {
      bad.push((h, got, want))
    }
  }
  expect(first_bad(bad)) == []
}
`)
	os.Stdout.WriteString(o.String())
}
