// nameBased: NewMD5, NewSHA1 and NewHash (SHA-256, version 8) of the four
// namespaces and of random ones, over empty, text and random names.
func nameBased(o *strings.Builder, r *rand.Rand) {
	o.WriteString("]\n\n/// (namespace, name in hex, google/uuid's NewMD5, NewSHA1, NewHash(sha256, 8))\nconst NAMED: List[(Str, Str, Str, Str, Str)] = [\n")
	spaces := []uuid.UUID{uuid.NameSpaceDNS, uuid.NameSpaceURL, uuid.NameSpaceOID, uuid.NameSpaceX500}
	names := [][]byte{nil, []byte("example.com"), []byte("https://go.dev/"), []byte("1.3.6.1"), []byte("cn=x"), []byte("\xff\x00")}
	for i := 0; i < 40; i++ {
		var u uuid.UUID
		r.Read(u[:])
		spaces = append(spaces, u)
		b := make([]byte, r.Intn(70))
		r.Read(b)
		names = append(names, b)
	}
	for i, sp := range spaces {
		for j, n := range names {
			if i >= 4 && j%7 != i%7 {
				continue
			}
			fmt.Fprintf(o, "  (%q, %q, %q, %q, %q),\n", sp.String(), fmt.Sprintf("%x", n), uuid.NewMD5(sp, n).String(), uuid.NewSHA1(sp, n).String(), uuid.NewHash(sha256.New(), sp, n, 8).String())
		}
	}
}

// fields: Variant, URN, Time, UnixTime, ClockSequence and NodeID of
// random UUIDs and of each version's bits.
func fields(o *strings.Builder, r *rand.Rand) {
	o.WriteString("]\n\n/// (UUID, google/uuid's Variant, URN, Time, UnixTime seconds and nanoseconds, ClockSequence, NodeID in hex)\nconst FIELDS: List[(Str, Str, Str, Int, Int, Int, Int, Str)] = [\n")
	var all []uuid.UUID
	all = append(all, uuid.Nil, uuid.Max, uuid.NameSpaceDNS)
	for i := 0; i < 200; i++ {
		var u uuid.UUID
		r.Read(u[:])
		if i%2 == 0 {
			u[6] = u[6]&0x0f | byte([]int{1, 2, 3, 4, 5, 6, 7, 8}[i/2%8])<<4
		}
		all = append(all, u)
	}
	for _, u := range all {
		sec, nsec := u.Time().UnixTime()
		fmt.Fprintf(o, "  (%q, %q, %q, %d, %d, %d, %d, %q),\n", u.String(), u.Variant().String(), u.URN(), int64(u.Time()), sec, nsec, u.ClockSequence(), fmt.Sprintf("%x", u.NodeID()))
	}
}

