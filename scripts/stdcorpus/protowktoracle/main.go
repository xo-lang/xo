func enc(m proto.Message) string {
	b, err := proto.MarshalOptions{Deterministic: true}.Marshal(m)
	if err != nil {
		panic(err)
	}
	return fmt.Sprintf("%x", b)
}

func hexs(b []byte) string { return fmt.Sprintf("%x", b) }

// val renders a Value as the Xo side does: n<bits>, s<len>:text, b0/b1, z,
// {key=val,...} in key order, [val,...], u for none.
func val(v *structpb.Value) string {
	switch k := v.GetKind().(type) {
	case nil:
		return "u"
	case *structpb.Value_NullValue:
		return "z"
	case *structpb.Value_NumberValue:
		return fmt.Sprintf("n%x", math.Float64bits(k.NumberValue))
	case *structpb.Value_StringValue:
		return fmt.Sprintf("s%d:%s", len(k.StringValue), k.StringValue)
	case *structpb.Value_BoolValue:
		if k.BoolValue {
			return "b1"
		}
		return "b0"
	case *structpb.Value_StructValue:
		return strct(k.StructValue)
	case *structpb.Value_ListValue:
		var p []string
		for _, e := range k.ListValue.GetValues() {
			p = append(p, val(e))
		}
		return "[" + strings.Join(p, ",") + "]"
	}
	panic("kind")
}

func strct(s *structpb.Struct) string {
	var keys []string
	for k := range s.GetFields() {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var p []string
	for _, k := range keys {
		p = append(p, fmt.Sprintf("%d:%s=%s", len(k), k, val(s.Fields[k])))
	}
	return "{" + strings.Join(p, ",") + "}"
}

var words = []string{"", "a", "kay", "héllo", "日本", "x y", "with tab", "0", "type.googleapis.com/pkg.Msg"}

// rjson is a random value as encoding/json decodes one: nil, bool,
// float64, string, []any or map[string]any.
func rjson(r *rand.Rand, depth int) any {
	k := r.Intn(7)
	if depth >= 3 && k >= 5 {
		k = 4
	}
	switch k {
	case 0:
		return nil
	case 1:
		return r.Intn(2) == 0
	case 2:
		return float64(r.Intn(2001) - 1000)
	case 3:
		return r.NormFloat64() * 1e6
	case 4:
		return words[r.Intn(len(words))]
	case 5:
		l := make([]any, r.Intn(4))
		for i := range l {
			l[i] = rjson(r, depth+1)
		}
		return l
	}
	m := map[string]any{}
	for i, n := 0, r.Intn(4); i < n; i++ {
		m[words[r.Intn(len(words))]] = rjson(r, depth+1)
	}
	return m
}

func rval(r *rand.Rand, depth int) *structpb.Value {
	n := 6
	if depth >= 3 {
		n = 4
	}
	switch r.Intn(n + 1) {
	case 0:
		return structpb.NewNullValue()
	case 1:
		return structpb.NewNumberValue([]float64{0, 1, -1, 1.5, 1e300, math.Inf(1), math.Inf(-1), 0.1, float64(r.Int63())}[r.Intn(9)])
	case 2:
		return structpb.NewStringValue(words[r.Intn(len(words))])
	case 3:
		return structpb.NewBoolValue(r.Intn(2) == 0)
	case 4:
		return &structpb.Value{}
	case 5:
		s := &structpb.Struct{Fields: map[string]*structpb.Value{}}
		for i, k := 0, r.Intn(4); i < k; i++ {
			s.Fields[words[r.Intn(len(words))]] = rval(r, depth+1)
		}
		return structpb.NewStructValue(s)
	default:
		l := &structpb.ListValue{}
		for i, k := 0, r.Intn(4); i < k; i++ {
			l.Values = append(l.Values, rval(r, depth+1))
		}
		return structpb.NewListValue(l)
	}
}

