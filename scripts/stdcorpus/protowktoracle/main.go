// ai renders what structpb's AsInterface returns as val renders a Value.
func ai(x any) string {
	switch y := x.(type) {
	case nil:
		return "z"
	case bool:
		if y {
			return "b1"
		}
		return "b0"
	case float64:
		return fmt.Sprintf("n%x", math.Float64bits(y))
	case string:
		return fmt.Sprintf("s%d:%s", len(y), y)
	case map[string]any:
		var keys []string
		for k := range y {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		var p []string
		for _, k := range keys {
			p = append(p, fmt.Sprintf("%d:%s=%s", len(k), k, ai(y[k])))
		}
		return "{" + strings.Join(p, ",") + "}"
	case []any:
		var p []string
		for _, e := range y {
			p = append(p, ai(e))
		}
		return "[" + strings.Join(p, ",") + "]"
	}
	panic(fmt.Sprintf("AsInterface gave %T", x))
}

