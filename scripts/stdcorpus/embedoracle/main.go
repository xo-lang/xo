// embedoracle writes the std/embed fuzz corpus (decision 0616's fuzz kind,
// task #233): seeded random paths, directories and glob patterns (the
// tree's own names, their parts, `.`, `..`, empty and doubled slashes, a
// leading `/` or `./`, trailing slashes, glob metacharacters, classes and
// escapes) asked of the tree of std/evidence/embed/stress/data (text,
// binary, an empty file, directories four deep), with Go's io/fs over it
// as the reference (an fstest.MapFS of its files: in memory and case
// sensitive as embed.FS, whatever the disk; the tree holds no `.` or `_`
// names, so embed.FS would hold the same files): fs.ReadFile for Dir.read and
// contains, fs.Sub of a directory then the files under it for
// sub(..).paths(), fs.Glob for fs().glob, fs.ReadDir for fs().read_dir.
// The test builds its Dir from the tree's paths (the stress program
// embeds the tree itself and checks the bytes).
// Dir.fs() is an Fs, with the real Fs's paths and glob (decision 0304):
// `/`, `.`, `./x` and `x/.` name what the OS would, which io/fs refuses, a
// `\` separates as `/` does and a `**` segment matches any directories;
// so Fs is asked only fs.ValidPath paths and patterns with neither.
//
// XO_EMBEDFUZZ_SEED (default 0, the committed corpus) moves the seed and
// XO_EMBEDFUZZ_N (default 400) sets how many queries of each kind are
// drawn; internal/stdtest's TestEmbedFuzz runs a fresh seed.
package main

import (
	"fmt"
	"io/fs"
	"math/rand"
	"os"
	"sort"
	"strconv"
	"strings"
	"testing/fstest"
)

func xq(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '$':
			b.WriteString(`\$`)
		case r == '\n':
			b.WriteString(`\n`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u{%x}`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func xlist(ss []string) string {
	q := make([]string, len(ss))
	for i, s := range ss {
		q[i] = xq(s)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

func envInt(name string, def int) int {
	if v, err := strconv.Atoi(os.Getenv(name)); err == nil {
		return v
	}
	return def
}

// TREE is the corpus's tree, from this module's directory
const TREE = "../../../std/evidence/embed/stress/data"

func main() {
	seed := int64(envInt("XO_EMBEDFUZZ_SEED", 0))
	n := envInt("XO_EMBEDFUZZ_N", 400)
	disk := os.DirFS(TREE)
	var files, dirs, parts []string
	mfs := fstest.MapFS{}
	err := fs.WalkDir(disk, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if strings.HasPrefix(d.Name(), ".") && p != "." || strings.HasPrefix(d.Name(), "_") {
			panic("embedoracle: the tree holds " + p + ", which embed leaves out")
		}
		if d.IsDir() {
			dirs = append(dirs, p)
		} else {
			files = append(files, p)
			mfs[p] = &fstest.MapFile{}
		}
		parts = append(parts, strings.Split(p, "/")...)
		return nil
	})
	if err != nil {
		panic(err)
	}
	var fsys fs.FS = mfs
	r := rand.New(rand.NewSource(seed*7919 + 5))
	pick := func(l []string) string { return l[r.Intn(len(l))] }
	path := func() string {
		var s string
		switch r.Intn(6) {
		case 0:
			s = pick(files)
		case 1:
			s = pick(dirs)
		case 2:
			s = pick(parts)
		case 3:
			s = pick(dirs) + "/" + pick(parts)
		case 4:
			s = pick(files)
			i := r.Intn(len(s) + 1)
			s = s[:i] + pick([]string{"", "/", "//", "/./", "/../", ".", "x", " "}) + s[i:]
		default:
			s = pick([]string{"", ".", "..", "/", "./", "a.txt/", "x.txt", "deep/a/b/c", "css//site.css", "../a.txt", "js/./app.js", "js/lib/../app.js", "A.TXT"})
		}
		return s
	}
	pattern := func() string {
		s := path()
		var b strings.Builder
		for _, c := range s {
			switch r.Intn(9) {
			case 0:
				b.WriteString("*")
			case 1:
				b.WriteString("?")
			case 2:
				b.WriteString(pick([]string{"[a-z]", "[^a]", "[!x]", "[a-]", "[]a]", "[", "[a", "]", "[]"}))
			default:
				b.WriteRune(c)
			}
		}
		if r.Intn(5) == 0 {
			return pick([]string{"*", "*/*", "*/*/*", "*.txt", "js/*/*.js", "[", "deep/*/*/*/*", "z/*", "*/", "a*b", "*s/*"})
		}
		return b.String()
	}
	// what Fs is not asked (above)
	osOnly := func(p string) bool {
		return !fs.ValidPath(p) || strings.Contains(p, "\\") || strings.Contains(p, "**")
	}
	var o strings.Builder
	o.WriteString("// Generated by scripts/stdcorpus from Go's io/fs over tree/ (" + os.Args[1] + ").\n")
	o.WriteString("// Do not edit: regenerate with go run ./scripts/stdcorpus embedfuzz.\n")
	o.WriteString("use std/embed\n\n/// the paths of std/evidence/embed/stress/data\nconst FILES: List[Str] = " + xlist(files) + "\n\n")
	o.WriteString("fn tree() -> embed.Dir {\n  var m: Map[Str, Bytes] = {}\n  for p in FILES {\n    m[p] = p.bytes()\n  }\n  embed.Dir{files: m}\n}\n\n")
	fmt.Fprintf(&o, "/// seed %d: (path, Go's fs.ReadFile found a file there)\nconst READS: List[(Str, Bool)] = [\n", seed)
	for i := 0; i < n; i++ {
		p := path()
		_, err := fs.ReadFile(fsys, p)
		fmt.Fprintf(&o, "  (%s, %v),\n", xq(p), err == nil)
	}
	o.WriteString("]\n\n/// (directory, the files under Go's fs.Sub of it, or no Sub)\nconst SUBS: List[(Str, Bool, List[Str])] = [\n")
	for i := 0; i < n/4; i++ {
		p := path()
		sub, err := fs.Sub(fsys, p)
		if st, serr := fs.Stat(fsys, p); err == nil && serr == nil && !st.IsDir() {
			// a file's Sub is the file named "."; Dir.sub is of directories
			continue
		}
		if err != nil {
			fmt.Fprintf(&o, "  (%s, false, []),\n", xq(p))
			continue
		}
		var got []string
		fs.WalkDir(sub, ".", func(q string, d fs.DirEntry, err error) error {
			if err == nil && !d.IsDir() {
				got = append(got, q)
			}
			return nil
		})
		sort.Strings(got)
		fmt.Fprintf(&o, "  (%s, true, %s),\n", xq(p), xlist(got))
	}
	o.WriteString("]\n\n/// (pattern, Go's fs.Glob refused it, its matches)\nconst GLOBS: List[(Str, Bool, List[Str])] = [\n")
	for i := 0; i < n; i++ {
		p := pattern()
		if osOnly(p) {
			continue
		}
		m, err := fs.Glob(fsys, p)
		sort.Strings(m)
		fmt.Fprintf(&o, "  (%s, %v, %s),\n", xq(p), err != nil, xlist(m))
	}
	o.WriteString("]\n\n/// (directory, Go's fs.ReadDir failed, its entries as NAME or NAME/)\nconst DIRS: List[(Str, Bool, List[Str])] = [\n")
	for i := 0; i < n/2; i++ {
		p := path()
		if osOnly(p) {
			continue
		}
		es, err := fs.ReadDir(fsys, p)
		var names []string
		for _, e := range es {
			if e.IsDir() {
				names = append(names, e.Name()+"/")
			} else {
				names = append(names, e.Name())
			}
		}
		fmt.Fprintf(&o, "  (%s, %v, %s),\n", xq(p), err != nil, xlist(names))
	}
	o.WriteString("]\n")
	o.WriteString(xoTests)
	fmt.Fprintf(os.Stderr, "embedoracle: seed %d, %d files and %d directories in the tree\n", seed, len(files), len(dirs))
	os.Stdout.WriteString(o.String())
}

const xoTests = `
test "Dir.read and contains agree with fs.ReadFile" {
  let d = tree()
  for (p, found) in READS {
    if d.read(p).is_some() != found { fault("read(${p}): ${d.read(p).is_some()}, Go ${found}") }
    if d.contains(p) != found { fault("contains(${p}): ${d.contains(p)}, Go ${found}") }
  }
}

test "Dir.sub(..).paths() agrees with fs.Sub" {
  let d = tree()
  for (p, ok, want) in SUBS {
    if ok && d.sub(p).paths() != want {
      fault("sub(${p}).paths() = ${d.sub(p).paths()}, Go ${want}")
    }
  }
}

test "Dir.fs().glob agrees with fs.Glob" {
  let f = tree().fs()
  for (p, bad, want) in GLOBS {
    match f.glob(p) {
      Ok(got) => {
        if bad { fault("glob(${p}) = ${got}, Go refuses the pattern") }
        if got.sort() != want { fault("glob(${p}) = ${got.sort()}, Go ${want}") }
      }
      Err(e) => { if !bad { fault("glob(${p}): ${e.display()}, Go ${want}") } }
    }
  }
}

test "Dir.fs().read_dir agrees with fs.ReadDir" {
  let f = tree().fs()
  for (p, bad, want) in DIRS {
    match f.read_dir(p) {
      Ok(es) => {
        let got = es.map(fn(e) { if e.is_dir { "${e.name}/" } else { e.name } })
        if bad { fault("read_dir(${p}) = ${got}, Go fails") }
        if got != want { fault("read_dir(${p}) = ${got}, Go ${want}") }
      }
      Err(e) => { if !bad { fault("read_dir(${p}): ${e.display()}, Go ${want}") } }
    }
  }
}
`
