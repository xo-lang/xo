// fakenetoracle writes the std/testing fuzz corpus (decision 0616's fuzz
// kind, task #233): seeded random sets of FakeNet patterns (Go 1.22's
// forms: a method or none, literal segments, {name} and {name...}
// wildcards, {$}, a trailing slash for a subtree) on a host of their own,
// and GET requests (paths drawn from the patterns' pieces), with
// net/http's ServeMux as the reference: the pattern it picks and the
// values of its wildcards. A set ServeMux refuses (a conflict, a bad
// pattern) is left out, and a request it answers with a redirect or a 405
// is one FakeNet has no handler for (a fake answers or fails, it never
// redirects; std/changes/testing.md 2026-11-11).
//
// XO_FAKENETFUZZ_SEED (default 0, the committed corpus) moves the seed
// and XO_FAKENETFUZZ_N (default 150) sets how many sets are drawn;
// internal/stdtest's TestFakenetFuzz runs a fresh seed.
package main

import (
	"fmt"
	"math/rand"
	"net/http"
	"net/http/httptest"
	"os"
	"strconv"
	"strings"
)

func xq(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '$':
			b.WriteString(`\$`)
		case r == '\n':
			b.WriteString(`\n`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u{%x}`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func xlist(ss []string) string {
	q := make([]string, len(ss))
	for i, s := range ss {
		q[i] = xq(s)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

func envInt(name string, def int) int {
	if v, err := strconv.Atoi(os.Getenv(name)); err == nil {
		return v
	}
	return def
}

var lits = []string{"a", "b", "users", "files", "x", "api", "v1"}

// pattern: a random Go 1.22 path pattern and the wildcard names it holds
func pattern(r *rand.Rand) (string, []string) {
	var segs, names []string
	n := r.Intn(4)
	for i := 0; i < n; i++ {
		switch r.Intn(5) {
		case 0:
			nm := fmt.Sprintf("w%d", i)
			segs = append(segs, "{"+nm+"}")
			names = append(names, nm)
		default:
			segs = append(segs, lits[r.Intn(len(lits))])
		}
	}
	p := "/" + strings.Join(segs, "/")
	switch r.Intn(5) {
	case 0:
		if p == "/" {
			p = "/{$}"
		} else {
			p += "/{$}"
		}
	case 1:
		if p != "/" {
			p += "/"
		}
	case 2:
		nm := "rest"
		if p == "/" {
			p = "/{" + nm + "...}"
		} else {
			p += "/{" + nm + "...}"
		}
		names = append(names, nm)
	}
	return p, names
}

func reqPath(r *rand.Rand) string {
	n := r.Intn(5)
	var segs []string
	for i := 0; i < n; i++ {
		if r.Intn(4) == 0 {
			segs = append(segs, strconv.Itoa(r.Intn(10)))
		} else {
			segs = append(segs, lits[r.Intn(len(lits))])
		}
	}
	p := "/" + strings.Join(segs, "/")
	if r.Intn(4) == 0 && p != "/" {
		p += "/"
	}
	return p
}

type route struct {
	pat   string // the fake's pattern, scheme and host included
	names []string
}

// one set: its routes, and each request with the route ServeMux picks
// (index, or -1) and its wildcards' values in name order
func set(r *rand.Rand, host string) ([]route, [][3]string, bool) {
	mux := http.NewServeMux()
	var routes []route
	ok := true
	func() {
		defer func() {
			if recover() != nil {
				ok = false
			}
		}()
		for i := 0; i < 1+r.Intn(5); i++ {
			p, names := pattern(r)
			m := []string{"", "GET ", "POST "}[r.Intn(3)]
			k := len(routes)
			routes = append(routes, route{m + "https://" + host + p, names})
			mux.HandleFunc(m+host+p, func(w http.ResponseWriter, q *http.Request) {
				var vs []string
				for _, nm := range names {
					vs = append(vs, nm+"="+q.PathValue(nm))
				}
				fmt.Fprintf(w, "%d %s", k, strings.Join(vs, ","))
			})
		}
	}()
	if !ok {
		return nil, nil, false
	}
	var reqs [][3]string
	for i := 0; i < 2+r.Intn(6); i++ {
		m := "GET"
		p := reqPath(r)
		q := httptest.NewRequest(m, "https://"+host+p, nil)
		w := httptest.NewRecorder()
		mux.ServeHTTP(w, q)
		if w.Code/100 == 3 {
			// a redirect, which a fake never answers with (above)
			continue
		}
		ans := "none"
		if w.Code == 200 {
			ans = w.Body.String()
		}
		reqs = append(reqs, [3]string{m, p, ans})
	}
	return routes, reqs, true
}

func main() {
	seed := int64(envInt("XO_FAKENETFUZZ_SEED", 0))
	n := envInt("XO_FAKENETFUZZ_N", 150)
	r := rand.New(rand.NewSource(seed*7919 + 7))
	var o strings.Builder
	o.WriteString("// Generated by scripts/stdcorpus from net/http's ServeMux (" + os.Args[1] + ").\n")
	o.WriteString("// Do not edit: regenerate with go run ./scripts/stdcorpus fakenetfuzz.\n")
	o.WriteString("use std/http\n\n")
	fmt.Fprintf(&o, "/// seed %d: (patterns, the wildcard names of each, requests as (method, path, ServeMux's \"INDEX name=value,...\" or \"none\"))\nconst SETS: List[(List[Str], List[List[Str]], List[(Str, Str, Str)])] = [\n", seed)
	kept, reqs := 0, 0
	for i := 0; i < n; i++ {
		host := fmt.Sprintf("h%d.example.test", i)
		routes, rq, ok := set(r, host)
		if !ok {
			continue
		}
		kept++
		var pats, names []string
		for _, rt := range routes {
			pats = append(pats, rt.pat)
			names = append(names, xlist(rt.names))
		}
		var rs []string
		for _, x := range rq {
			rs = append(rs, fmt.Sprintf("(%s, %s, %s)", xq(x[0]), xq("https://"+host+x[1]), xq(x[2])))
			reqs++
		}
		fmt.Fprintf(&o, "  (%s, [%s], [%s]),\n", xlist(pats), strings.Join(names, ", "), strings.Join(rs, ", "))
	}
	o.WriteString("]\n")
	o.WriteString(xoTests)
	fmt.Fprintf(os.Stderr, "fakenetoracle: seed %d, %d sets kept of %d, %d requests\n", seed, kept, n, reqs)
	os.Stdout.WriteString(o.String())
}

const xoTests = `
fn answer(net: Net, method: Str, url: Str) -> Str uses net.dial {
  match http.client(net).get(url) {
    Ok(resp) => if resp.status == 200 { resp.body.to_str() ?? "" } else { "status ${resp.status}" }
    Err(_) => "none"
  }
}

test "FakeNet picks the pattern net/http's ServeMux picks, with its wildcards" {
  var bad: List[Str] = []
  var n = 0
  for (pats, names, reqs) in SETS {
    for i in 0..pats.len() {
      let k = i
      let ns = names[i]
      os.net.handle(pats[i], fn(req: http.Request) -> http.Response {
        http.text(200, "${k} ${ns.map(fn(nm) { "${nm}=${req.param(nm)}" }).join(",")}")
      })
    }
    for (m, url, want) in reqs {
      n += 1
      let got = answer(os.net, m, url)
      if got != want {
        bad.push("${m} ${url}: got ${got}, ServeMux ${want}; patterns ${pats}")
      }
    }
  }
  if !bad.is_empty() {
    fault("${bad.len()} of ${n} requests differ, first: ${bad[0]}")
  }
}
`
