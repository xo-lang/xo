// Command charsetoracle prints the std/charset corpus: golang.org/x/text
// v0.43.0's encoding/unicode UTF-16 and charmap Latin-1 and Windows-1252
// decoders and encoders, htmlindex's labels, and Go's unicode/utf16, on
// hand picked and seeded random inputs. scripts/stdcorpus runs it; it is
// its own module so the repository's go.mod has no third-party
// requirement.
package main

