func hx(b []byte) string { return `"` + hex.EncodeToString(b) + `"` }

func xq(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"' || r == '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r == '$':
			b.WriteString(`\$`)
		case r >= 0x20 && r < 0x7f:
			b.WriteRune(r)
		default:
			fmt.Fprintf(&b, `\u{%x}`, r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

type enc struct {
	name string // the Charset variant
	e    encoding.Encoding
}

