// metricsoracle writes the std/metrics fuzz corpus (decision 0616's fuzz
// kind, task #261): seeded random registries of counters, gauges and
// histograms (with and without labels, label values with quotes,
// backslashes, newlines and Unicode, help text with escapes, buckets of
// several shapes) and random operations on them (counter adds, gauge sets
// and adds, observations on and between bucket bounds; values with NaN,
// infinities, signed zeros and wide exponents), with
// prometheus/client_golang v1.23.2 as the reference: std/metrics' text()
// must equal client_golang's text exposition (expfmt) of the same
// registry. Names are created in sorted order, so both orders agree (Go
// gathers by name, std/metrics in creation order).
//
// XO_METRICSFUZZ_SEED (default 0, the committed corpus) moves the seed and
// XO_METRICSFUZZ_N (default 60) sets how many registries are drawn;
// internal/stdtest's TestMetricsFuzz runs a fresh seed.
package main

import (
	"bytes"
	"fmt"
	"math"
	"math/rand"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/prometheus/client_golang/prometheus"
	"github.com/prometheus/common/expfmt"
)

func xq(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '$':
			b.WriteString(`\$`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\t':
			b.WriteString(`\t`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u{%x}`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func envInt(name string, def int) int {
	if v, err := strconv.Atoi(os.Getenv(name)); err == nil {
		return v
	}
	return def
}

// xf: an Xo expression for v (Float.parse keeps NaN, infinities and -0 exact)
func xf(v float64) string {
	return "(Float.parse(" + xq(strconv.FormatFloat(v, 'g', -1, 64)) + ") ?? 0.0)"
}

var labelVals = []string{"a", "b", "GET", "/x/y", "with \"quotes\"", `back\slash`, "new\nline", "naïve ✓", "", "tab\tsep", "日本"}
var helps = []string{"Requests.", "A \\ backslash.", "Two\nlines.", "Unicode ✓.", ""}

func value(r *rand.Rand, nonneg bool) float64 {
	var v float64
	switch r.Intn(9) {
	case 0:
		v = math.NaN()
	case 1:
		v = math.Inf(1)
	case 2:
		v = math.Inf(-1)
	case 3:
		v = math.Copysign(0, -1)
	case 4:
		v = math.Pow(10, float64(r.Intn(60)-30)) * float64(1+r.Intn(9))
	case 5:
		v = float64(r.Intn(1000))
	default:
		v = r.Float64() * float64(r.Intn(100)+1)
	}
	if nonneg {
		if math.IsNaN(v) || v < 0 || math.Signbit(v) {
			v = math.Abs(v)
			if math.IsNaN(v) {
				v = 1.5
			}
		}
	}
	return v
}

type inst struct {
	kind    string // counter, gauge, histogram
	name    string
	help    string
	labels  []string
	buckets []float64
}

func buckets(r *rand.Rand) []float64 {
	switch r.Intn(3) {
	case 0:
		return nil // the default
	case 1:
		return prometheus.LinearBuckets(float64(r.Intn(5)), float64(1+r.Intn(3)), 1+r.Intn(5))
	default:
		return prometheus.ExponentialBuckets(0.001*float64(1+r.Intn(5)), 2+float64(r.Intn(3)), 1+r.Intn(6))
	}
}

func main() {
	seed := int64(envInt("XO_METRICSFUZZ_SEED", 0))
	n := envInt("XO_METRICSFUZZ_N", 60)
	r := rand.New(rand.NewSource(seed*7919 + 11))
	var o strings.Builder
	o.WriteString("// Generated by scripts/stdcorpus from prometheus/client_golang v1.23.2 (" + os.Args[1] + ").\n")
	o.WriteString("// Do not edit: regenerate with go run ./scripts/stdcorpus metricsfuzz.\n")
	o.WriteString("use std/metrics\n\n")
	o.WriteString("/// The text less std/metrics' own families (xo_metrics_*, which Go has not).\n")
	o.WriteString("fn without_xo(t: Str) -> Str {\n  var out = \"\"\n  for l in t.lines() {\n    if l.starts_with(\"xo_metrics_\") || l.starts_with(\"# HELP xo_metrics_\") || l.starts_with(\"# TYPE xo_metrics_\") { continue }\n    out += l + \"\\n\"\n  }\n  out\n}\n")
	for c := 0; c < n; c++ {
		reg := prometheus.NewRegistry()
		var body strings.Builder
		body.WriteString("  let r = metrics.registry()\n")
		ni := 1 + r.Intn(4)
		names := map[string]bool{}
		var insts []inst
		for len(insts) < ni {
			nm := fmt.Sprintf("m%d_%s", r.Intn(50), []string{"total", "seconds", "bytes", "x"}[r.Intn(4)])
			if names[nm] {
				continue
			}
			names[nm] = true
			k := []string{"counter", "gauge", "histogram"}[r.Intn(3)]
			var ls []string
			for i := 0; i < r.Intn(3); i++ {
				ls = append(ls, fmt.Sprintf("l%d", i))
			}
			in := inst{kind: k, name: nm, help: helps[r.Intn(len(helps))], labels: ls}
			if k == "histogram" {
				in.buckets = buckets(r)
			}
			insts = append(insts, in)
		}
		sort.Slice(insts, func(i, j int) bool { return insts[i].name < insts[j].name })
		cvs := map[string]*prometheus.CounterVec{}
		gvs := map[string]*prometheus.GaugeVec{}
		hvs := map[string]*prometheus.HistogramVec{}
		for i, in := range insts {
			lsx := make([]string, len(in.labels))
			for j, l := range in.labels {
				lsx[j] = xq(l)
			}
			lx := "[" + strings.Join(lsx, ", ") + "]"
			switch in.kind {
			case "counter":
				v := prometheus.NewCounterVec(prometheus.CounterOpts{Name: in.name, Help: in.help}, in.labels)
				if len(in.labels) == 0 {
					v.WithLabelValues() // one series from the start, as Go's NewCounter and std/metrics' unlabelled counter
				}
				reg.MustRegister(v)
				cvs[in.name] = v
				fmt.Fprintf(&body, "  let _i%d = r.counter(%s, %s, %s)\n", i, xq(in.name), xq(in.help), lx)
			case "gauge":
				v := prometheus.NewGaugeVec(prometheus.GaugeOpts{Name: in.name, Help: in.help}, in.labels)
				if len(in.labels) == 0 {
					v.WithLabelValues()
				}
				reg.MustRegister(v)
				gvs[in.name] = v
				fmt.Fprintf(&body, "  let _i%d = r.gauge(%s, %s, %s)\n", i, xq(in.name), xq(in.help), lx)
			default:
				b := in.buckets
				if b == nil {
					b = prometheus.DefBuckets
				}
				v := prometheus.NewHistogramVec(prometheus.HistogramOpts{Name: in.name, Help: in.help, Buckets: b}, in.labels)
				if len(in.labels) == 0 {
					v.WithLabelValues()
				}
				reg.MustRegister(v)
				hvs[in.name] = v
				bs := make([]string, len(b))
				for j, x := range b {
					bs[j] = xf(x)
				}
				if in.buckets == nil {
					fmt.Fprintf(&body, "  let _i%d = r.histogram(%s, %s, %s)\n", i, xq(in.name), xq(in.help), lx)
				} else {
					fmt.Fprintf(&body, "  let _i%d = r.histogram(%s, %s, %s, buckets: [%s])\n", i, xq(in.name), xq(in.help), lx, strings.Join(bs, ", "))
				}
			}
		}
		for op := 0; op < 1+r.Intn(12); op++ {
			i := r.Intn(len(insts))
			in := insts[i]
			vals := make([]string, len(in.labels))
			vx := make([]string, len(in.labels))
			for j := range in.labels {
				vals[j] = labelVals[r.Intn(len(labelVals))]
				vx[j] = xq(vals[j])
			}
			vl := "[" + strings.Join(vx, ", ") + "]"
			switch in.kind {
			case "counter":
				v := value(r, true)
				cvs[in.name].WithLabelValues(vals...).Add(v)
				fmt.Fprintf(&body, "  _i%d.add(%s, %s)\n", i, xf(v), vl)
			case "gauge":
				v := value(r, false)
				if r.Intn(2) == 0 {
					gvs[in.name].WithLabelValues(vals...).Set(v)
					fmt.Fprintf(&body, "  _i%d.set(%s, %s)\n", i, xf(v), vl)
				} else {
					gvs[in.name].WithLabelValues(vals...).Add(v)
					fmt.Fprintf(&body, "  _i%d.add(%s, %s)\n", i, xf(v), vl)
				}
			default:
				v := value(r, false)
				if b := in.buckets; b != nil && r.Intn(2) == 0 {
					v = b[r.Intn(len(b))] // on a bound
				}
				hvs[in.name].WithLabelValues(vals...).Observe(v)
				fmt.Fprintf(&body, "  _i%d.observe(%s, %s)\n", i, xf(v), vl)
			}
		}
		mfs, err := reg.Gather()
		if err != nil {
			fmt.Fprintf(os.Stderr, "metricsoracle: case %d: %v\n", c, err)
			continue
		}
		var want bytes.Buffer
		for _, mf := range mfs {
			if _, err := expfmt.MetricFamilyToText(&want, mf); err != nil {
				panic(err)
			}
		}
		fmt.Fprintf(&o, "\ntest \"registry %d (seed %d)\" {\n%s  expect(without_xo(r.text())) == %s\n}\n", c, seed, body.String(), xq(want.String()))
	}
	fmt.Fprintf(os.Stderr, "metricsoracle: seed %d, %d registries\n", seed, n)
	os.Stdout.WriteString(o.String())
}
