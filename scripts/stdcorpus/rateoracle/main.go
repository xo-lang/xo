// Command rateoracle prints TestRateFuzz's cases: golang.org/x/time/rate
// v0.16.0's Limiter (std/rate's reference) driven at explicit times
// (AllowN, ReserveN, DelayFrom, CancelAt, SetLimitAt, SetBurstAt,
// TokensAt) by seeded random operation sequences. It is its own module so
// the repository's go.mod has no third-party requirement.
//
//	go run . fuzz SEED N
package main

import (
	"fmt"
	"math"
	"math/rand"
	"os"
	"strconv"
	"strings"
	"time"

	"golang.org/x/time/rate"

	"stdcorpus/rateoracle/hostile"
)

// t0 is the fake clock's start, well after a new limiter's last time.
var t0 = time.Unix(1000000000, 0)

func limitOf(rg *rand.Rand) rate.Limit {
	switch rg.Intn(8) {
	case 0:
		return rate.Inf
	case 1:
		return 0
	case 2:
		return rate.Every(time.Duration(1 + rg.Int63n(int64(3*time.Second))))
	case 3:
		return rate.Limit(rg.Float64() * 3)
	case 4:
		return []rate.Limit{0.7692307692307693, 1e-9, 1e9, 0.1, 1.0 / 3}[rg.Intn(5)]
	}
	return rate.Limit(1 + rg.Intn(100))
}

func main() {
	if len(os.Args) != 4 || os.Args[1] != "fuzz" {
		fmt.Fprintln(os.Stderr, "usage: rateoracle fuzz SEED N")
		os.Exit(2)
	}
	seed, _ := strconv.ParseInt(os.Args[2], 10, 64)
	n, _ := strconv.Atoi(os.Args[3])
	rg := rand.New(rand.NewSource(seed))
	var o strings.Builder
	fmt.Fprintf(&o, "// Generated by scripts/stdcorpus/rateoracle fuzz %d %d from golang.org/x/time/rate v0.16.0 (TestRateFuzz).\n\nuse std/rate\nuse std/testing\n\n", seed, n)
	o.WriteString("/// (limit bits, burst, operations, rate's answers): operations t:NS (the clock at t0 + NS), k (tokens, as bits), a:N (allow_n), r:N (reserve_n: ok and delay ns), d:J (reservation J's delay ns), c:J (cancel J), l:BITS (set_limit), b:N (set_burst)\nconst CASES: List[(Int, Int, Str, Str)] = [\n")
	for i := 0; i < n; i++ {
		lim := limitOf(rg)
		burst := rg.Intn(11)
		if rg.Intn(10) == 0 {
			burst = rg.Intn(1000)
		}
		if rg.Intn(20) == 0 {
			burst = int(hostile.Pick(rg, hostile.Ints())) // task #352
		}
		l := rate.NewLimiter(lim, burst)
		now := t0
		var at int64
		var rs []*rate.Reservation
		var ops, ans []string
		step := []int64{int64(time.Millisecond), int64(100 * time.Millisecond), int64(time.Second), 1}[rg.Intn(4)]
		for k := 1 + rg.Intn(40); k > 0; k-- {
			switch c := rg.Intn(14); {
			case c < 4:
				d := rg.Int63n(20) * step
				if rg.Intn(12) == 0 {
					d = -rg.Int63n(5) * step // the clock jumps back
				}
				at += d
				now = t0.Add(time.Duration(at))
				ops = append(ops, fmt.Sprintf("t:%d", at))
			case c < 5:
				ops = append(ops, "k")
				ans = append(ans, strconv.FormatInt(int64(math.Float64bits(l.TokensAt(now))), 10))
			case c < 8:
				m := countOf(rg, burst)
				ops = append(ops, fmt.Sprintf("a:%d", m))
				ans = append(ans, map[bool]string{true: "1", false: "0"}[l.AllowN(now, m)])
			case c < 10:
				m := countOf(rg, burst)
				r := l.ReserveN(now, m)
				rs = append(rs, r)
				ops = append(ops, fmt.Sprintf("r:%d", m))
				ans = append(ans, fmt.Sprintf("%v,%d", map[bool]string{true: "1", false: "0"}[r.OK()], int64(r.DelayFrom(now))))
			case c < 11:
				if len(rs) == 0 {
					continue
				}
				j := rg.Intn(len(rs))
				ops = append(ops, fmt.Sprintf("d:%d", j))
				ans = append(ans, strconv.FormatInt(int64(rs[j].DelayFrom(now)), 10))
			case c < 12:
				if len(rs) == 0 {
					continue
				}
				j := rg.Intn(len(rs))
				ops = append(ops, fmt.Sprintf("c:%d", j))
				rs[j].CancelAt(now)
			case c < 13:
				nl := limitOf(rg)
				ops = append(ops, fmt.Sprintf("l:%d", int64(math.Float64bits(float64(nl)))))
				l.SetLimitAt(now, nl)
			default:
				nb := rg.Intn(11)
				ops = append(ops, fmt.Sprintf("b:%d", nb))
				l.SetBurstAt(now, nb)
			}
		}
		fmt.Fprintf(&o, "  (%d, %d, %q, %q),\n", int64(math.Float64bits(float64(lim))), burst, strings.Join(ops, " "), strings.Join(ans, " "))
	}
	o.WriteString("]\n")
	o.WriteString(tests)
	fmt.Print(o.String())
}

const tests = `
fn t0() -> Time { Time.from_unix(1000000000) }

fn arg(w: Str) -> Int {
  let (_, a) = w.cut(":") ?? fault("op ${w}")
  Int.parse(a) ?? fault("arg ${w}")
}

/// The answers of the operations on a limiter (limit, burst) at the fake
/// clock's times.
fn replay(c: testing.FakeClock, lim: Float, burst: Int, ops: Str) -> Str uses clock {
  c.set(t0())
  let l = rate.new(lim, burst, c)
  var rs: List[rate.Reservation] = []
  var ans: List[Str] = []
  if ops == "" {
    return ""
  }
  for w in ops.split(" ") {
    match w.bytes()[0] {
      't' => c.set(t0() + Duration.from_nanos(arg(w)))
      'k' => ans.push("${l.tokens().to_bits()}")
      'a' => ans.push(if l.allow_n(arg(w)) { "1" } else { "0" })
      'r' => {
        let r = l.reserve_n(arg(w))
        rs.push(r)
        ans.push("${if r.ok() { "1" } else { "0" }},${r.delay().nanos()}")
      }
      'd' => ans.push("${rs[arg(w)].delay().nanos()}")
      'c' => rs[arg(w)].cancel()
      'l' => l.set_limit(Float.from_bits(arg(w)))
      _ => l.set_burst(arg(w))
    }
  }
  ans.join(" ")
}

test "std/rate's Limiter answers as golang.org/x/time/rate's at every time" {
  var bad: List[Str] = []
  var k = 0
  for (lim, burst, ops, want) in CASES {
    let got = replay(os.clock, Float.from_bits(lim), burst, ops)
    if got != want {
      let g = got.split(" ")
      let ws = want.split(" ")
      var i = 0
      while i < g.len() && i < ws.len() && g[i] == ws[i] {
        i += 1
      }
      bad.push("case ${k} (limit ${Float.from_bits(lim)}, burst ${burst}): answer ${i}: got ${g.get(i) ?? "(none)"} want ${ws.get(i) ?? "(none)"}; ops ${ops}")
    }
    k += 1
  }
  expect(bad[0..(if bad.len() < 5 { bad.len() } else { 5 })]) == []
}
`

// countOf is an allow_n or reserve_n count: up to burst+2, or one in ten
// a hostile Int (task #352: Int's edges, powers of two and their
// neighbours).
func countOf(rg *rand.Rand, burst int) int {
	if rg.Intn(10) == 0 {
		return int(hostile.Pick(rg, hostile.Ints()))
	}
	return rg.Intn(min(max(burst, 0), 1000) + 3)
}
