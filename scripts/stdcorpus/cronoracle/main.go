// Command cronoracle prints the std/cron corpus: github.com/robfig/cron/v3
// v3.0.1's ParseStandard and Next (std/cron's reference) on seeded random
// specs, zones and start times (including daylight saving changes), and on
// malformed specs. scripts/stdcorpus runs it; it is its own module so the
// repository's go.mod has no third-party requirement.
package main

import (
	"fmt"
	"math/rand"
	"os"
	"strconv"
	"strings"
	"time"

	"github.com/robfig/cron/v3"
)

func xq(s string) string {
	return strings.ReplaceAll(strconv.Quote(s), "$", `\$`)
}

func main() {
	rg := rand.New(rand.NewSource(58))
	zones := []string{"", "UTC", "America/New_York", "Europe/London", "America/Sao_Paulo", "Australia/Lord_Howe", "Asia/Kolkata", "Pacific/Auckland", "Europe/Berlin"}
	mins := []string{"*", "0", "5", "30", "59", "*/15", "0-30/10", "1,2,3", "10-20", "*/7", "?", "15/20", "0,30", "45-50"}
	hours := []string{"*", "0", "1", "2", "3", "9", "12", "23", "*/6", "1-5", "2,14", "9-17", "0-23/2", "22/1"}
	doms := []string{"*", "1", "15", "28", "29", "30", "31", "*/10", "1,15", "10-20", "?", "L1"[:0] + "5", "2/9"}
	months := []string{"*", "1", "2", "3", "6", "10", "11", "12", "jan", "JUN", "mar-oct", "*/3", "1,7", "feb,nov"}
	dows := []string{"*", "0", "1", "6", "mon", "SAT", "mon-fri", "sun,wed", "?", "1-5", "*/2", "tue/2"}
	descs := []string{"@yearly", "@annually", "@monthly", "@weekly", "@daily", "@midnight", "@hourly", "@every 1h30m", "@every 90s", "@every 10m", "@every 500ms", "@every 1h"}
	pick := func(l []string) string { return l[rg.Intn(len(l))] }

	// start times: random, and each year's DST weeks
	randStart := func() int64 { return time.Date(2019, 1, 1, 0, 0, 0, 0, time.UTC).Unix() + rg.Int63n(12*365*86400) }
	dst := []time.Time{
		time.Date(2026, 3, 8, 6, 0, 0, 0, time.UTC), time.Date(2026, 11, 1, 4, 0, 0, 0, time.UTC),
		time.Date(2026, 3, 29, 0, 0, 0, 0, time.UTC), time.Date(2026, 10, 25, 0, 0, 0, 0, time.UTC),
		time.Date(2018, 11, 3, 1, 0, 0, 0, time.UTC), time.Date(2026, 10, 4, 14, 0, 0, 0, time.UTC),
		time.Date(2026, 4, 5, 14, 0, 0, 0, time.UTC), time.Date(2026, 9, 27, 12, 0, 0, 0, time.UTC),
	}

	var o strings.Builder
	o.WriteString("// Generated by scripts/stdcorpus from github.com/robfig/cron/v3 v3.0.1 (ParseStandard, Next) on seeded specs, zones and\n// start times, and malformed specs.\n// Do not edit: regenerate with go run ./scripts/stdcorpus.\nuse std/cron\nuse std/time\n\n")
	o.WriteString("/// (spec, then (start unix seconds, the next fire unix seconds, -1 for none))\nconst NEXTS: List[(Str, List[(Int, Int)])] = [\n")
	seen := map[string]bool{}
	emit := func(spec string) {
		if seen[spec] {
			return
		}
		seen[spec] = true
		sched, err := cron.ParseStandard(spec)
		if err != nil {
			return
		}
		var pairs []string
		starts := []int64{}
		for i := 0; i < 5; i++ {
			starts = append(starts, randStart())
		}
		for _, d := range dst {
			starts = append(starts, d.Unix()+int64(rg.Intn(86400)))
		}
		starts = append(starts, 0, 1<<31)
		for _, s := range starts {
			t := time.Unix(s, 0).UTC()
			n := sched.Next(t)
			v := int64(-1)
			if !n.IsZero() {
				v = n.Unix()
			}
			pairs = append(pairs, fmt.Sprintf("(%d, %d)", s, v))
		}
		o.WriteString(fmt.Sprintf("  (%s, [%s]),\n", xq(spec), strings.Join(pairs, ", ")))
	}
	for _, d := range descs {
		for _, z := range zones[1:4] {
			emit("TZ=" + z + " " + d)
		}
		emit(d)
	}
	for i := 0; i < 420; i++ {
		spec := fmt.Sprintf("%s %s %s %s %s", pick(mins), pick(hours), pick(doms), pick(months), pick(dows))
		if z := pick(zones); z != "" {
			prefix := "TZ="
			if rg.Intn(3) == 0 {
				prefix = "CRON_TZ="
			}
			spec = prefix + z + " " + spec
		}
		emit(spec)
	}
	// fixed DST regressions: a time in a gap, a time in an overlap
	for _, z := range zones[2:] {
		emit("TZ=" + z + " 30 2 * * *")
		emit("TZ=" + z + " 30 1 * * *")
		emit("TZ=" + z + " 0 0 * * *")
		emit("TZ=" + z + " */20 * * * *")
	}
	o.WriteString("]\n\n/// (spec, robfig/cron's error text)\nconst ERRS: List[(Str, Str)] = [\n")
	bad := []string{"", "* * * *", "* * * * * *", "* * * * * * *", "60 * * * *", "* 24 * * *", "* * 0 * *", "* * 32 * *", "* * * 0 * ", "* * * 13 *", "* * * * 7", "a * * * *", "5-1 * * * *", "*/0 * * * *", "1-2-3 * * * *", "1/2/3 * * * *", "-1 * * * *", "+5 * * * *", "99999999999999999999 * * * *", "1.5 * * * *", "* * * foo *", "* * * * foo", "@bogus", "@every", "@reboot", "* * * * *x", "5- * * * *", "-5 * * * *", "0-60 * * * *", "*/ * * * *", "1,,2 * * * *", ", * * * *", "TZ=Nowhere/Land * * * * *", "feb-jan * * * *", "* * * jan-feb *", "* * * feb-jan *"}
	seenErr := map[string]bool{}
	for _, spec := range bad {
		if seenErr[spec] {
			continue
		}
		seenErr[spec] = true
		_, err := cron.ParseStandard(spec)
		if err == nil {
			// valid in robfig: not an error case, listed with an empty text
			o.WriteString(fmt.Sprintf("  (%s, \"\"),\n", xq(spec)))
			continue
		}
		txt := err.Error()
		if strings.HasPrefix(spec, "TZ=") {
			txt = "provided bad location"
		}
		o.WriteString(fmt.Sprintf("  (%s, %s),\n", xq(spec), xq(txt)))
	}
	o.WriteString("]\n\n")
	fmt.Fprint(os.Stdout, o.String())
	fmt.Fprint(os.Stdout, tests)
}

const tests = `/// The Go backend embeds only the zones a program names by a constant
/// (the native backends embed the whole database for cron's own lookup), so
/// the corpus names the zones its specs use.
fn embed_zones() -> List[Str] {
  var out: List[Str] = []
  for r in [time.zone("America/New_York"), time.zone("Europe/London"), time.zone("America/Sao_Paulo"), time.zone("Australia/Lord_Howe"), time.zone("Asia/Kolkata"), time.zone("Pacific/Auckland"), time.zone("Europe/Berlin")] {
    out.push(r.ok().map(fn(z) { z.name() }) ?? "")
  }
  out
}

fn unix_of(t: Time?) -> Int {
  match t {
    Some(x) => x.unix()
    None => -1
  }
}

test "next is robfig/cron's on every spec, zone and start" {
  expect(embed_zones().len()) == 7
  var bad: List[Str] = []
  for (spec, pairs) in NEXTS {
    let sched = match cron.parse(spec) {
      Ok(x) => x
      Err(e) => fault("parse ${spec}: ${e.display()}")
    }
    for (start, want) in pairs {
      let got = unix_of(sched.next(Time.from_unix(start)))
      if got != want {
        bad.push("${spec} from ${start}: ${got} want ${want}")
        break
      }
    }
  }
  expect(bad[0..(if bad.len() < 8 { bad.len() } else { 8 })]) == []
}

test "a bad spec has robfig/cron's error text" {
  var bad: List[Str] = []
  for (spec, want) in ERRS {
    match cron.parse(spec) {
      Ok(_) => {
        if want != "" {
          bad.push("${spec}: parsed, want ${want}")
        }
      }
      Err(e) => {
        let got = e.display()
        let ok = if want.starts_with("provided bad location") { got.starts_with(want) } else { got == want }
        if !ok {
          bad.push("${spec}: ${got} want ${want}")
        }
      }
    }
  }
  expect(bad) == []
}

test "the zone of a schedule" {
  let s = cron.parse("TZ=America/New_York 0 9 * * *").ok() ?? fault("parse")
  expect(s.zone().name()) == "America/New_York"
  let u = cron.parse("0 9 * * *").ok() ?? fault("parse")
  expect(u.zone().name()) == "UTC"
  let d = cron.parse("0 9 * * *", time.zone("Europe/Berlin").ok() ?? fault("zone")).ok() ?? fault("parse")
  expect(d.zone().name()) == "Europe/Berlin"
}
`
