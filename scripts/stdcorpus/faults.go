// Fault corpora: one small program per runtime fault, in
// internal/stdtest/testdata/faults, which TestSliceFaults builds and runs
// on every backend and compares with the case's want.txt (the Go backend's
// recorded behavior). A fault cannot run inside a test binary, so each
// case is a plain program; unlike the module corpora these are programs,
// not `xo test` files.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
)

// faultCase is one program: what it binds, the expression that faults or
// succeeds, and the spec claim it pins down.
type faultCase struct {
	name string
	decl string
	expr string
	spec string
}

// sliceFaultCases are the slice fault cases of core 3.6: a range of a Str
// or Bytes, in range and out of it. The Str's `héllo` is 6 bytes with é on
// bytes 1..2, so 1 and 3 are rune starts and 2 is not.
var sliceFaultCases = []faultCase{
	{"str_in", `let s = "héllo"`, `os.stdio.println(s[0..1])`, "core 3.6: a slice in range is the bytes lo..hi"},
	{"str_empty_start", `let s = "héllo"`, `os.stdio.println("[" + s[0..0] + "]")`, "core 3.6: an empty slice at the start"},
	{"str_empty_end", `let s = "héllo"`, `os.stdio.println("[" + s[6..6] + "]")`, "core 3.6: an empty slice at the end"},
	{"str_full", `let s = "héllo"`, `os.stdio.println(s[0..6])`, "core 3.6: a slice of the whole Str"},
	{"str_open_all", `let s = "héllo"`, `os.stdio.println(s[..])`, "core 3.6: s[..] is the whole Str"},
	{"str_open_lo", `let s = "héllo"`, `os.stdio.println(s[..3])`, "core 3.6: s[..n] starts at 0"},
	{"str_open_hi", `let s = "héllo"`, `os.stdio.println(s[3..])`, "core 3.6: s[n..] ends at the length"},
	{"str_runes", `let s = "héllo"`, `os.stdio.println(s[1..3])`, "core 3.6: a Str slice on rune boundaries is not a fault"},
	{"str_reversed", `let s = "héllo"`, `os.stdio.println(s[3..1])`, "core 3.6: b < a faults"},
	{"str_past_end", `let s = "héllo"`, `os.stdio.println(s[0..7])`, "core 3.6: b past the end faults"},
	{"str_open_past_end", `let s = "héllo"`, `os.stdio.println(s[..7])`, "core 3.6: s[..n] with n past the end faults as 0..n"},
	{"str_lo_past_end", `let s = "héllo"`, `os.stdio.println(s[7..])`, "core 3.6: s[a..] with a past the end faults as a..length"},
	{"str_neg_lo", `let s = "héllo"`, `os.stdio.println(s[-1..2])`, "core 3.6: a negative lo faults and prints it"},
	{"str_neg_hi", `let s = "héllo"`, `os.stdio.println(s[0..-1])`, "core 3.6: a negative hi faults and prints it"},
	{"str_uint_wrap", `let u: UInt64 = 18446744073709551615
  let s = "héllo"`, `os.stdio.println(s[0..u])`, "core 3.6: a UInt64 bound wraps to a negative Int, and the fault prints the wrapped value"},
	{"str_split_hi", `let s = "héllo"`, `os.stdio.println(s[0..2])`, "core 3.6: slicing a Str inside a UTF-8 sequence faults (hi inside é)"},
	{"str_split_lo", `let s = "héllo"`, `os.stdio.println(s[2..3])`, "core 3.6: slicing a Str inside a UTF-8 sequence faults (lo inside é)"},
	{"str_split_both", `let s = "héllo"`, `os.stdio.println(s[1..2])`, "core 3.6: slicing a Str inside a UTF-8 sequence faults (a range inside é)"},
	{"bytes_in", `let b = "héllo".bytes()`, `os.stdio.println("${b[0..2].len()}")`, "core 3.6: a Bytes slice in range"},
	{"bytes_empty_end", `let b = "héllo".bytes()`, `os.stdio.println("${b[6..6].len()}")`, "core 3.6: an empty Bytes slice at the end"},
	{"bytes_full", `let b = "héllo".bytes()`, `os.stdio.println("${b[0..6].len()}")`, "core 3.6: a slice of the whole Bytes"},
	{"bytes_open", `let b = "héllo".bytes()`, `os.stdio.println("${b[2..].len()}")`, "core 3.6: b[n..] ends at the length"},
	{"bytes_split_ok", `let b = "héllo".bytes()`, `os.stdio.println("${b[1..3].len()}")`, "core 3.6: Bytes has no UTF-8 boundary rule, so a slice inside é is not a fault"},
	{"bytes_reversed", `let b = "héllo".bytes()`, `os.stdio.println("${b[3..1].len()}")`, "core 3.6: b < a faults"},
	{"bytes_past_end", `let b = "héllo".bytes()`, `os.stdio.println("${b[0..7].len()}")`, "core 3.6: b past the end faults"},
	{"bytes_lo_past_end", `let b = "héllo".bytes()`, `os.stdio.println("${b[7..].len()}")`, "core 3.6: b[a..] with a past the end faults as a..length"},
	{"bytes_neg", `let b = "héllo".bytes()`, `os.stdio.println("${b[-1..2].len()}")`, "core 3.6: a negative lo faults and prints it"},
	{"bytes_uint_wrap", `let u: UInt64 = 18446744073709551615
  let b = "héllo".bytes()`, `os.stdio.println("${b[0..u].len()}")`, "core 3.6: a UInt64 bound wraps to a negative Int, and the fault prints the wrapped value"},
}

// faultProgram is the program source of c: a header, the spec claim, and
// the fault's line, so want.txt's position is stable.
func faultProgram(c faultCase) string {
	return "// Generated by scripts/stdcorpus from its fault cases. Do not edit:\n" +
		"// regenerate with go run ./scripts/stdcorpus.\n" +
		"//\n" +
		"// " + c.spec + "\n" +
		"\n" +
		"fn main(os: Os) {\n" +
		"  " + c.decl + "\n" +
		"  " + c.expr + "\n" +
		"}\n"
}

// writeFaultCorpora writes the fault programs, or with check only verifies
// that they are current, and returns whether anything differs.
func writeFaultCorpora(check bool) bool {
	dir := filepath.Join("internal", "stdtest", "testdata", "faults", "slice")
	want := map[string]string{}
	for _, c := range sliceFaultCases {
		want[filepath.Join(dir, c.name, "main.xo")] = faultProgram(c)
	}
	// a case directory the table no longer has is stale too
	if have, err := filepath.Glob(filepath.Join(dir, "*", "main.xo")); err == nil {
		for _, p := range have {
			if _, ok := want[p]; !ok {
				want[p] = ""
			}
		}
	}
	bad := false
	names := make([]string, 0, len(want))
	for p := range want {
		names = append(names, p)
	}
	sort.Strings(names)
	for _, p := range names {
		if check {
			old, err := os.ReadFile(p)
			if err != nil || string(old) != want[p] {
				fmt.Fprintf(os.Stderr, "stdcorpus: %s is stale: run go run ./scripts/stdcorpus\n", p)
				bad = true
			}
			continue
		}
		if want[p] == "" {
			// the case is gone: its directory and its recorded behavior go too
			if err := os.RemoveAll(filepath.Dir(p)); err != nil {
				fmt.Fprintln(os.Stderr, "stdcorpus:", err)
				bad = true
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			fmt.Fprintln(os.Stderr, "stdcorpus:", err)
			bad = true
			continue
		}
		if err := os.WriteFile(p, []byte(want[p]), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "stdcorpus:", err)
			bad = true
		}
	}
	return bad
}
