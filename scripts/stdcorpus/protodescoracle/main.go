// Command protodescoracle prints the std/protodesc corpus: the serialized
// FileDescriptorProto of protobuf-go v1.36.12's own descriptors (descriptor.proto,
// the well known types) and grpc-go v1.79.2's health, reflection and
// grpc_testing files, with the names and counts protodesc reports, so
// std/protodesc can be checked to decode and encode them byte for byte. It is
// its own module so the repository's go.mod has no third-party requirement.
package main

import (
	"fmt"
	"os"
	"strings"

	"google.golang.org/grpc/health/grpc_health_v1"
	reflpb "google.golang.org/grpc/reflection/grpc_reflection_v1"
	"google.golang.org/grpc/interop/grpc_testing"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/known/anypb"
	"google.golang.org/protobuf/types/known/apipb"
	"google.golang.org/protobuf/types/known/durationpb"
	"google.golang.org/protobuf/types/known/emptypb"
	"google.golang.org/protobuf/types/known/fieldmaskpb"
	"google.golang.org/protobuf/types/known/sourcecontextpb"
	"google.golang.org/protobuf/types/known/structpb"
	"google.golang.org/protobuf/types/known/timestamppb"
	"google.golang.org/protobuf/types/known/typepb"
	"google.golang.org/protobuf/types/known/wrapperspb"
)

func count(fd protoreflect.FileDescriptor) (msgs, fields, enums, services, methods int) {
	var walk func(ms protoreflect.MessageDescriptors)
	walk = func(ms protoreflect.MessageDescriptors) {
		for i := 0; i < ms.Len(); i++ {
			m := ms.Get(i)
			msgs++
			fields += m.Fields().Len()
			enums += m.Enums().Len()
			walk(m.Messages())
		}
	}
	walk(fd.Messages())
	enums += fd.Enums().Len()
	services = fd.Services().Len()
	for i := 0; i < services; i++ {
		methods += fd.Services().Get(i).Methods().Len()
	}
	return
}

func main() {
	files := []protoreflect.FileDescriptor{
		descriptorpb.File_google_protobuf_descriptor_proto,
		anypb.File_google_protobuf_any_proto, apipb.File_google_protobuf_api_proto,
		durationpb.File_google_protobuf_duration_proto, emptypb.File_google_protobuf_empty_proto,
		fieldmaskpb.File_google_protobuf_field_mask_proto, sourcecontextpb.File_google_protobuf_source_context_proto,
		structpb.File_google_protobuf_struct_proto, timestamppb.File_google_protobuf_timestamp_proto,
		typepb.File_google_protobuf_type_proto, wrapperspb.File_google_protobuf_wrappers_proto,
		grpc_health_v1.File_grpc_health_v1_health_proto, reflpb.File_grpc_reflection_v1_reflection_proto,
		grpc_testing.File_grpc_testing_test_proto, grpc_testing.File_grpc_testing_messages_proto,
	}
	var o strings.Builder
	o.WriteString("// Generated by scripts/stdcorpus from protobuf-go v1.36.12's and grpc-go v1.79.2's own file descriptors (" + os.Args[1] + ").\n")
	o.WriteString("// Do not edit: regenerate with go run ./scripts/stdcorpus.\n")
	o.WriteString("use std/protodesc\n\n")
	o.WriteString("/// (file name, package, messages, fields, enums, services, methods, serialized FileDescriptorProto as hex)\nconst FILES: List[(Str, Str, Int, Int, Int, Int, Int, Str)] = [\n")
	for _, fd := range files {
		b, err := proto.MarshalOptions{Deterministic: true}.Marshal(protodesc.ToFileDescriptorProto(fd))
		if err != nil {
			panic(err)
		}
		m, f, e, s, me := count(fd)
		fmt.Fprintf(&o, "  (\"%s\", \"%s\", %d, %d, %d, %d, %d, \"%x\"),\n", fd.Path(), fd.Package(), m, f, e, s, me, b)
	}
	o.WriteString("]\n")
	o.WriteString(xoTests)
	os.Stdout.WriteString(o.String())
}

const xoTests = `
fn hex(b: Bytes) -> Str {
  let digits = "0123456789abcdef".bytes()
  var o = BytesBuilder.new()
  for c in b {
    o.write_byte(digits[Int(c) / 16])
    o.write_byte(digits[Int(c) % 16])
  }
  o.freeze().to_str_lossy()
}

fn unhex(s: Str) -> Bytes {
  var o = BytesBuilder.new()
  let b = s.bytes()
  var i = 0
  while i + 1 < b.len() {
    o.write_byte(UInt8.wrapping_from(nib(Int(b[i])) * 16 + nib(Int(b[i + 1]))))
    i += 2
  }
  o.freeze()
}

fn nib(c: Int) -> Int { if c >= 97 { c - 87 } else { c - 48 } }

fn tally(m: protodesc.MessageDesc) -> (Int, Int, Int) {
  var msgs = 1
  var fields = m.field.len()
  var enums = m.enum_type.len()
  for n in m.nested_type {
    let (a, b, c) = tally(n)
    msgs += a
    fields += b
    enums += c
  }
  (msgs, fields, enums)
}

test "protoc and protobuf-go descriptors decode and encode back to the same bytes" {
  for (name, pkg, _, _, _, _, _, h) in FILES {
    let raw = unhex(h)
    let d = protodesc.decode(raw).or_fault("decode " + name)
    expect(d.name) == name
    expect(d.package) == pkg
    expect(hex(protodesc.encode(d))) == h
  }
}

test "the counts agree with protodesc" {
  for (name, _, msgs, fields, enums, services, methods, h) in FILES {
    let d = protodesc.decode(unhex(h)).or_fault("decode " + name)
    var m = 0
    var f = 0
    var e = d.enum_type.len()
    for x in d.message_type {
      let (a, b, c) = tally(x)
      m += a
      f += b
      e += c
    }
    var me = 0
    for s in d.service {
      me += s.method.len()
    }
    expect(m) == msgs
    expect(f) == fields
    expect(e) == enums
    expect(d.service.len()) == services
    expect(me) == methods
  }
}

test "a truncated descriptor is an error, never a panic" {
  for (_, _, _, _, _, _, _, h) in FILES {
    let raw = unhex(h)
    var cut = 1
    while cut < raw.len() {
      let _ = protodesc.decode(raw[0..cut]).ignore_err("a truncated descriptor may be refused; only a panic fails")
      cut += 7
    }
  }
}
`
