// Command bcryptoracle prints the std/bcrypt corpus: golang.org/x/crypto
// v0.58.0's bcrypt (std/bcrypt's reference) on seeded random passwords and
// costs, with salts from a seeded generator in place of crypto/rand, and on
// malformed hashes. scripts/stdcorpus runs it; it is its own module so the
// repository's go.mod has no third-party requirement.
package main

import (
	"crypto/rand"
	"fmt"
	"math/big"
	mrand "math/rand"
	"os"
	"strconv"
	"strings"

	"golang.org/x/crypto/bcrypt"
)

func xq(s string) string {
	q := strconv.Quote(s)
	return strings.ReplaceAll(q, "$", `\$`)
}

type seeded struct{ r *mrand.Rand }

func (s seeded) Read(p []byte) (int, error) { return s.r.Read(p) }

func res(err error) string {
	if err == nil {
		return "ok"
	}
	return "err " + err.Error()
}

func main() {
	rg := mrand.New(mrand.NewSource(26))
	rand.Reader = seeded{mrand.New(mrand.NewSource(27))}
	_ = big.NewInt
	var o strings.Builder
	o.WriteString("// Generated by scripts/stdcorpus from golang.org/x/crypto v0.58.0's bcrypt (GenerateFromPassword with a seeded salt, CompareHashAndPassword, Cost) on seeded random passwords and costs, and on malformed hashes (" + os.Args[1] + ").\n")
	o.WriteString("// Do not edit: regenerate with go run ./scripts/stdcorpus.\n")
	o.WriteString("use std/bcrypt\n\n")

	// (password, hash Go made of it, cost)
	o.WriteString("/// (password, the hash GenerateFromPassword made of it, its cost)\nconst MADE: List[(Str, Str, Int)] = [\n")
	pws := []string{"", "a", "allmine", "password", "pässwörd", "日本語のパスワード", strings.Repeat("x", 72), "with\x00nul", "  spaces  ", "$2a$10$"}
	for i := 0; i < 24; i++ {
		n := rg.Intn(40)
		var b strings.Builder
		for k := 0; k < n; k++ {
			b.WriteByte(byte(32 + rg.Intn(95)))
		}
		pws = append(pws, b.String())
	}
	costs := []int{4, 4, 5, 4, 6, 4}
	for i, pw := range pws {
		c := costs[i%len(costs)]
		h, err := bcrypt.GenerateFromPassword([]byte(pw), c)
		if err != nil {
			panic(err)
		}
		o.WriteString(fmt.Sprintf("  (%s, %s, %d),\n", xq(pw), xq(string(h)), c))
	}
	o.WriteString("]\n\n")

	// password length 73 and a cost outside the range
	_, e73 := bcrypt.GenerateFromPassword([]byte(strings.Repeat("y", 73)), 4)
	o.WriteString("const TOO_LONG: Str = " + xq(e73.Error()) + "\n")
	_, e32 := bcrypt.GenerateFromPassword([]byte("x"), 32)
	o.WriteString("const COST_32: Str = " + xq(e32.Error()) + "\n\n")

	// (hash, password, Go's CompareHashAndPassword result, Go's Cost result)
	good, _ := bcrypt.GenerateFromPassword([]byte("secret"), 4)
	g := string(good)
	salt := g[7:29]
	hv := g[29:]
	cases := []string{
		g,
		g[:58],
		"",
		"x" + g[1:],
		"$3a" + g[3:],
		"$2" + g[2:],
		"$2b" + g[3:],
		"$2x" + g[3:],
		g[:4] + "3x" + g[6:],
		g[:4] + "-5" + g[6:],
		g[:4] + "+4" + g[6:],
		g[:4] + "04" + g[6:],
		g[:4] + "03" + g[6:],
		g[:4] + "32" + g[6:],
		g[:4] + " 4" + g[6:],
		g[:4] + "4 " + g[6:],
		g[:4] + "é" + g[6:],
		g[:6] + "!" + g[7:],
		g[:6] + "x" + g[7:],
		g + "extra",
		g + "\n",
		g[:7] + strings.ToUpper(salt) + hv,
		g[:7] + salt[:10] + "+" + salt[11:] + hv,
		g[:7] + salt[:10] + "\n" + salt[11:] + hv,
		g[:7] + salt[:10] + "\r" + salt[11:] + hv,
		g[:7] + salt[:21] + "=" + hv,
		g[:7] + strings.Repeat("=", 22) + hv,
		g[:7] + salt + hv[:30],
		g[:7] + salt + strings.Repeat("A", 31),
		g[:7] + salt + hv[:30] + "A",
		g[:3] + "$04$" + salt + hv + "Q",
		"$2$04$" + salt + hv,
		"$2$04$" + salt + hv + "ab",
		"$2a$04$" + salt + hv + "abcdef",
		"$2a$04$" + salt[:5] + "\n\n" + salt[7:] + hv,
		"$2a$04$" + strings.Repeat("\n", 22) + hv,
	}
	o.WriteString("/// (hash, password, CompareHashAndPassword's result, Cost's result)\nconst CHECKS: List[(Str, Str, Str, Str)] = [\n")
	for _, c := range cases {
		cost, cerr := bcrypt.Cost([]byte(c))
		cs := "ok " + strconv.Itoa(cost)
		if cerr != nil {
			cs = "err " + cerr.Error()
		}
		for _, pw := range []string{"secret", "Secret"} {
			func() {
				defer func() {
					if r := recover(); r != nil {
						o.WriteString(fmt.Sprintf("  (%s, %s, %s, %s),\n", xq(c), xq(pw), xq("panic"), xq(cs)))
					}
				}()
				err := bcrypt.CompareHashAndPassword([]byte(c), []byte(pw))
				o.WriteString(fmt.Sprintf("  (%s, %s, %s, %s),\n", xq(c), xq(pw), xq(res(err)), xq(cs)))
			}()
		}
	}
	o.WriteString("]\n\n")
	c31, e31 := bcrypt.Cost([]byte(g[:4] + "31" + g[6:]))
	if e31 != nil || c31 != 31 {
		panic("cost 31")
	}
	o.WriteString("const COST_31_HASH: Str = " + xq(g[:4]+"31"+g[6:]) + "\n\n")
	o.WriteString(`test "cost reads the highest cost without hashing" {
  expect(bcrypt.cost(COST_31_HASH).ok()) == Some(31)
}

test "compare and cost are Go's CompareHashAndPassword and Cost on malformed hashes" {
  var bad: List[(Str, Str, Str, Str)] = []
  for (h, pw, want, want_cost) in CHECKS {
    var got = "ok"
    match bcrypt.compare(h, pw.bytes()) {
      Ok(_) => {}
      Err(e) => got = "err ${e.display()}"
    }
    var got_cost = ""
    match bcrypt.cost(h) {
      Ok(c) => got_cost = "ok ${c}"
      Err(e) => got_cost = "err ${e.display()}"
    }
    if got != want || got_cost != want_cost {
      bad.push((h, pw, got + " | " + got_cost, want + " | " + want_cost))
    }
  }
  expect(bad[0..(if bad.len() < 12 { bad.len() } else { 12 })]) == []
}

test "compare verifies the hashes Go made, and no other password" {
  for (pw, h, c) in MADE {
    expect(bcrypt.compare(h, pw.bytes()).is_ok()) == true
    expect(bcrypt.cost(h).ok()) == Some(c)
    expect(bcrypt.compare(h, ("~" + pw).bytes()).is_err()) == true
  }
}

test "hash makes a hash compare accepts, in Go's layout" {
  for (pw, _, c) in MADE {
    let h = bcrypt.hash(pw.bytes(), os.rand, c).ok() ?? ""
    expect(h.len()) == 60
    expect(h[0..4]) == "$2a$"
    expect(bcrypt.cost(h).ok()) == Some(c)
    expect(bcrypt.compare(h, pw.bytes()).is_ok()) == true
    expect(bcrypt.compare(h, ("~" + pw).bytes()).is_err()) == true
  }
}

test "hash draws a new salt each time, and applies Go's cost rules" {
  let a = bcrypt.hash(b"pw", os.rand, 4).ok() ?? ""
  let b = bcrypt.hash(b"pw", os.rand, 4).ok() ?? ""
  expect(a != b) == true
  expect(a[7..29] != b[7..29]) == true
  // a cost below the minimum is the default cost (10), which Go's test also checks by Cost
  expect(bcrypt.cost(bcrypt.hash(b"pw", os.rand, 3).ok() ?? "").ok()) == Some(10)
  expect(bcrypt.cost(bcrypt.hash(b"pw", os.rand, -1).ok() ?? "").ok()) == Some(10)
  match bcrypt.hash(b"pw", os.rand, 32) {
    Ok(_) => expect(false) == true
    Err(e) => expect(e.display()) == COST_32
  }
  match bcrypt.hash(("y").repeat(73).bytes(), os.rand, 4) {
    Ok(_) => expect(false) == true
    Err(e) => expect(e.display()) == TOO_LONG
  }
  expect(bcrypt.hash(("y").repeat(72).bytes(), os.rand, 4).is_ok()) == true
}
`)
	fmt.Print(o.String())
}
