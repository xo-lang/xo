package main

// fuzz SEED N prints a std/bcrypt test file of N fresh cases for decision
// 0616's fuzz kind (TestBcryptFuzz, task #99): hashes Go made at cost 4
// with seeded salts, changed as a stored or attacker-supplied hash could
// be (a character replaced, dropped, added or recased anywhere, the
// version, cost or salt rewritten, cut or extended), each compared with
// the right password, a wrong one, and passwords of 72 and more bytes,
// and read by Cost. Compare runs only where Go's Cost answers 6 or less
// (or fails), so a changed cost never makes a case slow. A case where Go
// panics must be an error in Xo.

import (
	"crypto/rand"
	"fmt"
	mrand "math/rand"
	"strconv"
	"strings"
	"unicode/utf8"

	"golang.org/x/crypto/bcrypt"

	"stdcorpus/bcryptoracle/hostile"
)

// hostileCosts: every third cost rewrite is one of these in place of its
// pick (task #352), chosen by a counter so the random stream is unchanged:
// digit runs past Int, Int's edges as text, a leading sign.
var hostileCosts = func() []string {
	cs := hostile.Digits()
	for _, v := range hostile.Ints() {
		cs = append(cs, strconv.FormatInt(v, 10))
	}
	return cs
}()

var hostileCostN int

const hashChars = "./ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"

func fuzzPassword(r *mrand.Rand) string {
	switch r.Intn(8) {
	case 0:
		return ""
	case 1:
		return strings.Repeat("p", 72)
	case 2:
		return strings.Repeat("p", 72+1+r.Intn(10))
	case 3:
		return "pässwörd\x00"
	}
	var b strings.Builder
	for k := r.Intn(30); k > 0; k-- {
		b.WriteByte(byte(32 + r.Intn(95)))
	}
	return b.String()
}

// fuzzHash changes h once or twice.
func fuzzHash(r *mrand.Rand, h string) string {
	for k := 1 + r.Intn(2); k > 0 && len(h) > 0; k-- {
		i := r.Intn(len(h))
		c := string(hashChars[r.Intn(len(hashChars))])
		if r.Intn(6) == 0 {
			c = string("$ \n=+-é\x00"[r.Intn(8)])
		}
		switch r.Intn(10) {
		case 0:
			h = h[:i] + h[i+1:]
		case 1:
			h = h[:i] + c + h[i:]
		case 2:
			h = strings.ToUpper(h[:i]) + h[i:]
		case 3:
			h = pick(r, "$2a$", "$2b$", "$2y$", "$2x$", "$2$", "$3a$", "2a$", "$2a") + h[min(4, len(h)):]
		case 4:
			if len(h) >= 7 {
				c := pick(r, "04", "4", "03", "05", "06", "31", "32", "99", "-4", " 4", "0x", "")
				if hostileCostN++; hostileCostN%3 == 0 {
					c = hostileCosts[(hostileCostN/3)%len(hostileCosts)]
				}
				h = h[:4] + c + h[6:]
			}
		case 5:
			h = h[:i]
		case 6:
			h += pick(r, "A", "extra", "\n", "==", strings.Repeat("A", r.Intn(5)))
		default:
			h = h[:i] + c + h[i+1:]
		}
	}
	return h
}

func pick(r *mrand.Rand, xs ...string) string { return xs[r.Intn(len(xs))] }

func fuzzMain(seed int64, n int) {
	r := mrand.New(mrand.NewSource(seed))
	rand.Reader = seeded{mrand.New(mrand.NewSource(seed + 1))}
	var o strings.Builder
	fmt.Fprintf(&o, "// Generated by internal/stdtest/bcryptfuzz_test.go through scripts/stdcorpus/bcryptoracle fuzz (seed %d, %d cases) from golang.org/x/crypto v0.58.0's bcrypt.\n", seed, n)
	o.WriteString("use std/bcrypt\n\n")
	o.WriteString("/// (hash, password, CompareHashAndPassword's result or \"skip\" (a cost over 6) or \"panic\", Cost's result)\nconst CHECKS: List[(Str, Str, Str, Str)] = [\n")
	var made []struct{ pw, h string }
	for len(made) < 8 {
		pw := fuzzPassword(r)
		h, err := bcrypt.GenerateFromPassword([]byte(pw), 4)
		if err != nil {
			continue // longer than 72 bytes
		}
		made = append(made, struct{ pw, h string }{pw, string(h)})
	}
	for i := 0; i < n; i++ {
		m := made[r.Intn(len(made))]
		h := m.h
		if r.Intn(6) != 0 {
			h = fuzzHash(r, h)
		}
		pw := m.pw
		switch r.Intn(4) {
		case 0:
			pw = fuzzPassword(r)
		case 1:
			if len(pw) == 72 {
				pw += pick(r, "!", "more")
			}
		}
		if !utf8.ValidString(h) || !utf8.ValidString(pw) {
			i-- // std/bcrypt takes a Str: valid UTF-8 only
			continue
		}
		cost, cerr := bcrypt.Cost([]byte(h))
		cs := "ok " + strconv.Itoa(cost)
		if cerr != nil {
			cs = "err " + cerr.Error()
		}
		want := "skip"
		if cerr != nil || cost <= 6 {
			want = func() (w string) {
				defer func() {
					if p := recover(); p != nil {
						w = "panic"
					}
				}()
				return res(bcrypt.CompareHashAndPassword([]byte(h), []byte(pw)))
			}()
		}
		fmt.Fprintf(&o, "  (%s, %s, %s, %s),\n", xq(h), xq(pw), xq(want), xq(cs))
	}
	o.WriteString("]\n\n")
	o.WriteString(`test "compare and cost are Go's CompareHashAndPassword and Cost on changed hashes" {
  var bad: List[Str] = []
  for (h, pw, want, want_cost) in CHECKS {
    var got_cost = ""
    match bcrypt.cost(h) {
      Ok(c) => got_cost = "ok ${c}"
      Err(e) => got_cost = "err ${e.display()}"
    }
    var got = want
    if want != "skip" {
      got = match bcrypt.compare(h, pw.bytes()) {
        Ok(_) => "ok"
        Err(e) => "err ${e.display()}"
      }
    }
    // where Go panics, Xo must refuse
    let same = if want == "panic" { got.starts_with("err ") } else { got == want }
    if !same || got_cost != want_cost {
      bad.push("[${h}] [${pw}]: ${got} | ${got_cost}, Go ${want} | ${want_cost}")
    }
  }
  if !bad.is_empty() {
    fault("${bad.len()} of ${CHECKS.len()} cases differ, first: ${bad[0]}")
  }
}
`)
	fmt.Print(o.String())
}
