// Command xcryptooracle prints the std/crypto corpus of the hashes and the
// AEAD that come from golang.org/x/crypto v0.58.0 (std/crypto's reference
// for them): blake2b (New256, New384, New512, New with a key, Sum*,
// MarshalBinary, NewXOF), sha3's NewLegacyKeccak256 and
// NewLegacyKeccak512, and chacha20poly1305's NewX, with crypto/hmac,
// crypto/hkdf and crypto/pbkdf2 over the hashes, on seeded inputs at the
// block boundaries and on chacha20poly1305's own XChaCha20-Poly1305 test
// vectors (chacha20poly1305_vectors_test.go, Copyright 2016 The Go
// Authors, BSD-style license). scripts/stdcorpus runs it; it is its own
// module so the repository's go.mod has no third-party requirement.
package main

import (
	"crypto"
	"crypto/hkdf"
	"crypto/hmac"
	"crypto/pbkdf2"
	"crypto/rand"
	"crypto/rsa"
	"encoding"
	"encoding/hex"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"hash"
	mrand "math/rand"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"

	"golang.org/x/crypto/blake2b"
	"golang.org/x/crypto/chacha20poly1305"
	"golang.org/x/crypto/sha3"
)

// hashes are the Hash variants of std/crypto, in HASHES's order.
var hashes = []struct {
	name string
	new  func() hash.Hash
}{
	{"Blake2b_256", func() hash.Hash { h, _ := blake2b.New256(nil); return h }},
	{"Blake2b_384", func() hash.Hash { h, _ := blake2b.New384(nil); return h }},
	{"Blake2b_512", func() hash.Hash { h, _ := blake2b.New512(nil); return h }},
	{"Keccak256", sha3.NewLegacyKeccak256},
	{"Keccak512", sha3.NewLegacyKeccak512},
}

var rg = mrand.New(mrand.NewSource(76))

func bytesN(n int) []byte {
	b := make([]byte, n)
	rg.Read(b)
	return b
}

func hx(b []byte) string { return strconv.Quote(hex.EncodeToString(b)) }

func errText(err error) string {
	if err == nil {
		return `""`
	}
	return strconv.Quote(err.Error())
}

func marshal(h hash.Hash) []byte {
	b, err := h.(encoding.BinaryMarshaler).MarshalBinary()
	if err != nil {
		panic(err)
	}
	return b
}

// xchachaVectors is the rows of chacha20poly1305's test table with a 24
// byte nonce, read from the module's source.
func xchachaVectors() [][5]string {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "golang.org/x/crypto").Output()
	if err != nil {
		panic(err)
	}
	path := filepath.Join(strings.TrimSpace(string(out)), "chacha20poly1305", "chacha20poly1305_vectors_test.go")
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		panic(err)
	}
	var rows [][5]string
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok || g.Tok != token.VAR {
			continue
		}
		for _, s := range g.Specs {
			vs := s.(*ast.ValueSpec)
			if vs.Names[0].Name != "chacha20Poly1305Tests" {
				continue
			}
			for _, e := range vs.Values[0].(*ast.CompositeLit).Elts {
				var r [5]string
				for i, f := range e.(*ast.CompositeLit).Elts {
					r[i], _ = strconv.Unquote(f.(*ast.BasicLit).Value)
				}
				// plaintext, aad, key, nonce, out
				if len(r[3]) == 2*chacha20poly1305.NonceSizeX {
					rows = append(rows, r)
				}
			}
		}
	}
	return rows
}

func main() {
	var o strings.Builder
	o.WriteString("// Generated by scripts/stdcorpus from golang.org/x/crypto v0.58.0's blake2b (New256, New384, New512, keyed New, MarshalBinary and UnmarshalBinary, NewXOF), sha3's NewLegacyKeccak256 and NewLegacyKeccak512, and chacha20poly1305's NewX, with crypto/hmac, crypto/hkdf and crypto/pbkdf2 over the hashes, on seeded inputs at the block boundaries and on chacha20poly1305's XChaCha20-Poly1305 test vectors (Copyright 2016 The Go Authors, BSD-style license) (" + os.Args[1] + ").\n")
	o.WriteString("// Do not edit: regenerate with go run ./scripts/stdcorpus.\n")
	o.WriteString("use std/crypto\n\n")
	o.WriteString("const HASHES: List[crypto.Hash] = [")
	for i, h := range hashes {
		if i > 0 {
			o.WriteString(", ")
		}
		o.WriteString("crypto.Hash." + h.name)
	}
	o.WriteString("]\n\n")

	// digests, HMACs, sizes
	lens := []int{0, 1, 3, 63, 64, 65, 71, 72, 73, 127, 128, 129, 135, 136, 137, 143, 144, 145, 255, 256, 257, 300, 1000}
	keyLens := []int{0, 1, 16, 32, 64, 71, 72, 73, 127, 128, 129, 136, 137, 200}
	o.WriteString("/// (hash, message, Go's digest, HMAC key, Go's HMAC, a split point)\nconst SUMS: List[(Int, Str, Str, Str, Str, Int)] = [\n")
	for hi, h := range hashes {
		for li, n := range lens {
			msg := bytesN(n)
			x := h.new()
			x.Write(msg)
			key := bytesN(keyLens[(li+hi)%len(keyLens)])
			m := hmac.New(h.new, key)
			m.Write(msg)
			fmt.Fprintf(&o, "  (%d, %s, %s, %s, %s, %d),\n", hi, hx(msg), hx(x.Sum(nil)), hx(key), hx(m.Sum(nil)), rg.Intn(n+1))
		}
	}
	o.WriteString("]\n\n")
	o.WriteString("/// Go's Size and BlockSize of each hash\nconst SIZES: List[(Int, Int)] = [")
	for i, h := range hashes {
		if i > 0 {
			o.WriteString(", ")
		}
		fmt.Fprintf(&o, "(%d, %d)", h.new().Size(), h.new().BlockSize())
	}
	o.WriteString("]\n\n")

	// MarshalBinary of a prefix
	o.WriteString("/// (hash, message, the length written before MarshalBinary, Go's state)\nconst STATES: List[(Int, Str, Int, Str)] = [\n")
	for hi, h := range hashes {
		for _, n := range []int{0, 1, 71, 72, 127, 128, 129, 136, 137, 256, 300} {
			msg := bytesN(n + 40)
			x := h.new()
			x.Write(msg[:n])
			fmt.Fprintf(&o, "  (%d, %s, %d, %s),\n", hi, hx(msg), n, hx(marshal(x)))
		}
	}
	o.WriteString("]\n\n")
	o.WriteString("/// (hash, a state, Go's UnmarshalBinary error)\nconst BAD_STATES: List[(Int, Str, Str)] = [\n")
	for hi, h := range hashes {
		good := marshal(h.new())
		other := marshal(hashes[(hi+3)%len(hashes)].new())
		for _, st := range [][]byte{nil, good[:3], good[:len(good)-1], append(append([]byte{}, good...), 0), other} {
			fmt.Fprintf(&o, "  (%d, %s, %s),\n", hi, hx(st), errText(h.new().(encoding.BinaryUnmarshaler).UnmarshalBinary(st)))
		}
	}
	o.WriteString("]\n\n")

	// keyed BLAKE2b
	o.WriteString("/// (size, key, message, Go's blake2b.New(size, key) sum)\nconst KEYED: List[(Int, Str, Str, Str)] = [\n")
	for _, size := range []int{1, 16, 20, 32, 33, 48, 63, 64} {
		for _, kl := range []int{0, 1, 32, 64} {
			key := bytesN(kl)
			msg := bytesN(rg.Intn(300))
			h, err := blake2b.New(size, key)
			if err != nil {
				panic(err)
			}
			h.Write(msg)
			fmt.Fprintf(&o, "  (%d, %s, %s, %s),\n", size, hx(key), hx(msg), hx(h.Sum(nil)))
		}
	}
	o.WriteString("]\n\n")
	o.WriteString("/// (size, key length, Go's blake2b.New error)\nconst KEYED_ERRS: List[(Int, Int, Str)] = [\n")
	for _, c := range [][2]int{{0, 0}, {65, 0}, {-1, 0}, {32, 65}, {0, 65}, {64, 64}, {1, 0}} {
		_, err := blake2b.New(c[0], make([]byte, c[1]))
		fmt.Fprintf(&o, "  (%d, %d, %s),\n", c[0], c[1], errText(err))
	}
	o.WriteString("]\n\n")
	mac, _ := blake2b.New256([]byte("key"))
	_, merr := mac.(encoding.BinaryMarshaler).MarshalBinary()
	o.WriteString("const MAC_STATE_ERR: Str = " + errText(merr) + "\n\n")

	// XOF
	o.WriteString("/// (size, key, message, read sizes, Go's reads: hex, or EOF)\nconst XOFS: List[(Int, Str, Str, List[Int], List[Str])] = [\n")
	for _, size := range []int{1, 31, 64, 65, 129, 1000, 0} {
		for _, kl := range []int{0, 16, 64} {
			key := bytesN(kl)
			msg := bytesN(rg.Intn(300))
			x, err := blake2b.NewXOF(uint32(size), key)
			if err != nil {
				panic(err)
			}
			x.Write(msg)
			var reads []string
			var got []string
			total := 0
			for total <= size || len(reads) < 4 {
				n := []int{1, 3, 61, 64, 65, 100, 0}[rg.Intn(7)]
				if len(reads) >= 8 {
					break
				}
				buf := make([]byte, n)
				k, err := x.Read(buf)
				reads = append(reads, strconv.Itoa(n))
				if err != nil {
					got = append(got, strconv.Quote(err.Error()))
				} else {
					got = append(got, hx(buf[:k]))
				}
				total += n
			}
			fmt.Fprintf(&o, "  (%d, %s, %s, [%s], [%s]),\n", size, hx(key), hx(msg), strings.Join(reads, ", "), strings.Join(got, ", "))
		}
	}
	o.WriteString("]\n\n")
	_, xk := blake2b.NewXOF(10, make([]byte, 65))
	_, xl := blake2b.NewXOF(1<<32-1, nil)
	o.WriteString("const XOF_KEY_ERR: Str = " + errText(xk) + "\n")
	o.WriteString("const XOF_LENGTH_ERR: Str = " + errText(xl) + "\n\n")

	// HKDF and PBKDF2
	o.WriteString("/// (hash, secret, salt, info, length, Go's hkdf.Key)\nconst HKDFS: List[(Int, Str, Str, Str, Int, Str)] = [\n")
	for hi, h := range hashes {
		for _, n := range []int{1, 32, 100} {
			secret, salt, info := bytesN(rg.Intn(80)), bytesN(rg.Intn(3)*40), bytesN(rg.Intn(30))
			k, err := hkdf.Key(h.new, secret, salt, string(info), n)
			if err != nil {
				panic(err)
			}
			fmt.Fprintf(&o, "  (%d, %s, %s, %s, %d, %s),\n", hi, hx(secret), hx(salt), hx(info), n, hx(k))
		}
	}
	o.WriteString("]\n\n")
	o.WriteString("/// (hash, password, salt, iterations, length, Go's pbkdf2.Key)\nconst PBKDF2S: List[(Int, Str, Str, Int, Int, Str)] = [\n")
	for hi, h := range hashes {
		for _, n := range []int{1, 32, 100} {
			pw, salt := bytesN(rg.Intn(40)), bytesN(16)
			it := 1 + rg.Intn(3)
			k, err := pbkdf2.Key(h.new, string(pw), salt, it, n)
			if err != nil {
				panic(err)
			}
			fmt.Fprintf(&o, "  (%d, %s, %s, %d, %d, %s),\n", hi, hx(pw), hx(salt), it, n, hx(k))
		}
	}
	o.WriteString("]\n\n")

	// XChaCha20-Poly1305
	o.WriteString("/// (key, nonce, plaintext, aad, Go's NewX Seal): chacha20poly1305's\n/// vectors with a 24 byte nonce, then seeded ones\nconst XCHACHA: List[(Str, Str, Str, Str, Str)] = [\n")
	for _, r := range xchachaVectors() {
		key, _ := hex.DecodeString(r[2])
		nonce, _ := hex.DecodeString(r[3])
		pt, _ := hex.DecodeString(r[0])
		aad, _ := hex.DecodeString(r[1])
		a, err := chacha20poly1305.NewX(key)
		if err != nil {
			panic(err)
		}
		sealed := a.Seal(nil, nonce, pt, aad)
		if hex.EncodeToString(sealed) != r[4] {
			panic("x/crypto disagrees with its own vector")
		}
		fmt.Fprintf(&o, "  (%s, %s, %s, %s, %s),\n", hx(key), hx(nonce), hx(pt), hx(aad), hx(sealed))
	}
	for _, n := range []int{0, 1, 15, 16, 17, 63, 64, 65, 255, 256, 257, 1000} {
		key, nonce, pt, aad := bytesN(32), bytesN(24), bytesN(n), bytesN(rg.Intn(40))
		a, _ := chacha20poly1305.NewX(key)
		fmt.Fprintf(&o, "  (%s, %s, %s, %s, %s),\n", hx(key), hx(nonce), hx(pt), hx(aad), hx(a.Seal(nil, nonce, pt, aad)))
	}
	o.WriteString("]\n\n")
	_, kerr := chacha20poly1305.NewX(make([]byte, 16))
	a, _ := chacha20poly1305.NewX(make([]byte, 32))
	if _, err := a.Open(nil, make([]byte, 24), make([]byte, 20), nil); err == nil {
		panic("NewX opened a forged message")
	}
	o.WriteString("const XCHACHA_KEY_ERR: Str = " + errText(kerr) + "\n")
	fmt.Fprintf(&o, "const XCHACHA_SIZES: (Int, Int) = (%d, %d)\n\n", a.NonceSize(), a.Overhead())

	// RSA's refusal of a hash without a DigestInfo prefix
	k, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil {
		panic(err)
	}
	_, rerr := rsa.SignPKCS1v15(nil, k, crypto.BLAKE2b_256, make([]byte, 32))
	o.WriteString("const RSA_UNSUPPORTED: Str = " + errText(rerr) + "\n")
	// PSS and OAEP of BLAKE2b-512 do not fit a 1024-bit key; a wrong label
	// is OAEP's decryption error
	k1, err := rsa.GenerateKey(rand.Reader, 1024)
	if err != nil {
		panic(err)
	}
	_, perr := rsa.SignPSS(rand.Reader, k1, crypto.BLAKE2b_512, make([]byte, 64), &rsa.PSSOptions{SaltLength: rsa.PSSSaltLengthEqualsHash})
	b512, _ := blake2b.New512(nil)
	_, oerr := rsa.EncryptOAEP(b512, rand.Reader, &k1.PublicKey, []byte("msg"), nil)
	if perr == nil || oerr == nil || perr.Error() != oerr.Error() {
		panic(fmt.Sprint("RSA too long: ", perr, oerr))
	}
	o.WriteString("const RSA_TOO_LONG: Str = " + errText(perr) + "\n")
	b256, _ := blake2b.New256(nil)
	c, err := rsa.EncryptOAEP(b256, rand.Reader, &k1.PublicKey, []byte("msg"), []byte("lbl"))
	if err != nil {
		panic(err)
	}
	_, derr := rsa.DecryptOAEP(b256, nil, k1, c, nil)
	o.WriteString("const RSA_DECRYPTION: Str = " + errText(derr) + "\n\n")

	o.WriteString(tests)
	fmt.Print(o.String())
}
