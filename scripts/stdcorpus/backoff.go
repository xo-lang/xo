// The std/backoff corpus: cenkalti/backoff v4's own tests
// (exponential_test.go TestBackOff, TestGetRandomizedInterval,
// TestBackOffOverflow; retry_test.go TestRetry, TestRetryPermanent;
// Copyright (c) 2014 Cenk Altı, MIT license), transcribed, with the
// delay sequences computed here by v4's formula (nextBackOff below) for
// a fixed list of random values, which the Xo tests feed through a
// Rand of their own.

// cenkalti/backoff v4 ExponentialBackOff, its arithmetic as written.
type expo struct {
	initial, maxInterval, maxElapsed time.Duration
	rf, mult                         float64
	current                          time.Duration
}

func (b *expo) next(r float64) time.Duration {
	v := randomValue(b.rf, r, b.current)
	if float64(b.current) >= float64(b.maxInterval)/b.mult {
		b.current = b.maxInterval
	} else {
		b.current = time.Duration(float64(b.current) * b.mult)
	}
	return v
}

func randomValue(rf, r float64, ci time.Duration) time.Duration {
	if rf == 0 {
		return ci
	}
	delta := rf * float64(ci)
	lo := float64(ci) - delta
	hi := float64(ci) + delta
	return time.Duration(lo + (r * (hi - lo + 1)))
}

