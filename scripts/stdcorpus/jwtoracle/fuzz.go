package main

// fuzz SEED N prints a std/jwt test file of N fresh cases for decision
// 0616's fuzz kind (TestJwtFuzz, task #99): tokens whose header and
// claims JSON is drawn at random (every algorithm; exp, nbf and iat as
// integers, fractions, strings, null or huge; aud a string, a list or
// neither; extra and repeated keys) and signed over the exact text, then
// changed as an attacker could (a character replaced, dropped or added,
// a segment from another token, padding, a dot more or less), verified
// under random options (allowed algorithms, now, leeway, issuer,
// audience, subject, exp required, the right or a wrong key). Each case
// carries golang-jwt's category, as the corpus's VERIFY does.

import (
	"bytes"
	"encoding/base64"
	"encoding/json"
	"errors"
	"fmt"
	"math"
	"slices"
	"unicode/utf8"

	"github.com/golang-jwt/jwt/v5"
	"math/rand"
	"os"
	"strings"
)

func fuzzMain(seed int64, n int) {
	r := rand.New(rand.NewSource(seed))
	var o strings.Builder
	fmt.Fprintf(&o, "// Generated by internal/stdtest/jwtfuzz_test.go through scripts/stdcorpus/jwtoracle fuzz (seed %d, %d cases) from github.com/golang-jwt/jwt/v5 v5.3.1.\n", seed, n)
	o.WriteString("use std/jwt\nuse std/crypto\n\n")
	o.WriteString("const HMAC_SECRET: Str = " + xq(hmacSecret) + "\n\n")
	o.WriteString("/// (name, private key PEM, public key PEM)\nconst KEYS: List[(Str, Str, Str)] = [\n")
	for _, k := range []string{"rsa", "rsa2", "p256", "p384", "p521", "ed25519"} {
		o.WriteString("  (" + xq(k) + ", " + xq(keyPEMs[k][0]) + ", " + xq(keyPEMs[k][1]) + "),\n")
	}
	o.WriteString("]\n\n")
	o.WriteString("/// (token, key name, allowed algs, now, leeway, iss, aud, sub, exp required, the category golang-jwt gives, note)\n")
	o.WriteString("const VERIFY: List[(Str, Str, Str, Int, Int, Str, Str, Str, Bool, Str, Str)] = [\n")
	skipped := 0
	for i := 0; i < n; {
		tok, key, op, note := fuzzCase(r)
		want := category(tok, key, op)
		if strings.HasPrefix(want, "other") {
			skipped++
			if skipped > n {
				fmt.Fprintln(os.Stderr, "jwtoracle fuzz: too many cases golang-jwt answers outside the categories:", want)
				os.Exit(1)
			}
			continue
		}
		if lastErr != nil {
			note += "; golang-jwt: " + lastErr.Error()
		}
		also, why := fuzzAlso(tok, key, op, want, lastErr)
		for _, c := range also {
			if !slices.Contains(strings.Split(want, "|"), c) {
				want += "|" + c
			}
		}
		if why != "" {
			note += "; also " + why
		}
		fmt.Fprintf(&o, "  (%s, %s, %s, %d, %d, %s, %s, %s, %v, %s, %s),\n", xq(tok), xq(key), xq(strings.Join(op.algs, ",")), op.now, op.leeway, xq(op.iss), xq(op.aud), xq(op.sub), !op.noExp, xq(want), xq(fmt.Sprintf("case %d: %s; options %+v", i, note, op)))
		i++
	}
	o.WriteString("]\n\n")
	o.WriteString("const SIGNED: List[(Str, Str, Str, Str)] = []\n")
	// a case passes when std/jwt gives one of the categories its want lists
	test := strings.Replace(jwtTests, "    if got != want {", "    if !want.split(\"|\").contains(got) {", 1)
	if test == jwtTests {
		fmt.Fprintln(os.Stderr, "jwtoracle fuzz: the VERIFY test's comparison moved")
		os.Exit(1)
	}
	o.WriteString(test)
	fmt.Print(o.String())
}

// fuzzAlso lists the categories std/jwt may answer besides golang-jwt's
// (want), and why:
//   - golang-jwt checks every claim and joins the errors; std/jwt stops at
//     the first, so any of the joined categories;
//   - a required iss, aud or sub that is missing: std/jwt documents it as
//     Issuer, Audience or Subject (golang-jwt: a missing claim);
//   - a signature that is not base64url: std/jwt documents Signature
//     (golang-jwt: malformed);
//   - a key that does not fit the header's alg: std/jwt refuses the
//     algorithm (alg confusion, its test "refuses a key that does not fit
//     the algorithm"; golang-jwt: an invalid signature);
//   - a header with crit: std/jwt refuses it as RFC 7515 4.1.11 says
//     (golang-jwt ignores it);
//   - a header or payload that is not UTF-8: std/jwt's JSON refuses it
//     as malformed
//     (Go's replaces the bytes);
//   - an iat that is not a number: std/jwt documents a time claim of the
//     wrong type as claim (golang-jwt reads iat only WithIssuedAt);
//   - a numeric date past 2^63 seconds, which wraps Go's time: claim;
//   - a numeric date of 0, which golang-jwt reads as absent (RFC 7519's
//     NumericDate 0 is a time): std/jwt's expired for exp, or ok while now
//     is within the leeway of it.
func fuzzAlso(tok, key string, op opts, want string, err error) ([]string, string) {
	var also, why []string
	add := func(c, w string) {
		also = append(also, c)
		why = append(why, w)
	}
	if err != nil {
		for _, c := range []struct {
			target error
			cat    string
		}{{jwt.ErrTokenExpired, "expired"}, {jwt.ErrTokenNotValidYet, "notyet"}, {jwt.ErrTokenInvalidIssuer, "issuer"}, {jwt.ErrTokenInvalidAudience, "audience"}, {jwt.ErrTokenInvalidSubject, "subject"}, {jwt.ErrInvalidType, "claim"}, {jwt.ErrTokenRequiredClaimMissing, "claim"}} {
			if errors.Is(err, c.target) && c.cat != want {
				add(c.cat, "joined "+c.cat)
			}
		}
		text := err.Error()
		for claim, cat := range map[string]string{"iss": "issuer", "aud": "audience", "sub": "subject"} {
			if strings.Contains(text, claim+" claim is required") {
				add(cat, "missing "+claim)
			}
		}
		if strings.Contains(text, "could not base64 decode signature") {
			add("signature", "signature not base64url")
		}
	}
	parts := strings.Split(tok, ".")
	if len(parts) != 3 {
		return also, strings.Join(why, ", ")
	}
	if hb, e := base64.RawURLEncoding.DecodeString(parts[0]); e == nil {
		if !utf8.Valid(hb) {
			add("malformed", "header not UTF-8")
		}
		var h map[string]any
		if json.Unmarshal(hb, &h) == nil {
			if name, ok := h["alg"].(string); ok && keyFamily(key) != keyFamily(algKey(name)) {
				add("alg", "key does not fit alg")
			}
			if _, ok := h["crit"]; ok {
				add("malformed", "crit")
			}
		}
	}
	pb, e := base64.RawURLEncoding.DecodeString(parts[1])
	if e != nil {
		return also, strings.Join(why, ", ")
	}
	if !utf8.Valid(pb) {
		add("malformed", "payload not UTF-8")
	}
	d := json.NewDecoder(bytes.NewReader(pb))
	d.UseNumber()
	var c map[string]any
	if d.Decode(&c) == nil {
		if v, ok := c["iat"]; ok {
			if _, num := v.(json.Number); !num {
				add("claim", "iat not a number")
			}
		}
		for _, k := range []string{"exp", "nbf", "iat"} {
			n, ok := c[k].(json.Number)
			if !ok {
				continue
			}
			f, _ := n.Float64()
			if math.Abs(f) >= 9.2e18 {
				add("claim", k+" wraps Go's time")
			}
			if f == 0 && k == "exp" {
				add("expired", "exp 0")
				if op.now < op.leeway {
					// std/jwt reads the time 0, still inside the leeway
					add("ok", "exp 0 within the leeway")
				}
			}
		}
	}
	return also, strings.Join(why, ", ")
}

func pick[T any](r *rand.Rand, xs ...T) T { return xs[r.Intn(len(xs))] }

// fuzzTime is a value for exp, nbf or iat, as JSON text.
func fuzzTime(r *rand.Rand) string {
	return pick(r, "1000", "1500", "1999", "2000", "2001", "1500.5", "1999.999", "0", "-5", "1e3", "2e3", "1e20", `"2000"`, "null", "true", "[2000]", "9223372036854775807", "2000.0")
}

func fuzzStr(r *rand.Rand) string {
	return pick(r, `"me"`, `"you"`, `"ann"`, `"bob"`, `""`, `"x"`, `"y"`, `"ann"`, `"me "`)
}

// fuzzClaims is a claims object's JSON text.
func fuzzClaims(r *rand.Rand) string {
	var kv []string
	add := func(k, v string) { kv = append(kv, fmt.Sprintf("%q:%s", k, v)) }
	if r.Intn(8) != 0 {
		add("exp", fuzzTime(r))
	}
	if r.Intn(3) == 0 {
		add("nbf", fuzzTime(r))
	}
	if r.Intn(3) == 0 {
		add("iat", fuzzTime(r))
	}
	if r.Intn(4) != 0 {
		add("iss", fuzzStr(r))
	}
	if r.Intn(4) != 0 {
		add("sub", fuzzStr(r))
	}
	switch r.Intn(5) {
	case 0:
		add("aud", fuzzStr(r))
	case 1:
		add("aud", `["x","y"]`)
	case 2:
		add("aud", pick(r, `[]`, `["y"]`, `[5]`, `"y"`, `null`, `["x",null]`))
	}
	if r.Intn(4) == 0 {
		add("name", pick(r, `"Ann"`, `{"a":[1,2]}`, `1.5`))
	}
	if r.Intn(10) == 0 && len(kv) > 0 {
		kv = append(kv, kv[r.Intn(len(kv))]) // a key twice
	}
	r.Shuffle(len(kv), func(i, j int) { kv[i], kv[j] = kv[j], kv[i] })
	return "{" + strings.Join(kv, ",") + "}"
}

// fuzzHeader is a header's JSON text for alg name.
func fuzzHeader(r *rand.Rand, name string) string {
	switch r.Intn(24) {
	case 0:
		return fmt.Sprintf(`{"alg":%q}`, pick(r, "none", "None", strings.ToLower(name), "HS256", "RS256", "ES256", "EdDSA", "PS256", ""))
	case 1:
		return fmt.Sprintf(`{"typ":"JWT","alg":%q,"kid":"k1"}`, name)
	case 2:
		return fmt.Sprintf(`{"alg":%q,"crit":["exp"]}`, name)
	case 3:
		return fmt.Sprintf(`{"alg":"none","alg":%q}`, name)
	case 4:
		return fmt.Sprintf(`{ "alg" : %q , "typ" : "JWT" }`, name)
	case 5:
		return `{"typ":"JWT"}`
	}
	return fmt.Sprintf(`{"alg":%q,"typ":"JWT"}`, name)
}

const b64chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"

// fuzzEdit changes one character of s: replaced, dropped or added.
func fuzzEdit(r *rand.Rand, s string) string {
	extra := b64chars + "+/=. !"
	i := 0
	if len(s) > 0 {
		i = r.Intn(len(s))
	}
	c := string(extra[r.Intn(len(extra))])
	switch {
	case len(s) == 0:
		return c
	case r.Intn(3) == 0:
		return s[:i] + s[i+1:]
	case r.Intn(2) == 0:
		return s[:i] + c + s[i:]
	}
	return s[:i] + c + s[i+1:]
}

func fuzzCase(r *rand.Rand) (string, string, opts, string) {
	a := algs[r.Intn(len(algs))]
	hdr, claims := fuzzHeader(r, a.name), fuzzClaims(r)
	h, p := b64(hdr), b64(claims)
	sig, err := a.method.Sign(h+"."+p, privKey(a.key))
	if err != nil {
		panic(err)
	}
	tok := h + "." + p + "." + b64(string(sig))
	note := "alg " + a.name + " header " + hdr + " claims " + claims
	parts := strings.Split(tok, ".")
	switch r.Intn(10) {
	case 0:
		k := r.Intn(3)
		parts[k] = fuzzEdit(r, parts[k])
		tok = strings.Join(parts, ".")
		note += fmt.Sprintf("; segment %d edited", k)
	case 1:
		tok = fuzzEdit(r, tok)
		note += "; edited"
	case 2:
		tok = pick(r, tok+".", tok+"=", parts[0]+"."+parts[1], "."+tok, parts[0]+".."+parts[2])
		note += "; dots or padding"
	case 3:
		other := algs[r.Intn(len(algs))]
		o2, _ := other.method.Sign(h+"."+p, privKey(other.key))
		tok = h + "." + p + "." + b64(string(o2))
		note += "; signed with " + other.name
	}
	op := opts{now: pick[int64](r, 0, 999, 1000, 1000, 1000, 1499, 1500, 1501, 1999, 2000, 2001, 3000), leeway: pick[int64](r, 0, 0, 1, 5, 600)}
	switch r.Intn(8) {
	case 0:
		op.algs = []string{pick(r, "HS256", "RS256", "ES256", "EdDSA", "PS256", "HS512")}
	case 1:
		op.algs = []string{a.name, "HS256", "ES256"}
	default:
		op.algs = []string{a.name}
	}
	if r.Intn(3) == 0 {
		op.iss = pick(r, "me", "you", "")
	}
	if r.Intn(3) == 0 {
		op.aud = pick(r, "x", "y", "z")
	}
	if r.Intn(4) == 0 {
		op.sub = pick(r, "ann", "bob")
	}
	op.noExp = r.Intn(3) == 0
	key := a.key
	if r.Intn(8) == 0 {
		key = a.other
	}
	return tok, key, op, note
}

// algKey is the key the corpus signs alg with ("" for an unknown alg).
func algKey(name string) string {
	for _, a := range algs {
		if a.name == name {
			return a.key
		}
	}
	return ""
}

// keyFamily is a key's kind and curve: the second RSA key and HMAC secret
// fit where the first do.
func keyFamily(k string) string { return strings.TrimSuffix(k, "2") }
