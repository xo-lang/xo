// Command jweoracle prints the std/jwt JWE corpus (decision 0660):
// github.com/go-jose/go-jose/v4 v4.1.9 encrypts payloads with fixed keys
// under every key management and content encryption algorithm std/jwt
// has, then decrypts each token and changed copies of it; the Xo test
// checks that jwt.decrypt gives the same payload or fails where go-jose
// fails. Randomness is a constant stream (package seed), so every
// regeneration prints the same tokens. scripts/stdcorpus runs it; it is
// its own module so the repository's go.mod has no third-party requirement.
//go:debug cryptocustomrand=1

