// The reverse direction (decision 0660's condition, task #39): std/jwt
// encrypts and go-jose decrypts. `jweoracle reverse` prints an Xo program
// that encrypts a payload under every key management and content
// encryption combination with the corpus's keys and prints one line a
// token (key name, payload hex, kid, token); `jweoracle decrypt` reads
// those lines and decrypts each with go-jose, checking the payload and the
// kid. internal/stdtest's TestJweGoJoseDecrypts runs both on each backend.

func reverseProgram() string {
	var o strings.Builder
	o.WriteString("// Generated by jweoracle reverse: std/jwt encrypts, go-jose decrypts (TestJweGoJoseDecrypts).\n")
	o.WriteString("use std/jwt\nuse std/crypto\n\n")
	o.WriteString("const PASSWORD: Str = " + xq(password) + "\n\n")
	o.WriteString("const KEYS: List[(Str, Str, Str)] = [\n")
	for _, n := range []string{"rsa", "p256", "p384", "p521"} {
		o.WriteString("  (" + xq(n) + ", " + xq(keyPEMs[n][0]) + ", " + xq(keyPEMs[n][1]) + "),\n")
	}
	o.WriteString("]\n\nconst COMBOS: List[(jwt.KeyAlg, jwt.Enc, Str)] = [\n")
	for _, a := range algs {
		for _, e := range encs {
			fmt.Fprintf(&o, "  (jwt.KeyAlg.%s, jwt.Enc.%s, %s),\n", a.xo, e.xo, xq(keyName(a.key, e.size)))
		}
	}
	o.WriteString("]\n")
	o.WriteString(jweHelpers)
	o.WriteString(`
fn main(os: Os) {
  for (i, (a, e, k)) in COMBOS.indexed() {
    // empty, short and long payloads; deflate on every third
    let payload = if i % 5 == 0 { b"" } else { "payload ${i} ".repeat(i % 7 * 40 + 1).bytes() }
    let opts = jwt.JweOptions{kid: Some("k${i}"), typ: if i % 2 == 0 { Some("JWT") } else { None }, deflate: i % 3 == 0, p2c: 1000 + i}
    let tok = jwt.encrypt(os.rand, a, e, enc_key(k), payload, opts).or_fault("encrypt ${i}")
    os.stdio.println("${k}\t${payload.to_hex()}\tk${i}\t${tok}")
  }
}
`)
	return o.String()
}

// decryptLines decrypts each line's token with go-jose and reports every
// line whose payload or kid differs; the exit status is 1 when one does or
// when no line came.
func decryptLines(in io.Reader, out io.Writer) int {
	sc := bufio.NewScanner(in)
	sc.Buffer(make([]byte, 1<<20), 1<<24)
	n, bad := 0, 0
	for sc.Scan() {
		f := strings.Split(sc.Text(), "\t")
		if len(f) != 4 {
			fmt.Fprintf(out, "bad line %q\n", sc.Text())
			bad++
			continue
		}
		n++
		key, want, kid, tok := f[0], f[1], f[2], f[3]
		obj, err := jose.ParseEncryptedCompact(tok, allAlgs, allEncs)
		if err != nil {
			fmt.Fprintf(out, "%s %s: parse: %v\n", kid, key, err)
			bad++
			continue
		}
		p, err := obj.Decrypt(decKey(key))
		if err != nil {
			fmt.Fprintf(out, "%s %s (%s %s): decrypt: %v\n", kid, key, obj.Header.Algorithm, obj.Header.ExtraHeaders["enc"], err)
			bad++
			continue
		}
		if hex.EncodeToString(p) != want {
			fmt.Fprintf(out, "%s %s: payload differs\n", kid, key)
			bad++
		}
		if obj.Header.KeyID != kid {
			fmt.Fprintf(out, "%s %s: kid %q\n", kid, key, obj.Header.KeyID)
			bad++
		}
	}
	fmt.Fprintf(out, "%d tokens, %d bad\n", n, bad)
	if bad > 0 || n == 0 {
		return 1
	}
	return 0
}
