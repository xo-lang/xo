func pick(r *rand.Rand, xs []string) string { return xs[r.Intn(len(xs))] }

var (
	intForms  = []string{"0", "1", "-5", "42", "0x1F", "0o17", "0b101", "017", "1_000", "+3", "9223372036854775807", "9223372036854775808", "-9223372036854775809", "18446744073709551615", "18446744073709551616", "1e3", "1.5", "-1.9", ".inf", "~", "null", "\"5\"", "'5'", "yes", "true", "abc", "\"\"", "1:30", "0x", "[1]", "{a: 1}", "!!int 7", "!!int x", "!!float 3", "!!str 5", "! 5", "2001-12-14", "1,000", "12e", "00", "08"}
	fltForms  = []string{"0", "1.5", ".5", "-.5", "1e10", "1E-3", "1_0.5", ".inf", "-.Inf", ".NAN", "0x10", "1:30", "12:30:45.5", "1e400", "x", "~", "true", "\"2.5\"", "+1.5", "5.", "1.2.3", "!!float 1", "!!float x", "[1.5]", "9223372036854775808", "-0"}
	strForms  = []string{"x", "hello world", "123", "true", "null", "~", "\"q\\nr\"", "'it''s'", "\"\"", "''", "|\n  line1\n  line2\n", ">\n  fold1\n  fold2\n", "|-\n  a\n", "[1, 2]", "{a: b}", "!!binary aGVsbG8=", "!!binary @@", "!!str 5", "&a v", "*a", "a: b", "- x", "é日本", "\"\\u00e9\"", "# not comment", "a #c", "'\\n'", "\"\\x41\"", "0x1F", "yes", "1.50"}
	boolForms = []string{"true", "false", "True", "FALSE", "yes", "no", "y", "n", "on", "off", "On", "1", "0", "\"true\"", "~", "null", "maybe", "!!bool true", "!!bool yes", "[true]"}
	listForms = []string{"[]", "[1, 2, 3]", "~", "[1, ~, 3]", "[a]", "5", "{a: 1}", "[1.5]", "[0x10]", "[[1]]", "[1, 2,]", "[ 1 , 2 ]", "!!seq [1]", "\n  - 1\n  - 2", "\n  - 1\n  - ~\n  - 3", "\n- 4\n- 5", "[\"1\"]", "[true]"}
	mapForms  = []string{"{}", "{a: b}", "~", "[a]", "{a: ~, b: 1}", "{1: x}", "{? [a]: b}", "{a: [1]}", "{a: {b: c}}", "{a: b, a: c}", "\n  a: b\n  c: d", "\n  a: 1\n  b: \"2\"", "!!map {a: b}", "{\"k k\": v}", "{a: }", "{a}", "{? a}", "{~: x}", "{true: y}", "{1.5: z}"}
	inForms   = []string{"{x: 1}", "~", "5", "[1]", "{x: a}", "{y: 1}", "{x: 1, x: 2}", "\n  x: 3", "\n  x: 3\n  y: 4", "!!map {x: 1}", "{x: 0x10}", "{}"}
)

func fuzzDoc(r *rand.Rand) string {
	keyForms := map[string][]string{"n": intForms, "f": fltForms, "s": strForms, "b": boolForms, "o": strForms, "l": listForms, "m": mapForms, "in": inForms}
	keys := []string{"n", "f", "s", "b", "o", "l", "m", "in"}
	var b strings.Builder
	nl := pick(r, []string{"\n", "\n", "\n", "\r\n"})
	switch r.Intn(12) {
	case 0:
		b.WriteString("---" + nl)
	case 1:
		b.WriteString("%YAML 1.1" + nl + "---" + nl)
	case 2:
		b.WriteString("# comment" + nl)
	}
	if r.Intn(10) == 0 {
		// a flow mapping document
		var ps []string
		for i := 0; i < 1+r.Intn(4); i++ {
			k := pick(r, keys)
			v := pick(r, keyForms[k])
			if strings.ContainsAny(v, "\n") {
				v = "x"
			}
			ps = append(ps, k+": "+v)
		}
		b.WriteString("{" + strings.Join(ps, ", ") + "}" + nl)
		return b.String()
	}
	n := 1 + r.Intn(7)
	anchored := false
	for i := 0; i < n; i++ {
		k := pick(r, keys)
		switch r.Intn(25) {
		case 0:
			k = pick(r, []string{"zz", "N", "\"n\"", "'s'", "? n", "n ", "1", "~", "true"})
		case 1:
			if !anchored {
				b.WriteString("base: &a {n: 1, s: from_anchor}" + nl)
				anchored = true
			}
			b.WriteString("<<: *a" + nl)
			continue
		case 2:
			b.WriteString("<<: " + pick(r, []string{"{n: 2}", "[{n: 3}, {n: 4, s: z}]", "{s: m}", "5", "~"}) + nl)
			continue
		case 3:
			b.WriteString("# a comment" + nl)
			continue
		}
		forms := keyForms[strings.Trim(k, "?\"' ")]
		if forms == nil {
			forms = strForms
		}
		v := pick(r, forms)
		if strings.HasPrefix(v, "\n") || strings.HasPrefix(v, "|") || strings.HasPrefix(v, ">") {
			b.WriteString(k + ":" + v)
			if !strings.HasSuffix(v, "\n") {
				b.WriteString(nl)
			}
		} else {
			b.WriteString(k + ": " + v + pick(r, []string{"", "", "", " # c"}) + nl)
		}
	}
	switch r.Intn(14) {
	case 0:
		b.WriteString("...\n---\nn: 2\n")
	case 1:
		b.WriteString("---\ns: second\n")
	}
	return b.String()
}

func fuzzCases(seed int64, n int) []string {
	r := rand.New(rand.NewSource(seed))
	var out []string
	for len(out) < n {
		raw := []byte(fuzzDoc(r))
		switch r.Intn(10) {
		case 0:
			raw = raw[:r.Intn(len(raw)+1)]
		case 1:
			if len(raw) > 0 {
				mut := "=[]{}\"'.#,\n :-&*!|>?"
				raw[r.Intn(len(raw))] = mut[r.Intn(len(mut))]
			}
		}
		if utf8.Valid(raw) {
			out = append(out, string(raw))
		}
	}
	return out
}

// safeShow is show, false when yaml.v3 panics on the document.
func safeShow(in []byte) (s string, ok bool) {
	defer func() {
		if recover() != nil {
			ok = false
		}
	}()
	return show(in), true
}

func fuzzMain(seedArg, nArg string) {
	seed, err := strconv.ParseInt(seedArg, 10, 64)
	if err != nil {
		panic(err)
	}
	n, err := strconv.Atoi(nArg)
	if err != nil {
		panic(err)
	}
	var o strings.Builder
	fmt.Fprintf(&o, "// Generated by scripts/stdcorpus from gopkg.in/yaml.v3 v3.0.1's Unmarshal on seeded random documents (seed %d, %d documents).\n", seed, n)
	o.WriteString("// Do not edit: regenerate with go run ./scripts/stdcorpus.\n")
	o.WriteString(xoPrelude)
	o.WriteString("/// (the YAML text, what yaml.v3 decodes it into T as)\nconst CASES: List[(Str, Str)] = [\n")
	skipped := 0
	for _, d := range fuzzCases(seed, n) {
		want, ok := safeShow([]byte(d))
		if !ok {
			skipped++ // yaml.v3 itself panics: no answer to compare with
			continue
		}
		fmt.Fprintf(&o, "  (%s, %s),\n", xq(d), xq(want))
	}
	fmt.Fprintf(os.Stderr, "yamloracle: %d documents skipped (yaml.v3 panics)\n", skipped)
	o.WriteString("]\n\n")
	// the same documents as Node trees, as encode_node text and as JSON
	o.WriteString("/// (the YAML text, what yaml.v3 parses it into as Node trees, writes back for the first, and decodes into an any then json.Marshal writes)\nconst NODE_CASES: List[(Str, Str, Str, Str)] = [\n")
	for _, d := range fuzzCases(seed, n) {
		if _, ok := safeShow([]byte(d)); !ok {
			continue
		}
		fmt.Fprintf(&o, "  (%s, %s, %s, %s),\n", xq(d), xq(nodesShow(d)), xq(emitShow(d)), xq(jsonShow(d)))
	}
	o.WriteString("]\n\ntest \"yaml fuzz: decode into a struct that derives Yaml is yaml.v3's Unmarshal\" {\n  for (text, want) in CASES {\n    expect(show(text)) == want\n  }\n}\n\ntest \"yaml fuzz: parse_all, encode_node and to_json are yaml.v3's\" {\n  for (text, nodes, emit, json) in NODE_CASES {\n    expect(show_nodes(text)) == nodes\n    if emit != \"SKIP\" {\n      expect(show_emit(text)) == emit\n    }\n    if json != \"SKIP\" {\n      expect(show_json(text)) == json\n    }\n  }\n}\n")
	fmt.Print(o.String())
}
