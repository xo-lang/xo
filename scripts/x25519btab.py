#!/usr/bin/env python3
# Generates std/native/llrt/x25519_btab.xo (python3 scripts/x25519btab.py
# > std/native/llrt/x25519_btab.xo): the fixed base table of x25519.xo's
# base (and Ed25519's signing), as Go's edwards25519 basepointTable: for i 0 to 31 and j 1 to 8,
# the multiple j 256^i B of the twisted Edwards curve's base point B
# (RFC 8032 5.1, the curve birationally equivalent to Curve25519, B
# mapping to u = 9), affine, as (y + x, y - x, 2 d x y) modulo p, each
# four 64 bit limbs, the lowest first.
p = 2**255 - 19
d = (-121665 * pow(121666, p - 2, p)) % p
by = (4 * pow(5, p - 2, p)) % p
bx = 15112221349535400772501151409588531511454012693041857206046113283949847762202
assert (-bx * bx + by * by - 1 - d * bx * bx * by * by) % p == 0
# B maps to u = (1 + y) / (1 - y) = 9
assert (1 + by) * pow(1 - by, p - 2, p) % p == 9


def add(a, b):
    x1, y1 = a
    x2, y2 = b
    t = d * x1 * x2 * y1 * y2 % p
    x3 = (x1 * y2 + y1 * x2) * pow(1 + t, p - 2, p) % p
    y3 = (y1 * y2 + x1 * x2) * pow(1 - t, p - 2, p) % p
    return (x3, y3)


def limbs(v):
    out = []
    for k in range(4):
        w = (v >> (64 * k)) & (2**64 - 1)
        if w >= 2**63:
            w -= 2**64
        assert w != -(2**63)
        out.append(w)
    return out


words = []
base = (bx, by)
for i in range(32):
    q = base
    for j in range(1, 9):
        x, y = q
        words += limbs((y + x) % p) + limbs((y - x) % p) + limbs(2 * d * x * y % p)
        q = add(q, base)
    # base becomes 256 base
    for _ in range(8):
        base = add(base, base)
assert len(words) == 32 * 8 * 12

# Go's basepointNafTable (nafLookupTable8): the odd multiples (2 k + 1) B
# for k 0 to 63, the same form, for Ed25519 verification's double scalar
# multiplication (variable time: its inputs are public)
naf = []
b2 = add((bx, by), (bx, by))
q = (bx, by)
for k in range(64):
    x, y = q
    naf += limbs((y + x) % p) + limbs((y - x) % p) + limbs(2 * d * x * y % p)
    q = add(q, b2)
assert len(naf) == 64 * 12

print("// Generated by scripts/x25519btab.py: the twisted Edwards curve's base")
print("// point's multiples j 256^i B for i 0 to 31 and j 1 to 8 (Go's")
print("// edwards25519 basepointTable), affine, as (y + x, y - x, 2 d x y)")
print("// modulo 2^255 - 19, each four 64 bit limbs, the lowest first: entry")
print("// (i, j) at word 12 (8 i + j - 1). x25519.xo base reads it. Do not edit")
print("// by hand.")
print()
print("/// X25519's fixed base table (see the file's head).")
print("pub const BTAB: List[Int] = [")
for r in range(0, len(words), 12):
    print("  " + ", ".join(str(w) for w in words[r:r + 12]) + ",")
print("]")
print()
print("/// Ed25519 verification's table: the odd multiples (2 k + 1) B for k 0")
print("/// to 63 (Go's basepointNafTable), the same form: entry k at word 12 k.")
print("pub const BNAF: List[Int] = [")
for r in range(0, len(naf), 12):
    print("  " + ", ".join(str(w) for w in naf[r:r + 12]) + ",")
print("]")
print()
print("/// 2 d modulo 2^255 - 19, four 64 bit limbs (Go's d2).")
print("pub const D2: List[Int] = [" + ", ".join(str(w) for w in limbs(2 * d % p)) + "]")
