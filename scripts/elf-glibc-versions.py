#!/usr/bin/env python3
# Writes selfhost/macho/glibc.xo, the symbol versions the ELF linker
# (decision 0182 stage 3) gives its imports, from a linux/arm64 glibc and
# libgcc_s: scripts/elf-glibc-versions.py DIR > selfhost/macho/glibc.xo,
# where DIR holds libc.so.6, libm.so.6, libpthread.so.0, and
# libgcc_s.so.1, for example copied out of Debian bullseye (glibc 2.31,
# the runtime pack's floor, decision 0157):
#   docker run --rm --platform linux/arm64 debian:bullseye tar -chf - \
#     -C /lib/aarch64-linux-gnu libc.so.6 libm.so.6 libpthread.so.0 \
#     libgcc_s.so.1 | tar -xf - -C DIR
# Every symbol's default version is listed, except libc.so.6's
# GLIBC_2.17 ones (the linker's default), GLIBC_PRIVATE, and libm's
# _FloatN aliases.
#
# --amd64 DIR > selfhost/macho/glibc_amd64.xo: the same from linux/amd64
# (decision 0254 stage 4; /lib/x86_64-linux-gnu, --platform linux/amd64),
# whose base version is GLIBC_2.2.5.
import os, re, struct, sys

LIBS = ['libc.so.6', 'libm.so.6', 'libpthread.so.0', 'libgcc_s.so.1']


def versions(path):
    b = open(path, 'rb').read()
    shoff = struct.unpack_from('<Q', b, 40)[0]
    shnum = struct.unpack_from('<H', b, 60)[0]
    hdrs = [struct.unpack_from('<IIQQQQIIQQ', b, shoff + 64 * i) for i in range(shnum)]

    def cstr(o):
        return b[o:b.index(b'\0', o)].decode()

    dynsym = [h for h in hdrs if h[1] == 11][0]
    strtab = hdrs[dynsym[6]][4]
    versym = [h for h in hdrs if h[1] == 0x6fffffff][0]
    verdef = [h for h in hdrs if h[1] == 0x6ffffffd][0]
    names = {}
    dstr = hdrs[verdef[6]][4]
    off = verdef[4]
    while True:
        _, flags, ndx, cnt, _, aux, nxt = struct.unpack_from('<HHHHIII', b, off)
        names[ndx] = cstr(dstr + struct.unpack_from('<I', b, off + aux)[0])
        if nxt == 0:
            break
        off += nxt
    out = []
    for k in range(dynsym[5] // 24):
        n, info, other, shn, val, size = struct.unpack_from('<IBBHQQ', b, dynsym[4] + 24 * k)
        if shn == 0 or n == 0:
            continue
        v = struct.unpack_from('<H', b, versym[4] + 2 * k)[0]
        if v & 0x8000 or (v & 0x7fff) < 2:
            continue
        out.append((cstr(strtab + n), names[v & 0x7fff]))
    return out


def main():
    amd64 = sys.argv[1] == '--amd64'
    d = sys.argv[-1]
    base = 'GLIBC_2.2.5' if amd64 else 'GLIBC_2.17'
    arch = 'linux/amd64' if amd64 else 'linux/arm64'
    groups = {}
    for lib in LIBS:
        for name, ver in versions(os.path.join(d, lib)):
            if ver == 'GLIBC_PRIVATE' or name == ver:
                continue
            if lib == 'libc.so.6' and ver == base:
                continue
            if lib in ('libm.so.6', 'libc.so.6') and re.search(r'f(32|64|128)x?(_l)?$', name):
                continue
            groups.setdefault((lib, ver), set()).add(name)
    print('// The symbol versions of the ELF linker\'s imports (decision 0182')
    print('// stage 3): the default version of every symbol of glibc 2.31\'s')
    print('// libc.so.6, libm.so.6, libpthread.so.0, and libgcc_s.so.1 on')
    print('// %s (Debian bullseye), as `cc` binds them, but libc.so.6\'s' % arch)
    print('// %s ones (the default). Generated by' % base)
    print('// scripts/elf-glibc-versions.py%s; do not edit.' % (' --amd64' if amd64 else ''))
    print('')
    print('const GLIBC_VERSIONS%s = """' % ('_AMD64' if amd64 else ''))
    for (lib, ver) in sorted(groups):
        names = sorted(groups[(lib, ver)])
        line = ''
        for n in names:
            if len(line) + len(n) > 90:
                print('%s %s%s' % (lib, ver, line))
                line = ''
            line += ' ' + n
        if line:
            print('%s %s%s' % (lib, ver, line))
    print('"""')


main()
