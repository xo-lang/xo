// nistecg256 prints std/native/llrt/nistec_g256.xo, the multiples
// j 16^w G of P-256's base point (w 0..63, j 1..15), affine, in the
// Montgomery domain (x 2^256 mod p), little endian 64 bit limbs as Int
// literals:
//
//	go run ./scripts/nistecg256 > std/native/llrt/nistec_g256.xo
package main

import (
	"crypto/elliptic"
	"fmt"
	"math/big"
	"os"
	"strings"
)

func main() {
	c := elliptic.P256()
	p := c.Params().P
	r := new(big.Int).Lsh(big.NewInt(1), 256)
	var words []string
	limbs := func(v *big.Int) {
		m := new(big.Int).Mod(new(big.Int).Mul(v, r), p)
		for i := 0; i < 4; i++ {
			w := new(big.Int).Rsh(m, uint(64*i))
			w.And(w, new(big.Int).SetUint64(^uint64(0)))
			words = append(words, fmt.Sprint(int64(w.Uint64())))
		}
	}
	for w := 0; w < 64; w++ {
		for j := 1; j < 16; j++ {
			k := new(big.Int).Lsh(big.NewInt(int64(j)), uint(4*w))
			x, y := c.ScalarBaseMult(k.Bytes())
			limbs(x)
			limbs(y)
		}
	}
	var b strings.Builder
	b.WriteString("// Generated by scripts/nistecg256 (math/big and crypto/elliptic): P-256's base\n")
	b.WriteString("// point's multiples j 16^w G for windows w 0 to 63 and digits j 1 to 15,\n")
	b.WriteString("// affine (x, y), in the Montgomery domain (x 2^256 mod p), each\n")
	b.WriteString("// coordinate four 64 bit limbs, the lowest first: entry (w, j) at word\n")
	b.WriteString("// 8 (15 w + j - 1). nistec.xo pt_mul_g reads it. Do not edit by hand.\n\n")
	b.WriteString("/// P-256's fixed base table (see the file's head).\n")
	b.WriteString("pub const G256: List[Int] = [\n")
	for i := 0; i < len(words); i += 8 {
		b.WriteString("  " + strings.Join(words[i:i+8], ", ") + ",\n")
	}
	b.WriteString("]\n")
	os.Stdout.WriteString(b.String())
}
