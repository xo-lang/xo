// gentuples writes std/rt/tuples_gen.go: the tuple types of 7 to Max
// elements (Tuple2 to Tuple6 are in core.go, show.go, and json.go), each
// with XoMark, XoDebug, XoEq, XoHash, XoCmp, XoJsonEnc, XoJsonDec. The Go
// backend names a tuple type TupleN for any N (compiler/gen go_type), so
// a wider tuple than the file has fails in go build; core 2.x sets no
// arity limit, and compiler/gen reports a tuple wider than Max as the Go
// backend's limit.
//
//	go run ./scripts/gentuples          # rewrite the file
//	go run ./scripts/gentuples -check   # fail when it is out of date
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strings"
)

// Max is the widest tuple std/rt declares; compiler/gen's GO_TUPLE_MAX
// must equal it.
const Max = 64

const path = "std/rt/tuples_gen.go"

func names(n int) []string {
	var out []string
	for i := 0; i < n; i++ {
		if i < 26 {
			out = append(out, string(rune('A'+i)))
		} else {
			out = append(out, fmt.Sprintf("T%d", i))
		}
	}
	return out
}

func fields(prefix string, n int) string {
	var fs []string
	for i := 0; i < n; i++ {
		fs = append(fs, fmt.Sprintf("%s.F%d", prefix, i))
	}
	return strings.Join(fs, ", ")
}

func gen() []byte {
	var b bytes.Buffer
	b.WriteString(`// Code generated by scripts/gentuples; DO NOT EDIT. The tuples of 7 to
// ` + fmt.Sprint(Max) + ` elements (Tuple2 to Tuple6 are in core.go, show.go, and json.go),
// with the same methods: XoMark, XoDebug, XoEq, XoHash, XoCmp, XoJsonEnc,
// XoJsonDec. The Go backend names a tuple type TupleN for any N; without
// these a wider tuple failed in go build.

package rt

import "strings"
`)
	for n := 7; n <= Max; n++ {
		ns := names(n)
		params := strings.Join(ns, ", ")
		ty := fmt.Sprintf("Tuple%d[%s]", n, params)
		fmt.Fprintf(&b, "\n// Tuple%d is a tuple of %d elements.\ntype Tuple%d[%s any] struct {\n", n, n, n, params)
		for i, x := range ns {
			fmt.Fprintf(&b, "\tF%d %s\n", i, x)
		}
		b.WriteString("}\n")
		fmt.Fprintf(&b, "\n// XoMark marks the lists held by the tuple's elements.\nfunc (t *%s) XoMark() {\n", ty)
		for i := range ns {
			fmt.Fprintf(&b, "\tMarkP(&t.F%d)\n", i)
		}
		b.WriteString("}\n")
		fmt.Fprintf(&b, "\n// XoDebug implements Debug.\nfunc (t %s) XoDebug(b *strings.Builder) {\n\ttupleDebug(b, %s)\n}\n", ty, fields("t", n))
		fmt.Fprintf(&b, "\n// XoEq implements Eq.\nfunc (t %s) XoEq(o any) bool {\n\tp, ok := o.(%s)\n\treturn ok && tupleEq([]any{%s}, []any{%s})\n}\n", ty, ty, fields("t", n), fields("p", n))
		fmt.Fprintf(&b, "\n// XoHash implements Hash.\nfunc (t %s) XoHash() uint64 {\n\treturn tupleHash(%s)\n}\n", ty, fields("t", n))
		fmt.Fprintf(&b, "\n// XoCmp implements Ord.\nfunc (t %s) XoCmp(o any) int {\n\tp := o.(%s)\n\treturn tupleCmp([]any{%s}, []any{%s})\n}\n", ty, ty, fields("t", n), fields("p", n))
		fmt.Fprintf(&b, "\n// XoJsonEnc encodes a tuple as an array.\nfunc (t %s) XoJsonEnc(tk *Task, w *JsonW) {\n\tw.ArrStart()\n", ty)
		for i := range ns {
			fmt.Fprintf(&b, "\tw.Elem()\n\tJsonEncP(tk, w, &t.F%d)\n", i)
		}
		b.WriteString("\tw.ArrEnd()\n}\n")
		fmt.Fprintf(&b, "\n// XoJsonDec decodes an array of %d elements.\nfunc (t *%s) XoJsonDec(tk *Task, x any, path string) *Json_DecodeErr {\n\treturn jsonTupleDec(x, path,\n", n, ty)
		for i := range ns {
			fmt.Fprintf(&b, "\t\tfunc(e any, p string) *Json_DecodeErr { return JsonDec(tk, &t.F%d, e, p) },\n", i)
		}
		b.WriteString("\t)\n}\n")
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	return out
}

func main() {
	check := flag.Bool("check", false, "fail when "+path+" is out of date")
	flag.Parse()
	want := gen()
	if *check {
		have, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(have, want) {
			fmt.Fprintf(os.Stderr, "%s is out of date: go run ./scripts/gentuples\n", path)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(path, want, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
