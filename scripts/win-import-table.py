#!/usr/bin/env python3
"""win-import-table.py: compiler/macho peimports.xo, the DLL that exports
each Windows function std/native/sys_windows.xo declares (decision 0254 6b
step 4: Xo's PE linker imports by this table, no SDK needed at link
time), read once from the import libraries of a Windows SDK (an xwin
sysroot: Windows Kits/10/Lib/VERSION/um/x64/*.lib, short import objects).

    python3 -I scripts/win-import-table.py SYSROOT > compiler/macho/peimports.xo
"""
import glob, os, re, struct, sys

def import_objects(path):
    d = open(path, 'rb').read()
    if not d.startswith(b'!<arch>\n'):
        return
    i = 8
    while i + 60 <= len(d):
        size = int(d[i + 48:i + 58].decode().strip())
        body = d[i + 60:i + 60 + size]
        # a short import object: Sig1 0, Sig2 0xFFFF, then the symbol and
        # the DLL name as C strings after the 20 byte header
        if len(body) > 20 and struct.unpack_from('<HH', body, 0) == (0, 0xFFFF):
            machine = struct.unpack_from('<H', body, 6)[0]
            names = body[20:].split(b'\0')
            if machine == 0x8664 and len(names) >= 2:
                yield names[0].decode(), names[1].decode()
        i += 60 + size + (size & 1)

def main():
    root = sys.argv[1]
    libs = sorted(glob.glob(os.path.join(root, 'Windows Kits', '10', 'Lib', '*', 'um', 'x64', '*.[Ll]ib')))
    here = os.path.dirname(os.path.abspath(__file__))
    decl = open(os.path.join(here, '..', 'std', 'native', 'sys_windows.xo')).read()
    want = sorted(set(re.findall(r'^fn ([A-Za-z_][A-Za-z0-9_]*)\(', decl, re.M)))
    # the libraries the runtime links (compiler/xo link.xo sys_link_args),
    # first, then the rest, so the first library naming a symbol wins
    order = ['kernel32', 'ws2_32', 'bcrypt', 'synchronization', 'ntdll', 'shell32', 'crypt32']
    libs.sort(key=lambda p: (order.index(os.path.basename(p).lower()[:-4]) if os.path.basename(p).lower()[:-4] in order else len(order), p.lower()))
    found = {}
    for lib in libs:
        for sym, dll in import_objects(lib):
            if sym in want and sym not in found:
                found[sym] = dll
    missing = [w for w in want if w not in found]
    if missing:
        sys.exit('not in any import library: ' + ' '.join(missing))
    print('// Generated by scripts/win-import-table.py from the Windows SDK\'s')
    print('// import libraries; do not edit. The DLL that exports each Windows')
    print('// function std/native/sys_windows.xo declares (decision 0254 6b step 4:')
    print('// Xo\'s PE linker, pelink.xo, imports by it).')
    print()
    print('/// The DLL of each imported Windows function.')
    print('pub fn pe_imports() -> Map[Str, Str] {')
    print('  {')
    for k in want:
        print(f'    "{k}": "{found[k]}",')
    print('  }')
    print('}')

main()
