#!/usr/bin/env python3
# Generates std/native/llrt/nistec.xo mul4p (python3 scripts/nistecmul4p.py): the Montgomery product for P-256's field
# prime p = 2^256 - 2^224 + 2^192 + 2^96 - 1 (limbs m0 = 2^64-1,
# m1 = 2^32-1, m2 = 0, m3 = 2^64-2^32+1; -p^-1 mod 2^64 = 1), CIOS over
# local words as mul4, the reduction by shifts.
out=[]
n=[0]
def v(p):
    n[0]+=1; return f"{p}{n[0]}"
def emit(s): out.append("  "+s)
def add(a,b):            # sum, carry
    s=v("s"); k=v("k")
    emit(f"let {s} = rt.int_wrap(0, {a}, {b})"); emit(f"let {k} = cpu.carry({a}, {b})"); return s,k
def wadd(a,b):
    s=v("w"); emit(f"let {s} = rt.int_wrap(0, {a}, {b})"); return s
for nm in ["f","g"]:
    for i in range(4): emit(f"let {nm}{i} = ld({nm}, {8*i})")
T=None
for i in range(4):
    # T += f * g_i
    if T is None:
        t=[]; c=None
        for j in range(4):
            lo=v("lo"); hi=v("hi")
            emit(f"let {lo} = rt.int_wrap(2, f{j}, g{i})"); emit(f"let {hi} = rt.u64_mul_hi(f{j}, g{i})")
            if c is None: t.append(lo); c=hi
            else:
                s,k=add(lo,c); t.append(s); c=wadd(hi,k)
        t.append(c); t.append("0")
    else:
        t=[]; c=None
        for j in range(4):
            lo=v("lo"); hi=v("hi")
            emit(f"let {lo} = rt.int_wrap(2, f{j}, g{i})"); emit(f"let {hi} = rt.u64_mul_hi(f{j}, g{i})")
            s,k=add(lo,T[j])
            if c is not None:
                s2,k2=add(s,c); s=s2; c=wadd(hi,wadd(k,k2))
            else:
                c=wadd(hi,k)
            t.append(s)
        s,k=add(T[4],c); t.append(s); t.append(wadd(T[5],k) if T[5]!="0" else k)
    # reduce: q = t0
    q=t[0]
    ql=v("ql"); qh=v("qh")
    emit(f"let {ql} = rt.int_wrap(3, {q}, 32)")
    emit(f"let {qh} = rt.int_wrap(4, {q}, 32)")
    # limb1: t1 + q*2^32 (with the q carried from limb 0)
    r1,k1=add(t[1],ql); c1=wadd(qh,k1)
    # limb2: t2 + c1
    r2,k2=add(t[2],c1)
    # limb3: t3 + q*m3 + k2, q*m3 = (q - ql) + 2^64 (q - qh - borrow(q, ql))
    lo3=v("lo"); hi3=v("hi")
    emit(f"let {lo3} = rt.int_wrap(1, {q}, {ql})")
    emit(f"let {hi3} = rt.int_wrap(1, rt.int_wrap(1, {q}, {qh}), cpu.borrow({q}, {ql}))")
    a3,ka=add(t[3],lo3); r3,kb=add(a3,k2); c3=wadd(hi3,wadd(ka,kb))
    # limb4
    r4,k4=add(t[4],c3)
    r5=wadd(t[5],k4) if t[5]!="0" else k4
    # shifted down a word: 5 words, the next round's top word 0
    T=[r1,r2,r3,r4,r5,"0"]
print("""/// mul4 for P-256's field prime (p's limbs 2^64 - 1, 2^32 - 1, 0,
/// 2^64 - 2^32 + 1; -1/p mod 2^64 = 1): CIOS over local words, each
/// reduction step by shifts (t0 + q m0 is q 2^64 exactly for q = t0, q
/// m1 + q is q 2^32, m2 is 0, q m3 is q 2^64 - q 2^32 + q). The same
/// result as mul4 with P-256's modulus; generated by
/// scripts/nistecmul4p.py.
fn mul4p(h: Int, f: Int, g: Int) {""")
print("\n".join(out))
print(f"  sub_m4(h, {T[0]}, {T[1]}, {T[2]}, {T[3]}, {T[4]}, -1, 4294967295, 0, -4294967295)")
print("}")
