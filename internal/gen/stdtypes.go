package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/xo-lang/xo/internal/ast"
	"github.com/xo-lang/xo/internal/check"
)

// preludeBuiltin lists prelude declarations the runtime implements by hand
// (core.go, list.go, ...), so StdTypes skips them.
var preludeBuiltin = map[string]bool{
	"Never": true, "Option": true, "Result": true,
	"Display": true, "Error": true, "Debug": true, "Eq": true, "Hash": true, "Ord": true, "Json": true, "OpenApi": true, "Proto": true, "SqlRow": true,
}

// StdTypes generates the Go declarations of the std structs, enums, and
// interfaces for package rt (std/rt/std_gen.go). Opaque handles (empty
// std structs) are written by hand in the runtime.
func StdTypes() ([]byte, error) {
	dir, err := os.MkdirTemp("", "xo-stdtypes-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(dir)
	src := "use std/cli\nuse std/http\nuse std/json\nuse std/log\nuse std/task\nuse std/time\n\nfn main() {}\n"
	if err := os.WriteFile(filepath.Join(dir, "all.xo"), []byte(src), 0o644); err != nil {
		return nil, err
	}
	res, err := check.Check([]string{dir})
	if err != nil {
		return nil, err
	}
	info := res.Info()
	g := &gen{info: info, pkgs: map[*check.Module]*pkgGen{}, modRoot: map[string]string{}, prelude: info.Prelude()}
	var mods []*check.Module
	for _, m := range info.AllModules() {
		if m.IsStd {
			mods = append(mods, m)
		}
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].Path < mods[j].Path })
	pg := &pkgGen{g: g, name: "rt", imports: map[string]string{}, adapt: map[string]bool{}, inRT: true}
	for _, m := range mods {
		pg.m = m
		for _, f := range m.Files {
			for _, d := range f.AST.Decls {
				var name string
				switch x := d.(type) {
				case *ast.StructDecl:
					name = x.Name.Name
				case *ast.EnumDecl:
					name = x.Name.Name
				case *ast.InterfaceDecl:
					name = x.Name.Name
				default:
					continue
				}
				t, ok := m.Scope[name].(*check.TypeObj)
				if !ok || t.Decl() != d {
					continue
				}
				if m.IsPrelude && preludeBuiltin[name] {
					continue
				}
				switch x := d.(type) {
				case *ast.StructDecl:
					if t.Opaque {
						continue
					}
					pg.genStructRT(t, x)
				case *ast.EnumDecl:
					pg.genEnum(t, x)
				case *ast.InterfaceDecl:
					pg.genInterface(t)
				}
			}
		}
	}
	if len(g.errs) > 0 {
		return nil, g.errList()
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen.StdTypes from std/*.xo. DO NOT EDIT.\n")
	b.WriteString("// Regenerate with: go test ./internal/gen -run TestStdTypes -update\n\n")
	b.WriteString("package rt\n\n")
	var paths []string
	for p := range pg.imports {
		if p == ModulePath+"/rt" {
			continue
		}
		paths = append(paths, p)
	}
	sort.Strings(paths)
	if len(paths) > 0 {
		b.WriteString("import (\n")
		for _, p := range paths {
			fmt.Fprintf(&b, "\t%q\n", p)
		}
		b.WriteString(")\n\n")
	}
	out := pg.out.String()
	// //line directives would point at std/*.xo, which is not part of the
	// build; drop them.
	var lines []string
	for _, l := range strings.Split(out, "\n") {
		if strings.HasPrefix(l, "//line ") {
			continue
		}
		lines = append(lines, l)
	}
	b.WriteString(strings.Join(lines, "\n"))
	return format.Source(b.Bytes())
}

// genStructRT is genStruct for std structs, which have no defaults or
// invariants.
func (pg *pkgGen) genStructRT(t *check.TypeObj, d *ast.StructDecl) {
	pg.genStruct(t, d)
}
