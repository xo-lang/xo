package gen

// Interface adapters for conversions in generic code.
//
// A value whose Go methods differ from an interface's (a method that
// cannot fail where the interface's can, or an error that converts) is
// wrapped in a generated adapter type when it is converted to the
// interface (ifaceAdapter in support.go). Generic Go code cannot do that:
// it converts a type parameter with rt.Iface, and the concrete type is
// only known at run time. So the generator records
//
//   - the interfaces generic code converts a type parameter to (targets;
//     for an interface whose arguments are type parameters, every
//     concrete instantiation of it seen in the program), and
//   - every concrete user type that appears in generated code (a value
//     reaching generic code has a concrete type that some code names),
//     and every instantiation of a std type whose methods are runtime
//     functions (List, Map, ...: rtFuncMethods), which has no Go methods,
//
// and generates, into package main, an adapter and an rt.RegAdapter call
// for every pair that type checks and needs one. rt.Iface consults the
// registry before giving up. Under --mono a specialized copy knows the
// concrete type and builds the adapter directly; the registry covers the
// generic fallback (and --no-mono).
//
// Residual gap: a concrete type that only exists inside generic code
// (generic code wrapping a type parameter, `Box[T]` instantiated only
// through T) is never named concretely, so it is not registered. Under
// --mono such code is specialized and does not need the registry.

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"

	"github.com/xo-lang/xo/internal/check"
)

// adaptState is the program wide record of what the registry may need.
type adaptState struct {
	kp      *pkgGen // keys types (Go type text as seen from package main)
	seen    map[*check.Named]bool
	types   map[string]check.Type
	targets map[string]check.Type
	objs    map[*check.TypeObj]bool // generic interfaces converted to with parameter arguments
}

func (g *gen) initAdapt() {
	g.ad = adaptState{
		kp:      &pkgGen{g: g, name: "main", imports: map[string]string{}, adapt: map[string]bool{}, noAdapt: true},
		seen:    map[*check.Named]bool{},
		types:   map[string]check.Type{},
		targets: map[string]check.Type{},
		objs:    map[*check.TypeObj]bool{},
	}
}

// noteType records a concrete user type named in generated code, or a std
// type whose methods are runtime functions (rtFuncMethods): it has no Go
// methods, so it satisfies an Xo interface only through an adapter.
func (pg *pkgGen) noteType(n *check.Named) {
	ad := &pg.g.ad
	if pg.noAdapt || ad.kp == nil || ad.seen[n] {
		return
	}
	ad.seen[n] = true
	if n.Obj.Module == nil || n.Obj.Module.IsStd && !rtFuncMethods(n.Obj) {
		return
	}
	var t check.Type = n
	if containsParam(t) {
		t = pg.monoType(t)
		if containsParam(t) {
			return
		}
	}
	ad.types[ad.kp.goType(t)] = t
}

// noteTarget records an interface that generic code converts a type
// parameter to with rt.Iface.
func (pg *pkgGen) noteTarget(to check.Type) {
	ad := &pg.g.ad
	if pg.noAdapt || ad.kp == nil {
		return
	}
	to = pg.monoType(to)
	n := pg.g.named(to)
	if n == nil || n.Obj.Kind != check.KInterface || n.Obj.Module.IsStd {
		return
	}
	if containsParam(to) {
		ad.objs[n.Obj] = true
		return
	}
	ad.targets[ad.kp.goType(to)] = to
}

// adaptFile is the Go source of package main's xo_adapt.go: the adapters
// and registrations rt.Iface may need (see the top of this file). It is
// always written, so a stale file from an earlier build cannot remain.
func (g *gen) adaptFile() ([]byte, error) {
	ad := &g.ad
	targets := map[string]check.Type{}
	for k, t := range ad.targets {
		targets[k] = t
	}
	for k, t := range ad.types {
		if n := g.named(t); n != nil && ad.objs[n.Obj] {
			targets[k] = t
		}
	}
	ap := &pkgGen{g: g, name: "main", imports: map[string]string{}, adapt: map[string]bool{}, noAdapt: true, noMono: true}
	var regs []string
	for _, tk := range sortedKeys(targets) {
		to := targets[tk]
		tn := g.named(to)
		for _, xk := range sortedKeys(ad.types) {
			from := ad.types[xk]
			if xk == tk || !hasMethodNames(g, from, tn) || !g.info.Implements(from, tn) {
				continue
			}
			name := ap.ifaceAdapter(from, to)
			if name == "" {
				continue
			}
			it, xt := ap.goType(to), ap.goType(from)
			regs = append(regs, fmt.Sprintf("\t%sRegAdapter[%s](func(v any) (%s, bool) {\n\t\tx, ok := v.(%s)\n\t\tif !ok {\n\t\t\treturn nil, false\n\t\t}\n\t\treturn %s{V: x}, true\n\t})", ap.rt(), it, it, xt, name))
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by xo. DO NOT EDIT.\n\n")
	b.WriteString("// Interface adapters for conversions of type parameters (rt.RegAdapter).\n\npackage main\n\n")
	if len(regs) == 0 {
		return format.Source(b.Bytes())
	}
	var paths []string
	for p := range ap.imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	b.WriteString("import (\n")
	for _, p := range paths {
		fmt.Fprintf(&b, "\t%s %q\n", ap.imports[p], p)
	}
	b.WriteString(")\n\n")
	b.Write(ap.out.Bytes())
	b.WriteString("func init() {\n" + strings.Join(regs, "\n") + "\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("gen: generated adapters do not parse: %v", err)
	}
	return src, nil
}

// hasMethodNames reports whether t has a method for every method name of
// interface iface (a cheap filter before Implements).
func hasMethodNames(g *gen, t check.Type, iface *check.Named) bool {
	for _, im := range iface.Obj.IfaceMeths {
		if m, _ := g.info.FindMethod(t, im.Name); m == nil {
			return false
		}
	}
	return true
}

func sortedKeys(m map[string]check.Type) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
