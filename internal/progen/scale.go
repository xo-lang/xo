package progen

import (
	"fmt"
	"strings"
)

// The scale suite's generator (bench/scale, design note
// knowledgebase/infrastructure/scale-suite.md): Scale(knob, n) writes a
// program that is large along one axis only, so build time, peak memory
// and binary size can be swept against n per axis, and ScaleWant gives
// the output the program must print, computed here, so every backend's
// result is checked against one value. The program reads its argument
// count plus 1 (1 when run with no arguments) so no backend folds the work to a
// constant.
//
// Knobs:
//   - fnlen: one function of n statements, a third of them ifs (blocks
//     and jumps grow with n: merge_jumps, read_var, dv_field)
//   - vars: n let bindings of one function, all live until a sum at its
//     end (register pressure, spill slots, frame size, debug variables)
//   - funcs: n functions in chains of 64 calls (symbols, call
//     relocations, functions per object)
//   - switch: one match of n Int arms (jump tables, compare trees)

// ScaleKnobs lists the knobs Scale knows, in sweep order.
var ScaleKnobs = []string{"fnlen", "vars", "funcs", "switch"}

// scaleMod keeps every value small, so no knob overflows at any n.
const scaleMod = 1000003

// scaleChain is the length of the funcs knob's call chains.
const scaleChain = 64

// Scale writes the program of knob at size n.
func Scale(knob string, n int) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// generated by internal/progen Scale(%q, %d)\n\n", knob, n)
	switch knob {
	case "fnlen":
		b.WriteString("fn big(x: Int) -> Int {\n  var a = x\n")
		for i := 0; i < n; i++ {
			if i%3 == 2 {
				fmt.Fprintf(&b, "  if a %% 7 == %d {\n    a = (a + %d) %% %d\n  }\n", i%7, i, scaleMod)
			} else {
				fmt.Fprintf(&b, "  a = (a * 31 + %d) %% %d\n", i, scaleMod)
			}
		}
		b.WriteString("  a\n}\n\nfn main(os: Os) {\n  os.stdio.println(\"${big(os.env.args().len() + 1)}\")\n}\n")
	case "vars":
		b.WriteString("fn big(x: Int) -> Int {\n")
		for i := 0; i < n; i++ {
			fmt.Fprintf(&b, "  let v%d = (x * %d + %d) %% %d\n", i, i%1000+1, i, scaleMod)
		}
		// a sum after the last binding, so every one is live to here
		b.WriteString("  var s = 0\n")
		for i := 0; i < n; i++ {
			fmt.Fprintf(&b, "  s = (s + v%d) %% %d\n", i, scaleMod)
		}
		b.WriteString("  s\n}\n\nfn main(os: Os) {\n  os.stdio.println(\"${big(os.env.args().len() + 1)}\")\n}\n")
	case "funcs":
		// f<i> calls f<i-1> inside a chain; main calls each chain's last
		for i := 0; i < n; i++ {
			if i%scaleChain == 0 {
				fmt.Fprintf(&b, "fn f%d(x: Int) -> Int {\n  (x * 3 + %d) %% %d\n}\n\n", i, i, scaleMod)
			} else {
				fmt.Fprintf(&b, "fn f%d(x: Int) -> Int {\n  (f%d(x) * 3 + %d) %% %d\n}\n\n", i, i-1, i, scaleMod)
			}
		}
		b.WriteString("fn main(os: Os) {\n  let x = os.env.args().len() + 1\n  var s = 0\n")
		for _, last := range scaleChainEnds(n) {
			fmt.Fprintf(&b, "  s = (s + f%d(x)) %% %d\n", last, scaleMod)
		}
		b.WriteString("  os.stdio.println(\"${s}\")\n}\n")
	case "switch":
		b.WriteString("fn arm(x: Int) -> Int {\n  match x {\n")
		for i := 0; i < n; i++ {
			fmt.Fprintf(&b, "    %d => %d\n", i, scaleArm(i))
		}
		fmt.Fprintf(&b, "    _ => -1\n  }\n}\n\nfn main(os: Os) {\n  let x = os.env.args().len() + 1\n  var s = 0\n  for i in 0..%d {\n    s = (s + arm(i * x - x + 1)) %% %d\n  }\n  os.stdio.println(\"${s}\")\n}\n", n+1, scaleMod)
	default:
		panic("progen.Scale: unknown knob " + knob)
	}
	return b.String()
}

// ScaleWant is the output of Scale(knob, n) run with no arguments.
func ScaleWant(knob string, n int) string {
	const x = 1
	var r int
	switch knob {
	case "fnlen":
		a := x
		for i := 0; i < n; i++ {
			if i%3 == 2 {
				if a%7 == i%7 {
					a = (a + i) % scaleMod
				}
			} else {
				a = (a*31 + i) % scaleMod
			}
		}
		r = a
	case "vars":
		s := 0
		for i := 0; i < n; i++ {
			s = (s + (x*(i%1000+1)+i)%scaleMod) % scaleMod
		}
		r = s
	case "funcs":
		f := make([]int, n)
		for i := 0; i < n; i++ {
			if i%scaleChain == 0 {
				f[i] = (x*3 + i) % scaleMod
			} else {
				f[i] = (f[i-1]*3 + i) % scaleMod
			}
		}
		s := 0
		for _, last := range scaleChainEnds(n) {
			s = (s + f[last]) % scaleMod
		}
		r = s
	case "switch":
		s := 0
		for i := 0; i <= n; i++ {
			v := -1
			if k := i*x - x + 1; k >= 0 && k < n {
				v = scaleArm(k)
			}
			s = (s + v) % scaleMod
		}
		r = s
	default:
		panic("progen.ScaleWant: unknown knob " + knob)
	}
	return fmt.Sprintln(r)
}

// scaleArm is the value of arm i: not linear in i, so the match stays a
// match and does not become arithmetic.
func scaleArm(i int) int { return i*7919%10007 + i%13 }

// scaleChainEnds are the last functions of the funcs knob's chains.
func scaleChainEnds(n int) []int {
	var ends []int
	for i := scaleChain - 1; i < n; i += scaleChain {
		ends = append(ends, i)
	}
	if n%scaleChain != 0 {
		ends = append(ends, n-1)
	}
	return ends
}
