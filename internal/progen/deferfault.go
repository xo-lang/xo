package progen

import (
	"fmt"
	"math/rand"
	"strings"
)

// DeferFaultProgram writes a program of seed whose functions fault inside
// deferred code: deferred blocks nested in deferred blocks, `let` and
// `for` patterns whose value faults (a list, Bytes, or Map loop inside a
// deferred block), deferred code in loops, and markers that show which
// deferred code ran. main runs each function under task.isolate with
// several arguments, some inside a scope's spawned task, so every backend
// must print the same lines: the deferred code registered before a fault
// runs, then the blocks around it (core 5.6, decision 0085;
// gotchas/native-deferred-block-fault-skips-defers.md). Program is not
// changed for it: the recorded parser dumps key on its text (decision
// 0217).
func DeferFaultProgram(seed int64) string {
	g := &dfg{r: rand.New(rand.NewSource(seed))}
	var b strings.Builder
	b.WriteString(dfPreamble)
	nf := 2 + g.r.Intn(3)
	var calls []string
	for i := 0; i < nf; i++ {
		f := fmt.Sprintf("case%d", i)
		g.fn = f
		body := g.stmts(0, 3)
		fmt.Fprintf(&b, "\nfn %s(io: Stdio, k: Int) -> Int uses stdio {\n%s\n  k\n}\n", f, indentLines(body, 1))
		for _, k := range []int{0, 1, 2, 3} {
			if g.r.Intn(3) == 0 {
				continue
			}
			label := fmt.Sprintf("%s(%d)", f, k)
			if g.r.Intn(4) == 0 {
				// in a spawned task: its fault reaches the scope
				calls = append(calls, fmt.Sprintf("show(io, %q, task.isolate(fn() -> Int ! () {\n    scope s {\n      s.spawn(fn() {\n        let _ = %s(io, %d)\n      })\n    }\n    0\n  }))", label+" task", f, k))
			} else {
				calls = append(calls, fmt.Sprintf("show(io, %q, task.isolate(fn() -> Int ! () { %s(io, %d) }))", label, f, k))
			}
		}
	}
	b.WriteString("\nfn main(os: Os) {\n  let io = os.stdio\n")
	for _, c := range calls {
		b.WriteString("  " + c + "\n")
	}
	b.WriteString("}\n")
	return b.String()
}

const dfPreamble = `// generated by TestDeferFaultProperty (internal/gen/deferfault_test.go)
use std/task

fn show(io: Stdio, label: Str, r: Result[Int, task.Isolated[()]]) uses stdio {
  match r {
    Ok(v) => io.println("${label}: ok ${v}")
    Err(task.Isolated.Faulted(info)) => io.println("${label}: fault ${info.msg} at ${info.location}")
    Err(_) => io.println("${label}: failed")
  }
}

// faults when k is 0
fn risky(label: Str, k: Int) -> Int {
  if k == 0 {
    fault("${label}")
  }
  12 / k
}
`

type dfg struct {
	r  *rand.Rand
	n  int
	fn string
}

func (g *dfg) name(p string) string {
	g.n++
	return fmt.Sprintf("%s%d", p, g.n)
}

// stmts is a list of 1 to 4 statements; depth counts the deferred blocks
// and nested blocks around them.
func (g *dfg) stmts(depth, max int) []string {
	var out []string
	n := 1 + g.r.Intn(4)
	for i := 0; i < n; i++ {
		out = append(out, g.stmt(depth, max))
	}
	return out
}

func (g *dfg) stmt(depth, max int) string {
	choice := g.r.Intn(9)
	if depth >= max && choice >= 4 {
		choice = g.r.Intn(4)
	}
	switch choice {
	case 0, 1: // a marker run at the block's end
		return fmt.Sprintf("defer io.println(\"  %s %s\")", g.fn, g.name("d"))
	case 2: // a let whose call faults for some k
		y := g.name("y")
		return fmt.Sprintf("let %s = risky(\"%s %s\", k - %d)\nio.println(\"  %s ${%s}\")", y, g.fn, y, g.r.Intn(4), y, y)
	case 3: // a plain statement
		return fmt.Sprintf("io.println(\"  %s %s\")", g.fn, g.name("p"))
	case 4, 5: // a deferred block
		return fmt.Sprintf("defer {\n%s\n}", indentLines(g.stmts(depth+1, max), 1))
	case 6: // a loop whose element is bound by a pattern
		v := g.name("x")
		z := g.name("z")
		switch g.r.Intn(3) {
		case 0:
			return fmt.Sprintf("for %s in [%d, %d, %d] {\n  let %s = risky(\"%s %s\", %s - k)\n  io.println(\"  %s ${%s}\")\n}", v, g.r.Intn(4), g.r.Intn(4), g.r.Intn(4), z, g.fn, z, v, z, z)
		case 1:
			return fmt.Sprintf("for %s in b\"ab\" {\n  let %s = risky(\"%s %s\", Int(%s) - 96 - k)\n  io.println(\"  %s ${%s}\")\n}", v, z, g.fn, z, v, z, z)
		default:
			kk := g.name("key")
			return fmt.Sprintf("for (%s, %s) in {\"a\": 1, \"b\": 2} {\n  let %s = risky(\"%s %s ${%s}\", %s - k)\n  io.println(\"  %s ${%s}\")\n}", kk, v, z, g.fn, z, kk, v, z, z)
		}
	case 7: // a nested block or a branch
		if g.r.Intn(2) == 0 {
			return fmt.Sprintf("{\n%s\n}", indentLines(g.stmts(depth+1, max), 1))
		}
		return fmt.Sprintf("if k > %d {\n%s\n}", g.r.Intn(3), indentLines(g.stmts(depth+1, max), 1))
	default: // deferred code in each iteration of a loop
		i := g.name("i")
		return fmt.Sprintf("for %s in 0..2 {\n  defer io.println(\"  %s iteration ${%s} defer\")\n%s\n}", i, g.fn, i, indentLines(g.stmts(depth+1, max), 1))
	}
}

// indentLines joins statements (each possibly several lines) indented by
// level steps of two spaces.
func indentLines(stmts []string, level int) string {
	pad := strings.Repeat("  ", level)
	var lines []string
	for _, s := range stmts {
		for _, l := range strings.Split(s, "\n") {
			lines = append(lines, pad+l)
		}
	}
	return strings.Join(lines, "\n")
}
