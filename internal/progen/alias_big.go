package progen

import (
	"fmt"
	"math/rand"
	"strings"
)

// AliasBig writes a program of seed for the one-field in-place update of a
// large list element (take_in_place): a struct of 12 to 16 fields of Int,
// Str, Float and List[Int], a list held by a var parameter, `xs[i].f = expr`
// and a var method setter `xs[i].set_f(v)`, a read of `xs[j].f` between (j
// may equal i), a call that pushes or pops on the same list between the read
// and the write, and the list shared (copied into another binding first) so
// copy-on-write must still copy. Each function runs with i == j and i != j.
func AliasBig(seed int64) string {
	r := rand.New(rand.NewSource(seed))
	n := 12 + r.Intn(5)
	kinds := make([]int, n) // 0 Int, 1 Str, 2 Float, 3 List[Int]
	for i := range kinds {
		kinds[i] = (i + r.Intn(2)) % 4
	}
	typ := []string{"Int", "Str", "Float", "List[Int]"}
	lit := func(k, e, f int) string {
		switch k {
		case 0:
			return fmt.Sprintf("%d", e*10+f)
		case 1:
			return fmt.Sprintf("\"s%d_%d\"", e, f)
		case 2:
			return fmt.Sprintf("%d.5", e*10+f)
		}
		return fmt.Sprintf("[%d, %d]", e, f)
	}
	// val writes a value of kind k from xs[j].f (a field of that kind), the index and constants
	val := func(k int, fs []int, src string) string {
		if len(fs) > 0 && r.Intn(3) > 0 {
			f := fs[r.Intn(len(fs))]
			switch k {
			case 0:
				return fmt.Sprintf("%s.f%d + i", src, f)
			case 1:
				return fmt.Sprintf("%s.f%d + \"x\"", src, f)
			case 2:
				return fmt.Sprintf("%s.f%d * 2.0", src, f)
			}
			return fmt.Sprintf("%s.f%d + [i]", src, f)
		}
		switch k {
		case 0:
			return fmt.Sprintf("j * %d", 3+r.Intn(5))
		case 1:
			return fmt.Sprintf("\"v%d\"", r.Intn(9))
		case 2:
			return fmt.Sprintf("%d.25", r.Intn(9))
		}
		return fmt.Sprintf("[j, %d]", r.Intn(9))
	}
	byKind := make([][]int, 4)
	for f, k := range kinds {
		byKind[k] = append(byKind[k], f)
	}
	var b strings.Builder
	b.WriteString("// generated by progen.AliasBig\n\nstruct W {\n")
	for f, k := range kinds {
		fmt.Fprintf(&b, "  f%d: %s\n", f, typ[k])
	}
	b.WriteString("}\n\n")
	for f, k := range kinds {
		fmt.Fprintf(&b, "pub fn (var w: W) set_f%d(v: %s) {\n  w.f%d = v\n}\n\n", f, typ[k], f)
	}
	b.WriteString("fn churn(var xs: List[W], i: Int) {\n  let last = xs[xs.len() - 1]\n  xs.push(last)\n  if i % 2 == 0 {\n    xs.pop()\n  }\n}\n\n")
	fns := 4 + r.Intn(3)
	for id := 0; id < fns; id++ {
		fmt.Fprintf(&b, "fn u%d(var xs: List[W], i: Int, j: Int) {\n", id)
		for s := 0; s < 3+r.Intn(4); s++ {
			f := r.Intn(n)
			k := kinds[f]
			switch r.Intn(4) {
			case 0: // read then write through the other index
				fmt.Fprintf(&b, "  let r%d = xs[j].f%d\n", s, f)
				fmt.Fprintf(&b, "  xs[i].f%d = %s\n", f, val(k, byKind[k], "xs[i]"))
				fmt.Fprintf(&b, "  xs[j].f%d = r%d\n", (f+1)%n, s)
				if kinds[(f+1)%n] != k {
					// a type mismatch is not allowed: undo the line above
					lines := strings.Split(strings.TrimRight(b.String(), "\n"), "\n")
					b.Reset()
					b.WriteString(strings.Join(lines[:len(lines)-1], "\n") + "\n")
					fmt.Fprintf(&b, "  xs[j].f%d = r%d\n", f, s)
				}
			case 1: // setter
				fmt.Fprintf(&b, "  xs[i].set_f%d(%s)\n", f, val(k, byKind[k], "xs[j]"))
			case 2: // churn between the read and the write
				fmt.Fprintf(&b, "  let q%d = xs[j].f%d\n", s, f)
				b.WriteString("  churn(xs, i)\n")
				fmt.Fprintf(&b, "  xs[i].f%d = q%d\n", f, s)
			default:
				fmt.Fprintf(&b, "  xs[i].f%d = %s\n", f, val(k, byKind[k], "xs[j]"))
			}
		}
		b.WriteString("}\n\n")
	}
	b.WriteString("fn show(xs: List[W]) -> Str {\n  var s = \"\"\n  for w in xs {\n    s = \"${s} (\"\n")
	for f := range kinds {
		if kinds[f] == 3 {
			fmt.Fprintf(&b, "    var t%d = 0\n    for x in w.f%d {\n      t%d = t%d * 7 + x\n    }\n    s = \"${s}${w.f%d.len()}:${t%d} \"\n", f, f, f, f, f, f)
			continue
		}
		fmt.Fprintf(&b, "    s = \"${s}${w.f%d} \"\n", f)
	}
	b.WriteString("    s = \"${s})\"\n  }\n  s\n}\n\n")
	b.WriteString("fn fresh() -> List[W] {\n  [")
	for e := 0; e < 3; e++ {
		if e > 0 {
			b.WriteString(", ")
		}
		b.WriteString("W{")
		for f, k := range kinds {
			if f > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "f%d: %s", f, lit(k, e, f))
		}
		b.WriteString("}")
	}
	b.WriteString("]\n}\n\nfn main(os: Os) {\n  for (i, j) in [(0, 0), (0, 1), (1, 0), (1, 1), (2, 2), (1, 2), (2, 0)] {\n")
	for id := 0; id < fns; id++ {
		fmt.Fprintf(&b, "    var a%d = fresh()\n    let snap%d = a%d\n    u%d(a%d, i, j)\n    os.stdio.println(\"u%d ${i} ${j}${show(a%d)} | ${show(snap%d)}\")\n", id, id, id, id, id, id, id, id)
	}
	b.WriteString("  }\n}\n")
	return b.String()
}
