package progen

import (
	"fmt"
	"math/rand"
	"strings"
)

// collKind is a local collection a Coll function changes in a loop.
type collKind struct {
	typ    string
	init   string
	size   func(c string) string
	grow   func(c, x string) string // a statement
	shrink func(c, x string) string // a statement, "" when the kind cannot shrink
	has    func(c, x string) string // a Bool expression
}

var collKinds = []collKind{
	{"Set[Int]", "#{}",
		func(c string) string { return c + ".len()" },
		func(c, x string) string { return c + ".add(" + x + ")" },
		func(c, x string) string { return "let _r = " + c + ".remove(" + x + ")" },
		func(c, x string) string { return c + ".contains(" + x + ")" }},
	{"List[Int]", "[]",
		func(c string) string { return c + ".len()" },
		func(c, x string) string { return c + ".push(" + x + ")" },
		func(c, x string) string { return "let _r = " + c + ".pop()" },
		func(c, x string) string {
			return "(" + c + ".len() > 0 && " + c + "[" + c + ".len() - 1] == " + x + ")"
		}},
	{"Map[Int, Int]", "{}",
		func(c string) string { return c + ".len()" },
		func(c, x string) string { return c + ".put(" + x + ", " + x + " * 3)" },
		func(c, x string) string { return "let _r = " + c + ".remove(" + x + ")" },
		func(c, x string) string { return c + ".contains(" + x + ")" }},
	{"Str", "\"\"",
		func(c string) string { return c + ".len()" },
		func(c, x string) string { return c + " = " + c + " + \"${(" + x + ") % 10}\"" },
		nil,
		func(c, x string) string { return c + ".contains(\"${(" + x + ") % 10}\")" }},
}

// Coll writes a program of seed whose functions each change a local Set,
// List, Map or Str in a loop and read its size and contents before and
// after the change, in loop conditions and in branches (the shape of a
// miscompile found 2026-11-01: a Set's len read around an add in a while
// loop). Every function returns a checksum that main prints.
func Coll(seed int64) string {
	r := rand.New(rand.NewSource(seed))
	var b strings.Builder
	b.WriteString("// generated by progen.Coll\n\n")
	n := 4 + r.Intn(5)
	for i := 0; i < n; i++ {
		b.WriteString(collFunc(r, i))
		b.WriteString("\n")
	}
	b.WriteString("fn main(os: Os) ! {\n")
	for i := 0; i < n; i++ {
		fmt.Fprintf(&b, "  os.stdio.println(\"f%d ${f%d(%d)}\")\n", i, i, r.Intn(7))
	}
	b.WriteString("}\n")
	return b.String()
}

func collFunc(r *rand.Rand, i int) string {
	k := collKinds[r.Intn(len(collKinds))]
	shape := r.Intn(7)
	if k.shrink == nil && shape == 5 {
		shape = 0
	}
	lim := 3 + r.Intn(9)
	mod := 2 + r.Intn(6)
	var body []string
	add := func(s string) { body = append(body, s) }
	add(fmt.Sprintf("var c: %s = %s", k.typ, k.init))
	add("var acc = k")
	step := func(v string) string { return "acc = (acc * 31 + " + v + ") % 1000003" }
	switch shape {
	case 0: // a flag loop around a size read (the miscompile)
		add("var more = true")
		add("var i = 0")
		add("while more {")
		add("  let n = " + k.size("c"))
		add(fmt.Sprintf("  if i < %d {", lim))
		add("    " + k.grow("c", "i"))
		add("  }")
		add("  i += 1")
		add("  more = " + k.size("c") + " != n")
		add("  " + step(k.size("c")))
		add("}")
	case 1: // size before and after in a counted loop
		add(fmt.Sprintf("for i in 0..%d {", lim*2))
		add("  let before = " + k.size("c"))
		add(fmt.Sprintf("  if i %% %d != 0 {", mod))
		add("    " + k.grow("c", "i+k"))
		add("  }")
		add("  " + step(k.size("c")+" - before"))
		add("}")
	case 2: // the size in the loop condition
		add("var i = 0")
		add(fmt.Sprintf("while %s < %d && i < 100 {", k.size("c"), lim))
		add("  " + k.grow("c", fmt.Sprintf("i * %d", 1+r.Intn(3))))
		add("  i += 1")
		add("  " + step(k.size("c")))
		add("}")
		add(step("i"))
	case 3: // break on contents or size
		add(fmt.Sprintf("for i in 0..%d {", lim*3))
		add("  " + k.grow("c", fmt.Sprintf("i %% %d", mod+1)))
		add("  if " + k.has("c", fmt.Sprintf("%d", r.Intn(mod+1))) + " {")
		add("    " + step("1000"))
		add("  }")
		add(fmt.Sprintf("  if %s >= %d {", k.size("c"), lim))
		add("    break")
		add("  }")
		add("  " + step(k.size("c")))
		add("}")
	case 4: // a fixpoint over a nested loop
		add("var more = true")
		add("while more {")
		add("  let n = " + k.size("c"))
		add(fmt.Sprintf("  for x in 0..%d {", lim))
		add("    if x == 0 || " + k.has("c", "x - 1") + " || x == k {")
		add("      " + k.grow("c", "x"))
		add("    }")
		add("  }")
		add("  more = " + k.size("c") + " != n")
		add("  " + step(k.size("c")))
		add("}")
	case 5: // grow and shrink chosen by the size
		add(fmt.Sprintf("for i in 0..%d {", lim*3))
		add(fmt.Sprintf("  if %s > %d {", k.size("c"), lim/2+1))
		add("    " + k.shrink("c", "i-1"))
		add("  } else {")
		add("    " + k.grow("c", "i"))
		add("  }")
		add("  " + step(k.size("c")))
		add("}")
	default: // a copy keeps its own size and contents
		add(fmt.Sprintf("for i in 0..%d {", lim))
		add("  " + k.grow("c", "i"))
		add("}")
		add("let snap = c")
		add("var j = 0")
		add(fmt.Sprintf("while j < %d {", mod+1))
		add("  " + k.grow("c", "j+100"))
		add("  j += 1")
		add("}")
		add(step(k.size("c")))
		add(step(k.size("snap")))
		add("if " + k.has("snap", "100") + " {")
		add("  " + step("7"))
		add("}")
	}
	add("return acc + " + k.size("c"))
	var b strings.Builder
	fmt.Fprintf(&b, "fn f%d(k: Int) -> Int {\n", i)
	for _, l := range body {
		b.WriteString("  " + l + "\n")
	}
	b.WriteString("}\n")
	return b.String()
}
