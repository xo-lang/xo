package progen

import (
	"fmt"
	"math/rand"
	"strings"
)

// AliasEmpty writes a program of seed for loop-entry reuse of the immortal
// empty list (rc.xo): a struct whose list field is left out of its literal
// (the declared default `[]`), another holder of that list before the loop (a
// local, another field, a closure), a loop that pushes to the field and reads
// or passes it between pushes, and in-place writes after a loop that may have
// run zero times. Each function runs with n of 0, 1 and several.
func AliasEmpty(seed int64) string {
	r := rand.New(rand.NewSource(seed))
	var b strings.Builder
	b.WriteString(`// generated by progen.AliasEmpty

struct R {
  name: Str
  xs: List[Int] = []
  alt: List[Int] = []
  tags: List[Str] = []
  k: Int
}

fn sum(xs: List[Int]) -> Int {
  var s = 0
  for x in xs { s += x }
  s
}

`)
	fns := 6 + r.Intn(5)
	for id := 0; id < fns; id++ {
		fmt.Fprintf(&b, "fn e%d(n: Int) -> Str {\n  var r = R{name: \"e%d\", k: %d}\n", id, id, r.Intn(5))
		out := []string{}
		holder := r.Intn(4)
		switch holder {
		case 0:
			b.WriteString("  let keep = r.xs\n")
			out = append(out, "keep ${keep.len()} ${sum(keep)}")
		case 1:
			b.WriteString("  r.alt = r.xs\n")
			if r.Intn(2) == 0 {
				b.WriteString("  r.alt.push(7)\n")
			}
		case 2:
			b.WriteString("  let held = r.xs\n  let f = fn() -> Int { held.len() * 100 + sum(held) }\n")
			out = append(out, "f ${f()}")
		}
		if r.Intn(3) == 0 {
			b.WriteString("  var snaps: List[List[Int]] = []\n  var total = 0\n")
			fmt.Fprintf(&b, "  for i in 0..n {\n    total += sum(r.xs)\n    snaps.push(r.xs)\n    r.xs.push(i + %d)\n", r.Intn(9))
			if r.Intn(2) == 0 {
				b.WriteString("    r.tags.push(\"t${r.xs.len()}\")\n")
			}
			if holder == 1 && r.Intn(2) == 0 {
				b.WriteString("    r.alt.push(i)\n")
			}
			b.WriteString("  }\n  var lens = \"\"\n  for s in snaps { lens = \"${lens}${s.len()},\" }\n")
			out = append(out, "total ${total} snaps ${lens}")
		} else {
			fmt.Fprintf(&b, "  for i in 0..n {\n    r.xs.push(i * %d)\n", 1+r.Intn(4))
			if r.Intn(3) == 0 {
				b.WriteString("    if i % 2 == 0 { r.xs.push(sum(r.xs)) }\n")
			}
			if holder == 1 && r.Intn(2) == 0 {
				b.WriteString("    r.alt.push(i)\n")
			}
			b.WriteString("  }\n")
		}
		post := []string{
			"  r.xs.insert(0, 5)\n", "  r.xs.heap_push(3)\n", "  r.xs.sort_in_place()\n",
			"  let p = r.xs.pop() ?? -1\n  out = out + p\n", "  r.xs.set(0, 9)\n", "  r.xs.push(4)\n",
		}
		b.WriteString("  var out = 0\n")
		for _, k := range r.Perm(len(post))[:r.Intn(4)] {
			s := post[k]
			if strings.Contains(s, "set(0") || strings.Contains(s, "insert") {
				// set needs an element: guard on the length
				if strings.Contains(s, "set(0") {
					s = "  if r.xs.len() > 0 { r.xs.set(0, 9) }\n"
				}
			}
			b.WriteString(s)
		}
		out = append(out, "xs ${r.xs.len()} ${sum(r.xs)} alt ${r.alt.len()} ${sum(r.alt)} tags ${r.tags.len()} out ${out}")
		fmt.Fprintf(&b, "  \"%s\"\n}\n\n", strings.Join(out, " "))
	}
	b.WriteString("fn main(os: Os) {\n  let k = os.env.args().len()\n  for n in [0 + k, 1 + k, 3 + k] {\n")
	for id := 0; id < fns; id++ {
		fmt.Fprintf(&b, "    os.stdio.println(e%d(n))\n", id)
	}
	b.WriteString("  }\n}\n")
	return b.String()
}
