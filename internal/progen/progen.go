// Package progen generates Xo programs for property tests (decision
// 0110): from a seed, a program that uses the optional parts of the syntax
// in random combinations (select arms, closures with and without declared
// types, every kind of pattern, defer, scopes, `?`, `??`, interpolation,
// literals, `with`, loops with labels). Every program checks clean.
// internal/gen's TestCompileProperty builds and runs them;
// internal/selfhost parses them with both parsers (decision 0127).
package progen

import (
	"fmt"
	"math/rand"
	"strings"
)

// pg writes one program: a fixed preamble of types and helpers, random
// feature functions, and a main that calls each of them.
type pg struct {
	inline int // > 0: inside `${}`, expressions stay on one line
	r      *rand.Rand
	n      int // fresh name counter
	decls  []string
	calls  []string // statements of main
}

// Program writes the program of seed: the preamble, 3 to 8 random
// feature functions, and a main that calls them.
func Program(seed int64) string {
	g := &pg{r: rand.New(rand.NewSource(seed))}
	features := []func(){g.fSelect, g.fClosure, g.fMatch, g.fDefer, g.fScope, g.fTry, g.fOptChain, g.fLoops, g.fValues, g.fNested, g.fNested}
	k := 3 + g.r.Intn(6)
	for i := 0; i < k; i++ {
		features[g.r.Intn(len(features))]()
	}
	var b strings.Builder
	b.WriteString(propPreamble)
	for _, d := range g.decls {
		b.WriteString("\n")
		b.WriteString(d)
	}
	b.WriteString("\nfn main(os: Os) ! {\n")
	for _, c := range g.calls {
		b.WriteString("  " + c + "\n")
	}
	b.WriteString("}\n")
	return b.String()
}

const propPreamble = `// generated by TestCompileProperty (internal/gen/compileprop_test.go)

enum Shape {
  Circle(r: Int)
  Rect(w: Int, h: Int)
  Dot
}

struct Pt {
  x: Int
  y: Int
}

type Id struct(Int)

enum Fail {
  Bad(msg: Str)
  Gone
} derive Display

fn may(n: Int) -> Int ! Fail {
  if n < 0 {
    return Err(Fail.Bad(msg: "negative ${n}"))
  }
  n
}

fn opt(n: Int) -> Int? {
  if n > 0 {
    return Some(n)
  }
  None
}
`

func (g *pg) name(p string) string {
	g.n++
	return fmt.Sprintf("%s%d", p, g.n)
}

func (g *pg) coin() bool { return g.r.Intn(2) == 0 }

func (g *pg) pick(xs ...string) string { return xs[g.r.Intn(len(xs))] }

// env is the locals in scope by type (Int, Str, Bool, List[Int], Pt,
// Shape, Int?).
type env map[string][]string

func (e env) with(t, name string) env {
	out := env{}
	for k, v := range e {
		out[k] = append([]string(nil), v...)
	}
	out[t] = append(out[t], name)
	return out
}

// ---------------------------------------------------------------------------
// Expressions of a type, depth bounded

func (g *pg) expr(t string, e env, d int) string {
	if vs := e[t]; len(vs) > 0 && g.r.Intn(3) == 0 {
		return vs[g.r.Intn(len(vs))]
	}
	if d <= 0 {
		return g.leaf(t, e)
	}
	switch t {
	case "Int":
		switch g.r.Intn(11) {
		case 0:
			return fmt.Sprintf("(%s %s %s)", g.expr("Int", e, d-1), g.pick("+", "-", "*"), g.expr("Int", e, d-1))
		case 1:
			return fmt.Sprintf("%s.len()", g.expr("List[Int]", e, d-1))
		case 2:
			return fmt.Sprintf("(%s ?? %s)", g.expr("Int?", e, d-1), g.expr("Int", e, d-1))
		case 3:
			return fmt.Sprintf("if %s { %s } else { %s }", g.expr("Bool", e, d-1), g.expr("Int", e, d-1), g.expr("Int", e, d-1))
		case 4:
			return fmt.Sprintf("%s.%s", g.expr("Pt", e, d-1), g.pick("x", "y"))
		case 5:
			if g.inline > 0 {
				return g.leaf("Int", e)
			}
			v := g.name("b")
			return fmt.Sprintf("{\n    let %s = %s\n    %s + 1\n  }", v, g.expr("Int", e, d-1), v)
		case 6:
			if g.inline > 0 {
				return g.leaf("Int", e)
			}
			return g.matchShape(e, d-1)
		case 7:
			return fmt.Sprintf("%s.len()", g.expr("Str", e, d-1))
		case 8:
			return fmt.Sprintf("%s.fold(0, fn(acc, v) { acc + v })", g.expr("List[Int]", e, d-1))
		case 9:
			return fmt.Sprintf("(%s.get(%s) ?? 0)", g.expr("Map[Str, Int]", e, d-1), g.expr("Str", e, d-1))
		default:
			return fmt.Sprintf("%s.0", g.expr("Id", e, d-1))
		}
	case "Str":
		g.inline++
		defer func() { g.inline-- }()
		switch g.r.Intn(5) {
		case 0:
			return fmt.Sprintf(`"n=${%s} s=${%s}"`, g.expr("Int", e, d-1), g.expr("Str", e, d-1))
		case 1:
			return fmt.Sprintf("(%s + %s)", g.expr("Str", e, d-1), g.expr("Str", e, d-1))
		case 2:
			return fmt.Sprintf(`"${%s.debug()}"`, g.pick(g.expr("Shape", e, d-1), g.expr("Pt", e, d-1), g.expr("List[Int]", e, d-1)))
		case 3:
			return fmt.Sprintf("%s.trim()", g.expr("Str", e, d-1))
		default:
			return fmt.Sprintf(`"${%s}"`, g.expr("Bool", e, d-1))
		}
	case "Bool":
		switch g.r.Intn(5) {
		case 0:
			return fmt.Sprintf("(%s %s %s)", g.expr("Int", e, d-1), g.pick("<", "<=", "==", "!=", ">"), g.expr("Int", e, d-1))
		case 1:
			return fmt.Sprintf("(%s %s %s)", g.expr("Bool", e, d-1), g.pick("&&", "||"), g.expr("Bool", e, d-1))
		case 2:
			return fmt.Sprintf("(%s is %s)", g.expr("Shape", e, d-1), g.pick("Circle(_)", "Rect(..)", "Dot", "Circle(1..=5)"))
		case 3:
			return fmt.Sprintf("!%s", g.expr("Bool", e, d-1))
		default:
			return fmt.Sprintf("%s.contains(%s)", g.expr("List[Int]", e, d-1), g.expr("Int", e, d-1))
		}
	case "Int?":
		switch g.r.Intn(4) {
		case 0:
			return fmt.Sprintf("Some(%s)", g.expr("Int", e, d-1))
		case 1:
			return fmt.Sprintf("opt(%s)", g.expr("Int", e, d-1))
		case 2:
			return fmt.Sprintf("%s.get(%s)", g.expr("List[Int]", e, d-1), g.expr("Int", e, d-1))
		default:
			return fmt.Sprintf("%s.first()", g.expr("List[Int]", e, d-1))
		}
	case "List[Int]":
		switch g.r.Intn(4) {
		case 0:
			return fmt.Sprintf("[%s, %s]", g.expr("Int", e, d-1), g.expr("Int", e, d-1))
		case 1:
			return fmt.Sprintf("%s.map(fn(v) { v * %d })", g.expr("List[Int]", e, d-1), 1+g.r.Intn(3))
		case 2:
			return fmt.Sprintf("%s.filter(fn(v: Int) -> Bool { v > %d })", g.expr("List[Int]", e, d-1), g.r.Intn(5))
		default:
			return fmt.Sprintf("(%s + [%s])", g.expr("List[Int]", e, d-1), g.expr("Int", e, d-1))
		}
	case "Map[Str, Int]":
		return fmt.Sprintf(`{"a": %s, %s: %s}`, g.expr("Int", e, d-1), g.expr("Str", e, d-1), g.expr("Int", e, d-1))
	case "Pt":
		if g.coin() {
			return fmt.Sprintf("Pt{x: %s, y: %s}", g.expr("Int", e, d-1), g.expr("Int", e, d-1))
		}
		return fmt.Sprintf("(%s with { %s: %s })", g.expr("Pt", e, d-1), g.pick("x", "y"), g.expr("Int", e, d-1))
	case "Shape":
		switch g.r.Intn(3) {
		case 0:
			return fmt.Sprintf("Shape.Circle(r: %s)", g.expr("Int", e, d-1))
		case 1:
			return fmt.Sprintf("Shape.Rect(w: %s, h: %s)", g.expr("Int", e, d-1), g.expr("Int", e, d-1))
		default:
			return "Shape.Dot"
		}
	case "Id":
		return fmt.Sprintf("Id(%s)", g.expr("Int", e, d-1))
	}
	return g.leaf(t, e)
}

func (g *pg) leaf(t string, e env) string {
	if vs := e[t]; len(vs) > 0 && g.coin() {
		return vs[g.r.Intn(len(vs))]
	}
	switch t {
	case "Int":
		return fmt.Sprint(g.r.Intn(20) - 5)
	case "Str":
		return g.pick(`"a"`, `" b "`, `""`, `"xo"`)
	case "Bool":
		return g.pick("true", "false")
	case "Int?":
		return g.pick("Some(3)", "opt(2)")
	case "List[Int]":
		return g.pick("[1, 2, 3]", "[0]", "[7, 8]")
	case "Map[Str, Int]":
		return `{"k": 1}`
	case "Pt":
		return "Pt{x: 1, y: 2}"
	case "Shape":
		return g.pick("Shape.Dot", "Shape.Circle(r: 2)", "Shape.Rect(w: 1, h: 3)")
	case "Id":
		return "Id(4)"
	}
	panic("no leaf of " + t)
}

// useAll is an Int expression that uses every binding of e (an unused
// binding is XO0110).
func (g *pg) useAll(e env) string {
	parts := []string{fmt.Sprint(g.r.Intn(5))}
	for t, vs := range e {
		for _, v := range vs {
			switch t {
			case "Int":
				parts = append(parts, v)
			case "Str", "List[Int]", "Map[Str, Int]":
				parts = append(parts, v+".len()")
			case "Pt":
				parts = append(parts, v+".x")
			case "Id":
				parts = append(parts, v+".0")
			case "Bool":
				parts = append(parts, "(if "+v+" { 1 } else { 0 })")
			case "Int?":
				parts = append(parts, "("+v+" ?? 0)")
			case "Shape":
				parts = append(parts, "\"${"+v+".debug()}\".len()")
			}
		}
	}
	return strings.Join(parts, " + ")
}

// matchShape is a match on a Shape whose arms use variant patterns
// (positional, named, `..`), or patterns that bind, guards, and `_`.
func (g *pg) matchShape(e env, d int) string {
	s := g.expr("Shape", e, d)
	var arms []string
	switch g.r.Intn(4) {
	case 0:
		// an or pattern binding the same name in both alternatives
		arms = append(arms, "Circle(v) | Rect(w: v, ..) => v", "Dot => 0")
	case 1:
		arms = append(arms, fmt.Sprintf("Circle(r) if r > %d => r", g.r.Intn(5)), "Circle(_) => -1", "Rect(w, h) => w * h", "Dot => 0")
	case 2:
		arms = append(arms, "Rect(w: a, h: b) => a + b", "Circle(r: r) => r", "_ => 7")
	default:
		arms = append(arms, "Dot => 1", "Circle(1..=3) | Circle(10) => 2", "Circle(..) => 3", "Rect(..) => 4")
	}
	return fmt.Sprintf("match %s {\n    %s\n  }", s, strings.Join(arms, "\n    "))
}

