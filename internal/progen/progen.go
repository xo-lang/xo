// Features: each adds a function and its call in main

func (g *pg) fSelect() {
	f := g.name("sel")
	var arms []string
	recv := g.r.Intn(3) // 0 none, 1 bound, 2 unbound
	if recv == 0 && !g.coin() {
		recv = 1
	}
	switch recv {
	case 1:
		arms = append(arms, "v = ch.recv() => got = v ?? -1")
	case 2:
		arms = append(arms, g.pick("ch.recv() => got = 1", "ch.recv() => {\n      got = 2\n    }"))
	}
	if g.coin() || len(arms) == 0 {
		arms = append(arms, fmt.Sprintf("out.send(%s) => got = 3", g.expr("Int", env{}, 1)))
	}
	if g.coin() {
		arms = append(arms, g.pick("after 1ms => got = 4", "after 5s => {}"))
	}
	g.r.Shuffle(len(arms), func(i, j int) { arms[i], arms[j] = arms[j], arms[i] })
	g.decls = append(g.decls, fmt.Sprintf(`fn %s(clock: Clock, k: Int) -> Int {
  let ch = Chan[Int].new(1)
  let out = Chan[Int].new(1)
  defer out.close()
  if k > 0 {
    ch.send(k)
  }
  var got = 0
  select {
    %s
  }
  let _c = clock.now()
  got
}
`, f, strings.Join(arms, "\n    ")))
	g.calls = append(g.calls, fmt.Sprintf("os.stdio.println(\"%s ${%s(os.clock, %d)}\")", f, f, g.r.Intn(3)))
}

func (g *pg) fClosure() {
	f := g.name("clo")
	var lines []string
	e := env{"Int": {"k"}}
	fails := false
	for i := 0; i < 1+g.r.Intn(3); i++ {
		c := g.name("c")
		body := g.expr("Int", e.with("Int", "a"), 2)
		switch g.r.Intn(6) {
		case 0: // everything declared
			lines = append(lines, fmt.Sprintf("let %s = fn(a: Int) -> Int { %s }", c, body))
			lines = append(lines, fmt.Sprintf("let r%s = %s(k)", c, c))
		case 1: // parameter type from the expected type
			lines = append(lines, fmt.Sprintf("let %s: fn(Int) -> Int = fn(a) { %s }", c, body))
			lines = append(lines, fmt.Sprintf("let r%s = %s(k)", c, c))
		case 2: // declared result and error type
			lines = append(lines, fmt.Sprintf("let %s = fn(a: Int) -> Int ! Fail { may(a)? + %s }", c, body))
			lines = append(lines, fmt.Sprintf("let r%s = %s(k)?", c, c))
			fails = true
		case 3: // error type inferred
			lines = append(lines, fmt.Sprintf("let %s = fn(a: Int) { may(a)? * 2 }", c))
			lines = append(lines, fmt.Sprintf("let r%s = %s(k)?", c, c))
			fails = true
		case 4: // passed to a higher order method
			lines = append(lines, fmt.Sprintf("let r%s = [k, 1].map(fn(a) { %s }).len()", c, body))
		default: // no result type, unit body
			lines = append(lines, fmt.Sprintf("let %s = fn(a: Int) {\n    let _u = a + 1\n  }", c))
			lines = append(lines, fmt.Sprintf("%s(k)", c))
			lines = append(lines, fmt.Sprintf("let r%s = 0", c))
		}
		e = e.with("Int", "r"+c)
	}
	ret, call := "Int", f+"(%d)"
	if fails {
		ret, call = "Int ! Fail", f+"(%d)?"
	}
	lines = append(lines, g.useAll(e))
	g.decls = append(g.decls, fmt.Sprintf("fn %s(k: Int) -> %s {\n  %s\n}\n", f, ret, strings.Join(lines, "\n  ")))
	g.calls = append(g.calls, fmt.Sprintf("os.stdio.println(\"%s ${%s}\")", f, fmt.Sprintf(call, g.r.Intn(9))))
}

func (g *pg) fMatch() {
	f := g.name("mat")
	e := env{"Int": {"k"}, "List[Int]": {"xs"}, "Shape": {"s"}, "Int?": {"o"}, "Pt": {"p"}}
	var parts []string
	for i := 0; i < 1+g.r.Intn(4); i++ {
		v := g.name("m")
		var m string
		switch g.r.Intn(7) {
		case 0: // list patterns
			m = fmt.Sprintf("match xs {\n    [] => 0\n    [a] => a\n    %s\n    [first, ..] => first\n  }", g.pick("[a, .., z] => a + z", "[.., z] if z > 2 => z", "[_, b] => b"))
		case 1: // newtype pattern
			m = fmt.Sprintf("match Id(%s) {\n    Id(n) => n\n  }", g.expr("Int", e, 1))
		case 2: // tuple, literal, range, and or patterns
			m = fmt.Sprintf("match (k, %s) {\n    (0, _) => 1\n    (1..=9, \"a\") | (1..=9, \"b\") => 2\n    (n, _) if n < 0 => n\n    (n, s2) => n + s2.len()\n  }", g.expr("Str", e, 1))
		case 3: // option with guard and a binding or pattern
			m = "match o {\n    Some(v) if v > 1 => v\n    Some(0) | None => 0\n    Some(v) => -v\n  }"
		case 4: // struct pattern
			m = "match p {\n    Pt{x: 0, ..} => 0\n    Pt{x, y} => x + y\n  }"
		case 5:
			m = g.matchShape(e, 1)
		default: // nested patterns and a Result
			m = "match may(k) {\n    Ok(0) => 0\n    Ok(v) => v\n    Err(Fail.Bad(msg: m)) => m.len()\n    Err(Gone) => -1\n  }"
		}
		parts = append(parts, fmt.Sprintf("let %s = %s", v, m))
		e = e.with("Int", v)
	}
	parts = append(parts, g.useAll(e))
	g.decls = append(g.decls, fmt.Sprintf("fn %s(k: Int, xs: List[Int], s: Shape, o: Int?, p: Pt) -> Int {\n  %s\n}\n", f, strings.Join(parts, "\n  ")))
	g.calls = append(g.calls, fmt.Sprintf("os.stdio.println(\"%s ${%s(%d, %s, %s, %s, %s)}\")", f, f, g.r.Intn(12)-2, g.leaf("List[Int]", nil), g.leaf("Shape", nil), g.leaf("Int?", nil), g.leaf("Pt", nil)))
}

func (g *pg) fDefer() {
	f := g.name("def")
	var body []string
	body = append(body, "var n = k")
	if g.coin() {
		body = append(body, g.pick("defer out.println(\"deferred ${k}\")", "defer {\n    out.println(\"block\")\n    out.println(\"done\")\n  }"))
	}
	inner := []string{"defer out.println(\"inner\")", fmt.Sprintf("n = n + %s", g.expr("Int", env{"Int": {"k"}}, 1))}
	if g.coin() {
		inner = append(inner, "if n > 3 {\n      return n\n    }")
	}
	body = append(body, fmt.Sprintf("{\n    %s\n  }", strings.Join(inner, "\n    ")))
	if g.coin() {
		body = append(body, "let r = may(n)?", "r")
		g.decls = append(g.decls, fmt.Sprintf("fn %s(out: Stdio, k: Int) -> Int ! Fail {\n  %s\n}\n", f, strings.Join(body, "\n  ")))
		g.calls = append(g.calls, fmt.Sprintf("os.stdio.println(\"%s ${%s(os.stdio, %d)?}\")", f, f, g.r.Intn(5)))
		return
	}
	body = append(body, "n")
	g.decls = append(g.decls, fmt.Sprintf("fn %s(out: Stdio, k: Int) -> Int {\n  %s\n}\n", f, strings.Join(body, "\n  ")))
	g.calls = append(g.calls, fmt.Sprintf("os.stdio.println(\"%s ${%s(os.stdio, %d)}\")", f, f, g.r.Intn(5)))
}

func (g *pg) fScope() {
	f := g.name("scp")
	var body []string
	fails := g.coin()
	body = append(body, fmt.Sprintf("let h = s.spawn(fn() { %s })", g.expr("Int", env{"Int": {"k"}}, 2)))
	if g.coin() {
		body = append(body, "s.spawn_background(fn() {\n      let _x = k * 2\n    })")
	}
	if fails {
		body = append(body, g.pick("s.spawn(fn() -> () ! Fail {\n      let _v = may(k)?\n    })", "let hf = s.spawn(fn() -> Int ! Fail { may(k - 1)? })\n    let _f = hf.await?"))
	}
	if g.coin() {
		body = append(body, "let g2 = s.group()\n    g2.spawn(fn() {\n      let _y = k + 1\n    })")
	}
	body = append(body, "h.await")
	ret, call := "Int", "%s(%d)"
	if fails {
		ret, call = "Int ! Fail", "%s(%d)?"
	}
	g.decls = append(g.decls, fmt.Sprintf("fn %s(k: Int) -> %s {\n  scope s {\n    %s\n  }\n}\n", f, ret, strings.Join(body, "\n    ")))
	g.calls = append(g.calls, fmt.Sprintf("os.stdio.println(\"%s ${%s}\")", f, fmt.Sprintf(call, f, g.r.Intn(4))))
}

func (g *pg) fTry() {
	f := g.name("try")
	e := env{"Int": {"k"}}
	var body []string
	for i := 0; i < 1+g.r.Intn(3); i++ {
		v := g.name("t")
		switch g.r.Intn(4) {
		case 0:
			body = append(body, fmt.Sprintf("let %s = may(%s)?", v, g.expr("Int", e, 1)))
		case 1:
			body = append(body, fmt.Sprintf("let %s = opt(%s) ?? %s", v, g.expr("Int", e, 1), g.expr("Int", e, 1)))
		case 2:
			body = append(body, fmt.Sprintf("let %s = may(k).ok() ?? opt(k) ?? 0", v))
		default:
			body = append(body, fmt.Sprintf("let %s = match may(k) {\n    Ok(x) => x\n    Err(e) => return Err(e)\n  }", v))
		}
		e = e.with("Int", v)
	}
	body = append(body, g.useAll(e))
	g.decls = append(g.decls, fmt.Sprintf("fn %s(k: Int) -> Int ! Fail {\n  %s\n}\n", f, strings.Join(body, "\n  ")))
	g.calls = append(g.calls, fmt.Sprintf("os.stdio.println(\"%s ${%s(%d)?}\")", f, f, g.r.Intn(6)))
}

func (g *pg) fOptChain() {
	f := g.name("opc")
	body := []string{
		g.pick("let x = p?.x", "let x = (p?.y)"),
		g.pick("let l = xs.get(x)?", "let l = opt(x)?"),
		fmt.Sprintf("Some(l + %s)", g.expr("Int", env{"Int": {"x"}}, 1)),
	}
	g.decls = append(g.decls, fmt.Sprintf("fn %s(p: Pt?, xs: List[Int]) -> Int? {\n  %s\n}\n", f, strings.Join(body, "\n  ")))
	arg := g.pick("Some(Pt{x: 1, y: 2})", "None")
	g.calls = append(g.calls, fmt.Sprintf("os.stdio.println(\"%s ${%s(%s, [4, 5, 6]) ?? -1}\")", f, f, arg))
}

func (g *pg) fLoops() {
	f := g.name("lp")
	var body []string
	body = append(body, "var acc = 0")
	switch g.r.Intn(3) {
	case 0:
		body = append(body, "var i = 0")
		body = append(body, fmt.Sprintf("while i < %d {\n    i += 1\n    if i == k {\n      continue\n    }\n    if acc > %d {\n      break\n    }\n    acc += i\n  }", 3+g.r.Intn(5), g.r.Intn(9)))
	case 1:
		body = append(body, "outer: for x in xs {\n    var j = 0\n    while {\n      j += 1\n      if j > x {\n        break\n      }\n      if j == k {\n        break outer\n      }\n      acc += j\n    }\n  }")
	default:
		body = append(body, "var i = 0", "let done = while {\n    i += 1\n    if i >= k {\n      break\n    }\n  }", "acc = i", "let _u: () = done")
	}
	if g.coin() {
		body = append(body, "while {\n    if acc >= 0 {\n      return acc\n    }\n    acc += 1\n  }")
	} else {
		body = append(body, "acc")
	}
	g.decls = append(g.decls, fmt.Sprintf("fn %s(k: Int, xs: List[Int]) -> Int {\n  %s\n}\n", f, strings.Join(body, "\n  ")))
	g.calls = append(g.calls, fmt.Sprintf("os.stdio.println(\"%s ${%s(%d, [2, 3])}\")", f, f, g.r.Intn(5)))
}

func (g *pg) fValues() {
	f := g.name("val")
	e := env{"Int": {"k"}}
	var body []string
	for _, t := range []string{"List[Int]", "Map[Str, Int]", "Pt", "Str", "Shape", "Bool"} {
		if g.coin() {
			v := g.name("v")
			body = append(body, fmt.Sprintf("let %s = %s", v, g.expr(t, e, 2)))
			e = e.with(t, v)
		}
	}
	if pts := e["Pt"]; len(pts) > 0 {
		v := g.name("w")
		body = append(body, fmt.Sprintf("var %s = %s with { y: k }", v, pts[0]), fmt.Sprintf("%s.x += 1", v))
		e = e.with("Pt", v)
	}
	if g.coin() {
		body = append(body, "var m: Map[Str, Int] = {}", "m[\"z\"] = k", "m.put(\"q\", 2)")
		e = e.with("Map[Str, Int]", "m")
	}
	body = append(body, fmt.Sprintf("\"%s ${%s} ${%s}\"", f, g.useAll(e), g.expr("Str", e, 1)))
	g.decls = append(g.decls, fmt.Sprintf("fn %s(k: Int) -> Str {\n  %s\n}\n", f, strings.Join(body, "\n  ")))
	g.calls = append(g.calls, fmt.Sprintf("os.stdio.println(%s(%d))", f, g.r.Intn(5)))
}

// ---------------------------------------------------------------------------
// Nested statements: the forms above inside one another (closures in
// scopes in select arms in loops, ...)

// sctx is what a block may do: fail (`?` on Fail), break and continue
// (in a loop), and the mutable sink it adds its bindings to.
type sctx struct {
	fail  bool
	loop  bool
	sink  string
	clock string // the Clock in scope ("" when none)
}

// fNested adds a function whose body is a random tree of statements.
func (g *pg) fNested() {
	f := g.name("nst")
	fail := g.coin()
	sink := g.name("sink")
	c := sctx{fail: fail, sink: sink, clock: "clock"}
	lines := []string{fmt.Sprintf("var %s = 0", sink)}
	lines = append(lines, g.stmts(env{"Int": {"k"}, "Shape": {"s"}}, 3, c)...)
	lines = append(lines, sink)
	ret, call := "Int", "%s(os.clock, %d, %s)"
	if fail {
		ret, call = "Int ! Fail", "%s(os.clock, %d, %s)?"
	}
	g.decls = append(g.decls, fmt.Sprintf("fn %s(clock: Clock, k: Int, s: Shape) -> %s {\n%s\n}\n", f, ret, indent(lines, 1)))
	g.calls = append(g.calls, fmt.Sprintf("os.stdio.println(\"%s ${%s}\")", f, fmt.Sprintf(call, f, g.r.Intn(6), g.leaf("Shape", nil))))
}

func indent(lines []string, n int) string {
	pad := strings.Repeat("  ", n)
	var out []string
	for _, l := range lines {
		for _, x := range strings.Split(l, "\n") {
			out = append(out, pad+x)
		}
	}
	return strings.Join(out, "\n")
}

// stmts is a block's statements: each binding it makes is added to the
// sink at its end, so nothing is unused.
func (g *pg) stmts(e env, d int, c sctx) []string {
	var lines []string
	local := env{}
	bind := func(t, v string) {
		e = e.with(t, v)
		local = local.with(t, v)
	}
	n := 1 + g.r.Intn(3)
	for i := 0; i < n; i++ {
		k := g.r.Intn(12)
		if d <= 0 {
			k = g.r.Intn(3)
		}
		switch k {
		case 0:
			v := g.name("x")
			lines = append(lines, fmt.Sprintf("let %s = %s", v, g.expr("Int", e, 1)))
			bind("Int", v)
		case 1:
			lines = append(lines, fmt.Sprintf("%s += %s", c.sink, g.expr("Int", e, 1)))
		case 2:
			if c.fail {
				v := g.name("q")
				lines = append(lines, fmt.Sprintf("let %s = may(%s)?", v, g.expr("Int", e, 1)))
				bind("Int", v)
			} else {
				lines = append(lines, fmt.Sprintf("%s += opt(%s) ?? 1", c.sink, g.expr("Int", e, 1)))
			}
		case 3: // if, with or without else
			th := g.stmts(e, d-1, c)
			if g.coin() {
				lines = append(lines, fmt.Sprintf("if %s {\n%s\n} else {\n%s\n}", g.expr("Bool", e, 1), indent(th, 1), indent(g.stmts(e, d-1, c), 1)))
			} else {
				lines = append(lines, fmt.Sprintf("if %s {\n%s\n}", g.expr("Bool", e, 1), indent(th, 1)))
			}
		case 4: // while with a counter, or for over a list
			lc := c
			lc.loop = true
			if g.coin() {
				w := g.name("w")
				body := append([]string{fmt.Sprintf("%s += 1", w)}, g.stmts(e, d-1, lc)...)
				lines = append(lines, fmt.Sprintf("var %s = 0\nwhile %s < %d {\n%s\n}", w, w, 1+g.r.Intn(3), indent(body, 1)))
			} else {
				v := g.name("it")
				lines = append(lines, fmt.Sprintf("for %s in %s {\n%s\n}", v, g.expr("List[Int]", e, 1), indent(append(g.stmts(e.with("Int", v), d-1, lc), fmt.Sprintf("%s += %s", c.sink, v)), 1)))
			}
		case 5: // break or continue under a condition
			if c.loop {
				lines = append(lines, fmt.Sprintf("if %s {\n  %s\n}", g.expr("Bool", e, 1), g.pick("break", "continue")))
			}
		case 6: // match with block arms
			arms := []string{
				fmt.Sprintf("Circle(r) => {\n%s\n}", indent(append(g.stmts(e.with("Int", "r"), d-1, c), fmt.Sprintf("%s += r", c.sink)), 1)),
				fmt.Sprintf("Rect(w: a, ..) | Circle(a) if a > 100 => %s += a", c.sink),
				fmt.Sprintf("Rect(..) => {\n%s\n}", indent(g.stmts(e, d-1, c), 1)),
				"Dot => {}",
			}
			// the guarded or arm must come before the Circle arm to matter;
			// either order checks
			if g.coin() {
				arms[0], arms[1] = arms[1], arms[0]
			}
			lines = append(lines, fmt.Sprintf("match %s {\n%s\n}", g.expr("Shape", e, 1), indent(arms, 1)))
		case 7: // defer, a block or one statement
			if g.coin() {
				lines = append(lines, fmt.Sprintf("defer {\n  let _d = %s\n}", g.expr("Int", e, 1)))
			} else {
				lines = append(lines, fmt.Sprintf("defer %s.trim()", g.expr("Str", e, 1)))
			}
		case 8: // a scope whose tasks run nested blocks
			sv := g.name("s")
			h := g.name("h")
			tf := c.fail && g.coin()
			inner := g.taskBody(e, d-1, tf, c.clock, false)
			await := h + ".await"
			if tf {
				await += "?"
			}
			body := []string{fmt.Sprintf("let %s = %s.spawn(%s)", h, sv, inner)}
			if g.coin() {
				body = append(body, fmt.Sprintf("%s.spawn_background(%s)", sv, g.taskBody(e, 0, false, c.clock, true)))
			}
			body = append(body, fmt.Sprintf("%s += %s", c.sink, await))
			lines = append(lines, fmt.Sprintf("scope %s {\n%s\n}", sv, indent(body, 1)))
		case 9: // select with block arms
			ch := g.name("ch")
			var arms []string
			if g.coin() {
				v := g.name("rv")
				arms = append(arms, fmt.Sprintf("%s = %s.recv() => {\n%s\n}", v, ch, indent(append(g.stmts(e, d-1, c), fmt.Sprintf("%s += %s ?? 0", c.sink, v)), 1)))
			} else {
				arms = append(arms, fmt.Sprintf("%s.recv() => {\n%s\n}", ch, indent(g.stmts(e, d-1, c), 1)))
			}
			if g.coin() {
				arms = append(arms, fmt.Sprintf("%s.send(%s) => %s += 1", ch, g.expr("Int", e, 1), c.sink))
			}
			if c.clock != "" && g.coin() {
				arms = append(arms, fmt.Sprintf("after %dms => {\n%s\n}", 1+g.r.Intn(3), indent(g.stmts(e, d-1, c), 1)))
			}
			lines = append(lines, fmt.Sprintf("let %s = Chan[Int].new(1)\n%s.send(%s)\nselect {\n%s\n}", ch, ch, g.expr("Int", e, 1), indent(arms, 1)))
		case 10: // a closure with a nested body, called
			cl := g.name("cl")
			cf := c.fail && g.coin()
			body := g.closureBody(e, d-1, cf)
			sig := "fn(a: Int) -> Int"
			call := cl + "(" + g.expr("Int", e, 1) + ")"
			if cf {
				sig += " ! Fail"
				call += "?"
			}
			lines = append(lines, fmt.Sprintf("let %s = %s {\n%s\n}", cl, sig, indent(body, 1)), fmt.Sprintf("%s += %s", c.sink, call))
		default: // optional chaining in a local closure returning an Option
			v := g.name("oc")
			lines = append(lines, fmt.Sprintf("let %s = fn(p: Pt?) -> Int? {\n  let x = p?.%s\n  Some(x + %s)\n}", v, g.pick("x", "y"), g.expr("Int", e, 1)), fmt.Sprintf("%s += %s(%s) ?? 0", c.sink, v, g.pick("Some(Pt{x: 1, y: 2})", "None")))
		}
	}
	if len(local) > 0 {
		lines = append(lines, fmt.Sprintf("%s += %s", c.sink, g.useAll(local)))
	}
	if len(lines) == 0 {
		lines = append(lines, fmt.Sprintf("%s += 1", c.sink))
	}
	return lines
}

// closureBody is the body of a closure `fn(a: Int) -> Int [! Fail]`: a
// sink of its own (a closure cannot change its captures, XO0502).
func (g *pg) closureBody(e env, d int, fail bool) []string {
	sink := g.name("cs")
	c := sctx{fail: fail, sink: sink}
	lines := []string{fmt.Sprintf("var %s = a", sink)}
	lines = append(lines, g.stmts(e.with("Int", "a"), d, c)...)
	return append(lines, sink)
}

// taskBody is a closure for spawn: `fn() -> Int [! Fail] { ... }`, or
// one returning () for spawn_background.
func (g *pg) taskBody(e env, d int, fail bool, clock string, background bool) string {
	sink := g.name("ts")
	c := sctx{fail: fail, sink: sink, clock: clock}
	lines := []string{fmt.Sprintf("var %s = 0", sink)}
	lines = append(lines, g.stmts(e, d, c)...)
	if background {
		// a background task
		return fmt.Sprintf("fn() {\n%s\n}", indent(append(lines, fmt.Sprintf("let _t = %s", sink)), 1))
	}
	sig := "fn() -> Int"
	if fail {
		sig += " ! Fail"
	}
	return fmt.Sprintf("%s {\n%s\n}", sig, indent(append(lines, sink), 1))
}
