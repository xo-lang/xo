package progen

import (
	"fmt"
	"math/rand"
	"strings"
)

// aliasField is a field of the struct an Alias program stores through two
// indexes of one list.
type aliasField struct {
	name  string
	float bool
}

// Alias writes a program of seed whose functions load fields of vs[i] and
// store fields of vs[j] in random order (adjacent fields, Float and Int, a
// struct of 4 to 6 words), and main calls each with i == j and i != j. The
// two indexes name one element only when they are equal, so a backend that
// pairs, sinks or reorders memory operations across the two paths differs
// from the others only on those calls (a miscompile found 2026-11-02: a
// pair of Float stores to vs[j] sunk past a load of vs[i] by slp_f64).
func Alias(seed int64) string {
	r := rand.New(rand.NewSource(seed))
	n := 4 + r.Intn(3)
	fields := make([]aliasField, n)
	mode := r.Intn(3) // all Float, mixed, all Int
	for i := range fields {
		f := mode == 0 || (mode == 1 && r.Intn(2) == 0)
		fields[i] = aliasField{string(rune('a' + i)), f}
	}
	var b strings.Builder
	b.WriteString("// generated by progen.Alias\n\nstruct V {\n")
	for _, f := range fields {
		t := "Int"
		if f.float {
			t = "Float"
		}
		fmt.Fprintf(&b, "  %s: %s\n", f.name, t)
	}
	b.WriteString("}\n\n")
	fns := 3 + r.Intn(3)
	for i := 0; i < fns; i++ {
		b.WriteString(aliasFunc(r, i, fields))
		b.WriteString("\n")
	}
	b.WriteString("fn show(vs: List[V]) -> Str {\n  var s = \"\"\n  for v in vs {\n    s = \"${s} (")
	for i, f := range fields {
		if i > 0 {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "${v.%s}", f.name)
	}
	b.WriteString(")\"\n  }\n  s\n}\n\n")
	b.WriteString("fn fresh(k: Float) -> List[V] {\n  [")
	for e := 0; e < 3; e++ {
		if e > 0 {
			b.WriteString(", ")
		}
		b.WriteString("V{")
		for i, f := range fields {
			if i > 0 {
				b.WriteString(", ")
			}
			if f.float {
				fmt.Fprintf(&b, "%s: %s", f.name, []string{"1.0", "2.5", "-0.75", "k", "3.0e100", "0.125"}[(e*3+i)%6])
			} else {
				fmt.Fprintf(&b, "%s: %d", f.name, e*7+i+1)
			}
		}
		b.WriteString("}")
	}
	b.WriteString("]\n}\n\nfn main(os: Os) {\n  let k = Float(os.env.args().len() + 1)\n")
	b.WriteString("  for (i, j) in [(0, 0), (0, 1), (1, 0), (1, 1), (2, 2), (1, 2), (2, 0)] {\n")
	for i := 0; i < fns; i++ {
		fmt.Fprintf(&b, "    var v%d = fresh(k)\n    m%d(v%d, i, j, k + 0.25)\n    os.stdio.println(\"m%d ${i} ${j}${show(v%d)}\")\n", i, i, i, i, i)
	}
	b.WriteString("  }\n}\n")
	return b.String()
}

func aliasFunc(r *rand.Rand, id int, fields []aliasField) string {
	var floats, ints []string
	for _, f := range fields {
		if f.float {
			floats = append(floats, f.name)
		} else {
			ints = append(ints, f.name)
		}
	}
	var lets []aliasField // locals defined so far (name, float)
	var body []string
	tmp := 0
	// expr writes an expression of the wanted type from loads of vs[i],
	// the locals defined so far, k and constants
	var expr func(float bool, d int) string
	expr = func(float bool, d int) string {
		var leaves []string
		if float {
			for _, f := range floats {
				leaves = append(leaves, "vs[i]."+f)
			}
			for _, l := range lets {
				if l.float {
					leaves = append(leaves, l.name)
				}
			}
			leaves = append(leaves, "k", "0.5", "1.0")
		} else {
			for _, f := range ints {
				leaves = append(leaves, "vs[i]."+f)
			}
			for _, l := range lets {
				if !l.float {
					leaves = append(leaves, l.name)
				}
			}
			leaves = append(leaves, "i", "j", "3")
		}
		if d == 0 || r.Intn(3) == 0 {
			return leaves[r.Intn(len(leaves))]
		}
		ops := []string{"+", "-"}
		if float {
			ops = append(ops, "*")
		}
		return "(" + expr(float, d-1) + " " + ops[r.Intn(len(ops))] + " " + expr(float, d-1) + ")"
	}
	n := 6 + r.Intn(7)
	for s := 0; s < n; s++ {
		if len(floats) >= 4 && r.Intn(4) == 0 {
			// a pack whose operand is another pack's lanes in the other order
			// (slp_f64 built it from scalars the pack replaced, 2026-11-02):
			// x0 = a - k, x1 = b - 1, then y0 = c0 + x1, y1 = c1 + x0, and more
			// packed operations after it
			a, b := floats[r.Intn(len(floats))], floats[r.Intn(len(floats))]
			c0, c1 := floats[r.Intn(len(floats))], floats[r.Intn(len(floats))]
			x0, x1 := fmt.Sprintf("x%d", tmp), fmt.Sprintf("x%d", tmp+1)
			tmp += 2
			body = append(body,
				fmt.Sprintf("  let %s = vs[i].%s - k", x0, a),
				fmt.Sprintf("  let %s = vs[i].%s - 1.0", x1, b),
				fmt.Sprintf("  vs[j].%s = vs[i].%s + %s", floats[r.Intn(len(floats))], c0, x1),
				fmt.Sprintf("  vs[j].%s = vs[i].%s + %s", floats[r.Intn(len(floats))], c1, x0))
			for m := r.Intn(3); m > 0; m-- {
				body = append(body, fmt.Sprintf("  vs[j].%s = vs[j].%s * %s", floats[r.Intn(len(floats))], floats[r.Intn(len(floats))], []string{x0, x1, "k"}[r.Intn(3)]))
			}
			continue
		}
		storeP := r.Intn(5) < 2
		if storeP {
			f := fields[r.Intn(len(fields))]
			if f.float && len(floats) == 0 || !f.float && len(ints) == 0 {
				continue
			}
			body = append(body, fmt.Sprintf("  vs[j].%s = %s", f.name, expr(f.float, 2)))
			continue
		}
		float := r.Intn(2) == 0
		if float && len(floats) == 0 {
			float = false
		}
		if !float && len(ints) == 0 {
			float = true
		}
		name := fmt.Sprintf("t%d", tmp)
		tmp++
		body = append(body, fmt.Sprintf("  let %s = %s", name, expr(float, 2)))
		lets = append(lets, aliasField{name, float})
	}
	// every local is used: a store of the last ones
	var sink []string
	for _, l := range lets {
		f := fields[r.Intn(len(fields))]
		if l.float == f.float {
			sink = append(sink, fmt.Sprintf("  vs[j].%s = %s", f.name, l.name))
		} else {
			sink = append(sink, fmt.Sprintf("  vs[i].%s = vs[i].%s", f.name, f.name))
			sink = append(sink, "  let _"+l.name+" = "+l.name)
		}
	}
	return fmt.Sprintf("fn m%d(var vs: List[V], i: Int, j: Int, k: Float) {\n%s\n%s\n}\n", id, strings.Join(body, "\n"), strings.Join(sink, "\n"))
}
