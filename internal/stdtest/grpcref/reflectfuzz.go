// reflectFuzz writes the std/grpcreflect fuzz cases of a seed (task #273, TestGrpcReflectFuzz): random
// ServerReflectionRequest and ServerReflectionResponse messages, valid ones and changed copies (cut short, a byte
// changed, two messages joined, a stray field added), each with what protobuf-go's Unmarshal reads from it.
func reflectFuzz(seed int64, n int) {
	r := rand.New(rand.NewSource(seed))
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by internal/stdtest/grpcref reflectfuzz (seed %d, %d cases) from protobuf-go's Unmarshal of\n// grpc-go's reflection messages; do not edit.\n", seed, n)
	b.WriteString(reflectFuzzXo)
	b.WriteString("\n/// (bytes hex, Go read it, host, kind, text, number)\nconst REQUESTS: List[(Str, Bool, Str, Int, Str, Int)] = [\n")
	for i := 0; i < n; i++ {
		raw := mutate(r, rfRequest(r), func() []byte { return rfRequest(r) })
		var m rpb.ServerReflectionRequest
		err := proto.Unmarshal(raw, &m)
		kind, text, num := 0, "", 0
		if err == nil {
			switch x := m.MessageRequest.(type) {
			case *rpb.ServerReflectionRequest_FileByFilename:
				kind, text = 1, x.FileByFilename
			case *rpb.ServerReflectionRequest_FileContainingSymbol:
				kind, text = 2, x.FileContainingSymbol
			case *rpb.ServerReflectionRequest_FileContainingExtension:
				kind, text, num = 3, x.FileContainingExtension.GetContainingType(), int(x.FileContainingExtension.GetExtensionNumber())
			case *rpb.ServerReflectionRequest_AllExtensionNumbersOfType:
				kind, text = 4, x.AllExtensionNumbersOfType
			case *rpb.ServerReflectionRequest_ListServices:
				kind = 5
			}
		}
		fmt.Fprintf(&b, "  (%q, %v, %s, %d, %s, %d),\n", hex.EncodeToString(raw), err == nil, xoStr(m.GetHost()), kind, xoStr(text), num)
	}
	b.WriteString("]\n\n/// (bytes hex, Go read it, kind, the answer as text)\nconst RESPONSES: List[(Str, Bool, Int, Str)] = [\n")
	for i := 0; i < n; i++ {
		raw := mutate(r, rfResponse(r), func() []byte { return rfResponse(r) })
		var m rpb.ServerReflectionResponse
		err := proto.Unmarshal(raw, &m)
		kind, text := 0, ""
		if err == nil {
			switch x := m.MessageResponse.(type) {
			case *rpb.ServerReflectionResponse_FileDescriptorResponse:
				var fs []string
				for _, f := range x.FileDescriptorResponse.GetFileDescriptorProto() {
					fs = append(fs, hex.EncodeToString(f))
				}
				kind, text = 4, strings.Join(fs, ",")
			case *rpb.ServerReflectionResponse_AllExtensionNumbersResponse:
				var ns []string
				for _, v := range x.AllExtensionNumbersResponse.GetExtensionNumber() {
					ns = append(ns, strconv.Itoa(int(v)))
				}
				kind, text = 5, x.AllExtensionNumbersResponse.GetBaseTypeName()+"|"+strings.Join(ns, ",")
			case *rpb.ServerReflectionResponse_ListServicesResponse:
				var ns []string
				for _, s := range x.ListServicesResponse.GetService() {
					ns = append(ns, s.GetName())
				}
				kind, text = 6, strings.Join(ns, ",")
			case *rpb.ServerReflectionResponse_ErrorResponse:
				kind, text = 7, strconv.Itoa(int(x.ErrorResponse.GetErrorCode()))+"|"+x.ErrorResponse.GetErrorMessage()
			}
		}
		fmt.Fprintf(&b, "  (%q, %v, %d, %s),\n", hex.EncodeToString(raw), err == nil, kind, xoStr(text))
	}
	b.WriteString("]\n")
	os.Stdout.WriteString(b.String())
}

// xoStr is s as an Xo string literal (valid UTF-8 only: an invalid string is never read).
func xoStr(s string) string {
	if !utf8.ValidString(s) {
		return `"<invalid>"`
	}
	var b strings.Builder
	b.WriteByte('"')
	for _, c := range s {
		switch {
		case c == '"' || c == '\\' || c == '$':
			b.WriteByte('\\')
			b.WriteRune(c)
		case c < 0x20 || c == 0x7f:
			fmt.Fprintf(&b, "\\u{%x}", c)
		default:
			b.WriteRune(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func rfText(r *rand.Rand) string {
	pool := []string{"", "a.proto", "pkg.Svc.Method", "b.Resp", "x", "grpc.reflection.v1.ServerReflection", "日本.proto", "with space", "\x00", "a\"b$c"}
	if r.Intn(4) == 0 {
		var b []byte
		for k := r.Intn(12); k > 0; k-- {
			b = append(b, byte(r.Intn(256)))
		}
		return string(b)
	}
	return pool[r.Intn(len(pool))]
}

func rfRequest(r *rand.Rand) []byte {
	m := &rpb.ServerReflectionRequest{Host: rfText(r)}
	switch r.Intn(6) {
	case 0:
		m.MessageRequest = &rpb.ServerReflectionRequest_FileByFilename{FileByFilename: rfText(r)}
	case 1:
		m.MessageRequest = &rpb.ServerReflectionRequest_FileContainingSymbol{FileContainingSymbol: rfText(r)}
	case 2:
		m.MessageRequest = &rpb.ServerReflectionRequest_FileContainingExtension{FileContainingExtension: &rpb.ExtensionRequest{ContainingType: rfText(r), ExtensionNumber: int32(r.Int63() - r.Int63())}}
	case 3:
		m.MessageRequest = &rpb.ServerReflectionRequest_AllExtensionNumbersOfType{AllExtensionNumbersOfType: rfText(r)}
	case 4:
		m.MessageRequest = &rpb.ServerReflectionRequest_ListServices{ListServices: rfText(r)}
	}
	b, err := proto.MarshalOptions{}.Marshal(m)
	if err != nil {
		// a string that is not UTF-8: written field by field instead
		return rawRequest(m)
	}
	return b
}

// rawRequest writes m without protobuf-go's UTF-8 check, so invalid strings reach the reader.
func rawRequest(m *rpb.ServerReflectionRequest) []byte {
	var b []byte
	str := func(num int, s string) {
		b = append(b, byte(num<<3|2))
		b = appendVarint(b, uint64(len(s)))
		b = append(b, s...)
	}
	str(1, m.Host)
	switch x := m.MessageRequest.(type) {
	case *rpb.ServerReflectionRequest_FileByFilename:
		str(3, x.FileByFilename)
	case *rpb.ServerReflectionRequest_FileContainingSymbol:
		str(4, x.FileContainingSymbol)
	case *rpb.ServerReflectionRequest_FileContainingExtension:
		var e []byte
		e = append(e, 1<<3|2)
		e = appendVarint(e, uint64(len(x.FileContainingExtension.ContainingType)))
		e = append(e, x.FileContainingExtension.ContainingType...)
		e = append(e, 2<<3)
		e = appendVarint(e, uint64(int64(x.FileContainingExtension.ExtensionNumber)))
		b = append(b, 5<<3|2)
		b = appendVarint(b, uint64(len(e)))
		b = append(b, e...)
	case *rpb.ServerReflectionRequest_AllExtensionNumbersOfType:
		str(6, x.AllExtensionNumbersOfType)
	case *rpb.ServerReflectionRequest_ListServices:
		str(7, x.ListServices)
	}
	return b
}

func appendVarint(b []byte, v uint64) []byte {
	for v >= 0x80 {
		b = append(b, byte(v)|0x80)
		v >>= 7
	}
	return append(b, byte(v))
}

func rfResponse(r *rand.Rand) []byte {
	m := &rpb.ServerReflectionResponse{ValidHost: "h"}
	if r.Intn(3) == 0 {
		m.OriginalRequest = &rpb.ServerReflectionRequest{Host: "o"}
	}
	switch r.Intn(5) {
	case 0:
		fr := &rpb.FileDescriptorResponse{}
		for k := r.Intn(3); k > 0; k-- {
			fr.FileDescriptorProto = append(fr.FileDescriptorProto, []byte(rfText(r)))
		}
		m.MessageResponse = &rpb.ServerReflectionResponse_FileDescriptorResponse{FileDescriptorResponse: fr}
	case 1:
		er := &rpb.ExtensionNumberResponse{BaseTypeName: "b.Resp"}
		for k := r.Intn(4); k > 0; k-- {
			er.ExtensionNumber = append(er.ExtensionNumber, int32(r.Intn(1<<20)-100))
		}
		m.MessageResponse = &rpb.ServerReflectionResponse_AllExtensionNumbersResponse{AllExtensionNumbersResponse: er}
	case 2:
		lr := &rpb.ListServiceResponse{}
		for k := r.Intn(3); k > 0; k-- {
			lr.Service = append(lr.Service, &rpb.ServiceResponse{Name: "s" + strconv.Itoa(k)})
		}
		m.MessageResponse = &rpb.ServerReflectionResponse_ListServicesResponse{ListServicesResponse: lr}
	case 3:
		m.MessageResponse = &rpb.ServerReflectionResponse_ErrorResponse{ErrorResponse: &rpb.ErrorResponse{ErrorCode: int32(r.Intn(20) - 2), ErrorMessage: "proto: not found"}}
	}
	b, err := proto.Marshal(m)
	if err != nil {
		panic(err)
	}
	return b
}

// mutate returns b as it is or a changed copy: cut short, a byte changed, joined with another, a stray field added.
func mutate(r *rand.Rand, b []byte, another func() []byte) []byte {
	switch r.Intn(8) {
	case 0:
		if len(b) > 0 {
			return b[:r.Intn(len(b))]
		}
	case 1:
		if len(b) > 0 {
			c := append([]byte(nil), b...)
			c[r.Intn(len(c))] ^= byte(1 + r.Intn(255))
			return c
		}
	case 2:
		return append(append([]byte(nil), b...), another()...)
	case 3:
		// an unknown field, varint or bytes
		if r.Intn(2) == 0 {
			return append(append([]byte(nil), b...), 15<<3, byte(r.Intn(128)))
		}
		return append(append([]byte(nil), b...), 16<<3|2, 0x02, 0x01, 0x02)
	}
	return b
}

// reflectFuzzXo checks std/grpcreflect's readers against the cases protobuf-go read.
const reflectFuzzXo = `use std/grpcreflect

fn req_parts(r: grpcreflect.Request) -> (Int, Str, Int) {
  match r {
    FileByFilename(n) => (1, n, 0)
    FileContainingSymbol(s) => (2, s, 0)
    FileContainingExtension(t, n) => (3, t, n)
    AllExtensionNumbersOfType(t) => (4, t, 0)
    ListServices => (5, "", 0)
    Empty => (0, "", 0)
  }
}

fn answer_parts(a: grpcreflect.Answer) -> (Int, Str) {
  match a {
    Files(fs) => (4, fs.map(fn(f) -> Str { f.to_hex() }).join(","))
    ExtensionNumbers(b, ns) => (5, b + "|" + ns.map(fn(n) -> Str { "${n}" }).join(","))
    Services(ns) => (6, ns.join(","))
    Error(c, m) => if c == 2 && m == "the response has no answer" { (0, "") } else { (7, "${c}|${m}") }
  }
}

test "std/grpcreflect reads requests as protobuf-go reads grpc-go's ServerReflectionRequest" {
  var bad: List[Str] = []
  for (h, ok, host, kind, text, num) in REQUESTS {
    let b = Bytes.from_hex(h).or_fault("hex")
    match grpcreflect.decode_request(b) {
      Ok((ho, r)) => {
        let (k, t, n) = req_parts(r)
        if !ok || ho != host || k != kind || t != text || n != num {
          bad.push("${h}: read (${ho}, ${k}, ${t}, ${n}), Go ${ok} (${host}, ${kind}, ${text}, ${num})")
        }
      }
      Err(e) => {
        if ok {
          bad.push("${h}: refused (${e.message}), Go read it")
        }
      }
    }
  }
  if !bad.is_empty() {
    fault("${bad.len()} of ${REQUESTS.len()} requests differ, first: ${bad[0]}")
  }
}

test "std/grpcreflect reads responses as protobuf-go reads grpc-go's ServerReflectionResponse" {
  var bad: List[Str] = []
  for (h, ok, kind, text) in RESPONSES {
    let b = Bytes.from_hex(h).or_fault("hex")
    match grpcreflect.decode_answer(b) {
      Ok(a) => {
        let (k, t) = answer_parts(a)
        if !ok || k != kind || t != text {
          bad.push("${h}: read (${k}, ${t}), Go ${ok} (${kind}, ${text})")
        }
      }
      Err(e) => {
        if ok {
          bad.push("${h}: refused (${e.message}), Go read it")
        }
      }
    }
  }
  if !bad.is_empty() {
    fault("${bad.len()} of ${RESPONSES.len()} responses differ, first: ${bad[0]}")
  }
}
`
