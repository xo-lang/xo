package main

import (
	"encoding/hex"
	"fmt"
	"math/rand"
	"os"
	"sort"
	"strconv"
	"strings"

	healthpb "google.golang.org/grpc/health/grpc_health_v1"
	"google.golang.org/protobuf/proto"
)

// healthFuzz writes the std/grpchealth fuzz cases of a seed (#152, TestGrpcHealthFuzz): random HealthCheckRequest,
// HealthCheckResponse and HealthListResponse messages, valid ones and changed copies (mutate), each with what
// protobuf-go's Unmarshal reads from it. The messages are written field by field, so strings that are not UTF-8
// reach the readers.
func healthFuzz(seed int64, n int) {
	r := rand.New(rand.NewSource(seed))
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by internal/stdtest/grpcref healthfuzz (seed %d, %d cases) from protobuf-go's Unmarshal of\n// grpc-go's health messages; do not edit.\n", seed, n)
	b.WriteString(healthFuzzXo)
	b.WriteString("\n/// (bytes hex, Go read it, service)\nconst REQUESTS: List[(Str, Bool, Str)] = [\n")
	for i := 0; i < n; i++ {
		raw := mutate(r, hfRequest(r), func() []byte { return hfRequest(r) })
		var m healthpb.HealthCheckRequest
		err := proto.Unmarshal(raw, &m)
		fmt.Fprintf(&b, "  (%q, %v, %s),\n", hex.EncodeToString(raw), err == nil, xoStr(m.GetService()))
	}
	b.WriteString("]\n\n/// (bytes hex, Go read it, status number)\nconst RESPONSES: List[(Str, Bool, Int)] = [\n")
	for i := 0; i < n; i++ {
		raw := mutate(r, hfResponse(r), func() []byte { return hfResponse(r) })
		var m healthpb.HealthCheckResponse
		err := proto.Unmarshal(raw, &m)
		fmt.Fprintf(&b, "  (%q, %v, %d),\n", hex.EncodeToString(raw), err == nil, int(m.GetStatus()))
	}
	b.WriteString("]\n\n/// (bytes hex, Go read it, the statuses as sorted \"name=number\" joined by \",\")\nconst LISTS: List[(Str, Bool, Str)] = [\n")
	for i := 0; i < n; i++ {
		raw := mutate(r, hfList(r), func() []byte { return hfList(r) })
		var m healthpb.HealthListResponse
		err := proto.Unmarshal(raw, &m)
		var ks []string
		for k, v := range m.GetStatuses() {
			ks = append(ks, k+"="+strconv.Itoa(int(v.GetStatus())))
		}
		sort.Strings(ks)
		fmt.Fprintf(&b, "  (%q, %v, %s),\n", hex.EncodeToString(raw), err == nil, xoStr(strings.Join(ks, ",")))
	}
	b.WriteString("]\n")
	os.Stdout.WriteString(b.String())
}

func hfStr(b []byte, num int, s string) []byte {
	b = append(b, byte(num<<3|2))
	b = appendVarint(b, uint64(len(s)))
	return append(b, s...)
}

func hfRequest(r *rand.Rand) []byte {
	if r.Intn(8) == 0 {
		return nil
	}
	return hfStr(nil, 1, rfText(r))
}

func hfStatus(r *rand.Rand) int64 {
	pool := []int64{0, 1, 2, 3, 9, -1, 1 << 31, 1<<32 + 2, -(1 << 40)}
	return pool[r.Intn(len(pool))]
}

func hfResponse(r *rand.Rand) []byte {
	s := hfStatus(r)
	if s == 0 && r.Intn(2) == 0 {
		return nil
	}
	return appendVarint([]byte{1 << 3}, uint64(s))
}

func hfList(r *rand.Rand) []byte {
	var b []byte
	for k := r.Intn(4); k > 0; k-- {
		var e []byte
		if r.Intn(6) != 0 {
			e = hfStr(e, 1, rfText(r))
		}
		if r.Intn(6) != 0 {
			v := hfResponse(r)
			e = append(e, 2<<3|2)
			e = appendVarint(e, uint64(len(v)))
			e = append(e, v...)
		}
		b = append(b, 1<<3|2)
		b = appendVarint(b, uint64(len(e)))
		b = append(b, e...)
	}
	return b
}

// healthFuzzXo checks std/grpchealth's readers against the cases protobuf-go read: responses and lists through
// check and list with a unary interceptor that answers the case's bytes, requests through a health server that
// gets the case's bytes as its request.
const healthFuzzXo = `use std/grpc
use std/grpchealth
use std/http

fn answering(base: grpc.Client, b: Bytes) -> grpc.Client {
  base.with_unary_interceptor(fn(_m, _r, _o, _inv) -> Bytes ! grpc.Status { Ok(b) })
}

fn status_text(r: Result[grpchealth.ServingStatus, grpc.Status]) -> Str {
  match r {
    Ok(v) => v.name()
    Err(e) => "error ${e.code.number()} (${e.message})"
  }
}

fn list_text(m: Map[Str, grpchealth.ServingStatus]) -> Str {
  var ks: List[Str] = []
  for (k, v) in m {
    ks.push("${k}=${v.number()}")
  }
  ks.sort().join(",")
}

test "std/grpchealth reads HealthCheckResponse as protobuf-go" uses (net, clock) {
  let base = grpc.client(http.client(os.net, timeout: 10s), "http://127.0.0.1:9")
  var bad: List[Str] = []
  for (h, ok, n) in RESPONSES {
    let b = Bytes.from_hex(h).or_fault("hex")
    match grpchealth.check(answering(base, b), "") {
      Ok(st) => {
        if !ok || st.number() != n {
          bad.push("${h}: read ${st.number()}, Go ${ok} ${n}")
        }
      }
      Err(e) => {
        if ok {
          bad.push("${h}: refused (${e.message}), Go read ${n}")
        }
      }
    }
  }
  if !bad.is_empty() {
    fault("${bad.len()} of ${RESPONSES.len()} responses differ, first: ${bad[0]}")
  }
}

test "std/grpchealth reads HealthListResponse as protobuf-go" uses (net, clock) {
  let base = grpc.client(http.client(os.net, timeout: 10s), "http://127.0.0.1:9")
  var bad: List[Str] = []
  for (h, ok, text) in LISTS {
    let b = Bytes.from_hex(h).or_fault("hex")
    match grpchealth.list(answering(base, b)) {
      Ok(m) => {
        let t = list_text(m)
        if !ok || t != text {
          bad.push("${h}: read ${t}, Go ${ok} ${text}")
        }
      }
      Err(e) => {
        if ok {
          bad.push("${h}: refused (${e.message}), Go read ${text}")
        }
      }
    }
  }
  if !bad.is_empty() {
    fault("${bad.len()} of ${LISTS.len()} lists differ, first: ${bad[0]}")
  }
}

test "the std/grpchealth server reads HealthCheckRequest as protobuf-go" uses (net, clock) {
  let h = grpchealth.new()
  h.set_serving_status("a.proto", grpchealth.ServingStatus.NotServing)
  h.set_serving_status("x", grpchealth.ServingStatus.Serving)
  var srv = grpc.server(os.clock)
  h.register(srv)
  let l = os.net.listen("127.0.0.1:0").or_fault("listen")
  let hs = http.server(l, srv.router()).with_protocols(#{http.Protocol.UnencryptedHttp2})
  var bad: List[Str] = []
  scope s {
    s.spawn_background(fn() { hs.serve().ignore_err("the test ends the server") })
    let base = grpc.client(http.client(os.net, timeout: 10s), "http://${hs.addr()}")
    for (hx, ok, service) in REQUESTS {
      let b = Bytes.from_hex(hx).or_fault("hex")
      let c = base.with_unary_interceptor(fn(m, _r, o, inv) -> Bytes ! grpc.Status { inv(m, b, o) })
      let got = grpchealth.check(c, "")
      if ok {
        let want = h.check(service)
        if got != want {
          bad.push("${hx}: got ${status_text(got)}, want ${status_text(want)} for ${service}")
        }
      } else {
        match got {
          Err(e) => {
            if e.code != grpc.Code.Internal {
              bad.push("${hx}: refused with code ${e.code.number()} (${e.message}), want Internal")
            }
          }
          Ok(v) => bad.push("${hx}: read (${v.name()}), Go refused it")
        }
      }
    }
  }
  if !bad.is_empty() {
    fault("${bad.len()} of ${REQUESTS.len()} requests differ, first: ${bad[0]}")
  }
}
`
