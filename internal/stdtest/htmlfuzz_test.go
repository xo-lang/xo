// A fuzz harness for std/html against Go's html package (decision 0461:
// a parser of untrusted input is fuzzed; decision 0616's fuzz kind).
// std/html is Go's EscapeString and UnescapeString (spec/std.md 39);
// HTML tokenizing and parsing are std/htmltok and std/htmlparse.
//
// Each case is a random text from an alphabet of entity references
// (named, the legacy names Go accepts without a semicolon, names that are
// a prefix of a longer one, case variants, decimal and hexadecimal
// numbers in range, past U+10FFFF, surrogates, the C1 code points
// browsers replace, zero, a run of digits past Int), the five characters
// escape_string replaces, and plain and multi-byte text, sometimes changed
// the way a hostile document would be (a byte replaced, deleted or
// inserted, or the text cut):
//
//   - escape_string prints what EscapeString prints;
//   - unescape_string prints what UnescapeString prints.
//
// The cases from seed 1 are the committed corpus
// testdata/corpus/htmlfuzz/htmlfuzz_test.xo, which TestStdCorpora runs on
// every corpus backend; TestHtmlFuzzCorpusCurrent checks it is what this
// generator writes (XO_HTMLFUZZ_WRITE=1 rewrites it). TestHtmlFuzz runs a
// fresh seed (XO_HTMLFUZZ_SEED, default 2; XO_HTMLFUZZ_N cases, default
// 2000) on XO_HTMLFUZZ_BACKENDS (default arm64 and llvm).
package stdtest

import (
	"fmt"
	"html"
	"math/rand"
	"os"
	"path/filepath"
	"strings"
	"testing"
	"unicode/utf8"
)

// hxAlphabet is what a random text is built from.
var hxAlphabet = []string{
	"a", "Z", "0", "9", " ", ";", "#", "x", "X", "&", "<", ">", "\"", "'",
	"é", "日", "😀", "\n",
	"&amp;", "&amp", "&AMP;", "&AMP", "&Amp;", "&lt;", "&lt", "&gt", "&quot",
	"&copy", "&copy;", "&COPY", "&nbsp", "&nbsp;", "&notin;", "&notit;",
	"&not", "&noti", "&gesl;", "&NotNestedLessLess;", "&acE;", "&ampx",
	"&amp;amp;", "&unknown;", "&;", "&#", "&#;", "&#x", "&#x;", "&#X41;",
	"&#39;", "&#34", "&#916;", "&#x3bb;", "&#x3BB", "&#0;", "&#128;",
	"&#x80;", "&#x9F;", "&#150", "&#xD800;", "&#xDFFF;", "&#x10FFFF;",
	"&#x110000;", "&#1114112;", "&#-1;",
	"&#65a", "&#x41g",
}

// hxHostile is a numeric reference of a hostile run of digits (task
// #352): decimal or hexadecimal, past Int or long with leading zeros, with
// or without its semicolon.
func hxHostile(r *rand.Rand) string {
	ref := "&#" + HostilePick(r, HostileDigits())
	if r.Intn(2) == 0 {
		ref = "&#" + HostilePick(r, []string{"x", "X"}) + HostilePick(r, HostileHex())
	}
	if r.Intn(4) != 0 {
		ref += ";"
	}
	return ref
}

// hxMutBytes are the bytes a mutation puts in (ASCII, so the text stays
// UTF-8 for an Xo Str literal).
const hxMutBytes = "&#;x0a9F<"

// hxText builds a text of 0 to 16 alphabet pieces, one in five then
// changed.
func hxText(r *rand.Rand) string {
	var b strings.Builder
	for i, n := 0, r.Intn(17); i < n; i++ {
		if r.Intn(12) == 0 {
			b.WriteString(hxHostile(r))
			continue
		}
		b.WriteString(hxAlphabet[r.Intn(len(hxAlphabet))])
	}
	s := b.String()
	if r.Intn(5) != 0 || s == "" {
		return s
	}
	bs := []byte(s)
	i := r.Intn(len(bs))
	switch r.Intn(4) {
	case 0:
		bs[i] = hxMutBytes[r.Intn(len(hxMutBytes))]
	case 1:
		bs = append(bs[:i], bs[i+1:]...)
	case 2:
		bs = append(bs[:i], append([]byte{hxMutBytes[r.Intn(len(hxMutBytes))]}, bs[i:]...)...)
	default:
		bs = bs[:i]
	}
	// a change may cut a rune: keep the case only when it is still UTF-8
	if !utf8.Valid(bs) {
		return s
	}
	return string(bs)
}

// hxCase is one text with Go's answers.
type hxCase struct{ text, esc, unesc string }

func hxCases(r *rand.Rand, n int) []hxCase {
	cs := make([]hxCase, 0, n)
	for len(cs) < n {
		t := hxText(r)
		cs = append(cs, hxCase{t, html.EscapeString(t), html.UnescapeString(t)})
	}
	return cs
}

const hxCheckXo = `use std/html

test "std/html escapes as Go's EscapeString" {
  var bad: List[Str] = []
  for (s, want, _) in CASES {
    let got = html.escape_string(s)
    if got != want {
      bad.push("${s.quote()}: got ${got.quote()} want ${want.quote()}")
    }
  }
  if !bad.is_empty() {
    fault("${bad.len()} of ${CASES.len()} escapes differ, first: ${bad[0]}")
  }
}

test "std/html unescapes as Go's UnescapeString" {
  var bad: List[Str] = []
  for (s, _, want) in CASES {
    let got = html.unescape_string(s)
    if got != want {
      bad.push("${s.quote()}: got ${got.quote()} want ${want.quote()}")
    }
  }
  if !bad.is_empty() {
    fault("${bad.len()} of ${CASES.len()} unescapes differ, first: ${bad[0]}")
  }
}
`

// hxXoFile is the generated test file.
func hxXoFile(seed int64, cases []hxCase) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by internal/stdtest/htmlfuzz_test.go (seed %d, %d cases) from Go's\n", seed, len(cases))
	b.WriteString("// html package; do not edit: XO_HTMLFUZZ_WRITE=1 go test ./internal/stdtest -run TestHtmlFuzzCorpusCurrent\n")
	b.WriteString("// rewrites it.\n")
	b.WriteString(hxCheckXo)
	b.WriteString("\n/// (text, EscapeString, UnescapeString)\nconst CASES: List[(Str, Str, Str)] = [\n")
	for _, c := range cases {
		fmt.Fprintf(&b, "  (%s, %s, %s),\n", xoStr(c.text), xoStr(c.esc), xoStr(c.unesc))
	}
	b.WriteString("]\n")
	return b.String()
}

// hxCoverage fails when the cases stop reaching unescape's outcomes.
func hxCoverage(t *testing.T, cases []hxCase) {
	t.Helper()
	changed, kept, numeric, legacy, repl := 0, 0, 0, 0, 0
	for _, c := range cases {
		if c.unesc != c.text {
			changed++
		} else if strings.Contains(c.text, "&") {
			kept++
		}
		if strings.Contains(c.text, "&#") && c.unesc != c.text {
			numeric++
		}
		if strings.Contains(c.unesc, "�") && !strings.Contains(c.text, "�") {
			repl++
		}
		for _, l := range []string{"&amp", "&copy", "&nbsp", "&not", "&lt", "&gt", "&quot", "&AMP"} {
			if strings.Contains(c.text, l) && !strings.Contains(c.text, l+";") {
				legacy++
				break
			}
		}
	}
	n := len(cases)
	if changed < n/2 || kept < n/50 || numeric < n/5 || legacy < n/5 || repl < n/20 {
		t.Fatalf("coverage fell: %d unescaped, %d with an & kept as it is, %d numeric, %d legacy names, %d replaced with U+FFFD of %d", changed, kept, numeric, legacy, repl, n)
	}
}

const hxCorpus = "testdata/corpus/htmlfuzz/htmlfuzz_test.xo"

// TestHtmlFuzzCorpusCurrent: the committed corpus is what seed 1 writes.
func TestHtmlFuzzCorpusCurrent(t *testing.T) {
	cases := hxCases(rand.New(rand.NewSource(1)), 2000)
	hxCoverage(t, cases)
	text := hxXoFile(1, cases)
	if os.Getenv("XO_HTMLFUZZ_WRITE") == "1" {
		if err := os.MkdirAll(filepath.Dir(hxCorpus), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(hxCorpus, []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	have, err := os.ReadFile(hxCorpus)
	if err != nil {
		t.Fatal(err)
	}
	if string(have) != text {
		t.Fatalf("%s is not what seed 1 writes (Go's html or the generator changed): XO_HTMLFUZZ_WRITE=1 go test ./internal/stdtest -run TestHtmlFuzzCorpusCurrent", hxCorpus)
	}
}

// TestHtmlFuzz runs a fresh seed's cases.
func TestHtmlFuzz(t *testing.T) {
	if testing.Short() {
		t.Skip("the html fuzz is a heavy test; its seed 1 corpus runs in TestStdCorpora")
	}
	seed := int64(envInt(t, "XO_HTMLFUZZ_SEED", 2))
	n := envInt(t, "XO_HTMLFUZZ_N", 2000)
	cases := hxCases(rand.New(rand.NewSource(seed)), n)
	runFuzzDir(t, "htmlfuzz_test.xo", hxXoFile(seed, cases), envBackends("XO_HTMLFUZZ_BACKENDS", []string{"arm64", "llvm"}), len(cases))
}
