// A fuzz harness for std/backoff's delays against cenkalti/backoff v4's
// ExponentialBackOff arithmetic (decision 0616's fuzz kind; task #116).
// Each case is a schedule (initial from 1ns to 10s, a multiplier from 0 to
// 5 with 1 and below-1 values, a randomization factor from 0 to 1, a max
// interval from 1ns to 1h) and runs of retries, each drawn with a random
// float (0, values near 1, and uniform ones). std/backoff's delay(attempt,
// rand) must be the k-th NextBackOff of a fresh ExponentialBackOff: the
// current interval randomized by getRandomValueFromInterval, then grown by
// incrementCurrentInterval. The model is cenkalti's code with each product
// rounded on its own (float64(a*b): Go fuses a*b+c on arm64; Xo's floats
// are strict, as Go's on amd64; gotchas/go-oracle-fma-arm64.md).
//
// The cases from seed 1 are the committed corpus
// testdata/corpus/backofffuzz/backofffuzz_test.xo, which TestStdCorpora
// runs on every corpus backend; TestBackoffFuzzCorpusCurrent checks it is
// what this generator writes (XO_BACKOFFFUZZ_WRITE=1 rewrites it).
// TestBackoffFuzz runs a fresh seed (XO_BACKOFFFUZZ_SEED, default 2;
// XO_BACKOFFFUZZ_N cases, default 2000) on XO_BACKOFFFUZZ_BACKENDS (default
// arm64 and llvm).
package stdtest

import (
	"fmt"
	"math"
	"math/rand"
	"strconv"
	"strings"
	"testing"
	"time"
)

type boCase struct {
	initial, maxInterval time.Duration
	mult, rf             float64
	rs                   []float64
	want                 []int64
}

// boRandom is getRandomValueFromInterval with each product rounded.
func boRandom(rf, r float64, ci time.Duration) time.Duration {
	if rf == 0 {
		return ci
	}
	delta := float64(rf * float64(ci))
	lo := float64(ci) - delta
	hi := float64(ci) + delta
	return time.Duration(lo + float64(r*(hi-lo+1)))
}

func boDur(r *rand.Rand, max time.Duration) time.Duration {
	switch r.Intn(4) {
	case 0:
		return time.Duration(1 + r.Intn(1000))
	case 1:
		return []time.Duration{time.Nanosecond, time.Millisecond, 500 * time.Millisecond, time.Second, 60 * time.Second, max}[r.Intn(6)]
	}
	return time.Duration(1 + r.Int63n(int64(max)))
}

func boCases(r *rand.Rand, n int) []boCase {
	cs := make([]boCase, 0, n)
	for len(cs) < n {
		c := boCase{initial: boDur(r, 10*time.Second), maxInterval: boDur(r, time.Hour)}
		switch r.Intn(5) {
		case 0:
			c.mult = []float64{0, 0.5, 1, 1.5, 2, 1.0000001, 0.999}[r.Intn(7)]
		default:
			c.mult = r.Float64() * 5
		}
		switch r.Intn(4) {
		case 0:
			c.rf = []float64{0, 0.5, 1, 0.1}[r.Intn(4)]
		default:
			c.rf = r.Float64()
		}
		cur := c.initial
		for k := r.Intn(40); k >= 0; k-- {
			var f float64
			switch r.Intn(5) {
			case 0:
				f = []float64{0, 0.5, 1 - 1e-9, math.Nextafter(1, 0), 1e-300}[r.Intn(5)]
			default:
				f = r.Float64()
			}
			c.rs = append(c.rs, f)
			c.want = append(c.want, int64(boRandom(c.rf, f, cur)))
			if float64(cur) >= float64(c.maxInterval)/c.mult {
				cur = c.maxInterval
			} else {
				cur = time.Duration(float64(float64(cur) * c.mult))
			}
		}
		cs = append(cs, c)
	}
	return cs
}

const boCheckXo = `use std/backoff

/// A Rand whose float() is f.
struct One {
  f: Float
}

fn (s: One) float() -> Float uses rand { s.f }
fn (s: One) int(lo: Int, hi: Int) -> Int uses rand { fault("int") }
fn (s: One) bool() -> Bool uses rand { fault("bool") }
fn (s: One) bytes(n: Int) -> Bytes uses rand { fault("bytes") }
fn (s: One) shuffle[T](xs: List[T]) -> List[T] uses rand { fault("shuffle") }

test "std/backoff's delays are cenkalti/backoff's NextBackOff" {
  var bad: List[(Int, Int, Int, Int)] = []
  for (i, (initial, max, mult, rf, rs, want)) in CASES.indexed() {
    let b = backoff.Backoff{initial: Duration.from_nanos(initial), multiplier: Float.from_bits(mult), randomization: Float.from_bits(rf), max_interval: Duration.from_nanos(max)}
    for (k, r) in rs.indexed() {
      let got = b.delay(k, One{f: Float.from_bits(r)}).nanos()
      if got != want[k] {
        bad.push((i, k, got, want[k]))
        break
      }
    }
  }
  expect(bad[0..(if bad.len() < 10 { bad.len() } else { 10 })]) == []
}
`

func boBits(f float64) string { return strconv.FormatInt(int64(math.Float64bits(f)), 10) }

func boXoFile(seed int64, cases []boCase) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by internal/stdtest/backofffuzz_test.go (seed %d, %d cases) from\n", seed, len(cases))
	b.WriteString("// cenkalti/backoff v4's ExponentialBackOff arithmetic (Copyright (c) 2014 Cenk Altı, MIT license);\n")
	b.WriteString("// do not edit: XO_BACKOFFFUZZ_WRITE=1 go test ./internal/stdtest -run TestBackoffFuzzCorpusCurrent rewrites it.\n")
	b.WriteString(boCheckXo)
	b.WriteString("\n/// (initial ns, max interval ns, multiplier and randomization as Float bits, each retry's float as bits, cenkalti's delays in ns)\nconst CASES: List[(Int, Int, Int, Int, List[Int], List[Int])] = [\n")
	for _, c := range cases {
		rs := make([]string, len(c.rs))
		ws := make([]string, len(c.want))
		for i := range c.rs {
			rs[i] = boBits(c.rs[i])
			ws[i] = strconv.FormatInt(c.want[i], 10)
		}
		fmt.Fprintf(&b, "  (%d, %d, %s, %s, [%s], [%s]),\n", int64(c.initial), int64(c.maxInterval), boBits(c.mult), boBits(c.rf), strings.Join(rs, ", "), strings.Join(ws, ", "))
	}
	b.WriteString("]\n")
	return b.String()
}

// boCoverage fails when the cases stop reaching the max interval, multipliers
// at or below 1, no jitter, and long runs.
func boCoverage(t *testing.T, cases []boCase) {
	t.Helper()
	capped, low, nojit, long := 0, 0, 0, 0
	for _, c := range cases {
		for _, w := range c.want {
			if c.rf == 0 && w == int64(c.maxInterval) {
				capped++
				break
			}
		}
		if c.mult <= 1 {
			low++
		}
		if c.rf == 0 {
			nojit++
		}
		if len(c.rs) > 20 {
			long++
		}
	}
	n := len(cases)
	if capped < n/50 || low < n/20 || nojit < n/20 || long < n/3 {
		t.Fatalf("coverage fell: %d capped, %d multipliers <= 1, %d without jitter, %d long of %d", capped, low, nojit, long, n)
	}
}

const boCorpus = "testdata/corpus/backofffuzz/backofffuzz_test.xo"

// TestBackoffFuzzCorpusCurrent: the committed corpus is what seed 1 writes.
func TestBackoffFuzzCorpusCurrent(t *testing.T) {
	cases := boCases(rand.New(rand.NewSource(1)), 400)
	boCoverage(t, cases)
	bxCorpusCurrent(t, boCorpus, "XO_BACKOFFFUZZ_WRITE", boXoFile(1, cases))
}

// TestBackoffFuzz runs a fresh seed's cases.
func TestBackoffFuzz(t *testing.T) {
	if testing.Short() {
		t.Skip("the backoff fuzz is a heavy test; its seed 1 corpus runs in TestStdCorpora")
	}
	seed := int64(envInt(t, "XO_BACKOFFFUZZ_SEED", 2))
	n := envInt(t, "XO_BACKOFFFUZZ_N", 2000)
	cases := boCases(rand.New(rand.NewSource(seed)), n)
	runFuzzDir(t, "backofffuzz_test.xo", boXoFile(seed, cases), envBackends("XO_BACKOFFFUZZ_BACKENDS", []string{"arm64", "llvm"}), len(cases))
}
