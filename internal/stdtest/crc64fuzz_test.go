// A fuzz harness for std/crc64 against Go's hash/crc64 (decision
// 0616's fuzz kind). Each case is random bytes (crData: 0 to 600 of them,
// a tenth longer, past std/native's slicing-by-8 words), a split point and
// a chunk size, each checked with the three polynomials (Iso, Ecma and
// Nvme, whose reversed polynomial 0x9a6c9329ac4bc9b5 goes to MakeTable):
//
//   - checksum gives what Checksum with that table gives;
//   - update continued from the checksum of the bytes before the split
//     gives the checksum of the whole, and update from 0 gives the
//     checksum;
//   - update over the bytes in chunks of the chunk size, from 0, gives
//     the one-shot checksum, as Go's hash.Hash64 written in those chunks.
//
// The cases from seed 1 are the committed corpus
// testdata/corpus/crc64fuzz/crc64fuzz_test.xo, which TestStdCorpora
// runs on every corpus backend; TestCrc64FuzzCorpusCurrent checks it is
// what this generator writes (XO_CRC64FUZZ_WRITE=1 rewrites it).
// TestCrc64Fuzz runs a fresh seed (XO_CRC64FUZZ_SEED, default 2;
// XO_CRC64FUZZ_N cases, default 2000) on XO_CRC64FUZZ_BACKENDS (default
// arm64 and llvm).
package stdtest

import (
	"encoding/hex"
	"fmt"
	"hash/crc64"
	"math/rand"
	"strings"
	"testing"

	"github.com/xo-lang/xo/internal/hostile"
)

// c6Case is one input, its split and chunk, and Go's checksum.
type c6Case struct {
	data            []byte
	split, chunk    int
	iso, ecma, nvme uint64
	// hostile, when set: update from start (a hostile Int, its bits the
	// crc Go's Update takes) gives starts' sums, ISO, ECMA and NVMe
	hostile bool
	start   int64
	fromS   [3]uint64
}

var c6Tables = []*crc64.Table{crc64.MakeTable(crc64.ISO), crc64.MakeTable(crc64.ECMA), crc64.MakeTable(0x9a6c9329ac4bc9b5)}

// c6Cases: with hostileStarts, every eighth case also updates from a
// hostile start (task #352), chosen by the case's index so the random
// stream, and the seed 1 corpus, are unchanged.
func c6Cases(r *rand.Rand, n, longMax int, hostileStarts bool) []c6Case {
	starts := hostile.Ints()
	for _, u := range hostile.Uints() {
		starts = append(starts, int64(u))
	}
	cs := make([]c6Case, 0, n)
	for len(cs) < n {
		k := r.Intn(601)
		switch r.Intn(10) {
		case 0:
			k = 600 + r.Intn(longMax-600+1)
		case 1, 2:
			k = r.Intn(17)
		}
		d := crData(r, k)
		c := c6Case{data: d, split: r.Intn(len(d) + 1), chunk: []int{1, 3, 7, 8, 9, 16, 63, 64, 512, 4096}[r.Intn(10)]}
		sums := []*uint64{&c.iso, &c.ecma, &c.nvme}
		for j, tb := range c6Tables {
			*sums[j] = crc64.Checksum(d, tb)
			h := crc64.New(tb)
			for i := 0; i < len(d); i += c.chunk {
				h.Write(d[i:min(i+c.chunk, len(d))])
			}
			if h.Sum64() != *sums[j] {
				panic("hash/crc64: chunked Write differs from the checksum")
			}
		}
		if hostileStarts && len(cs)%8 == 7 {
			c.hostile = true
			c.start = starts[(len(cs)/8)%len(starts)]
			for j, tb := range c6Tables {
				c.fromS[j] = crc64.Update(uint64(c.start), tb, d)
			}
		}
		cs = append(cs, c)
	}
	return cs
}

const c6CheckXo = `use std/crc64

test "std/crc64 checksums as Go's hash/crc64" {
  var bad: List[Str] = []
  for (h, _, _, iso, ecma, nvme) in CASES {
    let d = Bytes.from_hex(h).or_fault("hex")
    if crc64.checksum(d) != iso || crc64.checksum(d, crc64.Poly.Iso) != iso || crc64.checksum(d, crc64.Poly.Ecma) != ecma || crc64.checksum(d, crc64.Poly.Nvme) != nvme || crc64.update(0, d) != iso {
      bad.push("${d.len()} bytes ${h}")
    }
  }
  if !bad.is_empty() {
    fault("${bad.len()} of ${CASES.len()} inputs sum differently, first: ${bad[0]}")
  }
}

test "std/crc64 updates from a split and in chunks as Go's Update" {
  var bad: List[Str] = []
  for (h, k, chunk, iso, ecma, nvme) in CASES {
    let d = Bytes.from_hex(h).or_fault("hex")
    let n = d.len()
    var ok = true
    for (p, want) in [(crc64.Poly.Iso, iso), (crc64.Poly.Ecma, ecma), (crc64.Poly.Nvme, nvme)] {
      ok = ok && crc64.update(crc64.checksum(d[0..k], p), d[k..n], p) == want
      var c = 0
      var i = 0
      while i < n {
        let e = (i + chunk).min(n)
        c = crc64.update(c, d[i..e], p)
        i = e
      }
      ok = ok && c == want
    }
    if !ok {
      bad.push("${n} bytes at ${k}, chunks of ${chunk}: ${h}")
    }
  }
  if !bad.is_empty() {
    fault("${bad.len()} of ${CASES.len()} updates differ, first: ${bad[0]}")
  }
}
`

func c6XoFile(seed int64, cases []c6Case) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by internal/stdtest/crc64fuzz_test.go (seed %d, %d cases) from Go's\n", seed, len(cases))
	b.WriteString("// hash/crc64; do not edit: XO_CRC64FUZZ_WRITE=1 go test ./internal/stdtest -run TestCrc64FuzzCorpusCurrent\n")
	b.WriteString("// rewrites it.\n")
	b.WriteString(c6CheckXo)
	b.WriteString("\n/// (input hex, split, chunk, Iso, Ecma and Nvme checksums as Go's uint64 bits)\nconst CASES: List[(Str, Int, Int, Int, Int, Int)] = [\n")
	for _, c := range cases {
		fmt.Fprintf(&b, "  (%q, %d, %d, %d, %d, %d),\n", hex.EncodeToString(c.data), c.split, c.chunk, int64(c.iso), int64(c.ecma), int64(c.nvme))
	}
	b.WriteString("]\n")
	var hs []c6Case
	for _, c := range cases {
		if c.hostile {
			hs = append(hs, c)
		}
	}
	if len(hs) > 0 {
		b.WriteString(c6HostileXo)
		b.WriteString("\n/// (start, input hex, Go's Update from the start: ISO, ECMA, NVMe)\nconst STARTS: List[(Int, Str, Int, Int, Int)] = [\n")
		for _, c := range hs {
			fmt.Fprintf(&b, "  (%d, %q, %d, %d, %d),\n", c.start, hex.EncodeToString(c.data), int64(c.fromS[0]), int64(c.fromS[1]), int64(c.fromS[2]))
		}
		b.WriteString("]\n")
	}
	return b.String()
}

// c6HostileXo checks update from a hostile start (task #352): Int's edges
// and the unsigned ones with the top bit set.
const c6HostileXo = `
test "std/crc64 updates from a hostile start as Go's Update" {
  var bad: List[Str] = []
  for (start, h, iso, ecma, nvme) in STARTS {
    let d = Bytes.from_hex(h).or_fault("hex")
    if crc64.update(start, d) != iso || crc64.update(start, d, crc64.Poly.Ecma) != ecma || crc64.update(start, d, crc64.Poly.Nvme) != nvme {
      bad.push("from ${start}, ${d.len()} bytes ${h}")
    }
  }
  if !bad.is_empty() {
    fault("${bad.len()} of ${STARTS.len()} updates from a hostile start differ, first: ${bad[0]}")
  }
}
`

// c6Coverage fails when the cases stop reaching empty, short and long
// inputs (past 4,096 bytes) and splits at both ends.
func c6Coverage(t *testing.T, cases []c6Case, longMin int) {
	t.Helper()
	empty, short, long, atStart, atEnd := 0, 0, 0, 0, 0
	for _, c := range cases {
		switch {
		case len(c.data) == 0:
			empty++
		case len(c.data) < 17:
			short++
		case len(c.data) > longMin:
			long++
		}
		if c.split == 0 {
			atStart++
		}
		if c.split == len(c.data) {
			atEnd++
		}
	}
	n := len(cases)
	if empty < n/100 || short < n/10 || long < n/200 || atStart < n/50 || atEnd < n/50 {
		t.Fatalf("coverage fell: %d empty, %d short, %d over %d bytes, %d split at 0, %d split at the end of %d", empty, short, long, longMin, atStart, atEnd, n)
	}
}

const c6Corpus = "testdata/corpus/crc64fuzz/crc64fuzz_test.xo"

// TestCrc64FuzzCorpusCurrent: the committed corpus is what seed 1
// writes. Its long inputs stop at 5,000 bytes to keep the file small.
func TestCrc64FuzzCorpusCurrent(t *testing.T) {
	cases := c6Cases(rand.New(rand.NewSource(1)), 300, 5000, false)
	c6Coverage(t, cases, 4096)
	bxCorpusCurrent(t, c6Corpus, "XO_CRC64FUZZ_WRITE", c6XoFile(1, cases))
}

// TestCrc64Fuzz runs a fresh seed's cases.
func TestCrc64Fuzz(t *testing.T) {
	if testing.Short() {
		t.Skip("the crc64 fuzz is a heavy test; its seed 1 corpus runs in TestStdCorpora")
	}
	seed := int64(envInt(t, "XO_CRC64FUZZ_SEED", 2))
	n := envInt(t, "XO_CRC64FUZZ_N", 2000)
	cases := c6Cases(rand.New(rand.NewSource(seed)), n, 9000, seed != 1)
	runFuzzDir(t, "crc64fuzz_test.xo", c6XoFile(seed, cases), envBackends("XO_CRC64FUZZ_BACKENDS", []string{"arm64", "llvm"}), len(cases))
}
