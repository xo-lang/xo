// A differential of `derive Json(match: fold)` (decision 0550) against Go's
// encoding/json: objects whose keys are a struct's keys in random case
// (also through runes that fold to ASCII, the Kelvin sign and the long s,
// and through escapes), keys that fold to no field, duplicate keys, and
// values that do not fit, decoded into the same struct on both sides.
// Each case compares the fields set (the last member that selected each),
// or, on an error, the key of the field whose member failed first in
// document order (Go's UnmarshalTypeError.Field; Xo's DecodeErr path).
//
// TestJsonFoldDiff runs XO_JSONFOLD_N cases (default 1500) of seed
// XO_JSONFOLD_SEED (default 1) on XO_JSONFOLD_BACKENDS (default arm64,
// llvm and go).
package stdtest

import (
	"encoding/json"
	"errors"
	"fmt"
	"math/rand"
	"strings"
	"testing"
	"unicode"
)

// jfoldFields are the struct's fields: Go name, JSON key, and whether the
// value is a string (else an integer). Key and KEY fold equal, so a
// folded member selects the first declared (A).
var jfoldFields = []struct {
	goName, key string
	str         bool
}{
	{"A", "Key", false},
	{"B", "KEY", false},
	{"S", "straße", false},
	{"K", "k", true},
	{"U", "sun", false},
	{"N", "name", true},
}

type jfoldRec struct {
	A *int64  `json:"Key"`
	B *int64  `json:"KEY"`
	S *int64  `json:"straße"`
	K *string `json:"k"`
	U *int64  `json:"sun"`
	N *string `json:"name"`
}

var jfoldInts = []string{"1", "-2", "40", "1.5", "1e400", `"s"`, "true", "null", "[1]", "{}"}
var jfoldStrs = []string{`"a"`, `"é"`, `""`, "1", "null", "false"}

// jfoldKey is a spelling of key: as declared, a random case per rune, a
// rune that folds to the same letter, or an escape.
func jfoldKey(r *rand.Rand, key string) string {
	switch r.Intn(6) {
	case 0:
		return key
	case 1:
		return strings.ToUpper(key)
	case 2:
		var b strings.Builder
		for _, c := range key {
			if r.Intn(2) == 0 {
				c = unicode.ToUpper(c)
			} else {
				c = unicode.ToLower(c)
			}
			switch {
			case (c == 'k' || c == 'K') && r.Intn(3) == 0:
				b.WriteString("K")
			case (c == 's' || c == 'S') && r.Intn(3) == 0:
				b.WriteString("ſ")
			default:
				b.WriteRune(c)
			}
		}
		return b.String()
	case 3:
		// the first rune escaped
		c := []rune(key)[0]
		if r.Intn(2) == 0 {
			c = unicode.ToUpper(c)
		}
		return fmt.Sprintf("\\u%04x", c) + string([]rune(key)[1:])
	case 4:
		return strings.ToLower(key)
	}
	return strings.ToUpper(key[:1]) + key[1:]
}

var jfoldUnknown = []string{"x", "nam", "keys", "STRASSE", "su", "Kk", ""}

// jfoldCase is one object's text.
func jfoldCase(r *rand.Rand) string {
	n := r.Intn(7)
	parts := make([]string, 0, n)
	for i := 0; i < n; i++ {
		if r.Intn(6) == 0 {
			parts = append(parts, fmt.Sprintf("%q:%s", jfoldUnknown[r.Intn(len(jfoldUnknown))], jfPick(r, jfoldInts)))
			continue
		}
		f := jfoldFields[r.Intn(len(jfoldFields))]
		v := jfPick(r, jfoldInts)
		if f.str {
			v = jfPick(r, jfoldStrs)
		}
		if r.Intn(8) == 0 {
			// a value of the other kind
			if f.str {
				v = jfPick(r, jfoldInts)
			} else {
				v = jfPick(r, jfoldStrs)
			}
		}
		parts = append(parts, `"`+jfoldKey(r, f.key)+`":`+v)
	}
	return "{" + strings.Join(parts, ",") + "}"
}

// jfoldGo is Go's answer: "ok KEY=V|..." for the fields in order (none
// when unset), or "err KEY" for the field of the first type error.
func jfoldGo(in string) string {
	var rec jfoldRec
	err := json.Unmarshal([]byte(in), &rec)
	if err != nil {
		var te *json.UnmarshalTypeError
		if errors.As(err, &te) {
			for _, f := range jfoldFields {
				// go1.26 names the field by its JSON key, older Go by its name
				if te.Field == f.key || te.Field == f.goName {
					return "err " + f.key
				}
			}
		}
		return "err ?" + err.Error()
	}
	oi := func(p *int64) string {
		if p == nil {
			return "none"
		}
		return fmt.Sprint(*p)
	}
	os := func(p *string) string {
		if p == nil {
			return "none"
		}
		return *p
	}
	return fmt.Sprintf("ok Key=%s|KEY=%s|straße=%s|k=%s|sun=%s|name=%s", oi(rec.A), oi(rec.B), oi(rec.S), os(rec.K), oi(rec.U), os(rec.N))
}

const jfoldXo = `use std/json

struct JfFold {
  a as "Key": Int?
  b as "KEY": Int?
  s as "straße": Int?
  k: Str?
  u as "sun": Int?
  n as "name": Str?
} derive Json(match: fold)

fn jf_oi(o: Int?) -> Str {
  match o {
    Some(n) => "${n}"
    None => "none"
  }
}

fn jf_fold(raw: Bytes) -> Str {
  match json.decode[JfFold](raw) {
    Ok(r) => "ok Key=${jf_oi(r.a)}|KEY=${jf_oi(r.b)}|straße=${jf_oi(r.s)}|k=${r.k ?? "none"}|sun=${jf_oi(r.u)}|name=${r.n ?? "none"}"
    Err(e) => "err " + e.path.trim_prefix("$.")
  }
}

`

func jfoldXoFile(seed int64, n int) (string, int) {
	r := rand.New(rand.NewSource(seed))
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by internal/stdtest/jsonfold_test.go (seed %d) from Go's encoding/json.\n", seed)
	b.WriteString(jfoldXo)
	errs := 0
	for i := 0; i < n; i++ {
		in := jfoldCase(r)
		want := jfoldGo(in)
		if strings.HasPrefix(want, "err") {
			errs++
		}
		fmt.Fprintf(&b, "test \"json fold %d\" {\n  expect(jf_fold(%s)) == %s\n}\n\n", i, ufBytes([]byte(in)), xoStr(want))
	}
	return b.String(), errs
}

func TestJsonFoldDiff(t *testing.T) {
	if testing.Short() {
		t.Skip("the json fold differential builds and runs a program per backend")
	}
	seed := int64(envInt(t, "XO_JSONFOLD_SEED", 1))
	n := envInt(t, "XO_JSONFOLD_N", 1500)
	content, errs := jfoldXoFile(seed, n)
	if i := strings.Index(content, `"err ?`); i >= 0 {
		t.Fatalf("a case failed in Go with an error that is not a type error (the generator makes only type errors): %s", content[strings.LastIndex(content[:i], "expect("):i+200])
	}
	if errs < n/10 || errs > n*9/10 {
		t.Fatalf("%d of %d cases are errors; the generator should make both", errs, n)
	}
	runFuzzDir(t, "jsonfold_test.xo", content, envBackends("XO_JSONFOLD_BACKENDS", []string{"arm64", "llvm", "go"}), n)
}
