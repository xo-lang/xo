// A fuzz harness for std/tabwriter against Go's text/tabwriter (decision
// 0616's fuzz kind; task #116). Each case is a writer (min width, tab
// width, padding, pad byte space, tab, '.' or '-', and any sum of the six
// flags) and a text of cells: words with UTF-8 and invalid bytes, tabs and
// vertical tabs, newlines and form feeds, escaped runs between 0xff bytes,
// HTML tags and entities, empty cells and columns, written in random
// pieces (a piece can end inside a rune, an escape or an entity).
// std/tabwriter must return Go's output from flush, the bytes Go's Writer
// wrote to its io.Writer.
//
// The cases from seed 1 are the committed corpus
// testdata/corpus/tabwriterfuzz/tabwriterfuzz_test.xo, which TestStdCorpora
// runs on every corpus backend; TestTabwriterFuzzCorpusCurrent checks it is
// what this generator writes (XO_TABWRITERFUZZ_WRITE=1 rewrites it).
// TestTabwriterFuzz runs a fresh seed (XO_TABWRITERFUZZ_SEED, default 2;
// XO_TABWRITERFUZZ_N cases, default 2000) on XO_TABWRITERFUZZ_BACKENDS
// (default arm64 and llvm).
package stdtest

import (
	"bytes"
	"encoding/hex"
	"fmt"
	"math/rand"
	"strings"
	"testing"
	"text/tabwriter"

	"github.com/xo-lang/xo/internal/hostile"
)

type twCase struct {
	minw, tabw, pad int
	padc            byte
	flags           uint
	pieces          [][]byte
	want            []byte
}

var twWords = []string{"a", "bb", "ccc", "hello", "x y", "é", "日本語", "🙂", "\xff", "<b>", "</b>", "&amp;", "&lt;x", "&#39;", "&;", "<", ">", "", "", "12345678", "-", "\x80", "\xe6\x97"}

func twText(r *rand.Rand) []byte {
	var b bytes.Buffer
	for lines := 1 + r.Intn(8); lines > 0; lines-- {
		for cells := r.Intn(5); cells > 0; cells-- {
			for k := r.Intn(3); k > 0; k-- {
				w := twWords[r.Intn(len(twWords))]
				if r.Intn(12) == 0 {
					// an escaped run: tabs and line breaks inside pass through
					w = "\xff" + w + []string{"\t", "\n", "x"}[r.Intn(3)] + "\xff"
				}
				if b.Len()%11 == 5 {
					// the hostile dictionary (task #352): UTF-8 cut inside
					// a rune, which a cell's width counts a byte at a time,
					// chosen by the length so the cases after it stay as
					// they were
					cuts := hostile.CutUTF8("é日😀")
					w = cuts[b.Len()%len(cuts)] + w
				}
				b.WriteString(w)
			}
			b.WriteByte([]byte{'\t', '\t', '\t', '\v'}[r.Intn(4)])
		}
		for k := r.Intn(2); k > 0; k-- {
			b.WriteString(twWords[r.Intn(len(twWords))])
		}
		if lines > 1 || r.Intn(2) == 0 {
			b.WriteByte([]byte{'\n', '\n', '\n', '\f'}[r.Intn(4)])
		}
	}
	return b.Bytes()
}

func twCases(r *rand.Rand, n int) []twCase {
	cs := make([]twCase, 0, n)
	for len(cs) < n {
		c := twCase{minw: r.Intn(10), tabw: r.Intn(9), pad: r.Intn(4), padc: []byte{' ', '\t', '.', '-'}[r.Intn(4)], flags: uint(r.Intn(64))}
		text := twText(r)
		for len(text) > 0 {
			k := 1 + r.Intn(len(text))
			if r.Intn(3) == 0 {
				k = len(text)
			}
			c.pieces = append(c.pieces, text[:k])
			text = text[k:]
		}
		var out bytes.Buffer
		w := tabwriter.NewWriter(&out, c.minw, c.tabw, c.pad, c.padc, c.flags)
		for _, p := range c.pieces {
			w.Write(p)
		}
		w.Flush()
		c.want = out.Bytes()
		cs = append(cs, c)
	}
	return cs
}

const twCheckXo = `use std/tabwriter

fn render(minw: Int, tabw: Int, pad: Int, padc: Int, flags: Int, pieces: List[Str]) -> Str {
  var w = tabwriter.writer(minw, tabw, pad, pad_char: padc, flags: flags)
  for p in pieces {
    w.write(Bytes.from_hex(p).or_fault("hex"))
  }
  w.flush().to_hex()
}

test "std/tabwriter formats as Go's text/tabwriter" {
  var bad: List[(Int, Str, Str)] = []
  for (i, (minw, tabw, pad, padc, flags, pieces, want)) in CASES.indexed() {
    let got = render(minw, tabw, pad, padc, flags, pieces)
    if got != want {
      bad.push((i, got, want))
    }
  }
  expect(bad[0..(if bad.len() < 10 { bad.len() } else { 10 })]) == []
}
`

func twXoFile(seed int64, cases []twCase) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by internal/stdtest/tabwriterfuzz_test.go (seed %d, %d cases) from Go's\n", seed, len(cases))
	b.WriteString("// text/tabwriter; do not edit: XO_TABWRITERFUZZ_WRITE=1 go test ./internal/stdtest -run TestTabwriterFuzzCorpusCurrent\n")
	b.WriteString("// rewrites it.\n")
	b.WriteString(twCheckXo)
	b.WriteString("\n/// (min width, tab width, padding, pad byte, flags, the pieces written in hex, Go's output in hex)\nconst CASES: List[(Int, Int, Int, Int, Int, List[Str], Str)] = [\n")
	for _, c := range cases {
		ps := make([]string, len(c.pieces))
		for i, p := range c.pieces {
			ps[i] = fmt.Sprintf("%q", hex.EncodeToString(p))
		}
		fmt.Fprintf(&b, "  (%d, %d, %d, %d, %d, [%s], %q),\n", c.minw, c.tabw, c.pad, c.padc, c.flags, strings.Join(ps, ", "), hex.EncodeToString(c.want))
	}
	b.WriteString("]\n")
	return b.String()
}

// twCoverage fails when the cases stop reaching each flag, escapes, HTML
// and multi-piece writes.
func twCoverage(t *testing.T, cases []twCase) {
	t.Helper()
	flags := map[uint]int{}
	esc, html, multi := 0, 0, 0
	for _, c := range cases {
		for f := uint(1); f < 64; f <<= 1 {
			if c.flags&f != 0 {
				flags[f]++
			}
		}
		all := bytes.Join(c.pieces, nil)
		if bytes.Count(all, []byte{0xff}) >= 2 {
			esc++
		}
		if bytes.ContainsAny(all, "<&") {
			html++
		}
		if len(c.pieces) > 2 {
			multi++
		}
	}
	n := len(cases)
	for f := uint(1); f < 64; f <<= 1 {
		if flags[f] < n/3 {
			t.Fatalf("coverage fell: flag %d in %d of %d cases", f, flags[f], n)
		}
	}
	if esc < n/5 || html < n/3 || multi < n/3 {
		t.Fatalf("coverage fell: %d escaped, %d with HTML, %d written in pieces of %d", esc, html, multi, n)
	}
}

const twCorpus = "testdata/corpus/tabwriterfuzz/tabwriterfuzz_test.xo"

// TestTabwriterFuzzCorpusCurrent: the committed corpus is what seed 1 writes.
func TestTabwriterFuzzCorpusCurrent(t *testing.T) {
	cases := twCases(rand.New(rand.NewSource(1)), 400)
	twCoverage(t, cases)
	bxCorpusCurrent(t, twCorpus, "XO_TABWRITERFUZZ_WRITE", twXoFile(1, cases))
}

// TestTabwriterFuzz runs a fresh seed's cases.
func TestTabwriterFuzz(t *testing.T) {
	if testing.Short() {
		t.Skip("the tabwriter fuzz is a heavy test; its seed 1 corpus runs in TestStdCorpora")
	}
	seed := int64(envInt(t, "XO_TABWRITERFUZZ_SEED", 2))
	n := envInt(t, "XO_TABWRITERFUZZ_N", 2000)
	cases := twCases(rand.New(rand.NewSource(seed)), n)
	runFuzzDir(t, "tabwriterfuzz_test.xo", twXoFile(seed, cases), envBackends("XO_TABWRITERFUZZ_BACKENDS", []string{"arm64", "llvm"}), len(cases))
}
