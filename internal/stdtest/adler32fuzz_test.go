// A fuzz harness for std/adler32 against Go's hash/adler32 (decision
// 0616's fuzz kind). Each case is random bytes (crData: 0 to 600 of them,
// a tenth longer, past 5,552 bytes, the most Go's update adds before it
// takes the modulus, and past std/native's eight byte steps), a split
// point and a chunk size:
//
//   - checksum gives what Checksum gives;
//   - update continued from the checksum of the bytes before the split
//     gives the checksum of the whole, and update from 1 gives the
//     checksum;
//   - update over the bytes in chunks of the chunk size, from 1, gives
//     the one-shot checksum, as Go's hash.Hash32 written in those chunks.
//
// The cases from seed 1 are the committed corpus
// testdata/corpus/adler32fuzz/adler32fuzz_test.xo, which TestStdCorpora
// runs on every corpus backend; TestAdler32FuzzCorpusCurrent checks it is
// what this generator writes (XO_ADLER32FUZZ_WRITE=1 rewrites it).
// TestAdler32Fuzz runs a fresh seed (XO_ADLER32FUZZ_SEED, default 2;
// XO_ADLER32FUZZ_N cases, default 2000) on XO_ADLER32FUZZ_BACKENDS (default
// arm64 and llvm).
package stdtest

import (
	"encoding/hex"
	"fmt"
	"hash/adler32"
	"math/rand"
	"strings"
	"testing"
)

// adCase is one input, its split and chunk, and Go's checksum.
type adCase struct {
	data         []byte
	split, chunk int
	sum          uint32
}

func adCases(r *rand.Rand, n, longMax int) []adCase {
	cs := make([]adCase, 0, n)
	for len(cs) < n {
		k := r.Intn(601)
		switch r.Intn(10) {
		case 0:
			k = 600 + r.Intn(longMax-600+1)
		case 1, 2:
			k = r.Intn(17)
		}
		d := crData(r, k)
		// a run of 0xff makes the sums grow fastest, toward the modulus
		if r.Intn(8) == 0 {
			for i := range d {
				d[i] = 0xff
			}
		}
		c := adCase{data: d, split: r.Intn(len(d) + 1), chunk: []int{1, 3, 7, 8, 16, 63, 64, 512, 4096, 5552}[r.Intn(10)]}
		c.sum = adler32.Checksum(d)
		h := adler32.New()
		for i := 0; i < len(d); i += c.chunk {
			h.Write(d[i:min(i+c.chunk, len(d))])
		}
		if h.Sum32() != c.sum {
			panic("hash/adler32: chunked Write differs from the checksum")
		}
		cs = append(cs, c)
	}
	return cs
}

const adCheckXo = `use std/adler32

test "std/adler32 checksums as Go's hash/adler32" {
  var bad: List[Str] = []
  for (h, _, _, sum) in CASES {
    let d = Bytes.from_hex(h).or_fault("hex")
    if adler32.checksum(d) != sum || adler32.update(1, d) != sum {
      bad.push("${d.len()} bytes ${h}")
    }
  }
  if !bad.is_empty() {
    fault("${bad.len()} of ${CASES.len()} inputs sum differently, first: ${bad[0]}")
  }
}

test "std/adler32 updates from a split and in chunks as Go's Write" {
  var bad: List[Str] = []
  for (h, k, chunk, sum) in CASES {
    let d = Bytes.from_hex(h).or_fault("hex")
    let n = d.len()
    let ok = adler32.update(adler32.checksum(d[0..k]), d[k..n]) == sum
    var c = 1
    var i = 0
    while i < n {
      let e = (i + chunk).min(n)
      c = adler32.update(c, d[i..e])
      i = e
    }
    if !ok || c != sum {
      bad.push("${n} bytes at ${k}, chunks of ${chunk}: ${h}")
    }
  }
  if !bad.is_empty() {
    fault("${bad.len()} of ${CASES.len()} updates differ, first: ${bad[0]}")
  }
}
`

func adXoFile(seed int64, cases []adCase) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by internal/stdtest/adler32fuzz_test.go (seed %d, %d cases) from Go's\n", seed, len(cases))
	b.WriteString("// hash/adler32; do not edit: XO_ADLER32FUZZ_WRITE=1 go test ./internal/stdtest -run TestAdler32FuzzCorpusCurrent\n")
	b.WriteString("// rewrites it.\n")
	b.WriteString(adCheckXo)
	b.WriteString("\n/// (input hex, split, chunk, checksum)\nconst CASES: List[(Str, Int, Int, Int)] = [\n")
	for _, c := range cases {
		fmt.Fprintf(&b, "  (%q, %d, %d, %d),\n", hex.EncodeToString(c.data), c.split, c.chunk, c.sum)
	}
	b.WriteString("]\n")
	return b.String()
}

// adCoverage fails when the cases stop reaching empty, short and long
// inputs (past 5,552 bytes) and splits at both ends.
func adCoverage(t *testing.T, cases []adCase, longMin int) {
	t.Helper()
	empty, short, long, atStart, atEnd := 0, 0, 0, 0, 0
	for _, c := range cases {
		switch {
		case len(c.data) == 0:
			empty++
		case len(c.data) < 17:
			short++
		case len(c.data) > longMin:
			long++
		}
		if c.split == 0 {
			atStart++
		}
		if c.split == len(c.data) {
			atEnd++
		}
	}
	n := len(cases)
	if empty < n/100 || short < n/10 || long < n/200 || atStart < n/50 || atEnd < n/50 {
		t.Fatalf("coverage fell: %d empty, %d short, %d over %d bytes, %d split at 0, %d split at the end of %d", empty, short, long, longMin, atStart, atEnd, n)
	}
}

const adCorpus = "testdata/corpus/adler32fuzz/adler32fuzz_test.xo"

// TestAdler32FuzzCorpusCurrent: the committed corpus is what seed 1
// writes. Its long inputs stop at 6,000 bytes, past the 5,552 byte block,
// to keep the file small.
func TestAdler32FuzzCorpusCurrent(t *testing.T) {
	cases := adCases(rand.New(rand.NewSource(1)), 300, 6000)
	adCoverage(t, cases, 5552)
	bxCorpusCurrent(t, adCorpus, "XO_ADLER32FUZZ_WRITE", adXoFile(1, cases))
}

// TestAdler32Fuzz runs a fresh seed's cases.
func TestAdler32Fuzz(t *testing.T) {
	if testing.Short() {
		t.Skip("the adler32 fuzz is a heavy test; its seed 1 corpus runs in TestStdCorpora")
	}
	seed := int64(envInt(t, "XO_ADLER32FUZZ_SEED", 2))
	n := envInt(t, "XO_ADLER32FUZZ_N", 2000)
	cases := adCases(rand.New(rand.NewSource(seed)), n, 12000)
	runFuzzDir(t, "adler32fuzz_test.xo", adXoFile(seed, cases), envBackends("XO_ADLER32FUZZ_BACKENDS", []string{"arm64", "llvm"}), len(cases))
}
