// A fuzz harness for std/debug's routes (#152, decision 0616's fuzz kind; lead question 155): random query
// strings (escapes, '+', signs, repeated and near-miss keys, ';', bad escapes, long and non-ASCII digits) on
// GET /profile?... through debug.router on a FakeClock. The profile's length is the first sleep the handler
// asks for, and it must be what Go's net/http reads (url.ParseQuery's first value of "seconds", then
// strconv.ParseInt base 10, 30 when that fails) clamped to std/debug's 1 to 300 seconds. A request auth
// refuses is 403 with no sleep; every case must answer, with no fault and no hang. TestDebugFuzz runs
// XO_DEBUGFUZZ_SEED (default 2) with XO_DEBUGFUZZ_N cases (default 2000) on XO_DEBUGFUZZ_BACKENDS (default
// arm64 and llvm).
package stdtest

import (
	"fmt"
	"math/rand"
	"net/url"
	"strconv"
	"strings"
	"testing"
)

// debugFuzzValue is a random value for a query parameter, raw (as it goes on the wire).
func debugFuzzValue(r *rand.Rand) string {
	pool := []string{"", "0", "1", "5", "30", "299", "300", "301", "-1", "-0", "+5", "+", "-", "007", "1e2", "0x10",
		"1_0", "5.0", "5.", " 5", "5 ", "%205", "5%20", "+5+", "%2B5", "%2D3", "%35", "%3", "%zz", "5%", "abc", "9223372036854775807",
		"9223372036854775808", "-9223372036854775808", "99999999999999999999999", "%D9%A3", "٣", "%00", "5%005", "１"}
	switch r.Intn(4) {
	case 0:
		return strconv.Itoa(r.Intn(700) - 200)
	case 1:
		return pool[r.Intn(len(pool))] + pool[r.Intn(len(pool))]
	default:
		return pool[r.Intn(len(pool))]
	}
}

// debugFuzzQuery is a random raw query naming seconds and hz zero or more times.
func debugFuzzQuery(r *rand.Rand) string {
	keys := []string{"seconds", "seconds", "seconds", "hz", "hz", "Seconds", "second", "secondss", "sec%6Fnds", "seconds%00",
		"seconds+", "%73econds", "x", "", "seconds[]"}
	var parts []string
	for i, n := 0, r.Intn(5); i < n; i++ {
		k := keys[r.Intn(len(keys))]
		switch r.Intn(6) {
		case 0:
			parts = append(parts, k)
		case 1:
			parts = append(parts, k+"=")
		default:
			parts = append(parts, k+"="+debugFuzzValue(r))
		}
	}
	seps := []string{"&", "&", "&", ";", "&&"}
	var b strings.Builder
	for i, p := range parts {
		if i > 0 {
			b.WriteString(seps[r.Intn(len(seps))])
		}
		b.WriteString(p)
	}
	return b.String()
}

// debugWantSecs is the profile's length Go's net/http reads from raw, clamped as std/debug clamps it.
func debugWantSecs(raw string) int {
	vs, _ := url.ParseQuery(raw)
	n, err := strconv.ParseInt(vs.Get("seconds"), 10, 64)
	if err != nil {
		n = 30
	}
	return int(min(max(n, 1), 300))
}

func debugFuzz(seed int64, n int) string {
	r := rand.New(rand.NewSource(seed))
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by internal/stdtest TestDebugFuzz (seed %d, %d cases): the profile's length from Go's url.ParseQuery and strconv.ParseInt.\n\n", seed, n)
	b.WriteString("use std/debug\nuse std/http\n\n")
	b.WriteString("/// (raw query, auth answers true, the status, the profile's seconds or 0)\nconst CASES: List[(Str, Bool, Int, Int)] = [\n")
	for i := 0; i < n; i++ {
		q := debugFuzzQuery(r)
		auth := r.Intn(8) != 0
		status, secs := 403, 0
		if auth {
			status, secs = 200, debugWantSecs(q)
		}
		fmt.Fprintf(&b, "  (%s, %v, %d, %d),\n", xoStr(q), auth, status, secs)
	}
	b.WriteString("]\n\n")
	// a test per 100 cases: a profile takes about 30 ms of real time on
	// llvm and each test has 60 s, but xo test runs a process per core
	// and a loaded host (host 3, 2026-11-18: 8 of 10 tests of 500 cases
	// on llvm passed 60 s at seed 9) takes over 4 times as long
	for lo := 0; lo < n; lo += 100 {
		hi := min(lo+100, n)
		fmt.Fprintf(&b, `
test "debug's profile route reads seconds as Go's net/http does, cases %d to %d" {
  let ok = debug.router(os.clock, fn(_r) { true })
  let no = debug.router(os.clock, fn(_r) { false })
  var i = 0
  for (q, auth, status, secs) in CASES {
    if i >= %d && i < %d {
      let before = os.clock.sleeps().len()
      let r = if auth { ok } else { no }
      let got = r.call(http.new_request("GET", "/profile?" + q)).status
      let s = os.clock.sleeps()
      let slept = if s.len() > before { s[before].millis() / 1000 } else { 0 }
      expect("${i} ${q.quote()} ${got} ${slept}") == "${i} ${q.quote()} ${status} ${secs}"
    }
    i += 1
  }
}
`, lo, hi-1, lo, hi)
	}
	return b.String()
}

func TestDebugFuzz(t *testing.T) {
	if testing.Short() {
		t.Skip("the debug fuzz takes a CPU profile per case")
	}
	seed := envInt(t, "XO_DEBUGFUZZ_SEED", 2)
	n := envInt(t, "XO_DEBUGFUZZ_N", 2000)
	runFuzzDir(t, "debugfuzz_test.xo", debugFuzz(int64(seed), n), envBackends("XO_DEBUGFUZZ_BACKENDS", []string{"arm64", "llvm"}), n)
}
