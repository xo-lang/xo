// A fuzz harness for std/path against Go's path package (and
// path/filepath's Rel and IsLocal on Unix; decision 0616's fuzz kind).
// Each case is two random strings built from path pieces (separators
// doubled and trailing, ".", "..", names with dots, empty parts, the
// pattern bytes * ? [ ] ^ - \ and non-ASCII), and std/path must give
// Go's answers:
//
//   - clean, dir, base, ext, split and is_abs of the first are Go's
//     Clean, Dir, Base, Ext, Split and IsAbs;
//   - join(a, b) is Join(a, b); rel(a, b) is filepath.Rel(a, b), None
//     where it errors; is_local(a) is filepath.IsLocal(a);
//   - is_match(a, b) is Match(a, b), an error where Go reports
//     ErrBadPattern.
//
// The cases from seed 1 are the committed corpus
// testdata/corpus/pathfuzz/pathfuzz_test.xo, which TestStdCorpora runs on
// every corpus backend; TestPathFuzzCorpusCurrent checks it is what this
// generator writes (XO_PATHFUZZ_WRITE=1 rewrites it). TestPathFuzz runs a
// fresh seed (XO_PATHFUZZ_SEED, default 2; XO_PATHFUZZ_N cases, default
// 2000) on XO_PATHFUZZ_BACKENDS (default arm64 and llvm).
package stdtest

import (
	"fmt"
	"math/rand"
	"path"
	"path/filepath"
	"strings"
	"testing"

	"github.com/xo-lang/xo/internal/hostile"
)

type ptCase struct {
	a, b, want string
}

var ptPieces = []string{"/", "/", "//", ".", "..", "a", "b", "abc", "x.y", ".z", "a.b.c", "", "日本", "é.go", "-", "a b"}
var ptPatPieces = []string{"*", "?", "[a-c]", "[^x]", "[]a]", "[", "]", "\\", "\\*", "[a-]", "[-z]", "[\\]]", "^", "[!a]", "**", "[a", "\\"}

func ptPath(r *rand.Rand, pattern bool) string {
	var b strings.Builder
	for k := r.Intn(7); k > 0; k-- {
		if pattern && r.Intn(3) == 0 {
			b.WriteString(ptPatPieces[r.Intn(len(ptPatPieces))])
		} else {
			b.WriteString(ptPieces[r.Intn(len(ptPieces))])
		}
		if r.Intn(2) == 0 {
			b.WriteByte('/')
		}
	}
	if b.Len()%17 == 3 {
		// the hostile dictionary (task #352): ".." runs 1 to 100 deep,
		// chosen by the length so the cases after it stay as they were
		ds := hostile.Depths()
		b.WriteString(hostile.Nest("../", "", ds[b.Len()%len(ds)]/1000))
	}
	return b.String()
}

func ptBool(v bool) string { return fmt.Sprint(v) }

func ptCaseOf(a, b string) ptCase {
	d, f := path.Split(a)
	rel, err := filepath.Rel(a, b)
	if err != nil {
		rel = "err"
	}
	m, merr := path.Match(a, b)
	match := ptBool(m)
	if merr != nil {
		match = "err"
	}
	w := []string{path.Clean(a), path.Dir(a), path.Base(a), path.Ext(a), d, f, ptBool(path.IsAbs(a)), path.Join(a, b), rel, ptBool(filepath.IsLocal(a)), match}
	return ptCase{a, b, strings.Join(w, "\x01")}
}

func ptCases(r *rand.Rand, n int) []ptCase {
	cs := make([]ptCase, 0, n)
	for len(cs) < n {
		pat := r.Intn(3) == 0
		a := ptPath(r, pat)
		b := ptPath(r, false)
		if pat && r.Intn(2) == 0 {
			// a name the pattern may match: the pattern's literal bytes kept
			b = strings.NewReplacer("*", "xx", "?", "q", "[a-c]", "b", "[^x]", "y", "\\", "").Replace(a)
		}
		cs = append(cs, ptCaseOf(a, b))
	}
	return cs
}

const ptCheckXo = `use std/path

fn answer(a: Str, b: Str) -> Str {
  let (d, f) = path.split(a)
  let m = match path.is_match(a, b) {
    Ok(v) => "${v}"
    Err(_) => "err"
  }
  [path.clean(a), path.dir(a), path.base(a), path.ext(a), d, f, "${path.is_abs(a)}", path.join(a, b), path.rel(a, b) ?? "err", "${path.is_local(a)}", m].join("\u{1}")
}

test "std/path is Go's path (clean, dir, base, ext, split, is_abs, join, is_match) and filepath (rel, is_local)" {
  var bad: List[(Str, Str, Str, Str)] = []
  for (a, b, want) in CASES {
    let got = answer(a, b)
    if got != want {
      bad.push((a, b, got, want))
    }
  }
  expect(bad[0..(if bad.len() < 20 { bad.len() } else { 20 })]) == []
}
`

func ptXoFile(seed int64, cases []ptCase) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by internal/stdtest/pathfuzz_test.go (seed %d, %d cases) from Go's\n", seed, len(cases))
	b.WriteString("// path and path/filepath; do not edit: XO_PATHFUZZ_WRITE=1 go test ./internal/stdtest -run TestPathFuzzCorpusCurrent\n")
	b.WriteString("// rewrites it.\n")
	b.WriteString(ptCheckXo)
	b.WriteString("\n/// (a, b, Go's Clean Dir Base Ext Split IsAbs of a, Join(a, b), filepath.Rel(a, b) or err, filepath.IsLocal(a), Match(a, b) or err; joined by U+0001)\nconst CASES: List[(Str, Str, Str)] = [\n")
	for _, c := range cases {
		fmt.Fprintf(&b, "  (%s, %s, %s),\n", xoStr(c.a), xoStr(c.b), xoStr(c.want))
	}
	b.WriteString("]\n")
	return b.String()
}

// ptCoverage fails when the cases stop reaching each outcome: rel errors
// and values, bad patterns, matches and misses, local and not.
func ptCoverage(t *testing.T, cases []ptCase) {
	t.Helper()
	relErr, relOK, badPat, matched, missed, local := 0, 0, 0, 0, 0, 0
	for _, c := range cases {
		f := strings.Split(c.want, "\x01")
		if f[8] == "err" {
			relErr++
		} else {
			relOK++
		}
		switch f[10] {
		case "err":
			badPat++
		case "true":
			matched++
		default:
			missed++
		}
		if f[9] == "true" {
			local++
		}
	}
	n := len(cases)
	if relErr < n/20 || relOK < n/5 || badPat < n/50 || matched < n/50 || missed < n/5 || local < n/10 {
		t.Fatalf("coverage fell: rel %d err %d ok, match %d bad %d true %d false, %d local of %d", relErr, relOK, badPat, matched, missed, local, n)
	}
}

const ptCorpus = "testdata/corpus/pathfuzz/pathfuzz_test.xo"

// TestPathFuzzCorpusCurrent: the committed corpus is what seed 1 writes.
func TestPathFuzzCorpusCurrent(t *testing.T) {
	cases := ptCases(rand.New(rand.NewSource(1)), 500)
	ptCoverage(t, cases)
	bxCorpusCurrent(t, ptCorpus, "XO_PATHFUZZ_WRITE", ptXoFile(1, cases))
}

// TestPathFuzz runs a fresh seed's cases.
func TestPathFuzz(t *testing.T) {
	if testing.Short() {
		t.Skip("the path fuzz is a heavy test; its seed 1 corpus runs in TestStdCorpora")
	}
	seed := int64(envInt(t, "XO_PATHFUZZ_SEED", 2))
	n := envInt(t, "XO_PATHFUZZ_N", 2000)
	cases := ptCases(rand.New(rand.NewSource(seed)), n)
	runFuzzDir(t, "pathfuzz_test.xo", ptXoFile(seed, cases), envBackends("XO_PATHFUZZ_BACKENDS", []string{"arm64", "llvm"}), len(cases))
}
