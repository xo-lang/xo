// irParts is a module GenerateSSA printed, split into its parts (the
// comparison with the self hosted emitter, selfhost/llvm, decision 0166):
// the declarations of the runtime calls used, the named types, the
// globals (string literals and fault locations), and every definition by
// name, in the order the module has them.
type irParts struct {
	RTDecls []string
	Types   []string
	Globals []string
	// Defs maps a definition's name (`xo.dup.Str`, `x.main`, `xo_entry`)
	// to its text, from `define` to the line `}`.
	Defs  map[string]string
	Order []string
}

// irHead is what every module starts with.
const irHead = "; generated by xo build --backend=llvm (internal/llvm, from internal/ssa with reference counting)\n\n" + ssaRuntimeDecls

// splitIR splits ir (GenerateSSA's text, without target attributes).
func splitIR(ir string) (irParts, error) {
	p := irParts{Defs: map[string]string{}}
	rest, ok := strings.CutPrefix(ir, irHead)
	if !ok {
		return p, fmt.Errorf("the module does not start with the runtime declarations")
	}
	lines := strings.SplitAfter(rest, "\n")
	for i := 0; i < len(lines); i++ {
		l := lines[i]
		switch {
		case l == "\n" || l == "":
		case strings.HasPrefix(l, "declare "):
			p.RTDecls = append(p.RTDecls, l)
		case strings.HasPrefix(l, "%"):
			p.Types = append(p.Types, l)
		case strings.HasPrefix(l, "@."):
			p.Globals = append(p.Globals, l)
		case strings.HasPrefix(l, "define "):
			name := defName(l)
			var b strings.Builder
			for ; i < len(lines); i++ {
				b.WriteString(lines[i])
				if lines[i] == "}\n" {
					break
				}
			}
			if _, dup := p.Defs[name]; dup {
				return p, fmt.Errorf("two definitions of %s", name)
			}
			p.Defs[name] = b.String()
			p.Order = append(p.Order, name)
		default:
			return p, fmt.Errorf("unexpected line %q", l)
		}
	}
	return p, nil
}

// defName is the name a `define` line defines: the text between `@` and
// `(`, unquoted.
func defName(line string) string {
	at := strings.Index(line, "@")
	if at < 0 {
		return line
	}
	s := line[at+1:]
	if strings.HasPrefix(s, `"`) {
		// a quoted name: up to the closing quote (names hold no escapes
		// of `"`; strconv.Quote escapes them as \")
		for j := 1; j < len(s); j++ {
			if s[j] == '\\' {
				j++
				continue
			}
			if s[j] == '"' {
				return s[1:j]
			}
		}
		return s
	}
	if k := strings.Index(s, "("); k >= 0 {
		return s[:k]
	}
	return s
}

