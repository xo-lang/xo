// Package selfhost holds the Go side of the self hosted Xo tools under
// selfhost/: generators for tables the Xo code cannot compute itself, and
// (in its tests) the differential test that runs the Xo lexer against
// internal/lexer on every .xo file in the repository.
package selfhost

import (
	"fmt"
	"strconv"
	"strings"
)

// IsPrintTable returns the Xo source of selfhost/lexer/isprint.xo: the
// ranges of runes at or above U+0080 for which strconv.IsPrint is true,
// which the Xo port of strconv.QuoteRune needs (Xo's std has no Unicode
// tables beyond Rune.is_letter and friends, and no Int to Rune conversion).
func IsPrintTable() string {
	var pairs []string // lo, hi, lo, hi, ...
	in := false
	var lo rune
	for r := rune(0x80); r <= 0x110000; r++ {
		p := r <= 0x10FFFF && strconv.IsPrint(r)
		switch {
		case p && !in:
			lo = r
		case !p && in:
			pairs = append(pairs, fmt.Sprintf("0x%x", lo), fmt.Sprintf("0x%x", r-1))
		}
		in = p
	}
	var b strings.Builder
	b.WriteString("// Code generated by internal/selfhost (go test ./internal/selfhost -run TestIsPrintTable -update). DO NOT EDIT.\n\n")
	b.WriteString("/// Inclusive [lo, hi] pairs of the runes at or above U+0080 that\n")
	b.WriteString("/// strconv.IsPrint accepts, sorted. strconv follows the unicode tables of\n")
	b.WriteString("/// the Go release that runs the generator.\n")
	b.WriteString("const PRINT_RANGES = [\n")
	// One element per line, the layout `xo fmt` keeps.
	for _, p := range pairs {
		b.WriteString("  " + p + ",\n")
	}
	b.WriteString("]\n")
	return b.String()
}
