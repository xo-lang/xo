package llvm

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// http1TablesPath is the generated table module of the native HTTP/1.1
// server's request parsing, written in Xo (std/native/llrt/http1.xo,
// decision 0193 step 6).
var http1TablesPath = filepath.Join("..", "..", "std", "native", "llrt", "http1_tables.xo")

// http1Class is the class bits of a byte for http1.xo: the character
// sets of net/http, textproto, and net/url that xo_http.c tested one by
// one.
func http1Class(c byte) byte {
	alnum := c >= '0' && c <= '9' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z'
	in := func(set string) bool { return c != 0 && strings.IndexByte(set, c) >= 0 }
	var k byte
	if alnum || in("!#$%&'*+-.^_`|~") {
		k |= 1 // a token byte (RFC 7230 tchar)
	}
	if c >= 0x80 || c >= 0x21 && c <= 0x7e || c == ' ' || c == '\t' {
		k |= 2 // textproto's validHeaderValueByte
	}
	if alnum || in("!$&'()*+,;=:[]<>\"-_.~") {
		k |= 4 // url.shouldEscape's host bytes kept
	}
	if c >= '0' && c <= '9' || c >= 'a' && c <= 'f' || c >= 'A' && c <= 'F' {
		k |= 8 // a hex digit
	}
	if alnum || in("-._:~!$&'()*+,;=%@") {
		k |= 16 // url's validUserinfo
	}
	if alnum || in("!$%&()*+,-.:;=['\\]_~") && c != '\\' {
		k |= 32 // httpguts.ValidHostHeader
	}
	if alnum || in("-_.~") {
		k |= 64 // url.QueryEscape keeps it
	}
	if alnum || in("-_.~$&+,/:;=@") {
		k |= 128 // url.escape(s, encodePath) keeps it
	}
	return k
}

// http1Tables is the text of std/native/llrt/http1_tables.xo.
func http1Tables() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/llvm TestHTTP1Tables -golden-update. DO NOT\n")
	b.WriteString("// EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// The tables of std/native/llrt/http1.xo (decision 0193 step 6).\n\n")
	t := make([]byte, 256)
	for c := range 256 {
		t[c] = http1Class(byte(c))
	}
	b.WriteString("/// The classes of each byte: 1 a token byte (tchar), 2 a header value\n")
	b.WriteString("/// byte, 4 a URL host byte, 8 a hex digit, 16 a userinfo byte, 32 a\n")
	b.WriteString("/// Host header byte, 64 kept by url.QueryEscape, 128 kept in a path by\n")
	b.WriteString("/// url.escape.\n")
	fmt.Fprintf(&b, "pub const CLASS: Bytes = %s\n", xoBytesLit(t))
	return b.Bytes()
}

// TestHTTP1Tables checks that std/native/llrt/http1_tables.xo is current
// (-golden-update rewrites it).
func TestHTTP1Tables(t *testing.T) {
	want := http1Tables()
	if *updateGolden {
		if err := os.WriteFile(http1TablesPath, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(http1TablesPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s is stale: run go test ./internal/llvm -run TestHTTP1Tables -golden-update", http1TablesPath)
	}
}
