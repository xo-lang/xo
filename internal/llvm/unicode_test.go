// xoBytesLit is b as an Xo Bytes literal: printable ASCII as itself
// (except `"`, `\`, and `$`), every other byte \xhh.
func xoBytesLit(b []byte) string {
	var s bytes.Buffer
	s.WriteString(`b"`)
	for _, c := range b {
		if c >= 0x20 && c < 0x7f && c != '"' && c != '\\' && c != '$' {
			s.WriteByte(c)
		} else {
			fmt.Fprintf(&s, `\x%02x`, c)
		}
	}
	s.WriteByte('"')
	return s.String()
}

// put24 appends v as 24 bits big endian (two's complement for a negative
// delta).
func put24(b []byte, v int) []byte {
	if v < -(1<<23) || v >= 1<<23 {
		panic(fmt.Sprintf("unicode table value %d does not fit 24 bits", v))
	}
	u := uint32(v) & 0xFFFFFF
	return append(b, byte(u>>16), byte(u>>8), byte(u))
}

// put24le appends v as 24 bits little endian, followed by a zero byte, so a
// reader can take the value from one 8 byte load and a mask
// (rt.bytes_word & 0xFFFFFF in std/native/llrt/unicode.xo's u24); the
// caller appends the table's trailing pad.
func put24le(b []byte, v int) []byte {
	if v < -(1<<23) || v >= 1<<23 {
		panic(fmt.Sprintf("unicode table value %d does not fit 24 bits", v))
	}
	u := uint32(v) & 0xFFFFFF
	return append(b, byte(u), byte(u>>8), byte(u>>16))
}

// tablePad is the zero bytes after a u24 table: unicode.xo reads one entry
// with rt.bytes_word, which takes 8 bytes, and the last entry starts three
// bytes before the table's end.
var tablePad = make([]byte, 8)

// runeIXShift is the log2 of a class index block: a class's <NAME>_IX has an
// entry per 1 << runeIXShift runes from U+0080, the first range a rune of
// that block can be in (std/native/llrt/unicode.xo in_ranges_ix).
const runeIXShift = 10

// unicodeTables is the text of std/native/llrt/unicode_tables.xo: the case
// ranges of Go's unicode package (unicode.CaseRanges, with the title delta
// as well as the upper and lower ones), which the native runtime's
// Str.to_lower, Str.to_upper and Rune.to_title use so they map like
// strings.ToLower, strings.ToUpper and unicode.ToTitle (decision 0074),
// and the class ranges of every Rune class (is_letter, is_digit, is_print,
// is_upper, is_lower, is_title, is_punct, is_control, is_graphic, is_mark,
// is_symbol and is_number; decisions 0079 and 0081). Each table is one
// Bytes constant (static data in the binary, no allocation; decision 0180)
// of 24 bit big endian values.
func unicodeTables() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/llvm TestUnicodeTables -golden-update from\n")
	fmt.Fprintf(&b, "// Go's unicode and strconv tables (Unicode %s). DO NOT EDIT.\n", unicode.Version)
	b.WriteString("//\n// The tables of std/native/llrt/unicode.xo (decision 0180): each is a\n")
	b.WriteString("// Bytes constant of 24 bit little endian values, then 8 zero bytes,\n")
	b.WriteString("// so u24 reads one value with a single rt.bytes_word and a mask.\n\n")
	b.WriteString("/// A delta of CASE that means alternating upper and lower case pairs.\n")
	b.WriteString("pub const UPPER_LOWER: Int = 1114112\n\n")
	var cs []byte
	for _, c := range unicode.CaseRanges {
		cs = put24le(cs, int(c.Lo))
		cs = put24le(cs, int(c.Hi))
		cs = put24le(cs, int(c.Delta[unicode.UpperCase]))
		cs = put24le(cs, int(c.Delta[unicode.LowerCase]))
		cs = put24le(cs, int(c.Delta[unicode.TitleCase]))
	}
	cs = append(cs, tablePad...)
	b.WriteString("/// The number of case ranges (unicode.CaseRanges) in CASE.\n")
	fmt.Fprintf(&b, "pub const CASE_N: Int = %d\n\n", len(unicode.CaseRanges))
	b.WriteString("/// CASE_N ranges of 15 bytes: lo, hi, upper delta, lower delta, title\n")
	b.WriteString("/// delta (a delta in two's complement).\n")
	fmt.Fprintf(&b, "pub const CASE: Bytes = %s\n", xoBytesLit(cs))
	// classes of Rune (decision 0079): inclusive ranges of the runes at or
	// above U+0080 (below it the runtime tests ASCII directly)
	classes := []struct {
		name, doc string
		in        func(rune) bool
	}{
		{"LETTER", "unicode.IsLetter", unicode.IsLetter},
		{"DIGIT", "unicode.IsDigit", unicode.IsDigit},
		{"PRINT", "strconv.IsPrint", strconv.IsPrint},
		{"UPPER", "unicode.IsUpper", unicode.IsUpper},
		{"LOWER", "unicode.IsLower", unicode.IsLower},
		{"TITLE", "unicode.IsTitle", unicode.IsTitle},
		{"PUNCT", "unicode.IsPunct", unicode.IsPunct},
		{"CONTROL", "unicode.IsControl", unicode.IsControl},
		{"GRAPHIC", "unicode.IsGraphic", unicode.IsGraphic},
		{"MARK", "unicode.IsMark", unicode.IsMark},
		{"SYMBOL", "unicode.IsSymbol", unicode.IsSymbol},
		{"NUMBER", "unicode.IsNumber", unicode.IsNumber},
	}
	// direct tables of the runes U+0080 to U+07FF (two byte UTF-8: Latin,
	// Greek, Cyrillic, Armenian, Hebrew, Arabic): their case mappings and
	// class bits, so the common scripts need no search
	var lower2, upper2, title2 []byte
	for r := rune(0x80); r < 0x800; r++ {
		lower2 = put24le(lower2, int(unicode.ToLower(r)))
		upper2 = put24le(upper2, int(unicode.ToUpper(r)))
		title2 = put24le(title2, int(unicode.ToTitle(r)))
	}
	lower2 = append(lower2, tablePad...)
	upper2 = append(upper2, tablePad...)
	title2 = append(title2, tablePad...)
	b.WriteString("\n/// unicode.ToLower of the runes U+0080 to U+07FF, 3 bytes each from\n/// U+0080.\n")
	fmt.Fprintf(&b, "pub const LOWER2: Bytes = %s\n", xoBytesLit(lower2))
	b.WriteString("\n/// unicode.ToUpper of the runes U+0080 to U+07FF, 3 bytes each from\n/// U+0080.\n")
	fmt.Fprintf(&b, "pub const UPPER2: Bytes = %s\n", xoBytesLit(upper2))
	b.WriteString("\n/// unicode.ToTitle of the runes U+0080 to U+07FF, 3 bytes each from\n/// U+0080.\n")
	fmt.Fprintf(&b, "pub const TITLE2: Bytes = %s\n", xoBytesLit(title2))
	for _, c := range classes {
		// PRINT's bitmap covers the whole BMP: strconv.Quote asks IsPrint of
		// every rune it copies, runes below U+10000 are the bulk of non-ASCII
		// text, and one bitmap from U+0080 costs one branch less than a
		// bitmap to U+07FF and another one after it
		hi := rune(0x800)
		if c.name == "PRINT" {
			hi = 0x10000
		}
		bits := make([]byte, (hi-0x80)/8)
		for r := rune(0x80); r < hi; r++ {
			if c.in(r) {
				bits[(r-0x80)>>3] |= 1 << (r & 7)
			}
		}
		fmt.Fprintf(&b, "\n/// %s of the runes U+0080 to U+%04X: bit r & 7 of byte (r - 0x80) >> 3.\n", c.doc, hi-1)
		fmt.Fprintf(&b, "pub const %s_BITS: Bytes = %s\n", c.name, xoBytesLit(bits))
	}
	for _, c := range classes {
		var rs [][2]rune
		for r := rune(0x80); r <= unicode.MaxRune; r++ {
			if !c.in(r) {
				continue
			}
			if n := len(rs); n > 0 && rs[n-1][1] == r-1 {
				rs[n-1][1] = r
			} else {
				rs = append(rs, [2]rune{r, r})
			}
		}
		var t []byte
		for _, r := range rs {
			t = put24le(t, int(r[0]))
			t = put24le(t, int(r[1]))
		}
		t = append(t, tablePad...)
		fmt.Fprintf(&b, "\n/// The number of ranges in %s.\n", c.name)
		fmt.Fprintf(&b, "pub const %s_N: Int = %d\n\n", c.name, len(rs))
		fmt.Fprintf(&b, "/// The runes at or above U+0080 for which %s is true: %s_N\n", c.doc, c.name)
		b.WriteString("/// inclusive ranges of 6 bytes, lo and hi.\n")
		fmt.Fprintf(&b, "pub const %s: Bytes = %s\n", c.name, xoBytesLit(t))
		// the two level index: a 16 bit entry per runeIXShift rune block,
		// the first range a rune of that block can be in, so a lookup is
		// one load and a scan of the one or two ranges the block holds
		// instead of a binary search of the whole table
		ix := make([]byte, 0, 16)
		nblocks := (unicode.MaxRune + 1 - 0x80 + 1<<runeIXShift - 1) >> runeIXShift
		j := 0
		for blk := rune(0); blk < rune(nblocks); blk++ {
			start := rune(0x80) + blk<<runeIXShift
			for j < len(rs) && rs[j][1] < start {
				j++
			}
			ix = append(ix, byte(j), byte(j>>8))
		}
		ix = append(ix, tablePad...)
		fmt.Fprintf(&b, "\n/// The number of blocks in %s_IX: runeIXShift runes each from U+0080.\n", c.name)
		fmt.Fprintf(&b, "pub const %s_IX_N: Int = %d\n\n", c.name, nblocks)
		fmt.Fprintf(&b, "/// For %s: %s_IX_N 16 bit first candidate range indices, one per\n", c.doc, c.name)
		b.WriteString("/// runeIXShift rune block from U+0080, little endian.\n")
		fmt.Fprintf(&b, "pub const %s_IX: Bytes = %s\n", c.name, xoBytesLit(ix))
	}
	return b.Bytes()
}

// regexpCanonicalName is regexp/syntax's canonicalName: a leading
// capital, lowercase after it, no `_`, `-`, or space.
func regexpCanonicalName(name string) string {
	var b []byte
	first := true
	for i := 0; i < len(name); i++ {
		c := name[i]
		switch {
		case c == '_' || c == '-' || c == ' ':
			continue
		case first:
			if 'a' <= c && c <= 'z' {
				c -= 'a' - 'A'
			}
			first = false
		default:
			if 'A' <= c && c <= 'Z' {
				c += 'a' - 'A'
			}
		}
		b = append(b, c)
	}
	return string(b)
}

// regexpUnicodeTable is regexp/syntax's unicodeTable for a canonical
// name other than Any and Ascii (std/native/regexp.xo has those): the
// table, its fold table (nil for none), and the sign; a nil table for a
// name Go's regexp does not know.
func regexpUnicodeTable(name string) (tab, fold *unicode.RangeTable, sign int) {
	switch name {
	case "Assigned":
		return unicode.Cn, unicode.Cn, -1
	case "Lc":
		return unicode.Categories["LC"], unicode.FoldCategory["LC"], +1
	}
	if t := unicode.Categories[name]; t != nil {
		return t, unicode.FoldCategory[name], +1
	}
	if t := unicode.Scripts[name]; t != nil {
		return t, unicode.FoldScript[name], +1
	}
	for alias, actual := range unicode.CategoryAliases {
		if regexpCanonicalName(alias) == name {
			return unicode.Categories[actual], unicode.FoldCategory[actual], +1
		}
	}
	return nil, nil, 0
}

// rangePairs is t as sorted inclusive [lo, hi] pairs, adjacent runes
// merged (a stride other than 1 expanded).
func rangePairs(t *unicode.RangeTable) [][2]rune {
	var rs [][2]rune
	add := func(r rune) {
		if n := len(rs); n > 0 && rs[n-1][1] == r-1 {
			rs[n-1][1] = r
		} else {
			rs = append(rs, [2]rune{r, r})
		}
	}
	for _, x := range t.R16 {
		for r := rune(x.Lo); r <= rune(x.Hi); r += rune(x.Stride) {
			add(r)
		}
	}
	for _, x := range t.R32 {
		for r := rune(x.Lo); r <= rune(x.Hi); r += rune(x.Stride) {
			add(r)
		}
	}
	return rs
}

// regexpClassNames are the canonical names Go's regexp knows in
// \p{...}, sorted, without Any and Ascii.
func regexpClassNames() []string {
	seen := map[string]bool{"Assigned": true, "Lc": true}
	for k := range unicode.Categories {
		seen[regexpCanonicalName(k)] = true
	}
	for k := range unicode.Scripts {
		seen[regexpCanonicalName(k)] = true
	}
	for k := range unicode.CategoryAliases {
		seen[regexpCanonicalName(k)] = true
	}
	var names []string
	for n := range seen {
		if t, _, _ := regexpUnicodeTable(n); t != nil && n != "Any" && n != "Ascii" {
			names = append(names, n)
		}
	}
	sort.Strings(names)
	return names
}

// unicodeClasses is the text of std/native/llrt/unicode_classes.xo: the
// Unicode classes of Go's regexp/syntax (unicode.Categories, Scripts,
// FoldCategory, FoldScript, CategoryAliases, and Assigned), looked up by
// canonical name as regexp/syntax's unicodeTable does. A name Go's
// lookup cannot reach (a script with an underscore, such as Old_Italic:
// its canonical name is Olditalic) is left out, so it is an error
// natively as in Go.
func unicodeClasses() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/llvm TestUnicodeTables -golden-update from\n")
	fmt.Fprintf(&b, "// Go's unicode tables (Unicode %s). DO NOT EDIT.\n", unicode.Version)
	b.WriteString("//\n// The Unicode classes of std/native/regexp.xo's \\p{...}, as Go's\n")
	b.WriteString("// regexp/syntax looks them up (unicodeTable).\n\n")
	ids := map[*unicode.RangeTable]int{}
	var ranges, index []byte
	pairs := 0
	id := func(t *unicode.RangeTable) int {
		if t == nil {
			return -1
		}
		if k, ok := ids[t]; ok {
			return k
		}
		rs := rangePairs(t)
		index = put24(index, pairs)
		index = put24(index, len(rs))
		for _, r := range rs {
			ranges = put24(ranges, int(r[0]))
			ranges = put24(ranges, int(r[1]))
		}
		pairs += len(rs)
		ids[t] = len(ids)
		return ids[t]
	}
	var arms bytes.Buffer
	for _, n := range regexpClassNames() {
		tab, fold, sign := regexpUnicodeTable(n)
		ti := id(tab)
		fi := id(fold)
		fmt.Fprintf(&arms, "    %q => (%d, %d, %d)\n", n, ti, fi, sign)
	}
	b.WriteString("/// The ranges of the tables: inclusive lo and hi of 3 bytes each.\n")
	fmt.Fprintf(&b, "pub const RANGES: Bytes = %s\n\n", xoBytesLit(ranges))
	b.WriteString("/// The tables: the index of the first range in RANGES and the number\n")
	b.WriteString("/// of ranges, 3 bytes each.\n")
	fmt.Fprintf(&b, "pub const TABLES: Bytes = %s\n\n", xoBytesLit(index))
	b.WriteString("/// The table, the fold table (-1: none), and the sign (-1: the\n")
	b.WriteString("/// table's complement) of a canonical class name; a sign 0 for a name\n")
	b.WriteString("/// Go's regexp does not know.\n")
	b.WriteString("pub fn class_of(name: Str) -> (Int, Int, Int) {\n  match name {\n")
	b.Write(arms.Bytes())
	b.WriteString("    _ => (-1, -1, 0)\n  }\n}\n")
	return b.Bytes()
}

// TestUnicodeTables checks that std/native/llrt/unicode_tables.xo is
// generated from this Go's unicode tables (-golden-update rewrites it;
// decision 0198 deleted std/llrt/xo_unicode.c, the C path's copy).
func TestUnicodeTables(t *testing.T) {
	for _, f := range []struct {
		path string
		want []byte
	}{
		{unicodeTablesPath, unicodeTables()},
		{unicodeClassesPath, unicodeClasses()},
	} {
		if *updateGolden {
			if err := os.WriteFile(f.path, f.want, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		got, err := os.ReadFile(f.path)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got, f.want) {
			t.Errorf("%s is stale: run go test ./internal/llvm -run TestUnicodeTables -golden-update", f.path)
		}
	}
}
