// xoBytesLit is b as an Xo Bytes literal: printable ASCII as itself
// (except `"`, `\`, and `$`), every other byte \xhh.
func xoBytesLit(b []byte) string {
	var s bytes.Buffer
	s.WriteString(`b"`)
	for _, c := range b {
		if c >= 0x20 && c < 0x7f && c != '"' && c != '\\' && c != '$' {
			s.WriteByte(c)
		} else {
			fmt.Fprintf(&s, `\x%02x`, c)
		}
	}
	s.WriteByte('"')
	return s.String()
}

// put24 appends v as 24 bits big endian (two's complement for a negative
// delta).
func put24(b []byte, v int) []byte {
	if v < -(1<<23) || v >= 1<<23 {
		panic(fmt.Sprintf("unicode table value %d does not fit 24 bits", v))
	}
	u := uint32(v) & 0xFFFFFF
	return append(b, byte(u>>16), byte(u>>8), byte(u))
}

// unicodeTables is the text of std/native/llrt/unicode_tables.xo: the case
// ranges of Go's unicode package (unicode.CaseRanges), which the native
// runtime's Str.to_lower and Str.to_upper use so they map like
// strings.ToLower and strings.ToUpper (decision 0074), and the letter,
// digit, and printable rune ranges of Rune.is_letter, is_digit, is_print,
// and the quoting helpers (decision 0079). Each table is one Bytes
// constant (static data in the binary, no allocation; decision 0180) of
// 24 bit big endian values.
func unicodeTables() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/llvm TestUnicodeTables -golden-update from\n")
	fmt.Fprintf(&b, "// Go's unicode and strconv tables (Unicode %s). DO NOT EDIT.\n", unicode.Version)
	b.WriteString("//\n// The tables of std/native/llrt/unicode.xo (decision 0180): each is a\n")
	b.WriteString("// Bytes constant of 24 bit big endian values.\n\n")
	b.WriteString("/// A delta of CASE that means alternating upper and lower case pairs.\n")
	b.WriteString("pub const UPPER_LOWER: Int = 1114112\n\n")
	var cs []byte
	for _, c := range unicode.CaseRanges {
		cs = put24(cs, int(c.Lo))
		cs = put24(cs, int(c.Hi))
		cs = put24(cs, int(c.Delta[unicode.UpperCase]))
		cs = put24(cs, int(c.Delta[unicode.LowerCase]))
	}
	b.WriteString("/// The number of case ranges (unicode.CaseRanges) in CASE.\n")
	fmt.Fprintf(&b, "pub const CASE_N: Int = %d\n\n", len(unicode.CaseRanges))
	b.WriteString("/// CASE_N ranges of 12 bytes: lo, hi, upper delta, lower delta (a\n")
	b.WriteString("/// delta in two's complement).\n")
	fmt.Fprintf(&b, "pub const CASE: Bytes = %s\n", xoBytesLit(cs))
	// classes of Rune (decision 0079): inclusive ranges of the runes at or
	// above U+0080 (below it the runtime tests ASCII directly)
	classes := []struct {
		name, doc string
		in        func(rune) bool
	}{
		{"LETTER", "unicode.IsLetter", unicode.IsLetter},
		{"DIGIT", "unicode.IsDigit", unicode.IsDigit},
		{"PRINT", "strconv.IsPrint", strconv.IsPrint},
	}
	// direct tables of the runes U+0080 to U+07FF (two byte UTF-8: Latin,
	// Greek, Cyrillic, Armenian, Hebrew, Arabic): their case mappings and
	// class bits, so the common scripts need no search
	var lower2, upper2 []byte
	for r := rune(0x80); r < 0x800; r++ {
		lower2 = put24(lower2, int(unicode.ToLower(r)))
		upper2 = put24(upper2, int(unicode.ToUpper(r)))
	}
	b.WriteString("\n/// unicode.ToLower of the runes U+0080 to U+07FF, 3 bytes each from\n/// U+0080.\n")
	fmt.Fprintf(&b, "pub const LOWER2: Bytes = %s\n", xoBytesLit(lower2))
	b.WriteString("\n/// unicode.ToUpper of the runes U+0080 to U+07FF, 3 bytes each from\n/// U+0080.\n")
	fmt.Fprintf(&b, "pub const UPPER2: Bytes = %s\n", xoBytesLit(upper2))
	for _, c := range classes {
		bits := make([]byte, (0x800-0x80)/8)
		for r := rune(0x80); r < 0x800; r++ {
			if c.in(r) {
				bits[(r-0x80)>>3] |= 1 << (r & 7)
			}
		}
		fmt.Fprintf(&b, "\n/// %s of the runes U+0080 to U+07FF: bit r & 7 of byte (r - 0x80) >> 3.\n", c.doc)
		fmt.Fprintf(&b, "pub const %s2: Bytes = %s\n", c.name, xoBytesLit(bits))
	}
	for _, c := range classes {
		var rs [][2]rune
		for r := rune(0x80); r <= unicode.MaxRune; r++ {
			if !c.in(r) {
				continue
			}
			if n := len(rs); n > 0 && rs[n-1][1] == r-1 {
				rs[n-1][1] = r
			} else {
				rs = append(rs, [2]rune{r, r})
			}
		}
		var t []byte
		for _, r := range rs {
			t = put24(t, int(r[0]))
			t = put24(t, int(r[1]))
		}
		fmt.Fprintf(&b, "\n/// The number of ranges in %s.\n", c.name)
		fmt.Fprintf(&b, "pub const %s_N: Int = %d\n\n", c.name, len(rs))
		fmt.Fprintf(&b, "/// The runes at or above U+0080 for which %s is true: %s_N\n", c.doc, c.name)
		b.WriteString("/// inclusive ranges of 6 bytes, lo and hi.\n")
		fmt.Fprintf(&b, "pub const %s: Bytes = %s\n", c.name, xoBytesLit(t))
	}
	return b.Bytes()
}

// unicodeTablesC is the text of std/llrt/xo_unicode.c, the same tables
// for the C path of the Unicode operations (decision 0180: compiled only
// with -DXO_UNICODE_C, selected by XO_UNICODE=c).
func unicodeTablesC() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/llvm TestUnicodeTables -golden-update from\n")
	fmt.Fprintf(&b, "// Go's unicode and strconv tables (Unicode %s). DO NOT EDIT.\n\n", unicode.Version)
	b.WriteString("// xo_case_ranges: lo, hi, upper delta, lower delta; a delta of\n")
	b.WriteString("// XO_UPPER_LOWER means alternating upper and lower case pairs.\n")
	b.WriteString("#define XO_UPPER_LOWER (0x10FFFF + 1)\n\n")
	b.WriteString("typedef struct {\n\tint32_t lo, hi, up, low;\n} xo_case_range;\n\n")
	fmt.Fprintf(&b, "static const xo_case_range xo_case_ranges[%d] = {\n", len(unicode.CaseRanges))
	for _, c := range unicode.CaseRanges {
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X, %d, %d},\n", c.Lo, c.Hi, c.Delta[unicode.UpperCase], c.Delta[unicode.LowerCase])
	}
	b.WriteString("};\n")
	// classes of Rune (decision 0079): inclusive ranges of the runes at or
	// above U+0080 (below it the runtime tests ASCII directly)
	classes := []struct {
		name, doc string
		in        func(rune) bool
	}{
		{"xo_letter_ranges", "unicode.IsLetter", unicode.IsLetter},
		{"xo_digit_ranges", "unicode.IsDigit", unicode.IsDigit},
		{"xo_print_ranges", "strconv.IsPrint", strconv.IsPrint},
	}
	for _, c := range classes {
		var rs [][2]rune
		for r := rune(0x80); r <= unicode.MaxRune; r++ {
			if !c.in(r) {
				continue
			}
			if n := len(rs); n > 0 && rs[n-1][1] == r-1 {
				rs[n-1][1] = r
			} else {
				rs = append(rs, [2]rune{r, r})
			}
		}
		fmt.Fprintf(&b, "\n// %s: the runes at or above U+0080 for which %s is true.\n", c.name, c.doc)
		fmt.Fprintf(&b, "static const int32_t %s[%d][2] = {\n", c.name, len(rs))
		for _, r := range rs {
			fmt.Fprintf(&b, "\t{0x%04X, 0x%04X},\n", r[0], r[1])
		}
		b.WriteString("};\n")
	}
	return b.Bytes()
}

// TestUnicodeTables checks that std/native/llrt/unicode_tables.xo and
// std/llrt/xo_unicode.c are generated from this Go's unicode tables
// (-golden-update rewrites them).
