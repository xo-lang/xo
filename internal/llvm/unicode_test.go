// unicodeTables is the text of std/llrt/xo_unicode.c: the case ranges of
// Go's unicode package (unicode.CaseRanges), which the native runtime's
// Str.to_lower and Str.to_upper use so they map like strings.ToLower and
// strings.ToUpper (decision 0074), and the letter, digit, and printable
// rune ranges of Rune.is_letter, is_digit, is_print, and the quoting
// helpers (decision 0079).
func unicodeTables() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/llvm TestUnicodeTables -golden-update from\n")
	fmt.Fprintf(&b, "// Go's unicode and strconv tables (Unicode %s). DO NOT EDIT.\n\n", unicode.Version)
	b.WriteString("// xo_case_ranges: lo, hi, upper delta, lower delta; a delta of\n")
	b.WriteString("// XO_UPPER_LOWER means alternating upper and lower case pairs.\n")
	b.WriteString("#define XO_UPPER_LOWER (0x10FFFF + 1)\n\n")
	b.WriteString("typedef struct {\n\tint32_t lo, hi, up, low;\n} xo_case_range;\n\n")
	fmt.Fprintf(&b, "static const xo_case_range xo_case_ranges[%d] = {\n", len(unicode.CaseRanges))
	for _, c := range unicode.CaseRanges {
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X, %d, %d},\n", c.Lo, c.Hi, c.Delta[unicode.UpperCase], c.Delta[unicode.LowerCase])
	}
	b.WriteString("};\n")
	// classes of Rune (decision 0079): inclusive ranges of the runes at or
	// above U+0080 (below it the runtime tests ASCII directly)
	classes := []struct {
		name, doc string
		in        func(rune) bool
	}{
		{"xo_letter_ranges", "unicode.IsLetter", unicode.IsLetter},
		{"xo_digit_ranges", "unicode.IsDigit", unicode.IsDigit},
		{"xo_print_ranges", "strconv.IsPrint", strconv.IsPrint},
	}
	for _, c := range classes {
		var rs [][2]rune
		for r := rune(0x80); r <= unicode.MaxRune; r++ {
			if !c.in(r) {
				continue
			}
			if n := len(rs); n > 0 && rs[n-1][1] == r-1 {
				rs[n-1][1] = r
			} else {
				rs = append(rs, [2]rune{r, r})
			}
		}
		fmt.Fprintf(&b, "\n// %s: the runes at or above U+0080 for which %s is true.\n", c.name, c.doc)
		fmt.Fprintf(&b, "static const int32_t %s[%d][2] = {\n", c.name, len(rs))
		for _, r := range rs {
			fmt.Fprintf(&b, "\t{0x%04X, 0x%04X},\n", r[0], r[1])
		}
		b.WriteString("};\n")
	}
	return b.Bytes()
}

// TestUnicodeTables checks that std/llrt/xo_unicode.c is generated from
// this Go's unicode tables (-golden-update rewrites it).
func TestUnicodeTables(t *testing.T) {
	p := filepath.Join(rtDir, "xo_unicode.c")
	want := unicodeTables()
	if *updateGolden {
		if err := os.WriteFile(p, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s is stale: run go test ./internal/llvm -run TestUnicodeTables -golden-update", p)
	}
}
