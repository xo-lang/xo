package diag

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

var updateExplain = flag.Bool("update-explain", false, "rewrite selfhost/cli/core/explain_data.xo from the explanation tables")

// explainDataPath is the self hosted CLI's copy of the explanation tables
// (decision 0178 stage 2): `xo1 explain` reads it.
var explainDataPath = filepath.Join("..", "..", "selfhost", "cli", "core", "explain_data.xo")

// TestSelfhostExplainData checks that the generated Xo copy of
// Explanations, Descriptions, and SeverityOf is current; run with
// -update-explain to rewrite it after changing a text here.
func TestSelfhostExplainData(t *testing.T) {
	want := explainData()
	if *updateExplain {
		if err := os.WriteFile(explainDataPath, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(explainDataPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Errorf("%s is stale: run go test ./internal/diag -run TestSelfhostExplainData -update-explain", explainDataPath)
	}
}

// explainData renders the Xo source of the explanation tables.
func explainData() string {
	var codes []string
	for c := range Explanations {
		codes = append(codes, string(c))
	}
	sort.Strings(codes)
	var b strings.Builder
	b.WriteString(`// Code generated by internal/diag TestSelfhostExplainData from
// internal/diag/explain.go and codes.go; DO NOT EDIT. Regenerate with
//   go test ./internal/diag -run TestSelfhostExplainData -update-explain

/// The long form explanation of a diagnostic code (diag.Explanation),
/// with its severity and one line summary (diag.SeverityOf,
/// diag.Descriptions).
pub struct Expl {
  pub title: Str
  pub severity: Str
  pub summary: Str
  pub detail: Str
  pub example: Str
  pub fix: Str
}

/// The explanation of code (upper case, as XO0201), or None.
pub fn explanation(code: Str) -> Expl? {
  match code {
`)
	for _, c := range codes {
		e := Explanations[Code(c)]
		fmt.Fprintf(&b, "    %s => Some(Expl{title: %s, severity: %s, summary: %s, detail: %s, example: %s, fix: %s})\n",
			xoQuote(c), xoQuote(e.Title), xoQuote(string(SeverityOf(Code(c)))), xoQuote(Descriptions[Code(c)]),
			xoQuote(e.Detail), xoQuote(e.Example), xoQuote(e.Fix))
	}
	b.WriteString("    _ => None\n  }\n}\n")
	return b.String()
}

// xoQuote writes s as an Xo string literal: no interpolation (`$` is
// escaped), control characters escaped.
func xoQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '$':
			b.WriteString(`\$`)
		case '\n':
			b.WriteString(`\n`)
		case '\t':
			b.WriteString(`\t`)
		case '\r':
			b.WriteString(`\r`)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\u{%x}`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}
