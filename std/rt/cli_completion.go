package rt

import (
	"strconv"
	"strings"
)

// Shell completions (std.md 14.5, decision 0165): scripts for bash, zsh,
// and fish that complete subcommands, flags, and choice values from the
// declaration alone (the program does not run while completing). The
// native backends write the same text (std/native/cli.xo).

type cliNode struct {
	path  string
	c     *cliCmd
	flags []*cliFlag // the flags accepted there: the path's, root first
}

func cliNodes(root *cliCmd) []cliNode {
	var out []cliNode
	var walk func(c *cliCmd, path string, outer []*cliFlag)
	walk = func(c *cliCmd, path string, outer []*cliFlag) {
		flags := append(append([]*cliFlag(nil), outer...), c.flags...)
		out = append(out, cliNode{path, c, flags})
		for _, s := range c.cmds {
			walk(s, path+" "+s.name, flags)
		}
	}
	walk(root, root.name, nil)
	return out
}

// cliQ quotes s for bash and zsh: in single quotes, each quote inside closes the quotes, writes an escaped quote, and opens them again.
func cliQ(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

// cliFishQ quotes s for fish: '...' with \ and ' escaped.
func cliFishQ(s string) string {
	return "'" + strings.ReplaceAll(strings.ReplaceAll(s, `\`, `\\`), "'", `\'`) + "'"
}

// cliIdent is name with every byte but letters, digits, and _ as _.
func cliIdent(name string) string {
	b := []byte(name)
	for i, c := range b {
		if !(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '_') {
			b[i] = '_'
		}
	}
	return string(b)
}

// cliDesc is the first line of a help text.
func cliDesc(s string) string {
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		return s[:i]
	}
	return s
}

// cliWords are the words to offer at a command: subcommands, then flags.
func cliWords(root *cliCmd, n cliNode) []string {
	var ws []string
	for _, s := range n.c.cmds {
		ws = append(ws, s.name)
	}
	for _, f := range n.flags {
		ws = append(ws, "--"+f.name)
		if f.short != "" {
			ws = append(ws, "-"+f.short)
		}
	}
	ws = append(ws, "--help", "-h")
	if root.version != "" {
		ws = append(ws, "--version")
	}
	return ws
}

// cliFlagPats are the case patterns `path --name` and `path -s`.
func cliFlagPats(n cliNode, f *cliFlag) string {
	p := cliQ(n.path + " --" + f.name)
	if f.short != "" {
		p += "|" + cliQ(n.path+" -"+f.short)
	}
	return p
}

func cliBash(root *cliCmd) string {
	nodes := cliNodes(root)
	fn := "_" + cliIdent(root.name)
	var l []string
	l = append(l, "# bash completion for "+root.name+", generated by std/cli (decision 0165).",
		fn+"() {",
		`  local cur="${COMP_WORDS[COMP_CWORD]}" prev="${COMP_WORDS[COMP_CWORD-1]}" cmd=`+cliQ(root.name)+" i",
		"  for ((i = 1; i < COMP_CWORD; i++)); do",
		`    case "$cmd ${COMP_WORDS[i]}" in`)
	for _, n := range nodes[1:] {
		l = append(l, "      "+cliQ(n.path)+") cmd="+cliQ(n.path)+" ;;")
	}
	l = append(l, "    esac", "  done", `  case "$cmd $prev" in`)
	for _, n := range nodes {
		for _, f := range n.flags {
			switch {
			case f.kind == cliChoice:
				l = append(l, "    "+cliFlagPats(n, f)+`) COMPREPLY=($(compgen -W `+cliQ(strings.Join(f.choices, " "))+` -- "$cur")); return ;;`)
			case f.kind != cliBool:
				l = append(l, "    "+cliFlagPats(n, f)+") return ;;")
			}
		}
	}
	l = append(l, "  esac", `  case "$cmd" in`)
	for _, n := range nodes {
		l = append(l, "    "+cliQ(n.path)+`) COMPREPLY=($(compgen -W `+cliQ(strings.Join(cliWords(root, n), " "))+` -- "$cur")) ;;`)
	}
	l = append(l, "  esac", "}", "complete -o default -F "+fn+" "+root.name)
	return strings.Join(l, "\n") + "\n"
}

func cliZsh(root *cliCmd) string {
	nodes := cliNodes(root)
	fn := "_" + cliIdent(root.name)
	var l []string
	l = append(l, "#compdef "+root.name,
		"# zsh completion for "+root.name+", generated by std/cli (decision 0165).",
		fn+"() {",
		"  local cmd="+cliQ(root.name)+" i",
		"  for ((i = 2; i < CURRENT; i++)); do",
		`    case "$cmd ${words[i]}" in`)
	for _, n := range nodes[1:] {
		l = append(l, "      "+cliQ(n.path)+") cmd="+cliQ(n.path)+" ;;")
	}
	l = append(l, "    esac", "  done", `  case "$cmd ${words[CURRENT-1]}" in`)
	for _, n := range nodes {
		for _, f := range n.flags {
			switch {
			case f.kind == cliChoice:
				var cs []string
				for _, c := range f.choices {
					cs = append(cs, cliQ(c))
				}
				l = append(l, "    "+cliFlagPats(n, f)+") compadd -- "+strings.Join(cs, " ")+"; return ;;")
			case f.kind != cliBool:
				l = append(l, "    "+cliFlagPats(n, f)+") _files; return ;;")
			}
		}
	}
	l = append(l, "  esac", "  local -a items", `  case "$cmd" in`)
	var withArgs []string
	for _, n := range nodes {
		var items []string
		for _, s := range n.c.cmds {
			items = append(items, cliQ(s.name+":"+cliDesc(s.help)))
		}
		for _, f := range n.flags {
			items = append(items, cliQ("--"+f.name+":"+cliDesc(f.help)))
			if f.short != "" {
				items = append(items, cliQ("-"+f.short+":"+cliDesc(f.help)))
			}
		}
		items = append(items, cliQ("--help:show this help"), cliQ("-h:show this help"))
		if root.version != "" {
			items = append(items, cliQ("--version:show the version"))
		}
		l = append(l, "    "+cliQ(n.path)+") items=("+strings.Join(items, " ")+") ;;")
		if len(n.c.args) > 0 {
			withArgs = append(withArgs, cliQ(n.path))
		}
	}
	l = append(l, "  esac", "  _describe "+cliQ(root.name)+" items")
	if len(withArgs) > 0 {
		l = append(l, `  case "$cmd" in`, "    "+strings.Join(withArgs, "|")+") _files ;;", "  esac")
	}
	l = append(l, "}",
		`if [ "$funcstack[1]" = `+cliQ(fn)+" ]; then",
		"  "+fn+` "$@"`,
		"else",
		"  compdef "+fn+" "+root.name,
		"fi")
	return strings.Join(l, "\n") + "\n"
}

func cliFish(root *cliCmd) string {
	nodes := cliNodes(root)
	s := cliIdent(root.name)
	var l []string
	l = append(l, "# fish completion for "+root.name+", generated by std/cli (decision 0165).",
		"function __"+s+"_cmd",
		"    set -l cmd "+cliFishQ(root.name),
		"    for w in (commandline -opc)[2..-1]",
		`        switch "$cmd $w"`)
	for _, n := range nodes[1:] {
		l = append(l, "            case "+cliFishQ(n.path), "                set cmd "+cliFishQ(n.path))
	}
	l = append(l, "        end", "    end", "    echo $cmd", "end",
		"function __"+s+"_is",
		"    test (__"+s+"_cmd) = $argv[1]",
		"end",
		"complete -c "+root.name+" -f")
	for _, n := range nodes {
		pre := "complete -c " + root.name + ` -n "__` + s + "_is '" + n.path + `'"`
		for _, c := range n.c.cmds {
			l = append(l, pre+" -a "+cliFishQ(c.name)+" -d "+cliFishQ(cliDesc(c.help)))
		}
		for _, f := range n.flags {
			x := pre + " -l " + f.name
			if f.short != "" {
				x += " -s " + f.short
			}
			switch {
			case f.kind == cliChoice:
				x += " -x -a " + cliFishQ(strings.Join(f.choices, " "))
			case f.kind != cliBool:
				x += " -r -F"
			}
			l = append(l, x+" -d "+cliFishQ(cliDesc(f.help)))
		}
		l = append(l, pre+" -l help -s h -d 'show this help'")
		if root.version != "" {
			l = append(l, pre+" -l version -d 'show the version'")
		}
		if len(n.c.args) > 0 {
			l = append(l, pre+" -F")
		}
	}
	return strings.Join(l, "\n") + "\n"
}

// Cli_completion is `cli.completion(cmd, shell)`.
func Cli_completion(_ *Task, cmd Cli_Command, shell string) Result[string, Cli_CliErr] {
	root := cmd.c
	cliValidate(root, nil, root.version != "")
	switch shell {
	case "bash":
		return Ok[string, Cli_CliErr](cliBash(root))
	case "zsh":
		return Ok[string, Cli_CliErr](cliZsh(root))
	case "fish":
		return Ok[string, Cli_CliErr](cliFish(root))
	}
	return Err[string](Cli_CliErr{Tag: 3, P: Cli_CliErr_Usage{F_msg: "unknown shell " + strconv.Quote(shell) + " (one of bash, zsh, fish)", F_usage: cliUsageText([]*cliCmd{root})}})
}
